#!/usr/bin/env python3
"""Regenerates src/ecdh_fixtures.zig: XML Encryption 1.1 ECDH-ES documents written by xmlsec1 (C, OpenSSL backend,
run as a black box) for P-256, P-384 and P-521 with ConcatKDF parameters of every kind.

Needs xmlsec1 >= 1.3 and openssl on PATH. Usage (from the repository root):
    python3 -I modules/xmlenc/tools/gen_ecdh_fixtures.py > modules/xmlenc/src/ecdh_fixtures.zig

xmlsec1 takes the originator's key from its key manager by name (it neither writes nor reads a `dsig11:ECKeyValue`),
so the script splices the originator's `dsig11:ECKeyValue` into the document in place of the key name, which is
the form a standalone receiver reads; the plaintext is what xmlsec1 decrypts the original document to. The keys are
test material, freshly generated on every run.
"""
import os
import re
import subprocess
import sys
import tempfile

CURVES = [
    # name, openssl curve, coordinate bytes, NamedCurve URI, kw bits, content URI, session key, digest URI, hex params
    ("p256", "prime256v1", 32, "urn:oid:1.2.840.10045.3.1.7", 128, "http://www.w3.org/2001/04/xmlenc#aes128-cbc", "aes-128",
     "http://www.w3.org/2001/04/xmlenc#sha256", ("0000", "00414243", "00444546")),
    ("p384", "secp384r1", 48, "urn:oid:1.3.132.0.34", 192, "http://www.w3.org/2009/xmlenc11#aes192-gcm", "aes-192",
     "http://www.w3.org/2001/04/xmlenc#sha512", ("00416c67", "", "0070617274792d76")),
    ("p521", "secp521r1", 66, "urn:oid:1.3.132.0.35", 256, "http://www.w3.org/2009/xmlenc11#aes256-gcm", "aes-256",
     "http://www.w3.org/2001/04/xmlenc#sha256", ("00616c67", "0075", "")),
]
PLAIN = '<a:Doc xmlns:a="urn:example:doc"><a:Item>hello ecdh</a:Item></a:Doc>\n'

TEMPLATE = """<?xml version="1.0"?>
<xenc:EncryptedData xmlns:xenc="http://www.w3.org/2001/04/xmlenc#" xmlns:ds="http://www.w3.org/2000/09/xmldsig#" xmlns:xenc11="http://www.w3.org/2009/xmlenc11#" Type="http://www.w3.org/2001/04/xmlenc#Element">
  <xenc:EncryptionMethod Algorithm="{content}"/>
  <ds:KeyInfo>
    <xenc:EncryptedKey>
      <xenc:EncryptionMethod Algorithm="http://www.w3.org/2001/04/xmlenc#kw-aes{kw}"/>
      <ds:KeyInfo>
        <xenc:AgreementMethod Algorithm="http://www.w3.org/2009/xmlenc11#ECDH-ES">
          <xenc11:KeyDerivationMethod Algorithm="http://www.w3.org/2009/xmlenc11#ConcatKDF">
            <xenc11:ConcatKDFParams AlgorithmID="{aid}" PartyUInfo="{pu}" PartyVInfo="{pv}">
              <ds:DigestMethod Algorithm="{digest}"/>
            </xenc11:ConcatKDFParams>
          </xenc11:KeyDerivationMethod>
          <xenc:OriginatorKeyInfo><ds:KeyName>originator</ds:KeyName></xenc:OriginatorKeyInfo>
          <xenc:RecipientKeyInfo><ds:KeyName>recipient</ds:KeyName></xenc:RecipientKeyInfo>
        </xenc:AgreementMethod>
      </ds:KeyInfo>
      <xenc:CipherData><xenc:CipherValue/></xenc:CipherData>
    </xenc:EncryptedKey>
  </ds:KeyInfo>
  <xenc:CipherData><xenc:CipherValue/></xenc:CipherData>
</xenc:EncryptedData>
"""


def run(args, **kw):
    r = subprocess.run(args, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.exit("failed: %s\n%s%s" % (" ".join(args), r.stdout, r.stderr))
    return r.stdout


def keypair(tmp, name, curve, width):
    pem = os.path.join(tmp, name + ".pem")
    run(["openssl", "ecparam", "-name", curve, "-genkey", "-noout", "-out", pem])
    pub = os.path.join(tmp, name + "-pub.pem")
    run(["openssl", "ec", "-in", pem, "-pubout", "-out", pub])
    text = run(["openssl", "ec", "-in", pem, "-noout", "-text"])
    priv = re.search(r"priv:\s*((?:[0-9a-f:\s])+?)pub:", text).group(1)
    point = re.search(r"pub:\s*((?:[0-9a-f:\s])+?)ASN1 OID", text).group(1)
    d = bytes.fromhex(re.sub(r"[^0-9a-f]", "", priv))
    d = d.lstrip(b"\0").rjust(width, b"\0")
    q = bytes.fromhex(re.sub(r"[^0-9a-f]", "", point))
    assert len(d) == width and len(q) == 1 + 2 * width and q[0] == 4
    return pem, pub, d, q


def keypair_pub(tmp, pem, name):
    pub = os.path.join(tmp, name + "-pub2.pem")
    run(["openssl", "ec", "-in", pem, "-pubout", "-out", pub])
    return None, pub, None, None


def zig_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    import base64
    out = ["// SPDX-License-Identifier: MIT\n",
           "//! GENERATED by `tools/gen_ecdh_fixtures.py` (xmlsec1, OpenSSL backend); test material, do not edit.\n",
           "//! One XML Encryption 1.1 ECDH-ES `EncryptedData` per NIST curve, written by xmlsec1, the originator's\n",
           "//! `dsig11:ECKeyValue` spliced in, with the recipient's private scalar and the plaintext xmlsec1 decrypts it to.\n\n",
           "pub const Fixture = struct {\n    name: []const u8,\n    /// Recipient's static private scalar, big-endian, one coordinate wide.\n    scalar_hex: []const u8,\n    xml: []const u8,\n    plaintext: []const u8,\n};\n\n",
           "pub const fixtures = [_]Fixture{\n"]
    with tempfile.TemporaryDirectory() as tmp:
        plain = os.path.join(tmp, "plain.xml")
        open(plain, "w").write(PLAIN)
        for name, curve, width, uri, kw, content, session, digest, (aid, pu, pv) in CURVES:
            rpem, rpub, rd, rq = keypair(tmp, name + "-r", curve, width)
            opem, _, od, oq = keypair(tmp, name + "-o", curve, width)
            tmpl = os.path.join(tmp, name + "-t.xml")
            open(tmpl, "w").write(TEMPLATE.format(content=content, kw=kw, aid=aid, pu=pu, pv=pv, digest=digest))
            enc = os.path.join(tmp, name + "-e.xml")
            run(["xmlsec1", "--encrypt", "--privkey-pem:originator", opem, "--pubkey-pem:recipient", rpub,
                 "--session-key", session, "--xml-data", plain, "--output", enc, tmpl])
            doc = open(enc).read()
            doc = re.sub(r"^<\?xml[^>]*\?>\n", "", doc)
            ec = ('<ds:KeyValue><dsig11:ECKeyValue xmlns:dsig11="http://www.w3.org/2009/xmldsig11#"><dsig11:NamedCurve URI="%s"/>'
                  "<dsig11:PublicKey>%s</dsig11:PublicKey></dsig11:ECKeyValue></ds:KeyValue>") % (uri, base64.b64encode(oq).decode())
            marker = "<ds:KeyName>originator</ds:KeyName>"
            assert doc.count(marker) == 1
            doc = doc.replace(marker, ec)
            # What xmlsec1 itself decrypts the original (key names) document to: the recipient's private key and the
            # originator's public key, both by name.
            _, opub, _, _ = keypair_pub(tmp, opem, name + "-o")
            dec = run(["xmlsec1", "--decrypt", "--pubkey-pem:originator", opub, "--privkey-pem:recipient", rpem, enc])
            dec = re.sub(r"^<\?xml[^>]*\?>\n", "", dec)
            out.append("    .{\n        .name = %s,\n        .scalar_hex = %s,\n        .xml = %s,\n        .plaintext = %s,\n    },\n" % (
                zig_str(name), zig_str(rd.hex()), zig_str(doc), zig_str(dec)))
    out.append("};\n")
    sys.stdout.write("".join(out))


main()
