#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
#
# Regenerates src/asm/sha{256,512}-cryptogams.s, the block functions this
# module runs on x86-64 CPUs with the SHA extensions (SHA-256) or with
# AVX2 + BMI1 + BMI2 (both),
# from CRYPTOGAMS (Andy Polyakov's perlasm, https://github.com/dot-asm/cryptogams),
# used under its BSD-style licence (modules/sha2/NOTICE).
#
# THIS IS A RECIPE, run by a human from the repository root; nothing in the
# module or the build runs it. Needs curl, perl and sha256sum. The upstream
# files are pinned by commit AND by SHA-256. They are fetched into
# .zig-cache/foreign/cryptogams-<commit>/, which may be dropped at any time.
#
# What it changes, and nothing else (NOTICE repeats this):
#   - keeps only the AVX2 functions, SHA-256's SHA-extension function and
#     the constant tables out of perlasm's ELF output for sha256-x86_64.s /
#     sha512-x86_64.s (the run-time dispatcher, which reads OpenSSL's
#     OPENSSL_ia32cap_P, the SSSE3/AVX/XOP paths and SHA-512's SHA512-extension
#     path are dropped);
#   - renames the functions to zl_sha2_sha256_{avx2,shaext} and
#     zl_sha2_sha512_avx2 (.weak + .hidden, so they cannot clash with a linked
#     libcrypto, with another object carrying this module, or leave a shared
#     object)
#     and prefixes every local label with .Lzl_sha{256,512}_ (both files share
#     label names and end up in one object);
#   - drops the .note.gnu.property section (the object's notes are LLVM's).
#
# perlasm asks `$CC -Wa,-v` for the assembler version to decide whether to
# emit the AVX/AVX2 paths. It is handed a two-line stand-in that only prints a
# binutils version, so no compiler runs. Read before running (2026-10-26):
# besides that query, the two scripts run nothing, open only their output
# file, and touch no network (the Windows-only nasm/ml64 probes do not fire
# for the `elf` flavour).

set -euo pipefail

commit=4acc4a308eab6049d1cf1c7ba61b353a36ce0e2d
sha_pl=6ee974df19970f12cb7ec4c4c16736ee9cfe99bfb07abb9e71d7ed4274145d7a
sha_xlate=ae43d9ec5c89021f65a33f69bf1a3fda864ef9f13036e643edc8b0bf62a7aae1

[[ -f modules/sha2/tools/gen_cryptogams.sh ]] || { echo "run from the repository root" >&2; exit 2; }
work=.zig-cache/foreign/cryptogams-$commit
mkdir -p "$work/fakecc"
raw=https://raw.githubusercontent.com/dot-asm/cryptogams/$commit
for f in x86_64/sha512-x86_64.pl x86_64/x86_64-xlate.pl LICENSE; do
    [[ -f "$work/$(basename "$f")" ]] || curl -fsSL "$raw/$f" -o "$work/$(basename "$f")"
done
echo "$sha_pl  $work/sha512-x86_64.pl" | sha256sum -c --quiet
echo "$sha_xlate  $work/x86_64-xlate.pl" | sha256sum -c --quiet

printf '#!/bin/sh\necho "GNU assembler version 2.42"\n' > "$work/fakecc/cc"
chmod +x "$work/fakecc/cc"

out=modules/sha2/src/asm
mkdir -p "$out"
for bits in 256 512; do
    gen="$work/sha$bits-x86_64.s"
    CC="$work/fakecc/cc" perl "$work/sha512-x86_64.pl" elf "$gen"
    # SHA-256: the AVX2 path and the SHA-extension (SHA-NI) path; SHA-512:
    # AVX2 only (its SHA512-extension path needs Arrow Lake or later, which
    # nothing here can run or emulate).
    paths=avx2
    [[ $bits == 256 ]] && paths="avx2 shaext"
    tbl=K$bits
    dst="$out/sha$bits-cryptogams.s"
    {
        echo "# Generated by modules/sha2/tools/gen_cryptogams.sh -- do not edit."
        echo "# CRYPTOGAMS sha512-x86_64.pl @ $commit (https://github.com/dot-asm/cryptogams),"
        echo "# Copyright (c) 2006, CRYPTOGAMS by <appro@openssl.org>; BSD-style licence,"
        echo "# full text and the list of changes in modules/sha2/NOTICE."
        echo ".text"
        # The constant table: from its .type line up to the next function.
        # Its `.align 64` precedes the .type line upstream: vmovdqa loads
        # from it need the alignment.
        echo ".align 64"
        awk -v t="$tbl" '$0 ~ "^\\.type[ \t]+" t "," {on=1} on && /^\.(type[ \t]+sha.*,@function|globl)/ {exit} on' "$gen"
        for path in $paths; do
            fn=sha${bits}_block_data_order_$path
            # .weak, not .globl: two objects that both carry this module (two
            # static libraries built with zig-libs) must link, not collide.
            echo ".weak $fn"
            echo ".hidden $fn"
            # The function: from its .type line to its .size line.
            awk -v f="$fn" '$0 ~ "^\\.type[ \t]+" f "," {on=1} on {print} on && $0 ~ "^\\.size[ \t]+" f "," {exit}' "$gen"
        done
    } | sed -e "s/\\bsha${bits}_block_data_order_\\(avx2\\|shaext\\)\\b/zl_sha2_sha${bits}_\\1/g" \
            -e "s/\\.L\\([A-Za-z0-9_]\\)/.Lzl_sha${bits}_\\1/g" \
            -e "s/\\b\\($tbl[A-Za-z0-9_]*\\)\\b/.Lzl_sha${bits}_\\1/g" > "$dst"
    # Nothing outside the extracted function may be referenced or declared:
    # no OpenSSL symbol, no other upstream function, no unprefixed label.
    if grep -q 'OPENSSL\|ia32cap\|block_data_order' "$dst"; then echo "$dst references upstream symbols" >&2; exit 1; fi
    if grep -E '^[A-Za-z_.][A-Za-z0-9_.]*:' "$dst" | grep -vq '^\(\.Lzl_sha'"$bits"'_\|zl_sha2_sha'"$bits"'_[a-z0-9]*:\)'; then
        echo "$dst defines a label outside the zl_ prefixes" >&2; exit 1
    fi
    echo "$dst: $(wc -l < "$dst") lines"
done
