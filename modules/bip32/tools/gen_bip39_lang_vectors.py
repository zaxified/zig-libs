"""Write src/bip39_lang_vectors.zig: BIP-39 vectors for every non-English language.

    tools/gen_bip39_lang_vectors.py --data-dir <dir with bip-0039/*.txt and test_JP_BIP39.json>

For each language, four entropies mapped to a mnemonic and a seed by this script
(Python `hashlib` SHA-256 / PBKDF2-HMAC-SHA512 and `unicodedata` NFKD/NFC: an
independent implementation), with ASCII and non-ASCII passphrases, and the same
mnemonic in composed (NFC) form. The script asserts, before writing anything, that its
own algorithm reproduces the 24 official Japanese vectors of the BIP-39 Japanese test
suite (bip32JP/bip32JP.github.io `test_JP_BIP39.json`: entropy, mnemonic, passphrase,
seed); that file carries no licence, so it is only read here, never copied into the tree.
"""
import argparse
import hashlib
import json
import os
import unicodedata

LANGS = ["japanese", "spanish", "chinese_simplified", "chinese_traditional", "french", "italian", "korean", "czech", "portuguese"]
ENTS = [bytes(16), bytes([0x7F] * 16), bytes(range(32)), bytes([0xFF] * 24)]
PASS = ["", "TREZOR", "été 　Ａ가"]


def zq(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def words(d, lang):
    return [w for w in open(os.path.join(d, lang + ".txt"), encoding="utf-8").read().split("\n") if w]


def entropy_to_mnemonic(ws, ent, sep):
    bits = "".join(format(b, "08b") for b in ent)
    bits += "".join(format(b, "08b") for b in hashlib.sha256(ent).digest())[: len(ent) * 8 // 32]
    return sep.join(ws[int(bits[i : i + 11], 2)] for i in range(0, len(bits), 11))


def seed(m, p):
    m = unicodedata.normalize("NFKD", m)
    p = unicodedata.normalize("NFKD", p)
    return hashlib.pbkdf2_hmac("sha512", m.encode(), ("mnemonic" + p).encode(), 2048, 64).hex()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", required=True)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "bip39_lang_vectors.zig"))
    a = ap.parse_args()
    jp = json.load(open(os.path.join(a.data_dir, "test_JP_BIP39.json"), encoding="utf-8"))
    ws = words(a.data_dir, "japanese")
    for v in jp:
        assert unicodedata.normalize("NFKD", entropy_to_mnemonic(ws, bytes.fromhex(v["entropy"]), "　")) == unicodedata.normalize("NFKD", v["mnemonic"])
        assert seed(v["mnemonic"], v["passphrase"]) == v["seed"]
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("// SPDX-License-Identifier: MIT\n// Generated by tools/gen_bip39_lang_vectors.py. Do not hand-edit.\n\n")
        f.write("//! BIP-39 vectors for the nine non-English languages: per language four entropies with their mnemonic\n")
        f.write("//! (NFKD words, the language's separator), the same mnemonic composed (NFC, original separators),\n")
        f.write("//! and the seed under an ASCII or non-ASCII passphrase, computed by the generator with Python's own\n")
        f.write("//! SHA-256, PBKDF2 and Unicode normalisation (an implementation independent of this module). The\n")
        f.write("//! generator first checks its algorithm against the 24 official Japanese BIP-39 vectors.\n\n")
        f.write("pub const Cross = struct { language: []const u8, entropy: []const u8, mnemonic: []const u8, mnemonic_composed: []const u8, passphrase: []const u8, seed: []const u8 };\n")
        f.write("pub const cross = [_]Cross{\n")
        for lang in LANGS:
            w = words(a.data_dir, lang)
            sep = "　" if lang == "japanese" else " "
            for i, e in enumerate(ENTS):
                m = entropy_to_mnemonic(w, e, sep)
                p = PASS[i % 3]
                f.write("    .{ .language = %s, .entropy = %s, .mnemonic = %s, .mnemonic_composed = %s, .passphrase = %s, .seed = %s },\n" % (zq(lang), zq(e.hex()), zq(m), zq(unicodedata.normalize("NFC", m)), zq(p), zq(seed(m, p))))
        f.write("};\n")


if __name__ == "__main__":
    main()
