"""Transcribe the nine non-English BIP-39 wordlists into src/wordlist_<lang>.zig.

    tools/gen_wordlists.py --data-dir <dir holding bitcoin/bips bip-0039/*.txt>

Each file must hold 2048 distinct words that are already in NFKD (BIP-39 requires
it; the script refuses a word that is not). The Zig files list the words verbatim,
in file order (the index of a word is its 11-bit value), and are never hand-edited.
"""
import argparse
import os
import sys
import unicodedata

LANGS = ["japanese", "spanish", "chinese_simplified", "chinese_traditional", "french", "italian", "korean", "czech", "portuguese"]


def zq(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", required=True)
    ap.add_argument("--out-dir", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
    a = ap.parse_args()
    for lang in LANGS:
        words = [w for w in open(os.path.join(a.data_dir, lang + ".txt"), encoding="utf-8").read().split("\n") if w]
        assert len(words) == 2048 and len(set(words)) == 2048, lang
        for w in words:
            if unicodedata.normalize("NFKD", w) != w:
                sys.exit("%s: %r is not NFKD" % (lang, w))
        longest = max(len(w.encode("utf-8")) for w in words)
        path = os.path.join(a.out_dir, "wordlist_%s.zig" % lang)
        with open(path, "w", encoding="utf-8") as f:
            f.write("// SPDX-License-Identifier: MIT\n// Generated by tools/gen_wordlists.py from bitcoin/bips bip-0039/%s.txt. Do not hand-edit.\n\n" % lang)
            f.write("//! The official BIP-39 %s wordlist: 2048 distinct words in NFKD (as BIP-39 requires),\n" % lang.replace("_", " "))
            f.write("//! in file order (a word's index is its 11-bit value), longest word %d bytes.\n\n" % longest)
            f.write("pub const max_word_len = %d;\n\n" % longest)
            f.write("pub const words: [2048][]const u8 = .{\n")
            for i in range(0, 2048, 8):
                f.write("    " + ", ".join(zq(w) for w in words[i : i + 8]) + ",\n")
            f.write("};\n")
        print("wrote", path, longest, file=sys.stderr)


if __name__ == "__main__":
    main()
