"""Recipe for `src/client_certs.zig`: TEST client certificates for client
authentication, generated by Python `cryptography` (OpenSSL). Fresh keys every
run; the committed file is one such run. The keys are test fixtures, published
with the source: never use them for anything else.

    python3 -I tools/client_certs.py > src/client_certs.zig

- `ca_cert`: CN=tlsserver-test-client-ca, P-256, self-signed, CA:true,
  keyCertSign + cRLSign; `ca_name` is its subject (a DistinguishedName for
  certificate_authorities).
- `p256_cert`, `rsa2048_cert`, `ed25519_cert`: CN=client-<kind>, issued by the
  CA, CA:false, digitalSignature, extendedKeyUsage clientAuth.
- `server_only_cert` (P-256): extendedKeyUsage serverAuth only.
- `expired_cert` (P-256): valid 2020-01-01 .. 2021-01-01.
- `stranger_cert` (P-256): clientAuth, self-signed (no path to the CA).

Validity 2026-01-01 .. 2046-01-01 unless said otherwise. Each key as PKCS#8
DER (`*_pkcs8`), the EC ones also as their scalar (big-endian).
"""

import datetime

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, rsa
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

UTC = datetime.timezone.utc


def name(cn):
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def build(subject, issuer, pub, sign_key, hash_alg, ca=False, eku=None,
          not_before=datetime.datetime(2026, 1, 1, tzinfo=UTC),
          not_after=datetime.datetime(2046, 1, 1, tzinfo=UTC)):
    b = (x509.CertificateBuilder()
         .subject_name(subject).issuer_name(issuer)
         .public_key(pub)
         .serial_number(x509.random_serial_number())
         .not_valid_before(not_before)
         .not_valid_after(not_after)
         .add_extension(x509.BasicConstraints(ca=ca, path_length=None), critical=True))
    if ca:
        b = b.add_extension(x509.KeyUsage(
            digital_signature=False, content_commitment=False, key_encipherment=False,
            data_encipherment=False, key_agreement=False, key_cert_sign=True, crl_sign=True,
            encipher_only=False, decipher_only=False), critical=True)
    else:
        b = b.add_extension(x509.KeyUsage(
            digital_signature=True, content_commitment=False, key_encipherment=False,
            data_encipherment=False, key_agreement=False, key_cert_sign=False, crl_sign=False,
            encipher_only=False, decipher_only=False), critical=True)
    if eku is not None:
        b = b.add_extension(x509.ExtendedKeyUsage(eku), critical=False)
    return b.sign(sign_key, hash_alg).public_bytes(serialization.Encoding.DER)


def pkcs8(key):
    return key.private_bytes(serialization.Encoding.DER, serialization.PrivateFormat.PKCS8,
                             serialization.NoEncryption())


def zig(name, data):
    h = data.hex()
    lines = [h[i:i + 96] for i in range(0, len(h), 96)]
    body = " ++\n    ".join('"%s"' % l for l in lines)
    return "pub const %s = hx(%d, %s);" % (name, len(data), body)


def main():
    ca_key = ec.generate_private_key(ec.SECP256R1())
    ca_name = name("tlsserver-test-client-ca")
    ca = build(ca_name, ca_name, ca_key.public_key(), ca_key, hashes.SHA256(), ca=True)

    client = [ExtendedKeyUsageOID.CLIENT_AUTH]
    out = []
    p256 = ec.generate_private_key(ec.SECP256R1())
    out.append(("p256", build(name("client-p256"), ca_name, p256.public_key(), ca_key, hashes.SHA256(), eku=client), p256))
    rsak = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    out.append(("rsa2048", build(name("client-rsa2048"), ca_name, rsak.public_key(), ca_key, hashes.SHA256(), eku=client), rsak))
    edk = ed25519.Ed25519PrivateKey.generate()
    out.append(("ed25519", build(name("client-ed25519"), ca_name, edk.public_key(), ca_key, hashes.SHA256(), eku=client), edk))
    so = ec.generate_private_key(ec.SECP256R1())
    out.append(("server_only", build(name("client-server-only"), ca_name, so.public_key(), ca_key, hashes.SHA256(),
                                     eku=[ExtendedKeyUsageOID.SERVER_AUTH]), so))
    ex = ec.generate_private_key(ec.SECP256R1())
    out.append(("expired", build(name("client-expired"), ca_name, ex.public_key(), ca_key, hashes.SHA256(), eku=client,
                                 not_before=datetime.datetime(2020, 1, 1, tzinfo=UTC),
                                 not_after=datetime.datetime(2021, 1, 1, tzinfo=UTC)), ex))
    st = ec.generate_private_key(ec.SECP256R1())
    out.append(("stranger", build(name("client-stranger"), name("client-stranger"), st.public_key(), st, hashes.SHA256(),
                                  eku=client), st))

    print("// SPDX-License-Identifier: MIT")
    print("")
    print("//! TEST client certificates and private keys, generated by")
    print("//! `tools/client_certs.py` (Python `cryptography`): a client CA and leaves it")
    print("//! issued (see the script). Published test fixtures: never use these keys for")
    print("//! anything else.")
    print("")
    print(zig("ca_cert", ca))
    print("/// The CA's subject, DER (a DistinguishedName).")
    print(zig("ca_name", ca_name.public_bytes()))
    for kind, der, key in out:
        print(zig(kind + "_cert", der))
        print(zig(kind + "_pkcs8", pkcs8(key)))
        if isinstance(key, ec.EllipticCurvePrivateKey):
            print("/// The private scalar, big-endian.")
            print(zig(kind + "_scalar", key.private_numbers().private_value.to_bytes(32, "big")))
        if isinstance(key, ed25519.Ed25519PrivateKey):
            seed = key.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                                     serialization.NoEncryption())
            pub = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
            print("/// The secret key in std's form: seed ‖ public key.")
            print(zig(kind + "_secret", seed + pub))
        if isinstance(key, rsa.RSAPrivateKey):
            print("/// The private key, PKCS#1 DER.")
            print(zig(kind + "_pkcs1", key.private_bytes(serialization.Encoding.DER,
                                                          serialization.PrivateFormat.TraditionalOpenSSL,
                                                          serialization.NoEncryption())))
    print("")
    print("fn hx(comptime n: usize, comptime hex: []const u8) [n]u8 {")
    print("    @setEvalBranchQuota(1_000_000);")
    print("    var out: [n]u8 = undefined;")
    print('    _ = @import("std").fmt.hexToBytes(&out, hex) catch unreachable;')
    print("    return out;")
    print("}")


if __name__ == "__main__":
    main()
