#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Recipe for `src/key_vectors.zig`: private keys in every PEM form the
`openssl` command line writes, each with a self-signed certificate, for the
`keys` loader's tests. Fresh keys every run; the committed file is one such
run. Published TEST keys: never use them for anything else.

    python3 -I tools/key_vectors.py > src/key_vectors.zig

Needs `openssl` (3.x) and `zig` (for `zig fmt --stdin`) on PATH; works in a
temporary directory.
"""

import io
import os
import subprocess
import sys
import tempfile


def run(*args, cwd):
    subprocess.run(args, cwd=cwd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def read(cwd, name):
    with open(os.path.join(cwd, name)) as f:
        return f.read()


def cert(cwd, key, out, digest):
    args = ["openssl", "req", "-x509", "-new", "-key", key, "-out", out, "-days", "7300",
            "-subj", "/CN=tlsserver-test", "-addext", "subjectAltName=DNS:localhost"]
    if digest:
        args += ["-" + digest]
    run(*args, cwd=cwd)


def zig_str(s):
    lines = s.splitlines(keepends=True)
    return "\n".join("        \\\\" + l.rstrip("\n") for l in lines) + "\n"


def main():
    with tempfile.TemporaryDirectory() as d:
        version = subprocess.run(["openssl", "version"], check=True, capture_output=True, text=True).stdout.strip().split(" (")[0]
        cases = []
        # P-256: `ecparam -genkey` (an EC PARAMETERS block, then SEC1 with
        # [0] and [1]), and the same key as PKCS#8.
        run("openssl", "ecparam", "-name", "prime256v1", "-genkey", "-out", "p256.sec1", cwd=d)
        run("openssl", "pkcs8", "-topk8", "-nocrypt", "-in", "p256.sec1", "-out", "p256.p8", cwd=d)
        cert(d, "p256.p8", "p256.crt", "sha256")
        cases += [("p256-sec1", "ecdsa_p256", "p256.sec1", "p256.crt"),
                  ("p256-pkcs8", "ecdsa_p256", "p256.p8", "p256.crt")]
        # P-384: `genpkey` (PKCS#8), and the same key as SEC1 (`ec`).
        run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-384", "-out", "p384.p8", cwd=d)
        run("openssl", "ec", "-in", "p384.p8", "-out", "p384.sec1", cwd=d)
        cert(d, "p384.p8", "p384.crt", "sha384")
        cases += [("p384-pkcs8", "ecdsa_p384", "p384.p8", "p384.crt"),
                  ("p384-sec1", "ecdsa_p384", "p384.sec1", "p384.crt")]
        # Ed25519: PKCS#8 only (RFC 8410).
        run("openssl", "genpkey", "-algorithm", "ED25519", "-out", "ed.p8", cwd=d)
        cert(d, "ed.p8", "ed.crt", None)
        cases += [("ed25519-pkcs8", "ed25519", "ed.p8", "ed.crt")]
        # RSA-2048: `genpkey` (PKCS#8) and `rsa -traditional` (PKCS#1).
        run("openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", "rsa.p8", cwd=d)
        run("openssl", "rsa", "-traditional", "-in", "rsa.p8", "-out", "rsa.p1", cwd=d)
        cert(d, "rsa.p8", "rsa.crt", "sha256")
        cases += [("rsa-pkcs8", "rsa", "rsa.p8", "rsa.crt"),
                  ("rsa-pkcs1", "rsa", "rsa.p1", "rsa.crt")]
        # P-521: `genpkey` (PKCS#8), and the same key as SEC1.
        run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-521", "-out", "p521.p8", cwd=d)
        run("openssl", "ec", "-in", "p521.p8", "-out", "p521.sec1", cwd=d)
        cert(d, "p521.p8", "p521.crt", "sha512")
        cases += [("p521-pkcs8", "ecdsa_p521", "p521.p8", "p521.crt"),
                  ("p521-sec1", "ecdsa_p521", "p521.sec1", "p521.crt")]
        # ML-DSA (RFC 9881): OpenSSL's default "both" form (seed and expanded
        # key) and the seed-only form of the same key; the expanded-only form
        # is refused (`mldsa_expanded_pem`).
        for n in (44, 65, 87):
            k = "mldsa%d" % n
            run("openssl", "genpkey", "-algorithm", "ML-DSA-%d" % n, "-out", k + ".both", cwd=d)
            for form in ("seed-only", "priv-only"):
                run("openssl", "pkey", "-in", k + ".both", "-provparam", "ml-dsa.output_formats=" + form,
                    "-out", "%s.%s" % (k, form), cwd=d)
            cert(d, k + ".both", k + ".crt", None)
            cases += [("%s-both" % k, k, k + ".both", k + ".crt"),
                      ("%s-seed" % k, k, k + ".seed-only", k + ".crt")]
        # Refused: an encrypted PKCS#8 key and a secp256k1 key.
        run("openssl", "pkcs8", "-topk8", "-in", "p256.sec1", "-out", "p256.enc", "-passout", "pass:test", cwd=d)
        run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:secp256k1", "-out", "k256.p8", cwd=d)

        buf = io.StringIO()
        w = buf.write
        w("// SPDX-License-Identifier: MIT\n\n")
        w("//! TEST private keys in every PEM form `openssl` writes, each with a\n")
        w("//! self-signed certificate (CN=tlsserver-test), generated by\n")
        w("//! `tools/key_vectors.py` with %s. Published test fixtures:\n" % version)
        w("//! never use these keys for anything else. Do not edit by hand.\n\n")
        w("pub const Kind = enum { ecdsa_p256, ecdsa_p384, ecdsa_p521, ed25519, rsa, mldsa44, mldsa65, mldsa87 };\n\n")
        w("pub const Case = struct { name: []const u8, kind: Kind, key_pem: []const u8, cert_pem: []const u8 };\n\n")
        certs = {}
        for _, _, _, c in cases:
            if c not in certs:
                certs[c] = "cert_" + c.split(".")[0]
                w("const %s =\n%s;\n" % (certs[c], zig_str(read(d, c))))
        w("\npub const cases = [_]Case{\n")
        for name, kind, key, c in cases:
            w("    .{\n        .name = \"%s\",\n        .kind = .%s,\n        .key_pem =\n%s        ,\n        .cert_pem = %s,\n    },\n"
              % (name, kind, zig_str(read(d, key)), certs[c]))
        w("};\n\n")
        w("/// PKCS#8 `ENCRYPTED PRIVATE KEY` (password \"test\").\n")
        w("pub const encrypted_pem =\n%s;\n" % zig_str(read(d, "p256.enc")))
        w("/// `cases`' ML-DSA-44 key in the expanded-only form, which is refused.\n")
        w("pub const mldsa44_expanded_pem =\n%s;\n" % zig_str(read(d, "mldsa44.priv-only")))
        w("/// A secp256k1 key in PKCS#8: a curve the server does not sign with.\n")
        w("pub const k256_pem =\n%s;\n" % zig_str(read(d, "k256.p8")))
        out = subprocess.run(["zig", "fmt", "--stdin"], input=buf.getvalue(), check=True,
                             capture_output=True, text=True).stdout
        sys.stdout.write(out)


if __name__ == "__main__":
    main()
