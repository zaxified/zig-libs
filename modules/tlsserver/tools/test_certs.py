"""Recipe for `src/test_certs.zig`: self-signed TEST certificates and their
private keys (ECDSA P-256, ECDSA P-384, Ed25519, RSA-2048), generated by Python
`cryptography` (OpenSSL). Fresh keys every run; the committed file is one
such run. The keys are test fixtures, published with the source: never use
them for anything else.

    python3 -I tools/test_certs.py > src/test_certs.zig

Each certificate: subject = issuer = CN=tlsserver-test, SAN DNS:localhost,
valid 2026-01-01 .. 2046-01-01, signed by its own key.
"""

import datetime

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, rsa
from cryptography.x509.oid import NameOID


def cert(key, hash_alg):
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "tlsserver-test")])
    b = (x509.CertificateBuilder()
         .subject_name(name).issuer_name(name)
         .public_key(key.public_key())
         .serial_number(x509.random_serial_number())
         .not_valid_before(datetime.datetime(2026, 1, 1, tzinfo=datetime.timezone.utc))
         .not_valid_after(datetime.datetime(2046, 1, 1, tzinfo=datetime.timezone.utc))
         .add_extension(x509.SubjectAlternativeName([x509.DNSName("localhost")]), critical=False)
         .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True))
    return b.sign(key, hash_alg).public_bytes(serialization.Encoding.DER)


def zig(name, data):
    h = data.hex()
    lines = [h[i:i + 96] for i in range(0, len(h), 96)]
    body = " ++\n    ".join('"%s"' % l for l in lines)
    return "pub const %s = hx(%d, %s);" % (name, len(data), body)


def main():
    p256 = ec.generate_private_key(ec.SECP256R1())
    p384 = ec.generate_private_key(ec.SECP384R1())
    edk = ed25519.Ed25519PrivateKey.generate()
    rsak = rsa.generate_private_key(public_exponent=65537, key_size=2048)

    p256_scalar = p256.private_numbers().private_value.to_bytes(32, "big")
    p384_scalar = p384.private_numbers().private_value.to_bytes(48, "big")
    ed_seed = edk.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                                serialization.NoEncryption())
    ed_pub = edk.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    rsa_pkcs1 = rsak.private_bytes(serialization.Encoding.DER, serialization.PrivateFormat.TraditionalOpenSSL,
                                   serialization.NoEncryption())

    print("// SPDX-License-Identifier: MIT")
    print("")
    print("//! TEST certificates and private keys, generated by `tools/test_certs.py`")
    print("//! (Python `cryptography`). Self-signed, CN=tlsserver-test, SAN localhost.")
    print("//! Published test fixtures: never use these keys for anything else.")
    print("")
    print(zig("p256_cert", cert(p256, hashes.SHA256())))
    print("/// The P-256 private scalar, big-endian.")
    print(zig("p256_scalar", p256_scalar))
    print(zig("p384_cert", cert(p384, hashes.SHA384())))
    print("/// The P-384 private scalar, big-endian.")
    print(zig("p384_scalar", p384_scalar))
    print(zig("ed25519_cert", cert(edk, None)))
    print("/// The Ed25519 secret key in std's form: seed ‖ public key.")
    print(zig("ed25519_secret", ed_seed + ed_pub))
    print(zig("rsa2048_cert", cert(rsak, hashes.SHA256())))
    print("/// The RSA-2048 private key, PKCS#1 DER.")
    print(zig("rsa2048_pkcs1", rsa_pkcs1))
    print("")
    print("fn hx(comptime n: usize, comptime hex: []const u8) [n]u8 {")
    print("    @setEvalBranchQuota(1_000_000);")
    print("    var out: [n]u8 = undefined;")
    print('    _ = @import("std").fmt.hexToBytes(&out, hex) catch unreachable;')
    print("    return out;")
    print("}")


if __name__ == "__main__":
    main()
