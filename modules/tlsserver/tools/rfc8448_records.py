"""Recipe for `src/record_kat_vectors.zig`: the protected records of RFC 8448
section 3 (simple 1-RTT handshake, TLS_AES_128_GCM_SHA256) with the traffic
key, IV, sequence number, inner content type and plaintext each one was sealed
under; plus records for the two suites RFC 8448 does not cover
(TLS_AES_256_GCM_SHA384, TLS_CHACHA20_POLY1305_SHA256) sealed by OpenSSL
through Python `cryptography` — fixed keys/IVs/contents, padding, and sequence
numbers that exercise the high nonce octets.

Needs: the RFC text (https://www.rfc-editor.org/rfc/rfc8448.txt) and Python's
`cryptography` package (OpenSSL), which re-opens every extracted record as an
independent check that the extraction paired the right key, IV and sequence
number with each record before anything is written.

    python3 -I tools/rfc8448_records.py rfc8448.txt > src/record_kat_vectors.zig

Produces the Zig file on stdout; exits non-zero if any record fails to open.
"""

import re
import sys

import hashlib

from cryptography.hazmat.primitives.ciphers.aead import AESGCM, ChaCha20Poly1305


def strip_page_breaks(text):
    """Drop the page footer / form feed / header sequence, which splits long
    hex blocks across pages and would otherwise end a block early."""
    return re.sub(r"\n*Thomson +Informational +\[Page \d+\]\n\f\nRFC 8448 +TLS 1\.3 Traces +January 2019\n\n*", "\n", text)


def section3(text):
    # rindex: the first occurrences are the table of contents.
    return text[text.rindex("3.  Simple 1-RTT Handshake"):text.rindex("4.  Resumed 0-RTT Handshake")]


def hex_after(block, label):
    """The hex octets following `label` up to the first line that is not hex."""
    i = block.index(label) + len(label)
    out = []
    for n, line in enumerate(block[i:].split("\n")):
        s = line.strip()
        if n > 0 and not re.fullmatch(r"([0-9a-f]{2}\s*)+", s):
            break
        out += re.findall(r"\b[0-9a-f]{2}\b", s)
    return bytes.fromhex("".join(out))


def keys(sec, heading):
    i = sec.index(heading)
    block = sec[i:i + 1200]
    return hex_after(block, "key expanded (16 octets):"), hex_after(block, "iv expanded (12 octets):")


def records(sec):
    """Every '{side}  send <kind> record:' block whose complete record is protected (0x17)."""
    out = []
    for m in re.finditer(r"\{(client|server)\}  send (handshake|application_data|alert) record:", sec):
        block = sec[m.end():m.end() + 6000]
        payload = hex_after(block, re.search(r"payload \(\d+ octets\):", block).group(0))
        rec = hex_after(block, re.search(r"complete record \(\d+ octets\):", block).group(0))
        if rec[0] == 0x17:
            out.append((m.group(1), m.group(2), payload, rec))
    return out


def main():
    sec = section3(strip_page_breaks(open(sys.argv[1]).read()))
    server_hs = keys(sec, "{server}  derive write traffic keys for handshake data:")
    server_ap = keys(sec, "{server}  derive write traffic keys for application data:")
    client_hs = keys(sec, "{server}  derive read traffic keys for handshake data:")
    client_ap = keys(sec, "{client}  derive write traffic keys for application data:")

    recs = records(sec)
    # The order RFC 8448 section 3 sends them in, with the key each direction
    # is under at that point and its per-key sequence number.
    plan = [
        ("server_encrypted_extensions_to_finished", server_hs, 0, 22),
        ("client_finished", client_hs, 0, 22),
        ("server_new_session_ticket", server_ap, 0, 22),
        ("client_application_data", client_ap, 0, 23),
        ("server_application_data", server_ap, 1, 23),
        ("client_close_notify", client_ap, 1, 21),
        ("server_close_notify", server_ap, 2, 21),
    ]
    if len(recs) != len(plan):
        sys.exit(f"expected {len(plan)} protected records, found {len(recs)}")

    emit = []
    for (name, (key, iv), seq, ctype), (_side, _kind, payload, rec) in zip(plan, recs):
        nonce = iv[:4] + bytes(a ^ b for a, b in zip(iv[4:], seq.to_bytes(8, "big")))
        inner = AESGCM(key).decrypt(nonce, rec[5:], rec[:5])
        if inner != payload + bytes([ctype]):
            sys.exit(f"{name}: opened inner plaintext does not match the RFC payload + type")
        emit.append((name, key, iv, seq, ctype, payload, rec))

    print("// SPDX-License-Identifier: MIT")
    print("")
    print("//! RFC 8448 section 3 protected records (TLS_AES_128_GCM_SHA256), generated by")
    print("//! `tools/rfc8448_records.py` from the RFC text; every record was re-opened with")
    print("//! Python `cryptography` (OpenSSL) before it was written. Do not edit by hand.")
    print("")
    print("pub const Vector = struct {")
    print("    name: []const u8,")
    print("    key: [16]u8,")
    print("    iv: [12]u8,")
    print("    seq: u64,")
    print("    content_type: u8,")
    print("    plaintext: []const u8,")
    print("    record: []const u8,")
    print("};")
    print("")

    def lit(b):
        h = b.hex()
        parts = [h[i:i + 96] for i in range(0, len(h), 96)]
        return " ++\n            ".join(f'"{p}"' for p in parts)

    emit_foreign = []
    def fixed(label, n):
        out = b""
        while len(out) < n:
            out += hashlib.sha256((label + str(len(out))).encode()).digest()
        return out[:n]
    for suite, name, cls, klen in ((0x1302, "aes256gcm", AESGCM, 32), (0x1303, "chacha20poly1305", ChaCha20Poly1305, 32)):
        key = fixed(name + " key", klen)
        iv = fixed(name + " iv", 12)
        for seq, ctype, plen, pad in ((0, 22, 0, 0), (1, 23, 1, 0), (7, 23, 300, 13), (0x0123456789abcdef, 21, 2, 0), (2**64 - 2, 23, 1000, 0)):
            payload = fixed(f"{name} payload {seq}", plen)
            inner = payload + bytes([ctype]) + bytes(pad)
            header = bytes([0x17, 0x03, 0x03]) + (len(inner) + 16).to_bytes(2, "big")
            nonce = iv[:4] + bytes(a ^ b for a, b in zip(iv[4:], seq.to_bytes(8, "big")))
            rec = header + cls(key).encrypt(nonce, inner, header)
            emit_foreign.append((f"{name}_seq{seq}", suite, key, iv, seq, ctype, pad, payload, rec))

    print("pub const vectors = [_]Vector{")
    for name, key, iv, seq, ctype, payload, rec in emit:
        print("    .{")
        print(f'        .name = "{name}",')
        print(f'        .key = hx(16, "{key.hex()}"),')
        print(f'        .iv = hx(12, "{iv.hex()}"),')
        print(f"        .seq = {seq},")
        print(f"        .content_type = {ctype},")
        print(f"        .plaintext = &hx({len(payload)},\n            {lit(payload)}),")
        print(f"        .record = &hx({len(rec)},\n            {lit(rec)}),")
        print("    },")
    print("};")
    print("")
    print("/// Records sealed by OpenSSL (Python `cryptography`) for the suites RFC 8448")
    print("/// does not cover; `key` is the suite's key length.")
    print("pub const ForeignVector = struct {")
    print("    name: []const u8,")
    print("    suite: u16,")
    print("    key: []const u8,")
    print("    iv: [12]u8,")
    print("    seq: u64,")
    print("    content_type: u8,")
    print("    pad: usize,")
    print("    plaintext: []const u8,")
    print("    record: []const u8,")
    print("};")
    print("")
    print("pub const foreign_vectors = [_]ForeignVector{")
    for name, suite, key, iv, seq, ctype, pad, payload, rec in emit_foreign:
        print("    .{")
        print(f'        .name = "{name}",')
        print(f"        .suite = 0x{suite:04x},")
        print(f'        .key = &hx({len(key)}, "{key.hex()}"),')
        print(f'        .iv = hx(12, "{iv.hex()}"),')
        print(f"        .seq = {seq},")
        print(f"        .content_type = {ctype},")
        print(f"        .pad = {pad},")
        if payload:
            print(f"        .plaintext = &hx({len(payload)},\n            {lit(payload)}),")
        else:
            print('        .plaintext = "",')
        print(f"        .record = &hx({len(rec)},\n            {lit(rec)}),")
        print("    },")
    print("};")
    print("")
    print("fn hx(comptime n: usize, comptime hex: []const u8) [n]u8 {")
    print("    @setEvalBranchQuota(1_000_000);")
    print("    var out: [n]u8 = undefined;")
    print('    _ = @import("std").fmt.hexToBytes(&out, hex) catch unreachable;')
    print("    return out;")
    print("}")


if __name__ == "__main__":
    main()
