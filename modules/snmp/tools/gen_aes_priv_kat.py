"""Recipe for src/priv_kat.zig: AES-192/256 USM privacy known-answer vectors.

Independent re-derivation from the spec text, using only hashlib and the
`cryptography` package's AES-CFB128 (no snmp code):

  * RFC 3414 A.2/2.6: Ku = H(password cycled to 2^20 octets); Kul = H(Ku || engineID || Ku).
  * blumenthal (draft-blumenthal-aes-usm-04 3.1.2.1): Kul = Kul || H(Kul),
    repeated until enough bytes, then truncated to the key size.
  * reeder (net-snmp "Cisco" AES variants, keytools.c _kul_extend_reeder):
    Ku' = Ku-algorithm(Kul), Kul = Kul || (H(Ku' || engineID || Ku'));
    repeated until enough bytes, then truncated.
  * CFB128 (SP 800-38A), IV = engineBoots(4,BE) || engineTime(4,BE) || salt(8).

Run:  python3 -I tools/gen_aes_priv_kat.py > src/priv_kat.zig
The draft's own Appendix A vector (maplesyrup, SHA-1, 256-bit) is asserted.
"""
import hashlib
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

HASHES = [
    ("hmac_md5", hashlib.md5), ("hmac_sha1", hashlib.sha1),
    ("hmac_sha224", hashlib.sha224), ("hmac_sha256", hashlib.sha256),
    ("hmac_sha384", hashlib.sha384), ("hmac_sha512", hashlib.sha512),
]
ENGINE = bytes(11) + b"\x02"
PASSWORD = b"maplesyrup"
BOOTS, TIME = 5, 12345
SALT = bytes([0, 0, 0, 1, 0xDE, 0xAD, 0xBE, 0xEF])
PLAIN = bytes((i * 37 + 5) & 0xFF for i in range(37))  # not a block multiple


def ku(h, pw):
    """RFC 3414 A.2.1: hash of the password cycled to 1048576 octets."""
    m = h()
    idx = 0
    for _ in range(1048576 // 64):
        m.update(bytes(pw[(idx + j) % len(pw)] for j in range(64)))
        idx += 64
    return m.digest()


def localize(h, k, eng):
    return h(k + eng + k).digest()


def extend(h, how, kul, need):
    while len(kul) < need:
        if how == "blumenthal":
            kul += h(kul).digest()
        else:
            kul += localize(h, ku(h, kul), ENGINE)
    return kul[:need] if len(kul) > need else kul


def cfb(key, data):
    e = Cipher(algorithms.AES(key), modes.CFB(IV)).encryptor()
    return e.update(data) + e.finalize()


IV = BOOTS.to_bytes(4, "big") + TIME.to_bytes(4, "big") + SALT


def hx(b):
    return '"' + b.hex() + '"'


# Draft-blumenthal-aes-usm-04 Appendix A.
_k = localize(hashlib.sha1, ku(hashlib.sha1, PASSWORD), ENGINE)
assert _k.hex() == "6695febc9288e36282235fc7151f128497b38f3f", _k.hex()
assert extend(hashlib.sha1, "blumenthal", _k, 32).hex() == (
    "6695febc9288e36282235fc7151f128497b38f3f505e07eb9af25568fa1f5dbe")

print("// SPDX-License-Identifier: MIT")
print("// GENERATED by tools/gen_aes_priv_kat.py -- do not edit by hand.")
print("// AES-192/256 USM privacy KATs: password \"maplesyrup\", engineID 00*11 || 02,")
print("// boots 5, time 12345, salt 000000'01 deadbeef, 37-byte plaintext pattern (i*37+5).")
print("")
print("pub const Case = struct {")
print("    auth: []const u8, // usm.AuthProtocol tag name")
print("    priv: []const u8, // priv.PrivProtocol tag name")
print("    key_hex: []const u8, // localized + extended key, exactly keyLen() bytes")
print("    ct_hex: []const u8, // ciphertext of the plaintext pattern")
print("};")
print("")
print("pub const cases = [_]Case{")
for hn, h in HASHES:
    kul0 = localize(h, ku(h, PASSWORD), ENGINE)
    for pn, bits, how in [("aes192_cfb", 24, "blumenthal"), ("aes256_cfb", 32, "blumenthal"),
                          ("aes192_cisco_cfb", 24, "reeder"), ("aes256_cisco_cfb", 32, "reeder")]:
        key = extend(h, how, kul0, bits)[:bits]
        print(f"    .{{ .auth = \"{hn}\", .priv = \"{pn}\", .key_hex = {hx(key)}, .ct_hex = {hx(cfb(key, PLAIN))} }},")
print("};")
print("")
print("/// Multi-round extension (need = 64 bytes), through `usm.extendLocalizedKey` directly: the")
print("/// protocols only ever need one round (<= 32 bytes), so this is the only multi-round check.")
print("pub const ExtCase = struct { auth: []const u8, how: []const u8, key_hex: []const u8 };")
print("pub const ext64 = [_]ExtCase{")
for hn, h in HASHES[:3]:
    kul0 = localize(h, ku(h, PASSWORD), ENGINE)
    for how in ("blumenthal", "reeder"):
        print(f"    .{{ .auth = \"{hn}\", .how = \"{how}\", .key_hex = {hx(extend(h, how, kul0, 64))} }},")
print("};")
