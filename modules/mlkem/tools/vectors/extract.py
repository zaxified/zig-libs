#!/usr/bin/env python3 -I
"""Extract the reduced ML-KEM vector slice committed under src/testdata/.

Usage: python3 -I extract.py <dir with cctv/ acvp/ wp/ clones> <testdata out dir>
Sources are only READ (never executed). Recipe: clone into one directory
  git clone --depth 1 https://github.com/C2SP/CCTV.git cctv          (b88c4b206254, CC0-1.0)
  git clone --depth 1 --filter=blob:none --sparse https://github.com/usnistgov/ACVP-Server.git acvp
      && git -C acvp sparse-checkout set gen-val/json-files           (975de31eb83d, NIST/US-gov)
  git clone --depth 1 https://github.com/C2SP/wycheproof.git wp       (d17cc89fa5c8, Apache-2.0)
then run this script; the commit ids are written into the data file headers.

Line format (all values lower-case hex, whitespace separated, P = 512|768|1024):
  kg    P d z ek dk              ML-KEM.KeyGen_internal(d || z) -> ek, dk
  enc   P ek m c k               Encaps_internal(ek, m) -> c, k
  dec   P dk c k                 Decaps(dk, c) -> k (c may be a modified ciphertext)
  full  P d z m ek dk c k        keygen + encaps + decaps in one case
  ct    P seed sha3_256(ek) c k  keygen from seed, ek hash, Decaps(c) -> k
  ekchk P 0|1 ek                 encapsulation-key check must pass (1) / fail (0)
  dkchk P 0|1 dk                 decapsulation-key check must pass (1) / fail (0)
  modbase P ek                   bad key (modulus check must fail); base for the following `mod` lines
  mod   P off:hex[,off:hex]      modbase with bytes patched; must fail the modulus check
"""
import gzip, hashlib, json, os, sys

src, out = sys.argv[1], sys.argv[2]
PS = {"512": "ML-KEM-512", "768": "ML-KEM-768", "1024": "ML-KEM-1024"}
EK = {"512": 800, "768": 1184, "1024": 1568}
DK = {"512": 1632, "768": 2400, "1024": 3168}
CT = {"512": 768, "768": 1088, "1024": 1568}


def pnum(name):
    return name.rsplit("-", 1)[1]


def h(x):
    return x.lower()


def hdr(lines, title, url, commit, lic, note):
    lines.append("# " + title)
    lines.append("# source:  " + url)
    lines.append("# commit:  " + commit)
    lines.append("# licence: " + lic)
    lines.append("# " + note)
    lines.append("# generated by tools/vectors/extract.py; line formats are documented there")


def commit(d):
    return open(os.path.join(src, d, ".git", "HEAD")).read().strip() if False else ""


def write(name, lines):
    with open(os.path.join(out, name), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(name, sum(len(l) + 1 for l in lines), "bytes,", len(lines), "lines")


def sizes_ok(p, ek=None, dk=None, c=None):
    return ((ek is None or len(ek) == 2 * EK[p]) and (dk is None or len(dk) == 2 * DK[p])
            and (c is None or len(c) == 2 * CT[p]))


# ---------------------------------------------------------------- CCTV
def cctv(rev):
    L = []
    hdr(L, "C2SP CCTV ML-KEM", "https://github.com/C2SP/CCTV/tree/main/ML-KEM", rev, "CC0-1.0",
        "modulus only (delta-coded). CCTV unlucky/strcmp/accumulated target the FIPS 203 ipd (KeyGen = G(d), no k byte) and do not match the final spec; Wycheproof carries regenerated final-spec equivalents")
    base = os.path.join(src, "cctv", "ML-KEM")
    for p in ("512", "768", "1024"):
        rows = gzip.open(os.path.join(base, "modulus", f"ML-KEM-{p}.txt.gz"), "rt").read().split()
        b = bytes.fromhex(rows[0])
        assert len(b) == EK[p]
        L.append(f"modbase {p} {rows[0]}")
        for r in rows[1:]:
            x = bytes.fromhex(r)
            assert len(x) == len(b)
            d = [i for i in range(len(b)) if b[i] != x[i]]
            runs = []
            for i in d:
                if runs and runs[-1][0] + len(runs[-1][1]) == i:
                    runs[-1][1].append(x[i])
                else:
                    runs.append([i, bytearray([x[i]])])
            if not runs:
                continue  # duplicate of the base line (itself checked as a bad key)
            L.append(f"mod {p} " + ",".join(f"{o}:{v.hex()}" for o, v in runs))
    write("cctv.txt", L)


# ---------------------------------------------------------------- ACVP
def acvp(rev):
    L = []
    hdr(L, "NIST ACVP-Server ML-KEM (FIPS 203) internalProjection.json",
        "https://github.com/usnistgov/ACVP-Server/tree/master/gen-val/json-files/ML-KEM-{keyGen,encapDecap}-FIPS203[-tr1]",
        rev, "NIST work, not subject to copyright in the US (17 USC 105)",
        "keyGen first 8 cases per set; encaps first 8; up to 2 decap / ekCheck / dkCheck cases per (set, reason) from both encapDecap vector sets")
    base = os.path.join(src, "acvp", "gen-val", "json-files")
    j = json.load(open(os.path.join(base, "ML-KEM-keyGen-FIPS203", "internalProjection.json")))
    for g in j["testGroups"]:
        p = pnum(g["parameterSet"])
        for t in g["tests"][:8]:
            L.append(f"kg {p} {h(t['d'])} {h(t['z'])} {h(t['ek'])} {h(t['dk'])}")
    seen = set()
    cap = {}
    skipped = 0

    def room(*key):
        cap[key] = cap.get(key, 0) + 1
        return cap[key] <= 2  # at most 2 cases per (function, set, reason) keeps the slice small

    for ds in ("ML-KEM-encapDecap-FIPS203", "ML-KEM-encapDecap-FIPS203-tr1"):
        j = json.load(open(os.path.join(base, ds, "internalProjection.json")))
        for g in j["testGroups"]:
            p = pnum(g["parameterSet"])
            fn = g["function"]
            tests = g["tests"]
            if fn == "encapsulation":
                if ds.endswith("tr1"):
                    continue  # same shape as the first set; only the key format differs
                for t in tests[:8]:
                    L.append(f"enc {p} {h(t['ek'])} {h(t['m'])} {h(t['c'])} {h(t['k'])}")
            elif fn == "decapsulation":
                for t in tests:
                    if "dk" not in t or not sizes_ok(p, dk=h(t["dk"]), c=h(t["c"])):
                        skipped += 1
                        continue
                    line = f"dec {p} {h(t['dk'])} {h(t['c'])} {h(t['k'])}"
                    if line not in seen and room(fn, p, t.get("reason")):
                        seen.add(line)
                        L.append(line)
            elif fn in ("encapsulationKeyCheck", "decapsulationKeyCheck"):
                key = "ek" if fn.startswith("encap") else "dk"
                tag = "ekchk" if key == "ek" else "dkchk"
                for t in tests:
                    v = t.get(key)
                    if not v or not sizes_ok(p, **{key: h(v)}):
                        skipped += 1  # wrong-length keys cannot be expressed through fixed-size array APIs
                        continue
                    line = f"{tag} {p} {int(t['testPassed'])} {h(v)}"
                    if line not in seen and room(fn, p, t.get("reason"), t["testPassed"]):
                        seen.add(line)
                        L.append(line)
    print("acvp skipped (wrong length / missing dk):", skipped)
    write("acvp.txt", L)


# ---------------------------------------------------------------- Wycheproof
def wycheproof(rev):
    L = []
    hdr(L, "Wycheproof ML-KEM (testvectors_v1)", "https://github.com/C2SP/wycheproof/tree/main/testvectors_v1/mlkem_*",
        rev, "Apache-2.0",
        "all non-length-invalid special cases (rho/matrix, bit flips, random ct, malleable ct, key corruption, unreduced ek); first 8 'round 3 seeds' cases per file")
    base = os.path.join(src, "wp", "testvectors_v1")
    for p in ("512", "768", "1024"):
        # mlkem_P_test: seed-based decaps tests
        j = json.load(open(os.path.join(base, f"mlkem_{p}_test.json")))
        n3 = 0
        cls = {}
        for g in j["testGroups"]:
            for t in g["tests"]:
                if t["result"] != "valid":
                    continue  # invalid = wrong-length inputs, not expressible with fixed-size arrays
                c0 = t.get("comment", "")[:22]
                cls[c0] = cls.get(c0, 0) + 1
                if cls[c0] > 4 and not c0.startswith("Ciphertext modified"):
                    continue
                if t.get("comment", "").startswith("Test vector based on official round 3"):
                    n3 += 1
                    if n3 > 8:
                        continue
                ekh = hashlib.sha3_256(bytes.fromhex(t["ek"])).hexdigest()
                L.append(f"ct {p} {t['seed']} {ekh} {t['c']} {t['K']}")
        # keygen_seed
        j = json.load(open(os.path.join(base, f"mlkem_{p}_keygen_seed_test.json")))
        for t in j["testGroups"][0]["tests"][:8]:
            if t["result"] == "valid":
                s = t["seed"]
                L.append(f"kg {p} {s[:64]} {s[64:]} {t['ek']} {t['dk']}")
        # encaps
        j = json.load(open(os.path.join(base, f"mlkem_{p}_encaps_test.json")))
        nv = nb = 0
        for g in j["testGroups"]:
            for t in g["tests"]:
                if t["result"] == "valid":
                    nv += 1
                    if nv <= 8:
                        L.append(f"enc {p} {t['ek']} {t['m']} {t['c']} {t['K']}")
                elif "ModulusOverflow" not in t["flags"] and len(t["ek"]) == 2 * EK[p]:
                    nb += 1
                    if nb <= 16:
                        L.append(f"ekchk {p} 0 {t['ek']}")
        # semi-expanded decaps
        j = json.load(open(os.path.join(base, f"mlkem_{p}_semi_expanded_decaps_test.json")))
        for g in j["testGroups"]:
            for t in g["tests"]:
                if len(t["dk"]) != 2 * DK[p] or len(t["c"]) != 2 * CT[p]:
                    continue
                if t["result"] == "valid":
                    L.append(f"dec {p} {t['dk']} {t['c']} {t['K']}")
                else:
                    L.append(f"dkchk {p} 0 {t['dk']}")
    write("wycheproof.txt", L)


def gitrev(d):
    # .git/HEAD of a detached/shallow clone holds a branch ref; resolve via packed refs
    import subprocess  # noqa: only to read the commit id of the local clones
    return subprocess.run(["git", "-C", os.path.join(src, d), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()


cctv(gitrev("cctv"))
acvp(gitrev("acvp"))
wycheproof(gitrev("wp"))
