"""Turns Bitcoin Core's key_io_valid.json / key_io_invalid.json into
src/core_vectors.zig.

    curl -sL https://raw.githubusercontent.com/bitcoin/bitcoin/master/src/test/data/key_io_valid.json   -o key_io_valid.json
    curl -sL https://raw.githubusercontent.com/bitcoin/bitcoin/master/src/test/data/key_io_invalid.json -o key_io_invalid.json
    python3 tools/gen_core_vectors.py key_io_valid.json key_io_invalid.json <bitcoin master commit> > src/core_vectors.zig

The data is Bitcoin Core's (MIT, see ../NOTICE). Rows are transcribed
verbatim, in file order; nothing is added, dropped or reinterpreted.
"""
import hashlib
import json
import sys


def zstr(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append("\\x%02x" % b)
    return '"' + "".join(out) + '"'


def main():
    vpath, ipath, commit = sys.argv[1:4]
    vraw = open(vpath, "rb").read()
    iraw = open(ipath, "rb").read()
    valid = json.loads(vraw)
    invalid = json.loads(iraw)
    p = print
    p("// SPDX-License-Identifier: MIT")
    p("//! GENERATED by tools/gen_core_vectors.py -- do not edit by hand.")
    p("//!")
    p("//! Source: Bitcoin Core `src/test/data/key_io_valid.json` and")
    p("//! `key_io_invalid.json` (MIT, (c) The Bitcoin Core developers; see ../NOTICE),")
    p("//! fetched from `master` at commit %s." % commit)
    p("//! sha256(key_io_valid.json)   = %s" % hashlib.sha256(vraw).hexdigest())
    p("//! sha256(key_io_invalid.json) = %s" % hashlib.sha256(iraw).hexdigest())
    p("//! %d valid rows, %d invalid rows, transcribed verbatim in file order." % (len(valid), len(invalid)))
    p("")
    p("pub const Chain = enum { main, testnet4, signet, regtest };")
    p("")
    p("pub const Valid = struct {")
    p("    /// Address (or WIF string when `is_privkey`).")
    p("    string: []const u8,")
    p("    /// Hex of the scriptPubKey (address rows) or of the 32-byte key (WIF rows).")
    p("    hex: []const u8,")
    p("    chain: Chain,")
    p("    is_privkey: bool,")
    p("    /// WIF rows only; false for address rows.")
    p("    is_compressed: bool,")
    p("    /// Core also checks the all-upper / all-lower flipped spelling.")
    p("    try_case_flip: bool,")
    p("};")
    p("")
    p("pub const valid = [_]Valid{")
    for s, hx, o in valid:
        p("    .{ .string = %s, .hex = %s, .chain = .%s, .is_privkey = %s, .is_compressed = %s, .try_case_flip = %s }," % (
            zstr(s), zstr(hx), o["chain"],
            "true" if o["isPrivkey"] else "false",
            "true" if o.get("isCompressed") else "false",
            "true" if o.get("tryCaseFlip") else "false"))
    p("};")
    p("")
    p("/// Strings Core rejects as an address AND as a WIF key, on every chain.")
    p("pub const invalid = [_][]const u8{")
    for (s,) in invalid:
        p("    %s," % zstr(s))
    p("};")


main()
