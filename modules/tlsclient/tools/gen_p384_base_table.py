"""Regenerates src/p384_base_table.zig, the fixed-base comb table of `keygen.zig`.

  python3 -I modules/tlsclient/tools/gen_p384_base_table.py > modules/tlsclient/src/p384_base_table.zig

table[i][j] = (j + 1) * 2^(5 i) * G in affine coordinates, i < 78, j < 16
(SP 800-186 / SEC 2 secp384r1 constants below). Each coordinate is written as
the `limbs` of `std.crypto.ecc.P384.Fe`: six little-endian 64-bit words of
v * 2^384 mod p (std's fiat field keeps elements in the Montgomery domain).
Plain affine arithmetic with Python integers -- an implementation independent
of std's projective formulas, so the table is also a second check of them
(`keygen.zig` tests: entries against `mulPublic`, the comb against
`basePoint.mul`).

Why a generated file: same reason as `p521/tools/gen_base_table.py` -- 1248
points at comptime would cost every compile of tlsclient (and of http, which
imports it) minutes.
"""

P = 2**384 - 2**128 - 2**96 + 2**32 - 1
A = P - 3
GX = 0xAA87CA22BE8B05378EB1C71EF320AD746E1D3B628BA79B9859F741E082542A385502F25DBF55296C3A545E3872760AB7
GY = 0x3617DE4A96262C6F5D9E98BF9292DC29F8F41DBD289A147CE9DA3113B5F0B8C00A60B1CE1D7E819D7A431D7C90EA0E5F
B = 0xB3312FA7E23EE7E4988E056BE3F82D19181D9C6EFE8141120314088F5013875AC656398D8A2ED19D2A85C8EDD3EC2AEF
W, T, TEETH = 5, 78, 16
R = 2**384


def add(p, q):
    if p is None:
        return q
    if q is None:
        return p
    (x1, y1), (x2, y2) = p, q
    if x1 == x2:
        if (y1 + y2) % P == 0:
            return None
        lam = (3 * x1 * x1 + A) * pow(2 * y1, -1, P) % P
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, P) % P
    x3 = (lam * lam - x1 - x2) % P
    return (x3, (lam * (x1 - x3) - y1) % P)


def mont_limbs(v):
    m = v * R % P
    return [(m >> (64 * k)) & (2**64 - 1) for k in range(6)]


def fe(v):
    return ".{ .limbs = .{ " + ", ".join("0x%x" % l for l in mont_limbs(v)) + " } }"


def main():
    assert (GY * GY - (GX**3 + A * GX + B)) % P == 0, "G is not on the curve"
    out = [
        "// SPDX-License-Identifier: MIT",
        "// GENERATED by tools/gen_p384_base_table.py -- do not edit.",
        "//! table[i][j] = (j + 1)·2^(5i)·G, affine, std P384.Fe Montgomery limbs (see keygen.zig).",
        "",
        "const AffineCoordinates = @TypeOf(@import(\"std\").crypto.ecc.P384.basePoint.affineCoordinates());",
        "",
        "pub const table: [%d][%d]AffineCoordinates = .{" % (T, TEETH),
    ]
    base = (GX, GY)
    for _ in range(T):
        out.append("    .{")
        q = base
        for j in range(TEETH):
            # The comb's mixed addition is complete only for curve points;
            # x = 0 would also be std's affine-identity encoding.
            assert q is not None and q[0] != 0, "table point with x = 0"
            out.append("        .{ .x = %s, .y = %s }," % (fe(q[0]), fe(q[1])))
            q = add(q, base)
        out.append("    },")
        for _ in range(W):
            base = add(base, base)
    out.append("};")
    print("\n".join(out))


main()
