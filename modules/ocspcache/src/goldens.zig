//! A real, live-captured OCSP fetch/verify/cache round trip: the leaf and
//! issuer certificates of a real HTTPS host and the real OCSP response its
//! CA's responder returned for them.
//!
//! ## Why this file exists
//!
//! Every fixture in `ocspcache_test.zig` is CONSTRUCTED — its own doc comment
//! says so: an offline generator using `ocsp`'s `der_writer` +
//! `rsa.signPkcs1v15`/`rsa.selfSignedCert`, never a real CA. Its canned
//! `good_response*_bytes` hash their `CertID` with SHA-256 (the same
//! construction `ocsp_test.zig` uses), so — like `ocsp` itself before this
//! task — `ocspcache`'s own test suite has never driven `Cache.refresh`
//! against a response whose `CertID.hashAlgorithm` is SHA-1, nor against a
//! certificate whose Authority Information Access extension was actually
//! emitted by a CA rather than hand-built to match the shape this module
//! expects.
//!
//! ## Provenance
//!
//! Captured 2026-08-01 from `www.godaddy.com` (see `ocsp`'s own
//! `goldens.zig` for the exact capture recipe and the DigiCert capture this
//! repo also holds — this file reuses the GoDaddy capture specifically
//! because it is the **delegated-responder** case: `certs [0]` embeds a
//! real "Go Daddy Validation Authority - G2" certificate, directly signed by
//! the leaf's issuing CA and carrying `id-kp-OCSPSigning`, on a 4096-bit RSA
//! key). The bytes are duplicated here rather than imported from the `ocsp`
//! module's own test sources because `ocspcache_test.zig`'s own doc comment
//! already establishes that module boundary (`ocspcache`'s `build.zig`
//! dependency edge is `ocsp` + `http` + `x509` — its *public* API only, not
//! `ocsp`'s private `src/*_test.zig` — so nothing there is importable
//! anyway; these are plain captured DER bytes, not something that needs
//! `rsa`/`p256` to regenerate).
//!
//! `www.godaddy.com`'s leaf certificate carries a real Authority Information
//! Access extension whose `id-ad-ocsp` entry is `http://ocsp.godaddy.com/`
//! (verified independently via `openssl x509 -text`) — the first time
//! `discoverResponderUrl` runs against AIA bytes a CA actually emitted rather
//! than a hand-built extension shaped to match what this module expects to
//! find.
//!
//! Reference times (see `ocsp`'s `goldens.zig` for the derivation):
//! thisUpdate 2026-07-31T16:20:45Z = 1785514845,
//! nextUpdate 2026-08-04T16:19:45Z = 1785860385.
//!
//! ## Not covered here, with reasons
//!
//! - **A real "no responder URL" / malformed-AIA certificate** — a real cert
//!   simply not having AIA, or having a malformed one, isn't something to go
//!   find in the wild; `ocspcache_test.zig`'s constructed `subject_no_aia`
//!   fixture and `root.zig`'s malformed-DER unit tests already cover both
//!   structurally.
//! - **GET-form fetch against this real response** — the mock transport
//!   here always returns the response regardless of request shape (real or
//!   constructed), so POST vs. GET makes no difference to what gets
//!   exercised; `ocspcache_test.zig`'s own GET-form test already covers the
//!   URL-building path.
//! - **`revoked`/`unknown` real status, ECDSA signer** — see `ocsp`'s own
//!   `goldens.zig` "Not covered here" for why: neither exists in a real,
//!   still-live, non-revoked production certificate's OCSP answer.

