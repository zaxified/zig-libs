// A mock `Transport` that hands back the real captured response bytes —
// still no network access, but the payload it returns is what a real
// responder actually sent, not something this repo's own writer built.
const GoldenTransport = struct {
    calls: usize = 0,

    fn fetch(context: *anyopaque, gpa: std.mem.Allocator, req: ocspcache.FetchRequest) ocspcache.FetchError!ocspcache.FetchResponse {
        _ = req; // the real captured response is returned regardless of request shape
        const self: *GoldenTransport = @ptrCast(@alignCast(context));
        self.calls += 1;
        return .{ .status = 200, .body = try gpa.dupe(u8, &godaddy_response_der) };
    }

    fn transport(self: *GoldenTransport) ocspcache.Transport {
        return .{ .context = self, .fetchFn = fetch };
    }
};

