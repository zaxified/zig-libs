/// whether it should look like a fetch failure instead.
const MockTransport = struct {
    body: []const u8,
    status: u16 = 200,

    fn fetch(context: *anyopaque, gpa: std.mem.Allocator, req: ocspcache.FetchRequest) ocspcache.FetchError!ocspcache.FetchResponse {
        const self: *MockTransport = @ptrCast(@alignCast(context));
        _ = req;
        return .{ .status = self.status, .body = try gpa.dupe(u8, self.body) };
    }

    fn transport(self: *MockTransport) ocspcache.Transport {
        return .{ .context = self, .fetchFn = fetch };
    }
};

const this_update_unix: i64 = 1_798_761_600; // 2027-01-01T00:00:00Z, matches the fixture

pub fn main() !void {
    var da: std.heap.DebugAllocator(.{}) = .init;
    defer if (da.deinit() == .leak) @panic("leak");
    const gpa = da.allocator();

    // ── discover the responder URL straight from the certificate's AIA ──
    const url = (try ocspcache.discoverResponderUrl(&subject_der)) orelse return error.NoAiaFound;
    std.debug.print("discovered responder: {s}\n", .{url});

    // ── fetch + verify + cache, via the mock transport (no network) ─────
    var good_mock: MockTransport = .{ .body = &good_response };
    var cache = ocspcache.Cache.init(gpa, good_mock.transport(), .{});
    defer cache.deinit();

    try cache.refresh(&subject_der, &issuer_der, this_update_unix);
    const staple = (try cache.getStapled(gpa, &subject_der, this_update_unix)) orelse return error.MissingStaple;
    defer gpa.free(staple);
    std.debug.print("staple cached: {d} bytes, needsRefresh={}\n", .{
        staple.len,
        cache.needsRefresh(&subject_der, this_update_unix),
    });

    // ── a tampered response is rejected by name, cache left untouched ───
    var bad_mock: MockTransport = .{ .body = &tampered_response };
    var bad_cache = ocspcache.Cache.init(gpa, bad_mock.transport(), .{});
    defer bad_cache.deinit();
    bad_cache.refresh(&subject_der, &issuer_der, this_update_unix) catch |err| switch (err) {
        error.VerifyFailed => std.debug.print("tampered response correctly rejected\n", .{}),
        else => return err,
    };
    // Soft-fail posture: the failed refresh left nothing cached.
    std.debug.print("bad_cache has staple after failed refresh: {}\n", .{
        (try bad_cache.getStapled(gpa, &subject_der, this_update_unix)) != null,
    });

    // ── a responder that answers with a non-200 status is also nameable ──
    var down_mock: MockTransport = .{ .body = &.{}, .status = 503 };
    var down_cache = ocspcache.Cache.init(gpa, down_mock.transport(), .{});
    defer down_cache.deinit();
    down_cache.refresh(&subject_der, &issuer_der, this_update_unix) catch |err| switch (err) {
        error.ResponderHttpError => std.debug.print("responder outage (503) correctly surfaced\n", .{}),
        else => return err,
    };
}
