#!/usr/bin/env python3
"""Regenerate src/codespan_vectors.zig from the vendored insta snapshots.

    python3 -I modules/diagnostics/tools/codespan-goldens/gen.py

Reads snapshots/*.snap (upstream files, unmodified) and writes the expected
text of every case as a Zig string. A case whose upstream snapshot exists only
in the box-drawing charset is mapped to the ASCII charset character by
character (the layout is identical; see Chars::ascii() in upstream config.rs).
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "src" / "codespan_vectors.zig"

# case -> (snapshot file, needs the box-drawing -> ASCII mapping)
CASES = [
    ("empty", "term__empty__rich_ascii_no_color.snap", False),
    ("empty_ranges", "term__empty_ranges__rich_ascii_no_color.snap", False),
    ("message", "term__message__rich_ascii_no_color.snap", False),
    ("message_and_notes", "term__message_and_notes__rich_ascii_no_color.snap", False),
    ("message_errorcode", "term__message_errorcode__rich_ascii_no_color.snap", False),
    ("same_line", "term__same_line__rich_ascii_no_color.snap", False),
    ("same_ranges", "term__same_ranges__rich_ascii_no_color.snap", False),
    ("overlapping", "term__overlapping__rich_ascii_no_color.snap", False),
    ("multifile", "term__multifile__rich_ascii_no_color.snap", False),
    ("fizz_buzz", "term__fizz_buzz__rich_ascii_no_color.snap", False),
    ("multiline_overlapping", "term__multiline_overlapping__rich_ascii_no_color.snap", False),
    ("position_indicator", "term__position_indicator__rich_ascii_no_color.snap", False),
    ("multiline_omit", "term__multiline_omit__rich_no_color.snap", True),
    ("unicode", "term__unicode__rich_no_color.snap", True),
    ("unicode_spans", "term__unicode_spans__rich_no_color.snap", True),
    ("surrounding_lines", "term__surrounding_lines__rich_no_color.snap", True),
]

# Chars::box_drawing() -> Chars::ascii(); the two-character snippet_start first.
ASCII = [("\u250c\u2500", "-->"), ("\u2502", "|"), ("\u00b7", "."),
         ("\u256d", "/"), ("\u2570", "\\"), ("\u2500", "-")]


def body(path):
    text = path.read_text(encoding="utf-8")
    parts = text.split("---\n", 2)
    assert len(parts) == 3 and parts[0] == "", path
    return parts[2]


def zig(s):
    out = []
    for line in s.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\r", "\\r")
        out.append('"' + esc + '"')
    # one literal per line, joined with the newlines between them
    return " ++ \"\\n\" ++\n        ".join(out)


def main():
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// GENERATED by tools/codespan-goldens/gen.py -- do not edit.",
        "// Expected output of codespan-reporting 0.13.1 (Apache-2.0, upstream",
        "// commit decb0a0727e45bf2f04dcd3e4b4deb9517349fdc), the insta snapshots",
        "// tests/snapshots/term__<case>__rich_ascii_no_color.snap (a case that has only",
        "// the box-drawing snapshot is mapped to ASCII character by character).",
        "",
        "pub const Vector = struct { name: []const u8, expected: []const u8 };",
        "",
        "pub const vectors = [_]Vector{",
    ]
    for name, snap, to_ascii in CASES:
        b = body(HERE / "snapshots" / snap)
        if to_ascii:
            for a, z in ASCII:
                b = b.replace(a, z)
        lines.append("    .{ .name = \"%s\", .expected =\n        %s },\n" % (name, zig(b)))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


main()
