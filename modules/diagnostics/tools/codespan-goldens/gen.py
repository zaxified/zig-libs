#!/usr/bin/env python3
"""Regenerate src/codespan_vectors.zig from the vendored insta snapshots.

    python3 -I modules/diagnostics/tools/codespan-goldens/gen.py

Reads snapshots/*.snap (upstream files, unmodified) and writes the expected
text of every case as a Zig string. A case whose upstream snapshot exists only
in the box-drawing charset is mapped to the ASCII charset character by
character (the layout is identical; see Chars::ascii() in upstream config.rs).
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "src" / "codespan_vectors.zig"

# case -> the upstream ASCII snapshot, or None when upstream has only the
# box-drawing one. Every case has a `rich_no_color` (box drawing) snapshot.
CASES = [
    ("empty", True), ("empty_ranges", True), ("message", True), ("message_and_notes", True),
    ("message_errorcode", True), ("same_line", True), ("same_ranges", True), ("overlapping", True),
    ("multifile", True), ("fizz_buzz", True), ("multiline_overlapping", True), ("position_indicator", True),
    ("multiline_omit", False), ("unicode", False), ("unicode_spans", False), ("surrounding_lines", False),
]

# Chars::box_drawing() -> Chars::ascii(); the two-character snippet_start first.
ASCII = [("\u250c\u2500", "-->"), ("\u2502", "|"), ("\u00b7", "."),
         ("\u256d", "/"), ("\u2570", "\\"), ("\u2500", "-")]


def body(path):
    text = path.read_text(encoding="utf-8")
    parts = text.split("---\n", 2)
    assert len(parts) == 3 and parts[0] == "", path
    return parts[2]


def zig(s):
    out = []
    for line in s.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\r", "\\r")
        out.append('"' + esc + '"')
    # one literal per line, joined with the newlines between them
    return " ++ \"\\n\" ++\n        ".join(out)


def main():
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// GENERATED by tools/codespan-goldens/gen.py -- do not edit.",
        "// Expected output of codespan-reporting 0.13.1 (Apache-2.0, upstream",
        "// commit decb0a0727e45bf2f04dcd3e4b4deb9517349fdc), the insta snapshots",
        "// tests/snapshots/term__<case>__rich_no_color.snap (`box`, Chars::box_drawing())",
        "// and term__<case>__rich_ascii_no_color.snap (`ascii`; a case that has only the",
        "// box-drawing snapshot is mapped to ASCII character by character).",
        "",
        "pub const Vector = struct { name: []const u8, ascii: []const u8, box: []const u8 };",
        "",
        "pub const vectors = [_]Vector{",
    ]
    for name, has_ascii in CASES:
        box = body(HERE / "snapshots" / ("term__%s__rich_no_color.snap" % name))
        if has_ascii:
            ascii = body(HERE / "snapshots" / ("term__%s__rich_ascii_no_color.snap" % name))
        else:
            ascii = box
            for a, z in ASCII:
                ascii = ascii.replace(a, z)
        lines.append("    .{ .name = \"%s\",\n      .ascii =\n        %s,\n      .box =\n        %s },\n" % (name, zig(ascii), zig(box)))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


main()
