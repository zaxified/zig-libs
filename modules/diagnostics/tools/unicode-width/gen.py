#!/usr/bin/env python3
"""Regenerate src/width_table.zig from the unicode-width crate's tables.

    python3 -I modules/diagnostics/tools/unicode-width/gen.py PATH/TO/unicode-width-0.2.2/src/tables.rs

The crate is MIT OR Apache-2.0 (https://github.com/unicode-rs/unicode-width,
version 0.2.2, Unicode 17.0.0). Its `tables.rs` holds a three-level lookup
table (WIDTH_ROOT, WIDTH_MIDDLE, WIDTH_LEAVES) plus a `match` for the few code
points whose 2-bit leaf value is 3 ("special"). This script replays
`lookup_width` + `single_char_width` of that file for every code point
>= U+00A0 and writes the code points whose width is not 1 as sorted ranges
(width 0, 2, or 3 -- the crate gives U+17D8 a width of 3). Code points below
U+00A0 are handled by the caller (ASCII printable = 1, controls have none).
Ambiguous-width characters are narrow, as in `UnicodeWidthChar::width`.
"""
import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent.parent / "src" / "width_table.zig"


def bytes_of(src, name):
    m = re.search(r"static %s: Align\d+<.*?> = Align\d+\(\[(.*?)\]\);" % name, src, re.S)
    assert m, name
    return [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1))]


def special(cp):
    """The `match c` arm of `lookup_width` for a leaf value of 3 -> width."""
    if cp == 0x17D8:
        return 3
    if cp in (0xFE01, 0xFE0E, 0xFE0F):
        return 0
    if 0x1F3FB <= cp <= 0x1F3FF:
        return 2
    if cp == 0x5DC or 0x622 <= cp <= 0x882 or 0x1780 <= cp <= 0x17AF or cp == 0x1A10 \
            or 0x2D31 <= cp <= 0x2D6F or 0xA4FC <= cp <= 0xA4FD or cp == 0x10C03 \
            or cp in (0x16D67, 0x16D68) or 0x1F1E6 <= cp <= 0x1F1FF:
        return 1
    return 2  # `_ => (2, WidthInfo::EMOJI_PRESENTATION)`


def main():
    src = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    # Check the `match` above against the crate's text: every arm must be known.
    arms = re.search(r"if width < 3 \{.*?match c \{(.*?)\n        \}\n", src, re.S).group(1)
    expect = ["'\\u{A}'", "'\\u{5DC}'", "'\\u{622}'..='\\u{882}'", "'\\u{1780}'..='\\u{17AF}'",
              "'\\u{17D8}'", "'\\u{1A10}'", "'\\u{2D31}'..='\\u{2D6F}'", "'\\u{A4FC}'..='\\u{A4FD}'",
              "'\\u{FE01}'", "'\\u{FE0E}'", "'\\u{FE0F}'", "'\\u{10C03}'", "'\\u{16D67}'", "'\\u{16D68}'",
              "'\\u{1F1E6}'..='\\u{1F1FF}'", "'\\u{1F3FB}'..='\\u{1F3FF}'", "_"]
    got = [l.split("=>")[0].strip() for l in arms.split("\n") if "=>" in l]
    assert got == expect, got
    root = bytes_of(src, "WIDTH_ROOT")
    mid_flat = bytes_of(src, "WIDTH_MIDDLE")
    leaves_flat = bytes_of(src, "WIDTH_LEAVES")
    assert len(root) == 256 and len(mid_flat) % 64 == 0 and len(leaves_flat) % 32 == 0
    mid = [mid_flat[i:i + 64] for i in range(0, len(mid_flat), 64)]
    leaves = [leaves_flat[i:i + 32] for i in range(0, len(leaves_flat), 32)]

    def width(cp):
        t2 = mid[root[cp >> 13]][(cp >> 7) & 0x3F]
        w = (leaves[t2][(cp >> 2) & 0x1F] >> (2 * (cp & 3))) & 3
        return special(cp) if w == 3 else w

    ranges = []
    for cp in range(0xA0, 0x110000):
        if 0xD800 <= cp < 0xE000:
            continue
        w = width(cp)
        if w == 1:
            continue
        if ranges and ranges[-1][2] == w and ranges[-1][1] + 1 == cp:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, w])
    lines = [
        "// SPDX-License-Identifier: MIT AND Unicode-3.0",
        "// GENERATED by tools/unicode-width/gen.py -- do not edit.",
        "// Display widths of the code points >= U+00A0 whose width is not 1, replayed from",
        "// unicode-rs/unicode-width 0.2.2 src/tables.rs (MIT OR Apache-2.0; Unicode 17.0.0):",
        "// `single_char_width` = `lookup_width`, ambiguous characters narrow.",
        "",
        "pub const Range = struct { lo: u21, hi: u21, w: u2 };",
        "",
        "/// Sorted, disjoint. A code point >= U+00A0 in none of them is one column wide.",
        "pub const ranges = [_]Range{",
    ]
    for lo, hi, w in ranges:
        lines.append("    .{ .lo = 0x%X, .hi = 0x%X, .w = %d }," % (lo, hi, w))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(len(ranges), "ranges")


main()
