    // already hold survives the failure.
    try peer.recordSent(&kat.msg2);
    try testing.expectError(error.DecryptionFailed, peer.consumeReply(reply, 9));
    try testing.expectEqual(cookie_kat.cookie, peer.cookie.?);
    try testing.expectEqual(@as(u64, 5), peer.cookie_born_s);

    // A tampered ciphertext does not open either.
    try peer.recordSent(&kat.msg1);
    var bad = reply;
    bad.encrypted_cookie[0] ^= 1;
    try testing.expectError(error.DecryptionFailed, peer.consumeReply(bad, 9));
}

test "admit: a mac1-only flood is shed under load until the cookie round trip completes" {
    const io = std.testing.io;
    const rpub = (try Keypair.fromPrivateKey(kat.sr_priv)).public;
    var checker = CookieChecker.init(rpub, io, 1_000); // random secret, as in production
    defer checker.wipe();

    var ini = kat.initiator();
    const msg1 = try ini.createInitiation(io, kat.timestamp);
    const bytes1 = std.mem.asBytes(&msg1);

    // Not under load: mac1 is all that is asked for (today's behavior).
    try expectAdmission(checker.admit(io, 1_000, bytes1, &cookie_kat.addr, false), .accept);

    // Under load, mac1 alone buys nothing: the responder answers with 64 bytes
    // and does zero asymmetric work.
    const adm = checker.admit(io, 1_000, bytes1, &cookie_kat.addr, true);
    const reply = switch (adm) {
        .cookie_reply => |r| r,
        else => return error.TestUnexpectedResult,
    };
    try testing.expectEqual(@intFromEnum(MessageType.cookie_reply), reply.type);
    try testing.expectEqual(kat.idx_i, reply.receiver_index);

    // The genuine initiator — which, unlike a spoofed source, actually
    // receives the reply — retries with a valid mac2 and is admitted.
    var peer = PeerCookie.init(rpub);
    try peer.recordSent(bytes1);
    try peer.consumeReply(reply, 1_000);
    var ini2 = kat.initiator();
    ini2.cookie = peer.current(1_000);
    try testing.expect(ini2.cookie != null);
    const retry = try ini2.createInitiation(io, kat.timestamp);
    const bytes2 = std.mem.asBytes(&retry);
    try expectAdmission(checker.admit(io, 1_000, bytes2, &cookie_kat.addr, true), .accept);

    // THE anti-spoofing claim: the cookie is a MAC of the source address, so
    // the very same mac2-bearing message replayed from another address is
    // still shed.
    try expectAdmission(
        checker.admit(io, 1_000, bytes2, &cookie_kat.other_addr, true),
        .cookie_reply,
    );

    // Unauthenticated junk is dropped silently, never answered: a bad mac1, a
    // truncated datagram, and a type we do not MAC.
    var forged = msg1;
    forged.mac1[0] ^= 1;
    try expectAdmission(
        checker.admit(io, 1_000, std.mem.asBytes(&forged), &cookie_kat.addr, true),
        .drop,
    );
    try expectAdmission(checker.admit(io, 1_000, bytes1[0..100], &cookie_kat.addr, true), .drop);
    try expectAdmission(
        checker.admit(io, 1_000, &cookie_kat.reply, &cookie_kat.addr, true),
        .drop,
    );

    // A response (type 2) travels the same gate — mac2 is on both message types.
    var rsp = kat.responder();
    try rsp.consumeInitiation(msg1);
    const msg2 = try rsp.createResponse(io);
    try expectAdmission(
        checker.admit(io, 1_000, std.mem.asBytes(&msg2), &cookie_kat.addr, false),
        .drop, // msg2's mac1 is keyed on the INITIATOR's static key, not ours
    );
}

test "cookie secret rotates after two minutes, on both sides of the exchange" {
    const io = std.testing.io;
    const rpub = cookie_kat.responder_pub;

    // The two-minute figure itself, pinned (whitepaper 5.4.7 "every two
    // minutes"). The behavioral assertions below use literal seconds, not
    // these constants, so moving the value goes red here AND there.
    try testing.expectEqual(@as(u64, 120), cookie_secret_lifetime_s);
    try testing.expectEqual(@as(u64, 120), cookie_lifetime_s);

    var checker = CookieChecker.initWithSecret(rpub, cookie_kat.secret, 1_000);
    const at_0 = checker.cookieFor(io, 1_000, &cookie_kat.addr);
    try testing.expectEqual(cookie_kat.cookie, at_0);

    // 119 s in: same secret, same cookie.
    try testing.expectEqual(at_0, checker.cookieFor(io, 1_119, &cookie_kat.addr));
    try testing.expectEqual(cookie_kat.secret, checker.secret);

    // 120 s in: rolled, and every cookie issued under the old secret dies.
    const at_120 = checker.cookieFor(io, 1_120, &cookie_kat.addr);
    try testing.expect(!std.mem.eql(u8, &at_0, &at_120));
    try testing.expect(!std.mem.eql(u8, &cookie_kat.secret, &checker.secret));
    try testing.expectEqual(@as(u64, 1_120), checker.secret_born_s);

    // A clock that jumps backwards rolls it too, rather than extending its life.
    const rolled = checker.secret;
    _ = checker.cookieFor(io, 999, &cookie_kat.addr);
    try testing.expect(!std.mem.eql(u8, &rolled, &checker.secret));

    // wipe() ends the secret's life immediately.
    checker.wipe();
    try testing.expectEqual(@as([32]u8, @splat(0)), checker.secret);

    // Initiator side: the same two minutes bound how long a cookie is stamped.
    var peer = PeerCookie.init(rpub);
    peer.cookie = cookie_kat.cookie;
    peer.cookie_born_s = 1_000;
    try testing.expectEqual(cookie_kat.cookie, peer.current(1_119).?);
    try testing.expectEqual(@as(?noise.Mac, null), peer.current(1_120));
    try testing.expectEqual(@as(?noise.Mac, null), peer.current(999));
    try testing.expectEqual(@as(?noise.Mac, null), (PeerCookie.init(rpub)).current(1_000));
}

test "macFields admits exactly the two handshake message shapes" {
    var buf: [200]u8 = undefined;
    @memset(&buf, 0);

    // Too short to even hold a type tag and an index.
    try testing.expectError(error.NotAHandshakeMessage, macFields(buf[0..7]));
    // Right type, wrong length — both directions.
    @memcpy(buf[0..148], &kat.msg1);
    try testing.expectError(error.NotAHandshakeMessage, macFields(buf[0..147]));
    try testing.expectError(error.NotAHandshakeMessage, macFields(buf[0..149]));
    _ = try macFields(buf[0..148]);
    // A response's bytes are 92, not 148: mislabeling either way is rejected.
    @memcpy(buf[0..92], &kat.msg2);
    _ = try macFields(buf[0..92]);
    std.mem.writeInt(u32, buf[0..4], @intFromEnum(MessageType.handshake_initiation), .little);
    try testing.expectError(error.NotAHandshakeMessage, macFields(buf[0..92]));
    // Types the cookie layer does not MAC.
    for ([_]u32{ 0, 3, 4, 5, 0xFFFF_FFFF }) |t| {
        std.mem.writeInt(u32, buf[0..4], t, .little);
        try testing.expectError(error.NotAHandshakeMessage, macFields(buf[0..92]));
        try testing.expectError(error.NotAHandshakeMessage, macFields(buf[0..148]));
    }
    // recordSent inherits the same gate rather than storing garbage as a mac1.
    var peer = PeerCookie.init(cookie_kat.responder_pub);
    try testing.expectError(error.NotAHandshakeMessage, peer.recordSent(buf[0..64]));
    try testing.expectEqual(@as(?noise.Mac, null), peer.last_sent_mac1);
}

// ── integration test (real kernel WireGuard as the protocol oracle) ────────
//
// Gated like root.zig's netlink integration tests: Linux + euid 0 (run under
// `unshare -rn` for an isolated netns with CAP_NET_ADMIN) + the `ip`/`wg`
// tools + the wireguard kernel module, else `error.SkipZigTest`.
//
// The KERNEL plays the initiator (so it owns TAI64N clocking and retries);
// we are the responder on a plain UDP socket. Proof of key agreement: the
// kernel's post-handshake keepalive — a transport-data packet encrypted by
// the kernel under ITS T_send — must AEAD-decrypt under OUR derived
// `recv` key. That authenticates the entire handshake (both messages, PSK
// mix and transport-key split) against an implementation we did not write.

/// Run an external command; `error.SkipZigTest` when it cannot be spawned.
fn runCmd(gpa: std.mem.Allocator, io: std.Io, argv: []const []const u8) !u8 {
    const res = std.process.run(gpa, io, .{ .argv = argv }) catch return error.SkipZigTest;
    defer gpa.free(res.stdout);
    defer gpa.free(res.stderr);
    return switch (res.term) {
        .exited => |code| code,
        else => 255,
    };
}

/// Print an external command's output; `false` when it could not be spawned.
/// Diagnostics only, on a failure path — a failing diagnostic must never
/// replace the real error, so this reports and returns rather than failing.
fn dumpCmd(gpa: std.mem.Allocator, io: std.Io, argv: []const []const u8) bool {
    const res = std.process.run(gpa, io, .{ .argv = argv }) catch return false;
    defer gpa.free(res.stdout);
    defer gpa.free(res.stderr);
    std.debug.print("  --- ", .{});
    for (argv) |a| std.debug.print("{s} ", .{a});
    std.debug.print("---\n{s}{s}", .{ res.stdout, res.stderr });
    return true;
}

/// The netfilter ruleset, which is the first thing an EPERM from `sendto`
/// asks about. `nft` usually lives in sbin, which spawn's PATH lookup may not
/// cover — `modules/nftables` carries the same candidate list for the same
/// reason.
fn dumpRuleset(gpa: std.mem.Allocator, io: std.Io) void {
    for ([_][]const u8{ "nft", "/usr/sbin/nft", "/sbin/nft" }) |argv0| {
        if (dumpCmd(gpa, io, &.{ argv0, "list", "ruleset" })) return;
    }
    std.debug.print("  (no nft binary — netfilter state unknown)\n", .{});
}

/// Wall-clock seconds for the live interop test — the one place in this module
/// that needs a real clock, and it is a *test harness*, which is exactly the
/// role `transport.zig` assigns to the caller. Product code here never reads a
/// clock; it takes `now_s`.
fn nowSeconds() u64 {
    var ts: std.os.linux.timespec = undefined;
    _ = std.os.linux.clock_gettime(.REALTIME, &ts);
    return @intCast(ts.sec);
}

test "integration (root): live handshake with kernel WireGuard, keepalive decrypts" {
    if (builtin.os.tag != .linux) return error.SkipZigTest;
    const linux = std.os.linux;
    if (linux.geteuid() != 0) return error.SkipZigTest; // needs CAP_NET_ADMIN
    const gpa = testing.allocator;

    var threaded = std.Io.Threaded.init(gpa, .{});
    defer threaded.deinit();
    const io = threaded.io();

    // Fresh identities: ours (userspace responder) and the kernel's.
    const our_kp = Keypair.generate(io);
    const kernel_kp = Keypair.generate(io);
    var psk: PresharedKey = undefined;
    io.random(&psk);

    // UDP socket on loopback; the kernel peer's endpoint points at it.
    const sock_rc = linux.socket(linux.AF.INET, linux.SOCK.DGRAM | linux.SOCK.CLOEXEC, 0);
    if (linux.errno(sock_rc) != .SUCCESS) return error.SkipZigTest;
    const fd: i32 = @intCast(sock_rc);
    defer _ = linux.close(fd);
    var bind_addr: linux.sockaddr.in = .{
        .port = 0,
        .addr = std.mem.nativeToBig(u32, 0x7f000001), // 127.0.0.1
    };
    if (linux.errno(linux.bind(fd, @ptrCast(&bind_addr), @sizeOf(linux.sockaddr.in))) != .SUCCESS)
        return error.SkipZigTest;
    var bound: linux.sockaddr.in = undefined;
    var bound_len: linux.socklen_t = @sizeOf(linux.sockaddr.in);
    try testing.expectEqual(
        .SUCCESS,
        linux.errno(linux.getsockname(fd, @ptrCast(&bound), &bound_len)),
    );
    const our_port = std.mem.bigToNative(u16, bound.port);

    // Kernel-side device: our public key as its peer, endpoint = our socket,
    // persistent keepalive so the kernel initiates immediately. Configured
    // through this module's OWN genl control plane (root.zig) — not the `wg`
    // tool, which Ubuntu's AppArmor profile confines to /etc/wireguard key
    // files — dogfooding both halves of the module in one test.
    const wgctl = @import("root.zig");
    const ifname = "zigwghs0";
    if (try runCmd(gpa, io, &.{ "ip", "link", "add", ifname, "type", "wireguard" }) != 0)
        return error.SkipZigTest; // wireguard module unavailable
    defer _ = runCmd(gpa, io, &.{ "ip", "link", "del", ifname }) catch {};
    _ = try runCmd(gpa, io, &.{ "ip", "link", "set", "lo", "up" }); // fresh netns has lo down
    var wg = wgctl.Wireguard.open(gpa) catch return error.SkipZigTest;
    defer wg.close();
    try wg.setDevice(.{
        .ifname = ifname,
        .private_key = kernel_kp.private,
        .peers = &.{.{
            .public_key = our_kp.public,
            .preshared_key = psk,
            .endpoint = .{ .v4 = .{ .addr = .{ 127, 0, 0, 1 }, .port = our_port } },
            .persistent_keepalive_interval = 1,
        }},
    });
    try testing.expectEqual(@as(u8, 0), try runCmd(gpa, io, &.{ "ip", "link", "set", ifname, "up" }));

    // Responder state: we know the kernel's static public key (Noise IK).
    // A `Handshake` consumes exactly one initiation (`consumeInitiation`
    // asserts `state == .idle`), so a RETRY needs a fresh one — see the
    // initiation branch below.
    const freshHandshake = struct {
        fn make(kp: Keypair, remote: [32]u8, k: [32]u8) Handshake {
            return .{
                .static_keypair = kp,
                .remote_static_public = remote,
                .preshared_key = k,
                .local_index = 0x5a5a5a5a,
            };
        }
    }.make;
    var hs: Handshake = freshHandshake(our_kp, kernel_kp.public, psk);
    var session: ?transport.Session = null;

    // Exercise the retry path on every run instead of waiting for a loaded
    // machine to produce it: the FIRST response is deliberately not sent, so
    // the kernel's rekey timer must fire and re-initiate, and this responder
    // must handle that second initiation as a new handshake. Without that,
    // one lost or late response strands the test for its whole budget — which
    // is exactly how this test failed 1-in-60 under load (see
    // `~/CML/20260808-zig-libs-audit/modules/wireguard.md`, 2026-08-12).
    var drop_first_response = true;

    // Drive the exchange: initiation in → response out → keepalive in.
    var buf: [2048]u8 = undefined;
    // 60 × 500 ms = 30 s. The old budget was 20 s for a clean exchange; the
    // injected loss above deliberately costs one kernel REKEY_TIMEOUT (5 s,
    // plus up to 333 ms of jitter) before the retry arrives, so the budget
    // covers that on purpose rather than being widened to hide a race.
    var polls_left: u32 = 60;
    while (polls_left > 0) : (polls_left -= 1) {
        var pfd = [1]linux.pollfd{.{ .fd = fd, .events = linux.POLL.IN, .revents = 0 }};
        const prc = linux.poll(&pfd, 1, 500);
        try testing.expectEqual(.SUCCESS, linux.errno(prc));
        if (prc == 0) continue;

        var src: linux.sockaddr.in = undefined;
        var src_len: linux.socklen_t = @sizeOf(linux.sockaddr.in);
        const rrc = linux.recvfrom(fd, &buf, buf.len, 0, @ptrCast(&src), &src_len);
        try testing.expectEqual(.SUCCESS, linux.errno(rrc));
        const n = rrc;
        if (n < 4) continue;

        switch (std.mem.readInt(u32, buf[0..4], .little)) {
            @intFromEnum(MessageType.handshake_initiation) => {
                if (n != @sizeOf(MessageInitiation)) continue;
                // A retry is a NEW handshake, not a duplicate of the one we
                // already answered: the kernel picks fresh ephemerals, so the
                // response we sent for the previous initiation is dead to it.
                // Answering the retry is therefore mandatory, and this code
                // used to `continue` past it — which meant a single lost or
                // late response could never be recovered from.
                if (hs.state != .idle) {
                    hs = freshHandshake(our_kp, kernel_kp.public, psk);
                    session = null;
                }
                var msg1: MessageInitiation = undefined;
                @memcpy(std.mem.asBytes(&msg1), buf[0..@sizeOf(MessageInitiation)]);
                try hs.consumeInitiation(msg1);
                var msg2 = try hs.createResponse(io);
                // Through the real data-plane API, not a hand-rolled AEAD
                // call: this is what makes the kernel an oracle for
                // `transport.zig`'s framing, not only for the handshake.
                session = hs.transportSession(false, nowSeconds());
                if (drop_first_response) {
                    // The injected loss. Everything above already ran, so the
                    // kernel's rekey timer is what has to rescue this — the
                    // very path the retry handling above exists for.
                    drop_first_response = false;
                    continue;
                }
                const src_len_const: linux.socklen_t = src_len;
                const wrc = linux.sendto(
                    fd,
                    std.mem.asBytes(&msg2),
                    @sizeOf(MessageResponse),
                    0,
                    @ptrCast(&src),
                    src_len_const,
                );
                // A blink here is expensive to diagnose after the fact: the
                // errno alone cannot tell a netfilter LOCAL_OUT/POSTROUTING
                // drop (which the kernel reports as EPERM) from a cgroup BPF
                // egress program (also EPERM, and orthogonal to the network
                // namespace) from a malformed destination. Print what
                // separates them, so one future occurrence is conclusive
                // instead of costing another reproduction campaign.
                if (linux.errno(wrc) != .SUCCESS) {
                    var self_addr: linux.sockaddr.in = undefined;
                    var self_len: linux.socklen_t = @sizeOf(linux.sockaddr.in);
                    const gs = linux.getsockname(fd, @ptrCast(&self_addr), &self_len);
                    std.debug.print(
                        "\nwireguard live interop: sendto failed\n" ++
                            "  errno={s} ret={d}\n" ++
                            "  dst: family={d} addr=0x{x:0>8} port={d} (addrlen={d}, sizeof(sockaddr_in)={d})\n" ++
                            "  src: family={d} addr=0x{x:0>8} port={d} (getsockname errno={s})\n" ++
                            "  cgroup: ",
                        .{
                            @tagName(linux.errno(wrc)),
                            @as(isize, @bitCast(wrc)),
                            src.family,
                            std.mem.bigToNative(u32, src.addr),
                            std.mem.bigToNative(u16, src.port),
                            src_len_const,
                            @sizeOf(linux.sockaddr.in),
                            self_addr.family,
                            std.mem.bigToNative(u32, self_addr.addr),
                            std.mem.bigToNative(u16, self_addr.port),
                            @tagName(linux.errno(gs)),
                        },
                    );
                    _ = dumpCmd(gpa, io, &.{ "cat", "/proc/self/cgroup" });
                    dumpRuleset(gpa, io);
                    _ = dumpCmd(gpa, io, &.{ "ip", "-o", "addr" });
                    _ = dumpCmd(gpa, io, &.{ "ip", "-o", "link" });
                    _ = dumpCmd(gpa, io, &.{ "ip", "route", "show", "table", "all" });
                }
                try testing.expectEqual(.SUCCESS, linux.errno(wrc));
                try testing.expectEqual(@sizeOf(MessageResponse), wrc);
            },
            @intFromEnum(MessageType.transport_data) => {
                // Keepalive: 16-byte header + empty plaintext + 16-byte tag —
                // i.e. `transport.sealedLen(0)`, which is what the protocol's
                // "pad to a multiple of 16" rule yields for an EMPTY payload
                // (a rule that padded 0 up to 16 would make this 48).
                if (n != transport.sealedLen(0)) continue;
                if (session == null) continue; // transport before our response? ignore
                const sess = &session.?;
                try testing.expectEqual(hs.local_index, std.mem.readInt(u32, buf[4..8], .little));
                var empty: [0]u8 = .{};
                // THE oracle assertion: a kernel-encrypted packet opens
                // through our data-plane API under our derived receive key.
                // Everything the kernel had to agree with us about is in this
                // one call — nonce layout and endianness, empty AAD, header
                // layout, receiver index, and the padding rule.
                const r = try sess.recv.open(&empty, buf[0..n], nowSeconds());
                try testing.expectEqual(@as(usize, 0), r.len);
                return; // interop proven
            },
            else => continue,
        }
    }
    std.debug.print("kernel WireGuard interop: no decryptable keepalive within budget\n", .{});
    return error.TestUnexpectedResult;
}
