//! Noise_IKpsk2 handshake — the WireGuard cryptographic session handshake:
//! message wire layouts (`MessageInitiation`/`MessageResponse`/`CookieReply`/
//! `MessageTransport`) and the `Handshake` state machine that produces and
//! consumes them, ending in a split pair of transport data-plane keys.
//! Plus the cookie/mac2 layer (whitepaper 5.4.7): `CookieChecker.admit` is
//! the responder's cheap under-load gate in FRONT of that state machine, and
//! `PeerCookie` the initiator's side of the same round trip.
//!
//! This is the DATA-PLANE crypto handshake — distinct from (and independent
//! of) `../src/root.zig` (plus the `genetlink` module it builds on), which
//! speak the kernel's genetlink CONTROL-plane protocol (`wg`-style
//! device/peer configuration).
//! A handshake never touches netlink; a configured `Wireguard` device never
//! touches Noise. Both live under the one `wireguard` module because they
//! are the same protocol's two halves.
//!
//! Verification: a fixed-input known-answer test (deterministic static +
//! ephemeral keys, PSK, timestamp and indices) asserts the exact 148-byte
//! `MessageInitiation`, 92-byte `MessageResponse` and both transport keys
//! against a vector generated by an independent reference implementation
//! (Python: hashlib BLAKE2s/HMAC + OpenSSL X25519/ChaCha20-Poly1305 via
//! cryptography.io), itself validated against the wireguard-go KDF vectors
//! (no official full-handshake vector is published by the WireGuard
//! project). A gated integration test additionally completes a live
//! handshake as responder against the Linux kernel's WireGuard
//! implementation and decrypts a kernel-encrypted transport packet with the
//! derived keys. See `noise.zig` for the Noise primitives this state
//! machine is built on.
//!
//! Provenance: clean-room from the WireGuard protocol description
//! (J. A. Donenfeld, "WireGuard: Next Generation Kernel Network Tunnel",
//! NDSS 2017, https://www.wireguard.com/papers/wireguard.pdf, and
//! https://www.wireguard.com/protocol/), which documents the exact message
//! layouts and handshake steps reserved below. Design reference:
//! wireguard-go (golang.zx2c4.com/wireguard, MIT) and the Linux kernel
//! WireGuard implementation (GPL-2.0) — behavior/shape only; the message
//! layout and handshake step order are the standardized wire protocol, not
//! copyrightable expression; no source consulted or copied. See ../NOTICE.

const std = @import("std");
const builtin = @import("builtin");
const entropy = @import("entropy");
const noise = @import("noise.zig");
/// The transport-data (type 4) seal/open data plane the completed handshake
/// keys. Imported one way only — `transport.zig` knows nothing about the
/// handshake, so it stays usable with keys from any source.
const transport = @import("transport.zig");

comptime {
    // The mac1/mac2 computations and the KAT/interop tests view the extern
    // structs below as wire bytes via `std.mem.asBytes`, which is byte-exact
    // only on a little-endian host. Fail the build rather than silently emit
    // byte-swapped handshakes; `@compileError` instead of `assert` so the
    // message says what is wrong and how to fix it, not "reached unreachable
    // code".
    if (builtin.cpu.arch.endian() != .little) @compileError(
        "wireguard/handshake.zig assumes a little-endian host: WireGuard's wire " ++
            "integers are little-endian and this file views its `extern struct`s " ++
            "as wire bytes via `std.mem.asBytes`. To build for a big-endian " ++
            "target, first encode/decode the u32/u64 fields explicitly with " ++
            "`std.mem.writeInt`/`readInt` and `.little` (as `root.zig`'s " ++
            "`parseEndpoint`/`appendEndpoint` already do), then lift this guard.",
    );
}

// Note: `pub const meta` is declared once, canonically, in `root.zig` (per
// CONVENTIONS.md §4) — submodule files like this one do not repeat it. This
// file itself has no dependency on `netlink`/`genetlink` (those are the
// sibling control-plane half of the module, in root.zig).

// ── message type tag (first 4 bytes of every WireGuard wire message) ───────

/// `message_type` values — the little-endian `u32` at offset 0 of every
/// WireGuard wire message, used to dispatch an incoming UDP datagram.
pub const MessageType = enum(u32) {
    handshake_initiation = 1,
    handshake_response = 2,
    cookie_reply = 3,
    transport_data = 4,
    _,
};

// ── key types ───────────────────────────────────────────────────────────────

/// Raw X25519 scalar (private/secret key), 32 bytes.
pub const PrivateKey = [noise.X25519.secret_length]u8;
/// Raw X25519 point (public key), 32 bytes.
pub const PublicKey = [noise.X25519.public_length]u8;
/// Pre-shared symmetric key mixed into message 2 (psk2), 32 bytes. All-zero
/// is the WireGuard convention for "no PSK configured" (mixed in anyway —
/// mixing a fixed zero key is a no-op that keeps the code path uniform).
pub const PresharedKey = [32]u8;

/// A static or ephemeral X25519 identity.
pub const Keypair = struct {
    private: PrivateKey,
    public: PublicKey,

    /// Generate a fresh keypair (used for the per-handshake ephemeral).
    /// `io` supplies entropy, matching the `sealedbox` module's convention
    /// for std.crypto operations that need randomness.
    pub fn generate(io: std.Io) Keypair {
        const kp = noise.X25519.KeyPair.generate(io);
        return .{ .private = kp.secret_key, .public = kp.public_key };
    }

    /// Rebuild a keypair from a stored private key (recomputes the public
    /// key via X25519 base-point multiplication).
    pub fn fromPrivateKey(private: PrivateKey) error{IdentityElement}!Keypair {
        return .{ .private = private, .public = try noise.X25519.recoverPublicKey(private) };
    }
};

// ── wire message layouts (WireGuard protocol, byte-exact) ──────────────────
//
// Endianness: WireGuard's wire integers are little-endian, and these are
// `extern struct`s whose in-memory layout matches the wire byte-for-byte only
// on a little-endian host. That is enforced by the `comptime` guard at the top
// of this file, which fails the build on a big-endian target with an
// explanation — verified to fire by cross-compiling for s390x-linux. Lifting
// it means encoding the `u32`/`u64` fields explicitly with
// `std.mem.readInt`/`writeInt` and `.little`, the way `root.zig`'s
// `parseEndpoint`/`appendEndpoint` do. Field order below is chosen so no
// implicit padding is inserted (every multi-byte integer field already falls
// on a naturally aligned offset).

/// Type 1 — Initiator → Responder. 148 bytes on the wire.
pub const MessageInitiation = extern struct {
    /// `MessageType.handshake_initiation` (1), little-endian.
    type: u32,
    /// Locally assigned session index; echoed back by the responder as
    /// `receiver_index` in `MessageResponse`.
    sender_index: u32,
    /// The initiator's ephemeral public key, sent in the clear.
    unencrypted_ephemeral: [32]u8,
    /// `AEAD(k, 0, initiator_static_public, Hi)` — the initiator's static
    /// public key, encrypted+authenticated (32-byte key + 16-byte Poly1305 tag).
    encrypted_static: [32 + 16]u8,
    /// `AEAD(k, 0, TAI64N(now), Hi)` — a TAI64N timestamp, encrypted (12-byte
    /// TAI64N label + 16-byte tag), used for replay/most-recent-handshake
    /// detection.
    encrypted_timestamp: [12 + 16]u8,
    /// `MAC(mac1_key, message[0 .. end-32])` — cheap DoS-resistant check;
    /// always present.
    mac1: [16]u8,
    /// `MAC(cookie, message[0 .. end-16])` if a valid responder cookie is
    /// held, else all-zero.
    mac2: [16]u8,
};

/// Type 2 — Responder → Initiator. 92 bytes on the wire.
pub const MessageResponse = extern struct {
    /// `MessageType.handshake_response` (2), little-endian.
    type: u32,
    /// The responder's own newly assigned session index.
    sender_index: u32,
    /// Echo of the initiator's `sender_index` (`MessageInitiation.sender_index`).
    receiver_index: u32,
    /// The responder's ephemeral public key, sent in the clear.
    unencrypted_ephemeral: [32]u8,
    /// `AEAD(k, 0, ε, Hr)` — an empty-plaintext AEAD, just a 16-byte
    /// Poly1305 tag; confirms both sides agree on every derived key so far.
    encrypted_nothing: [0 + 16]u8,
    /// `MAC(mac1_key, message[0 .. end-32])`.
    mac1: [16]u8,
    /// `MAC(cookie, message[0 .. end-16])` if held, else all-zero.
    mac2: [16]u8,
};

/// Type 3 — either side → the other, only ever sent in reply to a message
/// whose mac2 the receiver could not validate against its current cookie
/// (i.e. under load, as an unforgeable "here is a fresh cookie" nudge).
/// **Not part of the Noise transcript** — no chaining-key/hash mixing;
/// authenticated instead by XChaCha20-Poly1305 keyed with the sender's own
/// mac1 key and a random 24-byte nonce (so it needs no handshake state).
/// 64 bytes on the wire.
pub const CookieReply = extern struct {
    /// `MessageType.cookie_reply` (3), little-endian.
    type: u32,
    /// Echoes the `sender_index` of the message being replied to.
    receiver_index: u32,
    /// Random nonce for the `XAead` encryption below (`noise.XAead.nonce_length`).
    nonce: [24]u8,
    /// `XAEAD(cookie_key, nonce, cookie, mac1_of_replied_message)` — a fresh
    /// 16-byte cookie plus its 16-byte Poly1305 tag.
    encrypted_cookie: [16 + 16]u8,
};

/// Fixed header of type 4 (transport data) messages — 16 bytes, followed by
/// a variable-length AEAD ciphertext (plaintext IP packet + 16-byte
/// Poly1305 tag), which is why this is a header-only type rather than a
/// fixed-size `extern struct` like the handshake messages.
pub const MessageTransportHeader = extern struct {
    /// `MessageType.transport_data` (4), little-endian.
    type: u32,
    /// The receiver's session index (theirs, learned during the handshake).
    receiver_index: u32,
    /// Monotonic nonce counter, doubling as the low 8 bytes of the AEAD
    /// nonce (the high 4 bytes are always zero, per the Noise/WireGuard
    /// convention of a 12-byte nonce = 4 zero bytes || 8-byte LE counter).
    counter: u64,
};

/// A full transport-data message: fixed header plus a caller-owned
/// ciphertext slice. Not an `extern struct` (variable length).
pub const MessageTransport = struct {
    header: MessageTransportHeader,
    /// `AEAD(T_send, counter, plaintext_packet, ε)` — ciphertext + 16-byte tag.
    ciphertext: []const u8,
};

comptime {
    // Byte-exact wire sizes (WireGuard protocol) — guards against accidental
    // padding if a field is ever reordered.
    std.debug.assert(@sizeOf(MessageInitiation) == 148);
    std.debug.assert(@sizeOf(MessageResponse) == 92);
    std.debug.assert(@sizeOf(CookieReply) == 64);
    std.debug.assert(@sizeOf(MessageTransportHeader) == 16);
}

// ── handshake state machine ─────────────────────────────────────────────────

/// One in-flight Noise_IKpsk2 handshake attempt (initiator or responder
/// side — the same struct plays both roles depending which method is
/// called first). Single-owner: one `Handshake` per session attempt, not
/// shared across threads.
pub const Handshake = struct {
    /// Our long-term (static) identity keypair.
    static_keypair: Keypair,
    /// The peer's long-term public key — known ahead of time (Noise `IK`:
    /// the initiator already knows the responder's static key).
    remote_static_public: PublicKey,
    /// Pre-shared key (psk2 — mixed in message 2). All-zero if unconfigured.
    preshared_key: PresharedKey = @splat(0),

    /// Our ephemeral keypair for this attempt, generated on the first step
    /// we take (`createInitiation` for the initiator, `createResponse` for
    /// the responder).
    local_ephemeral: ?Keypair = null,
    /// The peer's ephemeral public key, learned from their message.
    remote_ephemeral: ?PublicKey = null,

    /// Noise chaining key `ck` — the running KDF ratchet state.
    chaining_key: noise.ChainKey = undefined,
    /// Noise transcript hash `h`.
    hash: noise.HandshakeHash = undefined,

    /// Our locally assigned session index (goes out as `sender_index` on
    /// our own messages).
    local_index: u32 = 0,
    /// The peer's session index, learned from their message (goes out as
    /// `receiver_index` on our replies / all transport packets to them).
    remote_index: u32 = 0,

    /// The cookie most recently learned from this peer's `CookieReply`, or
    /// null when we hold none that is still fresh — which is the normal
    /// steady state, since cookies only ever appear when the peer is under
    /// load. Set it from `PeerCookie.current(now_s)` before
    /// `createInitiation`/`createResponse`: non-null stamps a real `mac2`
    /// into the message we build, null stamps the protocol's all-zero mac2.
    /// Kept as a plain value (not a `*PeerCookie`) so this struct stays
    /// clock-free — freshness is `PeerCookie`'s job.
    cookie: ?noise.Mac = null,

    /// The initiator's decrypted TAI64N timestamp, recorded by
    /// `consumeInitiation` so the caller can do the required per-peer
    /// most-recent-handshake bookkeeping (this module keeps no cross-attempt
    /// state, so it cannot reject `StaleTimestamp` itself).
    remote_timestamp: ?[12]u8 = null,

    /// Which step this attempt has completed — enforces the call order
    /// (`createInitiation` → `consumeResponse` for the initiator,
    /// `consumeInitiation` → `createResponse` for the responder).
    state: enum { idle, initiation_sent, initiation_consumed, complete } = .idle,

    pub const InitiationError = error{
        /// `local_ephemeral`/`chaining_key` already set — call once per attempt.
        AlreadyStarted,
        /// `remote_static_public` is a low-order/identity X25519 point.
        InvalidPublicKey,
    };
    pub const ConsumeInitiationError = error{
        /// mac1 did not match `HASH(LABEL_MAC1 || our_static_public)`.
        InvalidMac1,
        /// The encrypted static key or timestamp failed AEAD authentication
        /// (or the peer's ephemeral/static key was a low-order X25519 point
        /// — fail closed, indistinguishably from a bad tag).
        DecryptionFailed,
        /// Decrypted static key does not match a known peer (caller-side
        /// peer lookup failed before/while calling this).
        UnknownPeer,
        /// Timestamp is not newer than the last one seen from this peer
        /// (replay / out-of-order handshake rejection). Never returned here
        /// — reserved for callers doing the cross-attempt bookkeeping over
        /// `remote_timestamp` (see that field).
        StaleTimestamp,
    };
    pub const ResponseError = error{
        /// A response was already created for this attempt.
        AlreadyStarted,
        /// `consumeInitiation` has not succeeded on this handshake yet.
        NoInitiationConsumed,
        /// A peer key is a low-order/identity X25519 point.
        InvalidPublicKey,
    };
    pub const ConsumeResponseError = error{
        InvalidMac1,
        /// The empty-plaintext AEAD tag failed to verify (also covers a
        /// low-order ephemeral from the peer and a PSK mismatch — all
        /// indistinguishable by design).
        DecryptionFailed,
        /// This handshake never sent a `MessageInitiation` to respond to.
        NoPendingInitiation,
    };

    /// `Ck0/H0` derivation shared by both roles (whitepaper 5.4.2 first
    /// three lines): `ck = HASH(CONSTRUCTION)`, `h = HASH(ck || IDENTIFIER)`,
    /// `h = HASH(h || responder_static_public)`.
    fn initialState(responder_static_public: PublicKey) struct { ck: noise.ChainKey, h: noise.HandshakeHash } {
        var ck: noise.ChainKey = undefined;
        noise.Blake2s.hash(noise.CONSTRUCTION, &ck, .{});
        var h: noise.HandshakeHash = ck;
        noise.mixHash(&h, noise.IDENTIFIER);
        noise.mixHash(&h, &responder_static_public);
        return .{ .ck = ck, .h = h };
    }

    /// The 12-byte AEAD nonce for a 64-bit counter: 4 zero bytes followed by
    /// the counter, little-endian (whitepaper 5.4.6). Handshake messages
    /// always use counter 0 — which is why the handshake KATs below cannot
    /// detect an endianness error here and `transport.zig` pins the layout
    /// against fixed bytes. ONE definition, shared with the data plane, so
    /// that pinning covers this call site too.
    const counterNonce = transport.counterNonce;

    /// Initiator step 1: derive `Ci`/`Hi` from `noise.CONSTRUCTION` +
    /// `noise.IDENTIFIER` + `remote_static_public`, generate an ephemeral
    /// keypair, and produce the encrypted static-key + timestamp message.
    /// `io` supplies entropy for the ephemeral keypair; `now_tai64n` is the
    /// caller-supplied current TAI64N timestamp (12 bytes) — kept out of
    /// this module so it stays platform-agnostic (no clock syscalls here,
    /// consistent with the rest of `wireguard` treating wire codecs as pure
    /// functions over bytes).
    /// (A pre-seeded `local_ephemeral` is used instead of generating one —
    /// deterministic-test hook; leave it null in production.)
    pub fn createInitiation(
        self: *Handshake,
        io: std.Io,
        now_tai64n: [12]u8,
    ) InitiationError!MessageInitiation {
        if (self.state != .idle) return error.AlreadyStarted;
        const eph = self.local_ephemeral orelse Keypair.generate(io);
        self.local_ephemeral = eph;

        var st = initialState(self.remote_static_public);
        var msg: MessageInitiation = undefined;
        msg.type = @intFromEnum(MessageType.handshake_initiation);
        msg.sender_index = self.local_index;

        // e: ephemeral in the clear, mixed into ck and h.
        msg.unencrypted_ephemeral = eph.public;
        noise.kdf1(&st.ck, &eph.public);
        noise.mixHash(&st.h, &eph.public);

        // es: DH(Ei, Sr) → key for the encrypted static.
        var es = noise.X25519.scalarmult(eph.private, self.remote_static_public) catch
            return error.InvalidPublicKey;
        var k = noise.mixKey(&st.ck, &es);
        std.crypto.secureZero(u8, &es);
        noise.Aead.encrypt(
            msg.encrypted_static[0..32],
            msg.encrypted_static[32..48],
            &self.static_keypair.public,
            &st.h,
            counterNonce(0),
            k,
        );
        noise.mixHash(&st.h, &msg.encrypted_static);

        // ss: DH(Si, Sr) → key for the encrypted timestamp.
        var ss = noise.X25519.scalarmult(self.static_keypair.private, self.remote_static_public) catch
            return error.InvalidPublicKey;
        k = noise.mixKey(&st.ck, &ss);
        std.crypto.secureZero(u8, &ss);
        noise.Aead.encrypt(
            msg.encrypted_timestamp[0..12],
            msg.encrypted_timestamp[12..28],
            &now_tai64n,
            &st.h,
            counterNonce(0),
            k,
        );
        std.crypto.secureZero(u8, &k);
        noise.mixHash(&st.h, &msg.encrypted_timestamp);

        self.chaining_key = st.ck;
        self.hash = st.h;
        std.crypto.secureZero(u8, &st.ck);

        msg.mac1 = self.computeMac1(std.mem.asBytes(&msg)[0..@offsetOf(MessageInitiation, "mac1")]);
        msg.mac2 = self.stampMac2(std.mem.asBytes(&msg)[0..@offsetOf(MessageInitiation, "mac2")]);
        self.state = .initiation_sent;
        return msg;
    }

    /// Responder validates an incoming `MessageInitiation`: checks mac1,
    /// replays the initiator's transcript to decrypt+authenticate the
    /// static key and timestamp, and (on success) records the peer's
    /// ephemeral public key and session index so `createResponse` can reply.
    /// The caller is responsible for looking up which configured peer
    /// `remote_static_public` (decrypted here) belongs to, and for
    /// last-handshake/timestamp bookkeeping across repeated attempts.
    ///
    /// This is the EXPENSIVE path (one X25519 before anything can be
    /// rejected as forged), and it deliberately does not check mac2: mac2 is
    /// a MAC over the sender's source ADDRESS, which a `Handshake` never
    /// sees. Under load, run `CookieChecker.admit` on the raw datagram first
    /// — it checks mac1 and mac2 and answers with a `CookieReply` without
    /// constructing a `Handshake` at all, which is the only ordering in which
    /// the cookie layer actually sheds a flood.
    pub fn consumeInitiation(self: *Handshake, msg: MessageInitiation) ConsumeInitiationError!void {
        std.debug.assert(self.state == .idle); // one attempt per Handshake

        // mac1 first — cheap rejection before any DH (keyed with OUR static
        // public key: that is what the initiator derived the mac1 key from).
        const our_mac1_key = noise.mac1Key(self.static_keypair.public);
        const expected_mac1 = noise.keyedMac(
            &our_mac1_key,
            std.mem.asBytes(&msg)[0..@offsetOf(MessageInitiation, "mac1")],
        );
        if (!std.crypto.timing_safe.eql(noise.Mac, expected_mac1, msg.mac1))
            return error.InvalidMac1;

        // Replay the initiator's transcript (we are the responder — Ck0/H0
        // are derived from our own static public key).
        var st = initialState(self.static_keypair.public);
        noise.kdf1(&st.ck, &msg.unencrypted_ephemeral);
        noise.mixHash(&st.h, &msg.unencrypted_ephemeral);

        // es: DH(Sr, Ei) → decrypt the initiator's static public key.
        var es = noise.X25519.scalarmult(self.static_keypair.private, msg.unencrypted_ephemeral) catch
            return error.DecryptionFailed;
        var k = noise.mixKey(&st.ck, &es);
        std.crypto.secureZero(u8, &es);
        var peer_static: PublicKey = undefined;
        noise.Aead.decrypt(
            &peer_static,
            msg.encrypted_static[0..32],
            msg.encrypted_static[32..48].*,
            &st.h,
            counterNonce(0),
            k,
        ) catch return error.DecryptionFailed;
        noise.mixHash(&st.h, &msg.encrypted_static);
        if (!std.mem.eql(u8, &peer_static, &self.remote_static_public))
            return error.UnknownPeer;

        // ss: DH(Sr, Si) → decrypt + authenticate the timestamp.
        var ss = noise.X25519.scalarmult(self.static_keypair.private, peer_static) catch
            return error.DecryptionFailed;
        k = noise.mixKey(&st.ck, &ss);
        std.crypto.secureZero(u8, &ss);
        var ts: [12]u8 = undefined;
        noise.Aead.decrypt(
            &ts,
            msg.encrypted_timestamp[0..12],
            msg.encrypted_timestamp[12..28].*,
            &st.h,
            counterNonce(0),
            k,
        ) catch return error.DecryptionFailed;
        std.crypto.secureZero(u8, &k);
        noise.mixHash(&st.h, &msg.encrypted_timestamp);

        self.chaining_key = st.ck;
        self.hash = st.h;
        std.crypto.secureZero(u8, &st.ck);
        self.remote_ephemeral = msg.unencrypted_ephemeral;
        self.remote_timestamp = ts;
        self.remote_index = msg.sender_index;
        self.state = .initiation_consumed;
    }

    /// Responder step 2: generate our own ephemeral keypair, mix in the
    /// pre-shared key (psk2 — WireGuard's `Kdf3` step), and produce the
    /// empty-payload confirmation message. Requires `consumeInitiation` to
    /// have succeeded first.
    /// (A pre-seeded `local_ephemeral` is used instead of generating one —
    /// deterministic-test hook; leave it null in production.)
    pub fn createResponse(self: *Handshake, io: std.Io) ResponseError!MessageResponse {
        switch (self.state) {
            .initiation_consumed => {},
            .idle, .initiation_sent => return error.NoInitiationConsumed,
            .complete => return error.AlreadyStarted,
        }
        const remote_eph = self.remote_ephemeral.?; // set by consumeInitiation
        const eph = self.local_ephemeral orelse Keypair.generate(io);
        self.local_ephemeral = eph;

        var msg: MessageResponse = undefined;
        msg.type = @intFromEnum(MessageType.handshake_response);
        msg.sender_index = self.local_index;
        msg.receiver_index = self.remote_index;

        // e: our ephemeral in the clear.
        msg.unencrypted_ephemeral = eph.public;
        noise.kdf1(&self.chaining_key, &eph.public);
        noise.mixHash(&self.hash, &eph.public);

        // ee: DH(Er, Ei) — chaining-key only, no key output.
        var ee = noise.X25519.scalarmult(eph.private, remote_eph) catch
            return error.InvalidPublicKey;
        noise.kdf1(&self.chaining_key, &ee);
        std.crypto.secureZero(u8, &ee);

        // se: DH(Er, Si) — chaining-key only.
        var se = noise.X25519.scalarmult(eph.private, self.remote_static_public) catch
            return error.InvalidPublicKey;
        noise.kdf1(&self.chaining_key, &se);
        std.crypto.secureZero(u8, &se);

        // psk2: (ck, tau, k) = KDF3(ck, psk); h = HASH(h || tau).
        var psk_out = noise.kdf3(&self.chaining_key, &self.preshared_key);
        noise.mixHash(&self.hash, &psk_out.out1);

        // Empty-plaintext AEAD — proves agreement on every key derived so far.
        noise.Aead.encrypt(
            msg.encrypted_nothing[0..0],
            msg.encrypted_nothing[0..16],
            "",
            &self.hash,
            counterNonce(0),
            psk_out.out2,
        );
        std.crypto.secureZero(u8, std.mem.asBytes(&psk_out));
        noise.mixHash(&self.hash, &msg.encrypted_nothing);

        msg.mac1 = self.computeMac1(std.mem.asBytes(&msg)[0..@offsetOf(MessageResponse, "mac1")]);
        msg.mac2 = self.stampMac2(std.mem.asBytes(&msg)[0..@offsetOf(MessageResponse, "mac2")]);
        self.state = .complete;
        return msg;
    }

    /// Initiator validates the incoming `MessageResponse`: replays the
    /// responder's derivation (ephemeral DHs + psk2 mix) and authenticates
    /// the empty-payload AEAD tag. On success the handshake is complete and
    /// `deriveTransportKeys` may be called.
    pub fn consumeResponse(self: *Handshake, msg: MessageResponse) ConsumeResponseError!void {
        if (self.state != .initiation_sent) return error.NoPendingInitiation;
        const eph = self.local_ephemeral.?; // set by createInitiation

        // mac1 — keyed with OUR static public key (the responder derived it
        // from ours, since the message is addressed to us).
        const our_mac1_key = noise.mac1Key(self.static_keypair.public);
        const expected_mac1 = noise.keyedMac(
            &our_mac1_key,
            std.mem.asBytes(&msg)[0..@offsetOf(MessageResponse, "mac1")],
        );
        if (!std.crypto.timing_safe.eql(noise.Mac, expected_mac1, msg.mac1))
            return error.InvalidMac1;

        // Work on copies so a failed (possibly forged) response cannot
        // corrupt the pending handshake state.
        var ck = self.chaining_key;
        var h = self.hash;

        noise.kdf1(&ck, &msg.unencrypted_ephemeral);
        noise.mixHash(&h, &msg.unencrypted_ephemeral);

        // ee: DH(Ei, Er), then se: DH(Si, Er) — chaining-key only.
        var ee = noise.X25519.scalarmult(eph.private, msg.unencrypted_ephemeral) catch
            return error.DecryptionFailed;
        noise.kdf1(&ck, &ee);
        std.crypto.secureZero(u8, &ee);
        var se = noise.X25519.scalarmult(self.static_keypair.private, msg.unencrypted_ephemeral) catch
            return error.DecryptionFailed;
        noise.kdf1(&ck, &se);
        std.crypto.secureZero(u8, &se);

        // psk2 mix, then authenticate the empty payload.
        var psk_out = noise.kdf3(&ck, &self.preshared_key);
        defer std.crypto.secureZero(u8, std.mem.asBytes(&psk_out));
        noise.mixHash(&h, &psk_out.out1);
        var empty: [0]u8 = .{};
        noise.Aead.decrypt(
            &empty,
            msg.encrypted_nothing[0..0],
            msg.encrypted_nothing[0..16].*,
            &h,
            counterNonce(0),
            psk_out.out2,
        ) catch return error.DecryptionFailed;
        noise.mixHash(&h, &msg.encrypted_nothing);

        self.chaining_key = ck;
        self.hash = h;
        std.crypto.secureZero(u8, &ck);
        self.remote_ephemeral = msg.unencrypted_ephemeral;
        self.remote_index = msg.sender_index;
        self.state = .complete;
    }

    /// Final step, either side, once the handshake completed (initiator
    /// after `consumeResponse`, responder after `createResponse`): split
    /// the chaining key into the two directional transport keys.
    /// `Kdf2(ck, ε) = (k1, k2)`; the initiator's `send` is the responder's
    /// `recv` and vice versa — WireGuard fixes this by having the
    /// *initiator* take `(send, recv) = (k1, k2)` and the *responder* take
    /// `(send, recv) = (k2, k1)`, so both sides must know which role they
    /// played to call this correctly.
    /// Consumes the handshake: the chaining key, transcript hash and the
    /// ephemeral private key are wiped — only the returned keys survive.
    pub fn deriveTransportKeys(self: *Handshake, is_initiator: bool) transport.TransportKeys {
        std.debug.assert(self.state == .complete);
        // Kdf2(ck, ε) = (T1, T2): kdf2 leaves T1 in the chaining key and
        // returns T2.
        const t2 = noise.kdf2(&self.chaining_key, "");
        const t1 = self.chaining_key;
        std.crypto.secureZero(u8, &self.chaining_key);
        std.crypto.secureZero(u8, &self.hash);
        if (self.local_ephemeral) |*kp| std.crypto.secureZero(u8, &kp.private);
        return if (is_initiator)
            .{ .send = t1, .recv = t2 }
        else
            .{ .send = t2, .recv = t1 };
    }

    /// The one-call bridge from a completed handshake to the data plane:
    /// derive the transport keys and wire them, with both session indices,
    /// into a `transport.Session`. Prefer this over calling
    /// `deriveTransportKeys` by hand — it is what makes the send/receive key
    /// and the local/remote index assignment impossible to swap (a swap
    /// round-trips against yourself and fails against every real peer).
    /// Consumes the handshake exactly as `deriveTransportKeys` does.
    ///
    /// `now_s` is the caller's clock at the moment the handshake completed —
    /// the session's `born_s`, from which `transport.reject_after_time_s` (180 s)
    /// and `transport.rekey_after_time_s` (120 s) are measured. Required, not
    /// optional: a session with no birth time is a session that never expires,
    /// and the same `now_s` convention already runs through this file's cookie
    /// layer (`CookieChecker.refresh`, `PeerCookie.current`).
    pub fn transportSession(self: *Handshake, is_initiator: bool, now_s: u64) transport.Session {
        const local = self.local_index;
        const remote = self.remote_index;
        return transport.Session.init(self.deriveTransportKeys(is_initiator), local, remote, now_s);
    }

    /// `MAC(mac1_key(remote_static_public), msg_bytes_before_mac1)` — the
    /// mac1 field of any message we send to this peer. `msg_bytes_before_mac1`
    /// is the wire encoding of the message up to (not including) its mac1
    /// field.
    pub fn computeMac1(self: *const Handshake, msg_bytes_before_mac1: []const u8) noise.Mac {
        const key = noise.mac1Key(self.remote_static_public);
        return noise.keyedMac(&key, msg_bytes_before_mac1);
    }

    /// `MAC(cookie, msg_bytes_before_mac2)` if `cookie` is a currently-valid
    /// cookie received from this peer, else an all-zero mac2 (per protocol,
    /// only computed under load after receiving a `CookieReply`).
    pub fn computeMac2(
        self: *const Handshake,
        msg_bytes_before_mac2: []const u8,
        cookie: [16]u8,
    ) noise.Mac {
        _ = self;
        return noise.keyedMac(&cookie, msg_bytes_before_mac2);
    }

    /// The mac2 field of a message we are building: `computeMac2` under the
    /// cookie held in `self.cookie`, or the protocol's all-zero mac2 when we
    /// hold none. This is the ONE place the two cases are decided, so no
    /// message-building path can forget either half.
    fn stampMac2(self: *const Handshake, msg_bytes_before_mac2: []const u8) noise.Mac {
        const cookie = self.cookie orelse return @splat(0);
        return self.computeMac2(msg_bytes_before_mac2, cookie);
    }
};

// ── cookie / mac2: the under-load DoS mitigation (whitepaper 5.4.7) ────────
//
// mac1 alone is not a DoS defense: its key is `HASH(LABEL_MAC1 ||
// responder_static_public)`, derived from a PUBLIC value, so anyone who knows
// the responder's public key can forge a mac1-passing initiation from a
// spoofed source address and make the responder spend an X25519 plus two AEAD
// opens on it. The cookie layer is what turns that into a round-trip
// requirement: a loaded responder answers with a `CookieReply` carrying
// `cookie = MAC(Rm, Am)` — a MAC of the SOURCE ADDRESS under a secret that
// rotates every two minutes — and thereafter only accepts messages from that
// address whose `mac2` proves possession of the cookie. A spoofed source never
// receives the reply, so it can never produce the mac2.
//
// Two pieces of state, one per role:
//   * `CookieChecker` — responder side: the rotating secret `Rm`, mac2
//     validation, and cookie-reply generation.
//   * `PeerCookie` — initiator side: the cookie learned from a peer's reply
//     and how long it stays usable.
// Neither reads a clock or a socket: the caller passes `now_s` (seconds, any
// monotonic epoch) and the opaque source-address bytes, matching this module's
// standing rule that its codecs are pure functions over bytes.

/// The responder's cookie secret `Rm` "changes every two minutes" (5.4.7).
pub const cookie_secret_lifetime_s: u64 = 120;
/// …and a cookie is derived from that secret, so an initiator must stop using
/// one after the same two minutes: past that the responder has (or is about to
/// have) rotated `Rm` and the mac2 would simply be rejected.
pub const cookie_lifetime_s: u64 = 120;

/// The three regions of a handshake message the cookie layer works on, plus
/// the two MACs already in it. Slices borrow the caller's buffer.
pub const MacFields = struct {
    /// `msg.sender_index` — echoed as the cookie reply's `receiver_index`.
    sender_index: u32,
    /// `msg[0 .. offsetof(msg.mac1)]` — what mac1 is computed over.
    mac1_input: []const u8,
    /// `msg[0 .. offsetof(msg.mac2)]` — what mac2 is computed over (mac1
    /// included: mac2 covers the whole message before itself).
    mac2_input: []const u8,
    /// The mac1 carried by the message. Doubles as the associated data of a
    /// cookie reply sent in answer to it.
    mac1: noise.Mac,
    /// The mac2 carried by the message (all-zero when the sender held no cookie).
    mac2: noise.Mac,
};

pub const MacFieldsError = error{
    /// Not a type-1/type-2 handshake message of the exact protocol length —
    /// nothing the cookie layer has any business MACing.
    NotAHandshakeMessage,
};

comptime {
    // `macFields` below indexes both message types by the same rule (indices
    // at 4, the two MACs as the trailing 32 bytes). Assert that rather than
    // trust it, so a field reorder fails the build instead of MACing garbage.
    std.debug.assert(@offsetOf(MessageInitiation, "sender_index") == 4);
    std.debug.assert(@offsetOf(MessageResponse, "sender_index") == 4);
    std.debug.assert(@offsetOf(MessageInitiation, "mac1") == @sizeOf(MessageInitiation) - 32);
    std.debug.assert(@offsetOf(MessageResponse, "mac1") == @sizeOf(MessageResponse) - 32);
    std.debug.assert(@offsetOf(MessageInitiation, "mac2") == @sizeOf(MessageInitiation) - 16);
    std.debug.assert(@offsetOf(MessageResponse, "mac2") == @sizeOf(MessageResponse) - 16);
}

/// Locate the mac1/mac2 regions of a raw handshake datagram, rejecting
/// anything that is not exactly a `MessageInitiation` or `MessageResponse`.
/// Length is checked against the type tag (not merely `>= 32`) so a truncated
/// or oversized datagram is dropped before any MAC is computed over it.
pub fn macFields(msg_bytes: []const u8) MacFieldsError!MacFields {
    if (msg_bytes.len < 8) return error.NotAHandshakeMessage;
    const wire_len: usize = switch (@as(MessageType, @enumFromInt(
        std.mem.readInt(u32, msg_bytes[0..4], .little),
    ))) {
        .handshake_initiation => @sizeOf(MessageInitiation),
        .handshake_response => @sizeOf(MessageResponse),
        else => return error.NotAHandshakeMessage,
    };
    if (msg_bytes.len != wire_len) return error.NotAHandshakeMessage;
    return .{
        .sender_index = std.mem.readInt(u32, msg_bytes[4..8], .little),
        .mac1_input = msg_bytes[0 .. wire_len - 32],
        .mac2_input = msg_bytes[0 .. wire_len - 16],
        .mac1 = msg_bytes[wire_len - 32 ..][0..16].*,
        .mac2 = msg_bytes[wire_len - 16 ..][0..16].*,
    };
}

/// What a responder should do with an inbound handshake datagram, decided
/// before any Diffie-Hellman happens — the whole point of the layer.
pub const Admission = union(enum) {
    /// mac1 is valid and either we are not under load or mac2 checked out:
    /// go ahead and spend the asymmetric crypto (`Handshake.consumeInitiation`
    /// / `consumeResponse`).
    accept,
    /// Under load and the sender has no valid cookie for this source address:
    /// send these 64 bytes back and do NO further work on the datagram.
    cookie_reply: CookieReply,
    /// Not a handshake message, or mac1 does not verify: drop silently, as
    /// WireGuard's design requires (never answer an unauthenticated packet
    /// with anything but a cookie reply).
    drop,
};

/// Responder-side cookie state — one per local device (it is keyed on OUR
/// static public key, not on any peer's), shared across every peer and every
/// in-flight handshake.
pub const CookieChecker = struct {
    /// `HASH(LABEL_MAC1 || our_static_public)` — precomputed mac1 key for
    /// messages addressed to us.
    mac1_key: noise.HandshakeHash,
    /// `HASH(LABEL_COOKIE || our_static_public)` — the XAEAD key our cookie
    /// replies are encrypted under. Derived from a public value by design:
    /// the reply is meant to be readable by whoever actually received it, and
    /// its authentication comes from the associated data (the mac1 of the
    /// message being answered), which only someone on the path or the genuine
    /// sender knows.
    cookie_key: noise.HandshakeHash,
    /// `Rm` — the rotating secret every cookie is MACed under. Secret: wipe
    /// with `wipe()` when discarding the checker.
    secret: [32]u8,
    /// When `secret` was generated, in the caller's `now_s` epoch.
    secret_born_s: u64,

    /// Fresh checker with a random `Rm`. Fail-closed: `initWithSecret`'s
    /// own doc says it — a predictable `Rm` makes every cookie forgeable,
    /// which is the whole security of this layer — and this signature
    /// returns a `CookieChecker`, so a weak draw could not be reported.
    pub fn init(our_static_public: PublicKey, io: std.Io, now_s: u64) CookieChecker {
        var self = initWithSecret(our_static_public, undefined, now_s);
        entropy.fill(io, &self.secret);
        return self;
    }

    /// Deterministic-test seam: a checker with a caller-chosen `Rm`. Use
    /// `init` in production — a predictable secret makes every cookie
    /// forgeable, which is the whole security of this layer.
    pub fn initWithSecret(our_static_public: PublicKey, secret: [32]u8, now_s: u64) CookieChecker {
        return .{
            .mac1_key = noise.mac1Key(our_static_public),
            .cookie_key = noise.cookieKey(our_static_public),
            .secret = secret,
            .secret_born_s = now_s,
        };
    }

    /// Wipe `Rm`. Every cookie issued under it stops verifying.
    pub fn wipe(self: *CookieChecker) void {
        std.crypto.secureZero(u8, &self.secret);
        self.secret_born_s = 0;
    }

    /// Roll `Rm` once it has lived `cookie_secret_lifetime_s`, which is what
    /// bounds a stolen cookie's usefulness. A clock that moved BACKWARDS also
    /// rolls it: extending a secret's life on a bad timestamp is the one
    /// failure mode worth avoiding here, and re-rolling only costs the peers
    /// one extra round trip.
    pub fn refresh(self: *CookieChecker, io: std.Io, now_s: u64) void {
        if (now_s >= self.secret_born_s and
            now_s - self.secret_born_s < cookie_secret_lifetime_s) return;
        // Same fail-closed reason as `init` — rotating onto a guessable
        // `Rm` is strictly worse than not rotating at all.
        entropy.fill(io, &self.secret);
        self.secret_born_s = now_s;
    }

    /// `cookie = MAC(Rm, Am)` for one source address, rotating `Rm` first if
    /// it is due. `source_address` is opaque to this module — whatever stable
    /// encoding of the peer's address the caller uses (e.g. 4-or-16 IP bytes
    /// plus the 2 port bytes). It only has to be the SAME bytes when the
    /// cookie is issued and when a later mac2 is checked; anything that varies
    /// per packet would issue cookies that can never be used.
    pub fn cookieFor(
        self: *CookieChecker,
        io: std.Io,
        now_s: u64,
        source_address: []const u8,
    ) noise.Mac {
        self.refresh(io, now_s);
        return noise.keyedMac(&self.secret, source_address);
    }

    /// Constant-time mac1 check — the cheap "is this even addressed to us"
    /// filter that runs before everything else.
    pub fn checkMac1(self: *const CookieChecker, f: MacFields) bool {
        const expected = noise.keyedMac(&self.mac1_key, f.mac1_input);
        return std.crypto.timing_safe.eql(noise.Mac, expected, f.mac1);
    }

    /// Constant-time mac2 check against the cookie this source address would
    /// currently be issued. An all-zero mac2 (the sender holds no cookie)
    /// simply fails to match, which is exactly the desired outcome.
    pub fn checkMac2(
        self: *CookieChecker,
        io: std.Io,
        now_s: u64,
        f: MacFields,
        source_address: []const u8,
    ) bool {
        const cookie = self.cookieFor(io, now_s, source_address);
        const expected = noise.keyedMac(&cookie, f.mac2_input);
        return std.crypto.timing_safe.eql(noise.Mac, expected, f.mac2);
    }

    /// Build the type-3 answer to a message we refuse to work on:
    /// `encrypted_cookie = XAEAD(cookie_key, nonce, cookie, msg.mac1)` with a
    /// fresh random nonce (5.4.7).
    pub fn createReply(
        self: *CookieChecker,
        io: std.Io,
        now_s: u64,
        f: MacFields,
        source_address: []const u8,
    ) CookieReply {
        var nonce: [noise.XAead.nonce_length]u8 = undefined;
        // Fail-closed: this nonce's only job is to never repeat under one
        // `Rm`, and a repeat leaks the XOR of two cookies (see
        // `createReplyWithNonce`). Returns a `CookieReply`, no error channel.
        entropy.fill(io, &nonce);
        return self.createReplyWithNonce(io, now_s, f, source_address, nonce);
    }

    /// Deterministic-test seam for `createReply`. Production callers use
    /// `createReply`: two replies under one `Rm` with the same nonce leak the
    /// XOR of their cookies.
    pub fn createReplyWithNonce(
        self: *CookieChecker,
        io: std.Io,
        now_s: u64,
        f: MacFields,
        source_address: []const u8,
        nonce: [noise.XAead.nonce_length]u8,
    ) CookieReply {
        const cookie = self.cookieFor(io, now_s, source_address);
        var reply: CookieReply = .{
            .type = @intFromEnum(MessageType.cookie_reply),
            .receiver_index = f.sender_index,
            .nonce = nonce,
            .encrypted_cookie = undefined,
        };
        noise.XAead.encrypt(
            reply.encrypted_cookie[0..16],
            reply.encrypted_cookie[16..32],
            &cookie,
            &f.mac1, // associated data — binds the reply to the exact message
            nonce,
            self.cookie_key,
        );
        return reply;
    }

    /// The complete inbound decision for one handshake datagram: parse, mac1,
    /// then (only when `under_load`) mac2, answering with a cookie reply when
    /// the sender cannot prove a round trip. Runs before any `Handshake`
    /// exists — that is what makes it a defense rather than a formality, since
    /// the expensive X25519 lives on the far side of `.accept`.
    ///
    /// `under_load` is the caller's policy call (queue depth, handshakes/sec —
    /// whatever it measures); this module has no view of the socket. Callers
    /// should additionally rate-limit replies per source address, so that a
    /// flood cannot turn one 148-byte initiation into one 64-byte reply
    /// forever.
    pub fn admit(
        self: *CookieChecker,
        io: std.Io,
        now_s: u64,
        msg_bytes: []const u8,
        source_address: []const u8,
        under_load: bool,
    ) Admission {
        const f = macFields(msg_bytes) catch return .drop;
        if (!self.checkMac1(f)) return .drop;
        if (!under_load) return .accept;
        if (self.checkMac2(io, now_s, f, source_address)) return .accept;
        return .{ .cookie_reply = self.createReply(io, now_s, f, source_address) };
    }
};

/// Initiator-side cookie state — one per peer we send handshake messages to
/// (it is keyed on THAT peer's static public key). Feed `Handshake.cookie`
/// from `current(now_s)`.
pub const PeerCookie = struct {
    /// `HASH(LABEL_COOKIE || peer_static_public)` — the key the peer encrypts
    /// its cookie replies to us under.
    cookie_key: noise.HandshakeHash,
    /// The cookie from the peer's last reply, if any.
    cookie: ?noise.Mac = null,
    /// When that cookie arrived, in the caller's `now_s` epoch.
    cookie_born_s: u64 = 0,
    /// mac1 of the last handshake message we sent this peer — the associated
    /// data any cookie reply to it will be authenticated with, so a reply can
    /// only be consumed by whoever actually saw that message.
    last_sent_mac1: ?noise.Mac = null,

    pub fn init(peer_static_public: PublicKey) PeerCookie {
        return .{ .cookie_key = noise.cookieKey(peer_static_public) };
    }

    /// Record a handshake message we just put on the wire. Call it for every
    /// initiation/response sent to this peer: without the stored mac1 a reply
    /// to it cannot be opened.
    pub fn recordSent(self: *PeerCookie, msg_bytes: []const u8) MacFieldsError!void {
        self.last_sent_mac1 = (try macFields(msg_bytes)).mac1;
    }

    pub const ConsumeReplyError = error{
        /// No `recordSent` since the last consumed reply — nothing this reply
        /// could be an answer to.
        NoPendingMessage,
        /// The XAEAD tag did not verify under `cookie_key` and the stored
        /// mac1: a reply to some other message, or a forgery by someone who
        /// never saw ours.
        DecryptionFailed,
    };

    /// Decrypt a peer's `CookieReply` and adopt the cookie inside it. Callers
    /// route the datagram here by its `receiver_index` (our own session index
    /// on the message we sent). On failure nothing is adopted — a bad reply
    /// cannot clear a cookie we already hold.
    pub fn consumeReply(
        self: *PeerCookie,
        reply: CookieReply,
        now_s: u64,
    ) ConsumeReplyError!void {
        const aad = self.last_sent_mac1 orelse return error.NoPendingMessage;
        var cookie: noise.Mac = undefined;
        noise.XAead.decrypt(
            &cookie,
            reply.encrypted_cookie[0..16],
            reply.encrypted_cookie[16..32].*,
            &aad,
            reply.nonce,
            self.cookie_key,
        ) catch return error.DecryptionFailed;
        self.cookie = cookie;
        self.cookie_born_s = now_s;
    }

    /// The cookie to stamp into `Handshake.cookie`, or null once it has aged
    /// past `cookie_lifetime_s` (or the clock moved backwards) — at which
    /// point the protocol says to go back to an all-zero mac2 rather than send
    /// one the peer will reject.
    pub fn current(self: *const PeerCookie, now_s: u64) ?noise.Mac {
        const cookie = self.cookie orelse return null;
        if (now_s < self.cookie_born_s) return null;
        if (now_s - self.cookie_born_s >= cookie_lifetime_s) return null;
        return cookie;
    }
};

