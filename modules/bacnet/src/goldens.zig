        const d = try decodeAll(try bytesOf(find("readproperty_ack_string"), &buf));
        const ack = try service.ReadPropertyAck.decode(d.apdu.complex_ack.data);
        try testing.expectEqual(types.PropertyIdentifier.object_name, ack.property);
