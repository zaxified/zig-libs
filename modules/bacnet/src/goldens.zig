const testing = std.testing;

fn bytesOf(g: Golden, buf: []u8) ![]u8 {
    return std.fmt.hexToBytes(buf, g.hex);
}

/// Decodes a golden datagram down to the APDU, returning the layers.
const Decoded = struct {
    bvlc: bvll.Message,
    npdu: npdu.Npdu,
    apdu: apdu.Apdu,
};

fn decodeAll(dgram: []const u8) !Decoded {
    const b = try bvll.decode(dgram);
    const n = try npdu.decode(b.npdu().?);
    const a = try apdu.decode(n.payload.apdu);
    return .{ .bvlc = b, .npdu = n, .apdu = a };
}

test "goldens: every third-party datagram decodes at all four layers" {
    var buf: [256]u8 = undefined;
    for (wire) |g| {
        const dgram = try bytesOf(g, &buf);
        const d = decodeAll(dgram) catch |e| {
            std.debug.print("golden '{s}' failed to decode: {t}\n", .{ g.name, e });
            return e;
        };
        // Every one of them is a plain NPDU with no routing fields and
        // protocol version 1 — that is what a same-subnet exchange looks like.
        try testing.expectEqual(@as(usize, 2), d.npdu.header_len);
        // And every APDU's service body is reachable (i.e. nothing is
        // segmented in this table).
        try testing.expect(!d.apdu.isSegmented());
        _ = try d.apdu.serviceData();
    }
}

test "goldens: every datagram re-encodes to the identical octets" {
    var buf: [256]u8 = undefined;
    var out: [256]u8 = undefined;
    for (wire) |g| {
        const dgram = try bytesOf(g, &buf);
        const d = try decodeAll(dgram);

        // Rebuild from the decoded APDU, not from the input slice.
        var a_buf: [256]u8 = undefined;
        const a = try apdu.encode(d.apdu, &a_buf);
        var n_buf: [256]u8 = undefined;
        const n = try npdu.encode(d.npdu.npci, a, &n_buf);
        const again = try bvll.encode(switch (d.bvlc.function()) {
            .original_unicast_npdu => .{ .original_unicast_npdu = n },
            .original_broadcast_npdu => .{ .original_broadcast_npdu = n },
            else => unreachable,
        }, &out);
        testing.expectEqualSlices(u8, dgram, again) catch |e| {
            std.debug.print("golden '{s}' did not round-trip\n", .{g.name});
            return e;
        };
    }
}

test "goldens: every primitive tag decodes and re-encodes identically" {
    var buf: [32]u8 = undefined;
    var out: [32]u8 = undefined;
    for (primitives) |g| {
        const bytes = try bytesOf(g, &buf);
        const t = tag.decodeHeader(bytes) catch |e| {
            std.debug.print("primitive '{s}' header failed: {t}\n", .{ g.name, e });
            return e;
        };
        const n = try tag.encodeHeader(t, &out);
        testing.expectEqualSlices(u8, bytes[0..n], out[0..n]) catch |e| {
            std.debug.print("primitive '{s}' header not canonical\n", .{g.name});
            return e;
        };

        // Application-tagged ones must also survive a value round trip.
        if (t.class == .application and t.form == .primitive) {
            var r = tag.Reader.init(bytes);
            const v = try r.appValue();
            try testing.expect(r.atEnd());
            var w = tag.Writer.init(&out);
            w.appValue(v) catch |e| {
                std.debug.print("primitive '{s}' value re-encode failed: {t}\n", .{ g.name, e });
                return e;
            };
            testing.expectEqualSlices(u8, bytes, w.written()) catch |e| {
                std.debug.print("primitive '{s}' value not byte-identical\n", .{g.name});
                return e;
            };
        }
    }
}

fn find(name: []const u8) Golden {
    for (wire) |g| {
        if (std.mem.eql(u8, g.name, name)) return g;
    }
    unreachable;
}

test "goldens field by field: discovery" {
    var buf: [256]u8 = undefined;

    {
        const d = try decodeAll(try bytesOf(find("whois_unbounded"), &buf));
        try testing.expectEqual(bvll.Function.original_broadcast_npdu, d.bvlc.function());
        const u = d.apdu.unconfirmed_request;
        try testing.expectEqual(types.UnconfirmedService.who_is, u.service);
        const wi = try service.WhoIs.decode(u.data);
        try testing.expectEqual(@as(?u32, null), wi.low);
        try testing.expect(wi.matches(0) and wi.matches(4194303));
    }
    {
        const d = try decodeAll(try bytesOf(find("whois_range_1_100"), &buf));
        const wi = try service.WhoIs.decode(d.apdu.unconfirmed_request.data);
        try testing.expectEqual(@as(?u32, 1), wi.low);
        try testing.expectEqual(@as(?u32, 100), wi.high);
    }
    {
        // The wide form: high limit is the 22-bit maximum, encoded in 3
        // octets (`1b 3f ff ff`), which is the boundary an implementation that
        // hardcodes 4-octet unsigneds gets wrong.
        const d = try decodeAll(try bytesOf(find("whois_wide"), &buf));
        const wi = try service.WhoIs.decode(d.apdu.unconfirmed_request.data);
        try testing.expectEqual(@as(?u32, 0), wi.low);
        try testing.expectEqual(@as(?u32, 4194303), wi.high);
    }
    {
        const d = try decodeAll(try bytesOf(find("iam_599"), &buf));
        const iam = try service.IAm.decode(d.apdu.unconfirmed_request.data);
        try testing.expect(iam.device.eql(.{ .type = .device, .instance = 599 }));
        try testing.expectEqual(@as(u32, 1476), iam.max_apdu_accepted);
        try testing.expectEqual(types.Segmentation.none, iam.segmentation);
        try testing.expectEqual(@as(u16, 999), iam.vendor_id);
    }
    {
        const d = try decodeAll(try bytesOf(find("iam_segmented"), &buf));
        const iam = try service.IAm.decode(d.apdu.unconfirmed_request.data);
        try testing.expectEqual(tag.ObjectId.unconfigured_instance, iam.device.instance);
        try testing.expectEqual(@as(u32, 480), iam.max_apdu_accepted);
        try testing.expectEqual(types.Segmentation.both, iam.segmentation);
    }
    {
        const d = try decodeAll(try bytesOf(find("whohas_by_name"), &buf));
        const wh = try service.WhoHas.decode(d.apdu.unconfirmed_request.data);
        try testing.expectEqualStrings("ZONE-TEMP", wh.target.object_name);
        try testing.expectEqual(@as(?u32, null), wh.low);
    }
    {
        const d = try decodeAll(try bytesOf(find("whohas_by_id"), &buf));
        const wh = try service.WhoHas.decode(d.apdu.unconfirmed_request.data);
        try testing.expect(wh.target.object_id.eql(.{ .type = .analog_input, .instance = 3 }));
        try testing.expectEqual(@as(?u32, 1), wh.low);
        try testing.expectEqual(@as(?u32, 100), wh.high);
    }
    {
        const d = try decodeAll(try bytesOf(find("ihave"), &buf));
        const ih = try service.IHave.decode(d.apdu.unconfirmed_request.data);
        try testing.expect(ih.device.eql(.{ .type = .device, .instance = 599 }));
        try testing.expect(ih.object.eql(.{ .type = .analog_input, .instance = 3 }));
        try testing.expectEqualStrings("ZONE-TEMP", ih.object_name);
    }
}

