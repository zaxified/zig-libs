    var buf: [256]u8 = undefined;
    {
        const d = try decodeAll(try bytesOf(find("readproperty_req"), &buf));
        const r = d.apdu.confirmed_request;
        try testing.expectEqual(@as(u8, 1), r.invoke_id);
        try testing.expectEqual(types.ConfirmedService.read_property, r.service);
        try testing.expectEqual(apdu.MaxApdu.up_to_1476, r.max_apdu);
        try testing.expectEqual(apdu.MaxSegments.unspecified, r.max_segments);
        try testing.expectEqual(@as(?apdu.SegmentInfo, null), r.segment);
        const rp = try service.ReadProperty.decode(r.data);
        try testing.expect(rp.object.eql(.{ .type = .analog_input, .instance = 5 }));
        try testing.expectEqual(types.PropertyIdentifier.present_value, rp.property);
        try testing.expectEqual(@as(?u32, null), rp.array_index);
    }
    {
        const d = try decodeAll(try bytesOf(find("readproperty_req_arrayindex"), &buf));
