//! **Byte-exact goldens produced by an independent BACnet stack.**
//!
//! Every datagram in `wire` was emitted by Python **bacpypes3 0.0.106**
//! (Joel Bender; the reference open-source BACnet implementation), driven as a
//! black box: build the service object, let it encode through its own APDU →
//! NPDU → BVLC layers, print the octets. Nothing in this module was derived
//! from those octets — they are the oracle, checked against afterwards.
//!
//! Three assertions run over the whole table, and they are what makes it a
//! test rather than a data dump:
//!
//! 1. **Every datagram decodes** — BVLC, NPDU, APDU, and the service body.
//! 2. **Every datagram re-encodes to the identical octets**, rebuilt from the
//!    *decoded* fields through this module's own writers. So it is the
//!    encoder being checked, not a memcpy.
//! 3. **A representative subset is asserted field by field** against what the
//!    frame is supposed to mean.
//!
//! See SPEC.md for what is third-party-validated versus self-derived, and for
//! the live-interop story.

