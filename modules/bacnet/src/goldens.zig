test "goldens: the table covers every PDU type and every modelled service" {
    var buf: [256]u8 = undefined;
    var seen_pdu = std.EnumSet(apdu.PduType).initEmpty();
    var seen_confirmed = std.AutoHashMap(types.ConfirmedService, void).init(testing.allocator);
    defer seen_confirmed.deinit();
    var seen_unconfirmed = std.AutoHashMap(types.UnconfirmedService, void).init(testing.allocator);
    defer seen_unconfirmed.deinit();

    for (wire) |g| {
        const d = try decodeAll(try bytesOf(g, &buf));
        seen_pdu.insert(d.apdu.pduType());
        switch (d.apdu) {
            .confirmed_request => |r| try seen_confirmed.put(r.service, {}),
            .unconfirmed_request => |u| try seen_unconfirmed.put(u.service, {}),
            .complex_ack => |c| try seen_confirmed.put(c.service, {}),
            .simple_ack => |s| try seen_confirmed.put(s.service, {}),
            else => {},
        }
    }

    // Seven of the eight PDU types are here; SegmentACK is not, because
    // nothing in this module produces or consumes a segmented transfer (see
    // SPEC.md's deferred list) and a golden for it would be self-derived.
    for ([_]apdu.PduType{
        .confirmed_request, .unconfirmed_request, .simple_ack,
        .complex_ack,       .err,                 .reject,
        .abort,
    }) |t| {
        try testing.expect(seen_pdu.contains(t));
    }
    try testing.expect(!seen_pdu.contains(.segment_ack));

    for ([_]types.ConfirmedService{
        .read_property, .read_property_multiple,     .write_property,
        .subscribe_cov, .confirmed_cov_notification, .read_range,
    }) |s| {
        try testing.expect(seen_confirmed.contains(s));
    }
    for ([_]types.UnconfirmedService{
        .who_is, .i_am, .who_has, .i_have, .unconfirmed_cov_notification,
    }) |s| {
        try testing.expect(seen_unconfirmed.contains(s));
    }
}
