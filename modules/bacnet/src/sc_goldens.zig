fn bytes(g: Golden, buf: []u8) []u8 {
    return std.fmt.hexToBytes(buf, g.hex) catch unreachable;
}

/// Looks a golden up by name. Indices into `wire` would silently point at the
/// wrong frame the moment a vector is inserted; a name cannot.
fn named(comptime name: []const u8) Golden {
    const index = comptime blk: {
        for (wire, 0..) |g, i| {
            if (std.mem.eql(u8, g.name, name)) break :blk i;
        }
        @compileError("no golden named " ++ name);
    };
    return wire[index];
}

// ── tests ──────────────────────────────────────────────────────────────────

const testing = std.testing;

test "every third-party frame decodes" {
    var buf: [256]u8 = undefined;
    for (wire) |g| {
        const frame = bytes(g, &buf);
        _ = sc.decode(frame) catch |e| {
            std.debug.print("golden {s} failed to decode: {t}\n", .{ g.name, e });
            return e;
        };
    }
}

test "every third-party frame re-encodes to the identical octets" {
    // Rebuilt from the *decoded* fields through this module's own writer, so a
    // regression in the encoder cannot hide behind a memcpy of the input.
    var buf: [256]u8 = undefined;
    var out: [256]u8 = undefined;
    for (wire) |g| {
        const frame = bytes(g, &buf);
        const msg = try sc.decode(frame);
        const again = try sc.encode(msg, &out);
        testing.expectEqualSlices(u8, frame, again) catch |e| {
            std.debug.print("golden {s} did not round-trip\n", .{g.name});
            return e;
        };
    }
}

test "the golden table covers all thirteen BVLC functions" {
    var seen = [_]bool{false} ** 13;
    var buf: [256]u8 = undefined;
    for (wire) |g| {
        const msg = try sc.decode(bytes(g, &buf));
        seen[@intFromEnum(msg.function())] = true;
    }
    for (seen, 0..) |ok, i| {
        if (!ok) {
            std.debug.print("no golden for BVLC function 0x{x:0>2}\n", .{i});
            return error.MissingCoverage;
        }
    }
}

test "field by field: connect_request" {
    var buf: [64]u8 = undefined;
    const msg = try sc.decode(bytes(named("connect_request"), &buf));
    try testing.expectEqual(@as(u16, 1), msg.header.message_id);
    try testing.expectEqual(@as(?sc.Vmac, null), msg.header.source);
    const c = msg.payload.connect_request;
    try testing.expectEqualSlices(u8, &.{ 1, 2, 3, 4, 5, 6 }, &c.vmac.octets);
    var text: [40]u8 = undefined;
    try testing.expectEqualStrings(
        "00112233-4455-6677-8899-aabbccddeeff",
        try std.fmt.bufPrint(&text, "{f}", .{c.uuid}),
    );
    try testing.expectEqual(@as(u16, 1400), c.max_bvlc_length);
    try testing.expectEqual(@as(u16, 1300), c.max_npdu_length);
}

test "field by field: the maximum connect proposal" {
    var buf: [64]u8 = undefined;
    const msg = try sc.decode(bytes(named("connect_request_max"), &buf));
    try testing.expectEqual(@as(u16, 0xABCD), msg.header.message_id);
    try testing.expect(msg.header.source != null);
    try testing.expectEqual(@as(u16, 65535), msg.payload.connect_request.max_bvlc_length);
    try testing.expectEqual(@as(u16, 65535), msg.payload.connect_request.max_npdu_length);
}

test "field by field: advertisement, all three hub states" {
    var buf: [64]u8 = undefined;
    const primary = try sc.decode(bytes(named("advertisement"), &buf));
    try testing.expectEqual(sc.HubConnectionStatus.connected_to_primary, primary.payload.advertisement.hub_status);
    try testing.expectEqual(sc.DirectConnectionSupport.supported, primary.payload.advertisement.direct_connections);
    try testing.expectEqual(@as(u16, 1400), primary.payload.advertisement.max_bvlc_length);

    const none = try sc.decode(bytes(named("advertisement_nohub"), &buf));
    try testing.expectEqual(sc.HubConnectionStatus.no_hub_connection, none.payload.advertisement.hub_status);
    try testing.expectEqual(sc.DirectConnectionSupport.unsupported, none.payload.advertisement.direct_connections);
    try testing.expectEqual(@as(u16, 1497), none.payload.advertisement.max_bvlc_length);
    try testing.expectEqual(@as(u16, 1476), none.payload.advertisement.max_npdu_length);

    const failover = try sc.decode(bytes(named("advertisement_failover"), &buf));
    try testing.expectEqual(sc.HubConnectionStatus.connected_to_failover, failover.payload.advertisement.hub_status);
    try testing.expectEqualSlices(u8, &.{ 1, 2, 3, 4, 5, 6 }, &failover.header.source.?.octets);
}

test "field by field: the NAK's error block" {
    var buf: [64]u8 = undefined;
    const msg = try sc.decode(bytes(named("result_nak"), &buf));
    const r = msg.payload.result;
    try testing.expectEqual(sc.Function.connect_request, r.function);
    try testing.expectEqual(sc.ResultCode.nak, r.code);
    try testing.expectEqual(types.ErrorClass.communication, r.err.?.class);
    try testing.expectEqual(types.ErrorCode.node_duplicate_vmac, r.err.?.code);
    try testing.expectEqualStrings("duplicate", r.err.?.details);
}

test "field by field: an option list of two, with the more bit chaining them" {
    var buf: [64]u8 = undefined;
    const msg = try sc.decode(bytes(named("encapsulated_two_options"), &buf));
    var it = sc.optionIterator(msg.header.destination_options);
    const first = (try it.next()).?;
    try testing.expectEqual(sc.OptionType.secure_path, first.type);
    try testing.expect(first.must_understand);
    try testing.expectEqual(@as(?[]const u8, null), first.data);
    const second = (try it.next()).?;
    const p = try second.asProprietary();
    try testing.expectEqual(@as(u16, 1), p.vendor_id);
    try testing.expectEqual(@as(u8, 0), p.option_type);
    try testing.expectEqual(@as(usize, 0), p.data.len);
    try testing.expectEqual(@as(?sc.Option, null), try it.next());
    try testing.expectEqualSlices(u8, &.{ 0x01, 0x00 }, msg.payload.encapsulated_npdu);
}

test "field by field: both option lists and both VMACs at once" {
    var buf: [64]u8 = undefined;
    const msg = try sc.decode(bytes(named("encapsulated_all_fields"), &buf));
    try testing.expectEqual(@as(u8, 0x0F), msg.header.controlOctet());
    try testing.expectEqual(@as(usize, 1), msg.header.destination_options.len);
    try testing.expectEqual(@as(usize, 1), msg.header.data_options.len);
    try testing.expect(msg.header.hasSecurePath());
    try testing.expectEqual(@as(?sc.Option, null), try msg.header.unsupportedOption());
}

test "the bodies are rebuilt from scratch, not carried along as opaque octets" {
    // Encoding from freshly-constructed values, with no decode in the loop,
    // is what proves the *encoder* agrees with the oracle rather than the
    // decoder agreeing with itself.
    var out: [64]u8 = undefined;

    const cr: sc.Message = .{
        .header = .{ .message_id = 1 },
        .payload = .{ .connect_request = .{
            .vmac = .{ .octets = .{ 1, 2, 3, 4, 5, 6 } },
            .uuid = sc.Uuid.parse("00112233-4455-6677-8899-aabbccddeeff").?,
            .max_bvlc_length = 1400,
            .max_npdu_length = 1300,
        } },
    };
    var expect: [64]u8 = undefined;
    try testing.expectEqualSlices(
        u8,
        bytes(named("connect_request"), &expect),
        try sc.encode(cr, &out),
    );

    const adv: sc.Message = .{
        .header = .{ .message_id = 5 },
        .payload = .{ .advertisement = .{
            .hub_status = .connected_to_primary,
            .direct_connections = .supported,
            .max_bvlc_length = 1400,
            .max_npdu_length = 1300,
        } },
    };
    try testing.expectEqualSlices(
        u8,
        bytes(named("advertisement"), &expect),
        try sc.encode(adv, &out),
    );

    const bad = sc.nak(.connect_request, 1, null, null, .{
        .header_marker = 0,
        .class = .communication,
        .code = .node_duplicate_vmac,
        .details = "duplicate",
    });
    try testing.expectEqualSlices(
        u8,
        bytes(named("result_nak"), &expect),
        try sc.encode(bad, &out),
    );

    const pm: sc.Message = .{
        .header = .{ .message_id = 0x00AA },
        .payload = .{ .proprietary_message = .{
            .vendor_id = 999,
            .function = 42,
            .data = &.{ 0xDE, 0xAD, 0xBE, 0xEF },
        } },
    };
    try testing.expectEqualSlices(
        u8,
        bytes(named("proprietary_message"), &expect),
        try sc.encode(pm, &out),
    );
}

test "the header option list is rebuilt from scratch too" {
    var data: [8]u8 = undefined;
    const pd = try sc.encodeProprietaryOptionData(
        .{ .vendor_id = 1, .option_type = 0, .data = &.{} },
        &data,
    );
    var list: [16]u8 = undefined;
    const opts = try sc.encodeOptions(&.{
        sc.Option.secure_path,
        .{ .type = .proprietary, .must_understand = false, .data = pd },
    }, &list);

    const msg: sc.Message = .{
        .header = .{ .message_id = 0x0103, .destination_options = opts },
        .payload = .{ .encapsulated_npdu = &.{ 0x01, 0x00 } },
    };
    var out: [64]u8 = undefined;
    var expect: [64]u8 = undefined;
    try testing.expectEqualSlices(
        u8,
        bytes(named("encapsulated_two_options"), &expect),
        try sc.encode(msg, &out),
    );
}

test "bacnet_stack_divergence: a second oracle disagrees on byte order only" {
    // These four frames came from bacnet-stack's `bvlc-sc.c`, compiled and run
    // as a black box for exactly the same inputs as the bacpypes3 goldens
    // above. Every structural decision matches; every 16-bit field is byte
    // swapped. The test states that as fact so the decision to follow
    // bacpypes3 and Wireshark (big-endian) stays visible and reviewable rather
    // than living in a comment.
    var buf: [64]u8 = undefined;

    // bacnet-stack's Heartbeat-Request with message id 1.
    const hb = try sc.decode(std.fmt.hexToBytes(&buf, "0a000100") catch unreachable);
    try testing.expectEqual(sc.Function.heartbeat_request, hb.function());
    // Big-endian reading: 0x0100. Little-endian would have been 1.
    try testing.expectEqual(@as(u16, 0x0100), hb.header.message_id);

    // ... and its Connect-Request, whose maxima come out byte-swapped.
    const cr = try sc.decode(std.fmt.hexToBytes(
        &buf,
        "0600010001020304050600112233445566778899aabbccddeeff78051405",
    ) catch unreachable);
    try testing.expectEqual(@as(u16, 0x7805), cr.payload.connect_request.max_bvlc_length);
    try testing.expectEqual(@as(u16, 0x1405), cr.payload.connect_request.max_npdu_length);

    // The two stacks *do* agree octet for octet whenever every 16-bit field is
    // a palindrome — message id 0x0101 here — which isolates the disagreement
    // to byte order and nothing else.
    const both_agree = "01010101410100";
    const decoded = try sc.decode(std.fmt.hexToBytes(&buf, both_agree) catch unreachable);
    try testing.expectEqual(@as(u16, 0x0101), decoded.header.message_id);
    try testing.expect(decoded.header.hasSecurePath());
    var out: [32]u8 = undefined;
    try testing.expectEqualSlices(
        u8,
        std.fmt.hexToBytes(buf[32..], both_agree) catch unreachable,
        try sc.encode(decoded, &out),
    );
}
