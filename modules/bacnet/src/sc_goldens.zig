//! **Byte-exact BACnet/SC goldens, and the byte-order question they settled.**
//!
//! Every frame in `wire` was emitted by Python **bacpypes3 0.0.106**'s
//! `bacpypes3.sc.bvll` encoders, driven as a black box: construct the LPDU,
//! set its header fields, call `encode()`, print the octets. Nothing in
//! `sc.zig` was derived from them — they are the oracle, checked against
//! afterwards.
//!
//! Three assertions run over the whole table:
//!
//! 1. **Every frame decodes**, header and body.
//! 2. **Every frame re-encodes to the identical octets** from its *decoded*
//!    fields, through this module's own writer. So it is the encoder under
//!    test, not a memcpy.
//! 3. **A representative subset is asserted field by field**, and a coverage
//!    test asserts the table really does contain all thirteen BVLC functions
//!    so it cannot silently rot.
//!
//! ## The byte-order finding
//!
//! A **second** independent implementation was compiled and driven as an
//! oracle: `bvlc-sc.c` from the **bacnet-stack** project (C, GPL-2.0 with
//! linking exception; nothing was copied — it was compiled and run through its
//! published prototypes). The two stacks agree on **every structural
//! question** — field order, field widths, which control bit means what, the
//! option marker's bit layout, that the option Header Length is two octets,
//! that destination options precede data options which precede the payload,
//! and that a `BVLC-Result` NAK is marker/class/code/details with no
//! terminator on the details string.
//!
//! They disagree on exactly one thing: bacnet-stack writes every 16-bit field
//! (message id, option header length, the connect maxima, the error class and
//! code, the proprietary vendor id) **little-endian**; bacpypes3 writes them
//! **big-endian**. Wireshark 4.6.4's `packet-bvlc.c` BACnet/SC dissector — a
//! third, independent reading of Annex AB — dissects all of them with
//! `ENC_BIG_ENDIAN`, and big-endian is BACnet's convention everywhere else
//! (Annex J's BVLC length, the NPDU's DNET/SNET, every clause 20.2 multi-octet
//! value). **This module is big-endian.** `bacnet_stack_divergence` below
//! records the disagreement as a live test rather than a comment, so the
//! decision stays visible.
//!
//! See SPEC.md for what is third-party-validated versus self-derived.

const std = @import("std");
const types = @import("types.zig");
const sc = @import("sc.zig");

pub const Golden = struct {
    name: []const u8,
    /// One complete BACnet/SC BVLC message — what would ride in one binary
    /// WebSocket frame.
    hex: []const u8,
};

