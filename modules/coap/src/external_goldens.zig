//! **External anchor: real CoAP (RFC 7252) datagrams, captured once from a
//! real client and a real server, frozen here and asserted offline.**
//!
//! Before this file, README/SPEC described this module as clean-room from
//! RFC 7252 with NO third-party CoAP source consulted — true, but it also
//! meant every golden datagram, every option encoding, the block-wise
//! transfers and the Observe registration were ALL self-authored and
//! self-round-tripped (`serialize` → `parse` → compare with the original).
//! A misreading of the spec shared between our encoder and our decoder is
//! invisible to that. This file closes the gap with datagrams this module
//! never produced, from two independent real CoAP implementations:
//!
//!   * `aiocoap-client` (aiocoap 0.4.17) — a real, independent CoAP client.
//!   * a real `aiocoap.resource.Site` server (same aiocoap version), exposing
//!     a plain resource, a large resource (forces automatic Block2), a PUT
//!     target (forces automatic Block1), and an `ObservableResource`.
//!
//! ## What was captured, and how
//! Real UDP sessions on loopback (`127.0.0.1`, ephemeral high ports),
//! captured with a byte-logging UDP proxy sitting between the two (neither
//! side is ours) — `aiocoap-client` talking to the real server through it:
//!
//!   1. **Plain GET** `/hello` → `2.05 Content` with a short text body.
//!   2. **Block2 GET** `/big` (a 3000-byte resource) — the server volunteers
//!      Block2 at the default SZX 6 (1024 B) with no Block2 option on the
//!      client's first request; the client then requests block 1 and 2 by
//!      number. Three full request/response pairs, byte-exact, are frozen —
//!      the complete real transfer, not a hand-picked fragment.
//!   3. **Block1 PUT** `/data` (a 3000-byte body) — the client volunteers
//!      Block1 unprompted; its FIRST request additionally chains a
//!      **Size1** option (value 3000) in the same datagram — a real
//!      3-option delta chain (Uri-Path → Block1 → Size1) this module's own
//!      hand-built tests never produced (Size1 is a one-time hint, not
//!      repeated on later blocks). The
//!      server answers `2.31 Continue` on non-final blocks, `2.04 Changed`
//!      on the last — exactly this module's own `server.piggyback` pattern,
//!      now driven by a real client. (Payload is a uniform `'X' * 3000`
//!      body with no interesting entropy; each request is frozen with only
//!      its first 64 payload bytes to keep this file's size proportionate —
//!      the header + option chain, the actual information this test
//!      anchors, is complete and untouched. The real total length is
//!      recorded alongside each block.)
//!   4. **Observe** `/obs` — register (Observe: 0 on GET), then the server
//!      pushes two live notifications (Observe: 1, 2) after a separate
//!      process calls `POST /bump`, each a fresh CONfirmable message (new
//!      message id, same token) that the client empty-ACKs — the actual
//!      live push this module's own C7 tests could only simulate by calling
//!      `Sequence.next()` and `Server.separate` by hand.
//!   5. **Multi-byte Block value** — `/big` regenerated at 17000 bytes (17
//!      blocks) so block 16 needs a **2-byte** Block2 value (`NUM=16`
//!      doesn't fit the 4-bit single-byte NUM field) — this module's own
//!      hand-built Block tests round-trip multi-byte NUM through its OWN
//!      encoder/decoder pair, which (see the teeth-check below) proves
//!      nothing about whether that pair's byte convention matches anyone
//!      else's. This is a real peer's actual multi-byte encoding.
//!
//! ## A real (non-bug) finding: Uri-Host is never elided
//! RFC 7252 §6.4 says Uri-Host "SHOULD" be elided when it exactly matches
//! the destination the request is sent to. `aiocoap-client` does this (the
//! captured `hello_get` below has NO Uri-Host option at all, even though the
//! request goes to `coap://127.0.0.1:...`) — matching its own
//! `--no-set-hostname` flag description. This module's
//! `options.optionsFromUri` always emits Uri-Host unconditionally; it never
//! elides. Not a bug (both are spec-legal; eliding is a SHOULD, not a MUST)
//! but a genuine interop/efficiency gap surfaced only by comparing against
//! a real client's request shape — see the cross-encoder check below, which
//! therefore compares against a manually-built `coap.Message` (matching
//! `aiocoap`'s shape) rather than `client.Client.buildRequest`'s output.
//!
//! ## Attribution
//! Running installed `aiocoap` (client CLI + library server) purely as a
//! black-box protocol peer — never consulting or copying its source — needs
//! no `NOTICE` entry; root `NOTICE` §0 exempts this explicitly, the same
//! pattern already applied to `protobuf`, `syslog`, `opcua`, `wireguard`.
//!
//! Capture host: Linux 7.0.0-28-generic x86-64. `aiocoap` 0.4.17 (default
//! transport tuning: `MAX_REGULAR_BLOCK_SIZE_EXP` = 6 ⇒ 1024-byte blocks).

