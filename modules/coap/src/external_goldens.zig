// ── 2. Block2 GET: full real 3-block reassembly ─────────────────────────────

fn bigFormula(i: usize) u8 {
    return @truncate(i *% 31 +% 7);
}

test "external: aiocoap Block2 GET /big -- full real 3-block transfer reassembles exactly" {
    const reqs = [_][]const u8{ bytes.big3000_get_b0, bytes.big3000_get_b1, bytes.big3000_get_b2 };
    const resps = [_][]const u8{ bytes.big3000_resp_b0, bytes.big3000_resp_b1, bytes.big3000_resp_b2 };

    var store: [4096]u8 = undefined;
    var reasm = block.Assembler.init(&store);

    for (reqs, resps, 0..) |req_bytes, resp_bytes, i| {
        var qopts: [4]coap.Option = undefined;
        const req = try coap.parse(req_bytes, &qopts);
        try testing.expectEqual(coap.Code.get, req.code);
        var found_path = false;
        for (req.options) |o| {
            if (o.number == options.number.uri_path) {
                try testing.expectEqualStrings("big", o.value);
                found_path = true;
            }
            if (o.number == options.number.block2 and i > 0) {
                const b = try block.Block.decode(o.value);
                try testing.expectEqual(@as(u32, @intCast(i)), b.num);
            }
        }
        try testing.expect(found_path);

        var ropts: [4]coap.Option = undefined;
        const resp = try coap.parse(resp_bytes, &ropts);
        try testing.expectEqual(coap.Code.content, resp.code);
        try testing.expectEqualSlices(u8, req.token, resp.token);
        var blk: ?block.Block = null;
        for (resp.options) |o| {
            if (o.number == options.number.block2) blk = try block.Block.decode(o.value);
        }
        const b = blk.?;
        try testing.expectEqual(@as(u32, @intCast(i)), b.num);
        try testing.expectEqual(@as(u3, 6), b.szx); // 1024-byte blocks
        try testing.expectEqual(i < 2, b.more);

        try reasm.accept(b, resp.payload);
    }

    try testing.expect(reasm.isComplete());
    try testing.expectEqual(@as(usize, 3000), reasm.payload().len);
    for (reasm.payload(), 0..) |got, i| {
        try testing.expectEqual(bigFormula(i), got);
    }
}

// ── 3. Block1 PUT: real chained Block1+Size1 option delta ──────────────────

test "external: aiocoap Block1 PUT /data -- real Block1+Size1 chain, server answers 2.31/2.04" {
    const reqs = [_][]const u8{ bytes.data_put_b0, bytes.data_put_b1, bytes.data_put_b2 };
    const resps = [_][]const u8{ bytes.data_resp_b0, bytes.data_resp_b1, bytes.data_resp_b2 };
    const real_lens = [_]usize{ bytes.data_put_b0_real_payload_len, bytes.data_put_b1_real_payload_len, bytes.data_put_b2_real_payload_len };

    // Each request here is frozen with only its first 64 real payload bytes
    // (see the module doc comment) -- offsets num*1024 no longer line up
    // contiguously across blocks, so running every block through one
    // `Assembler` (or even a fresh one per non-zero-offset block) would
    // reject block 1/2 as non-contiguous — correctly: this file doesn't
    // actually carry the intervening bytes. `Assembler` is exercised on
    // block 0 alone below (offset 0 is trivially contiguous); blocks 1/2 are
    // checked directly against their real decoded fields instead.

    for (reqs, resps, real_lens, 0..) |req_bytes, resp_bytes, real_len, i| {
        var qopts: [4]coap.Option = undefined;
        const req = try coap.parse(req_bytes, &qopts);
        try testing.expectEqual(coap.Code.put, req.code);

        var blk1: ?block.Block = null;
        var size1: ?u64 = null;
        for (req.options) |o| {
            if (o.number == options.number.block1) blk1 = try block.Block.decode(o.value);
            // Real 3-option chain: Uri-Path(11) -> Block1(27) -> Size1(60),
            // spanning two consecutive extended-nibble deltas in one
            // datagram -- never produced by this module's own hand-built
            // option-boundary tests.
            if (o.number == options.number.size1) size1 = options.decodeUint(o.value);
        }
        try testing.expectEqual(@as(u32, @intCast(i)), blk1.?.num);
        try testing.expectEqual(@as(u3, 6), blk1.?.szx);
        try testing.expectEqual(i < 2, blk1.?.more);
        // Real aiocoap behavior: Size1 is only chained onto the FIRST Block1
        // request (a one-time hint), not repeated on every block.
        if (i == 0) {
            try testing.expectEqual(@as(u64, 3000), size1.?); // real total body size
        } else {
            try testing.expectEqual(@as(?u64, null), size1);
        }

        // Every truncated payload byte we DO have is the real 'X' (0x58)
        // content -- not merely "parsing succeeded".
        for (req.payload) |b| try testing.expectEqual(@as(u8, 'X'), b);

        if (i == 0) {
            // Offset 0 is trivially contiguous: exercise the real Assembler
            // against the real first-block descriptor + real bytes.
            var store: [128]u8 = undefined;
            var asm_ = block.Assembler.init(&store);
            try asm_.accept(blk1.?, req.payload);
            try testing.expect(!asm_.isComplete()); // more=true: not the final block
            try testing.expectEqual(req.payload.len, asm_.payload().len);
        }
        try testing.expectEqual(@as(usize, if (i == 2) 952 else 1024), real_len);

        var ropts: [4]coap.Option = undefined;
        const resp = try coap.parse(resp_bytes, &ropts);
        try testing.expectEqualSlices(u8, req.token, resp.token);
        if (i < 2) {
            try testing.expectEqual(coap.Code.@"continue", resp.code); // 2.31
        } else {
            try testing.expectEqual(coap.Code.changed, resp.code); // 2.04
        }
    }

    // Real total across the three blocks (truncated capture, full option
    // metadata): 1024 + 1024 + 952 = 3000, matching the first block's Size1.
    try testing.expectEqual(@as(usize, 1024 + 1024 + 952), bytes.data_put_b0_real_payload_len + bytes.data_put_b1_real_payload_len + bytes.data_put_b2_real_payload_len);
}

// ── 4. Observe: real registration + real live-pushed notifications ─────────

test "external: aiocoap Observe register + two REAL live-pushed notifications" {
    var reg_opts: [4]coap.Option = undefined;
    const reg = try coap.parse(bytes.observe_register, &reg_opts);
    try testing.expectEqual(coap.Code.get, reg.code);
    var registering = false;
    for (reg.options) |o| {
        if (o.number == options.number.observe) registering = observe.decodeValue(o.value) == observe.request.register;
    }
    try testing.expect(registering);

    var ack_opts: [4]coap.Option = undefined;
    const ack = try coap.parse(bytes.observe_register_ack, &ack_opts);
    try testing.expectEqual(coap.Type.ack, ack.type);
    try testing.expectEqualSlices(u8, reg.token, ack.token);
    var initial_seq: ?u24 = null;
    for (ack.options) |o| {
        if (o.number == options.number.observe) initial_seq = observe.decodeValue(o.value);
    }
    try testing.expectEqual(@as(u24, 0), initial_seq.?);
    try testing.expectEqualStrings("0", ack.payload);

    // Drive OUR OWN Registry/Sequence with the REAL notification sequence
    // numbers a live server actually pushed -- not hand-picked values.
    var storage: [2]observe.Registry.Entry = undefined;
    var reg_table = observe.Registry.init(&storage);
    _ = reg_table.register(reg.token, 1, initial_seq.?);

    const notifies = [_][]const u8{ bytes.observe_notify1, bytes.observe_notify2 };
    const acks = [_][]const u8{ bytes.observe_notify1_ack, bytes.observe_notify2_ack };
    const expect_payload = [_][]const u8{ "1", "2" };
    for (notifies, acks, expect_payload) |note_bytes, ack_bytes, want_payload| {
        var nopts: [4]coap.Option = undefined;
        const note = try coap.parse(note_bytes, &nopts);
        try testing.expectEqual(coap.Type.confirmable, note.type); // a fresh separate CON, not piggybacked
        try testing.expectEqualSlices(u8, reg.token, note.token); // same token, new message id
        try testing.expectEqualStrings(want_payload, note.payload);
        var seq: ?u24 = null;
        for (note.options) |o| {
            if (o.number == options.number.observe) seq = observe.decodeValue(o.value);
        }
        try testing.expectEqual(Registry_Update.accepted, reg_table.notify(reg.token, 1, seq.?).?);

        // The client's real empty-ACK echoes the notification's message id.
        var aopts: [1]coap.Option = undefined;
        const client_ack = try coap.parse(ack_bytes, &aopts);
        try testing.expectEqual(coap.Type.ack, client_ack.type);
        try testing.expectEqual(coap.Code.empty, client_ack.code);
        try testing.expectEqual(note.message_id, client_ack.message_id);
    }

    // A replay of the first (now stale) sequence is rejected by OUR freshness
    // check, anchored to real sequence values.
    var first_seq: u24 = undefined;
    {
        var nopts: [4]coap.Option = undefined;
        const note = try coap.parse(bytes.observe_notify1, &nopts);
        for (note.options) |o| {
            if (o.number == options.number.observe) first_seq = observe.decodeValue(o.value);
        }
    }
    try testing.expectEqual(Registry_Update.stale, reg_table.notify(reg.token, 1, first_seq).?);
}

const Registry_Update = observe.Registry.Update;

