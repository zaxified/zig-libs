#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Regenerate `src/rdata_vectors.zig`: TLSA, SSHFP, URI, NAPTR and SVCB/HTTPS
rdata rendered by dnspython (2.8.0 when last run) from presentation text and
pinned as goldens for `src/rdata.zig`.

    python3 -I modules/dns/tools/rdata_oracle.py > modules/dns/src/rdata_vectors.zig

The bytes are dnspython's `Rdata.to_wire()` (names uncompressed, as every
rdata of these types is); the expected fields are read off dnspython's parsed
objects, not off our parser. Needs dnspython -- a foreign toolchain the
module's tests must never require, which is why this lives in tools/
(CONVENTIONS.md §9).
"""

import io

import dns.rdata
import dns.rdtypes.svcbbase as sb
import dns.version


def zb(b):
    return '"' + "".join(f"\\x{c:02x}" for c in b) + '"'


def lst(items):
    """`&.{ a, b }` the way `zig fmt` writes it (no padding for 0 or 1 items)."""
    if not items:
        return "&.{}"
    if len(items) == 1:
        return f"&.{{{items[0]}}}"
    return "&.{ " + ", ".join(items) + " }"


def rd(ty, text):
    return dns.rdata.from_text("IN", ty, text)


def name_text(n):
    s = n.to_text()
    return "" if s == "." else s.rstrip(".")


out = []
w = out.append
w("// SPDX-License-Identifier: MIT")
w("")
w(f"//! GENERATED by `tools/rdata_oracle.py` from dnspython {dns.version.version} -- do not edit.")
w("//! Wire rdata of TLSA / SSHFP / URI / NAPTR / SVCB / HTTPS records and the")
w("//! field values dnspython parsed out of the same presentation text.")
w("")
w("pub const Tlsa = struct { wire: []const u8, usage: u8, selector: u8, matching: u8, data: []const u8 };")
w("pub const Sshfp = struct { wire: []const u8, algorithm: u8, fp_type: u8, fingerprint: []const u8 };")
w("pub const Uri = struct { wire: []const u8, priority: u16, weight: u16, target: []const u8 };")
w("pub const Naptr = struct { wire: []const u8, order: u16, preference: u16, flags: []const u8, services: []const u8, regexp: []const u8, replacement: []const u8 };")
w("pub const Param = struct { key: u16, value: []const u8 };")
w("pub const Svcb = struct {")
w("    /// 64 (SVCB) or 65 (HTTPS).")
w("    ty: u16,")
w("    wire: []const u8,")
w("    priority: u16,")
w("    target: []const u8,")
w("    params: []const Param,")
w("    alpn: ?[]const []const u8,")
w("    no_default_alpn: bool,")
w("    port: ?u16,")
w("    ipv4hint: ?[]const [4]u8,")
w("    ipv6hint: ?[]const [16]u8,")
w("    ech: ?[]const u8,")
w("    mandatory: ?[]const u16,")
w("};")
w("")

# ── TLSA ────────────────────────────────────────────────────────────────
w("pub const tlsa = [_]Tlsa{")
for t in [
    "3 1 1 " + "0f" * 8 + "a5" * 24,
    "0 0 0 3082010a0282010100",
    "2 0 2 " + "5c" * 64,
    "1 1 2 " + "e3" * 64,
]:
    r = rd("TLSA", t)
    w(f"    .{{ .wire = {zb(r.to_wire())}, .usage = {r.usage}, .selector = {r.selector}, .matching = {r.mtype}, .data = {zb(r.cert)} }},")
w("};")
w("")

# ── SSHFP ───────────────────────────────────────────────────────────────
w("pub const sshfp = [_]Sshfp{")
for t in ["1 1 " + "ab" * 20, "4 2 " + "12" * 32, "3 2 " + "fe" * 32]:
    r = rd("SSHFP", t)
    w(f"    .{{ .wire = {zb(r.to_wire())}, .algorithm = {r.algorithm}, .fp_type = {r.fp_type}, .fingerprint = {zb(r.fingerprint)} }},")
w("};")
w("")

# ── URI ─────────────────────────────────────────────────────────────────
w("pub const uri = [_]Uri{")
for t in [
    '10 1 "ftp://ftp1.example.com/public"',
    '20 5 "https://example.com/a?b=c"',
    '0 0 "x"',
]:
    r = rd("URI", t)
    w(f"    .{{ .wire = {zb(r.to_wire())}, .priority = {r.priority}, .weight = {r.weight}, .target = {zb(r.target)} }},")
w("};")
w("")

# ── NAPTR ───────────────────────────────────────────────────────────────
w("pub const naptr = [_]Naptr{")
for t in [
    '100 10 "u" "E2U+sip" "!^.*$!sip:info@example.com!" .',
    '10 100 "S" "SIP+D2U" "" _sip._udp.example.com.',
    '65535 0 "" "" "" .',
    '1 2 "a" "x" "!(.*)!\\\\1!" Mixed.Case.example.',
]:
    r = rd("NAPTR", t)
    w(f"    .{{ .wire = {zb(r.to_wire())}, .order = {r.order}, .preference = {r.preference}, .flags = {zb(r.flags)}, .services = {zb(r.service)}, .regexp = {zb(r.regexp)}, .replacement = {zb(name_text(r.replacement).encode())} }},")
w("};")
w("")

# ── SVCB / HTTPS ────────────────────────────────────────────────────────
ECH = "AEX+DQBBAAAgACBD7B5vD3DqrG6bpUQtT8Zl7s3pIuVvmuVgMbHnLhN0NQAEAAEAAQASY2xvdWRmbGFyZS1lY2guY29tAAA="
svcb_texts = [
    ("HTTPS", "1 . alpn=h2,h3 ipv4hint=104.16.132.229,104.16.133.229 ech=" + ECH + " ipv6hint=2606:4700::6810:84e5,2606:4700::6810:85e5"),
    ("HTTPS", "0 pool.svc.example.com."),
    ("SVCB", "1 foo.example.org. mandatory=alpn,ipv4hint alpn=h2,h3-29 ipv4hint=192.0.2.1"),
    ("HTTPS", "16 svc.example.net. no-default-alpn alpn=h3 port=8443"),
    ("SVCB", "2 . key65400=abc key667=hello"),
    ("HTTPS", "1 ."),
    ("SVCB", "3 Mixed.Case.example. mandatory=port port=0"),
]
w("pub const svcb = [_]Svcb{")
for ty, t in svcb_texts:
    r = rd(ty, t)
    params = []
    alpn = None
    nda = False
    port = None
    v4 = None
    v6 = None
    ech = None
    mand = None
    for k, p in r.params.items():
        b = io.BytesIO()
        if p is not None:  # dnspython stores an empty value (no-default-alpn) as None
            p.to_wire(b)
        params.append((int(k), b.getvalue()))
        if int(k) == 2:
            nda = True
        elif isinstance(p, sb.ALPNParam):
            alpn = list(p.ids)
        elif isinstance(p, sb.PortParam):
            port = p.port
        elif isinstance(p, sb.IPv4HintParam):
            v4 = [bytes(map(int, a.split("."))) for a in p.addresses]
        elif isinstance(p, sb.IPv6HintParam):
            import ipaddress
            v6 = [ipaddress.IPv6Address(a).packed for a in p.addresses]
        elif isinstance(p, sb.ECHParam):
            ech = p.ech
        elif isinstance(p, sb.MandatoryParam):
            mand = [int(x) for x in p.keys]
    params.sort()
    zty = 65 if ty == "HTTPS" else 64
    ps = lst([f".{{ .key = {k}, .value = {zb(v)} }}" for k, v in params])
    z_alpn = "null" if alpn is None else lst([zb(a) for a in alpn])
    z_v4 = "null" if v4 is None else lst([".{ " + ", ".join(str(c) for c in a) + " }" for a in v4])
    z_v6 = "null" if v6 is None else lst([".{ " + ", ".join(str(c) for c in a) + " }" for a in v6])
    z_ech = "null" if ech is None else zb(ech)
    z_m = "null" if mand is None else lst([str(x) for x in mand])
    w("    .{")
    w(f"        .ty = {zty},")
    w(f"        .wire = {zb(r.to_wire())},")
    w(f"        .priority = {r.priority},")
    w(f'        .target = "{name_text(r.target)}",')
    w(f"        .params = {ps},")
    w(f"        .alpn = {z_alpn},")
    w(f"        .no_default_alpn = {'true' if nda else 'false'},")
    w(f"        .port = {'null' if port is None else port},")
    w(f"        .ipv4hint = {z_v4},")
    w(f"        .ipv6hint = {z_v6},")
    w(f"        .ech = {z_ech},")
    w(f"        .mandatory = {z_m},")
    w("    },")
w("};")
print("\n".join(out))
