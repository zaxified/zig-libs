func main() {
	out := flag.String("out", "", "write the Zig vectors file here (default stdout)")
	flag.Parse()

	var b bytes.Buffer
	fmt.Fprintf(&b, "// SPDX-License-Identifier: MIT\n")
	fmt.Fprintf(&b, "// GENERATED by modules/dns/tools/go_oracle (%s, golang.org/x/net v0.59.0) -- do not hand-edit.\n", runtime.Version())
	fmt.Fprintf(&b, "//! dnsmessage verdicts on this module's own case tables, replayed by\n")
	fmt.Fprintf(&b, "//! `go_oracle.zig`. Regenerate with the command in tools/go_oracle/main.go.\n\n")
	b.WriteString(`/// A decoded message as text, one line per part, in the form both sides
/// render: header "id=.. qr=.. op=.. aa=.. tc=.. rd=.. ra=.. rcode=..",
/// question "name type class", record "name type class ttl RDATA" where RDATA
/// is "A a.b.c.d", "AAAA <hex>", "NS|CNAME|PTR name", "MX pref name",
/// "TXT <hex>,<hex>,..", "SOA mname rname serial refresh retry expire minimum",
/// "SRV prio weight port target", "OPT size ext version do <hex options>", or
/// "RAW <hex>" for any other type. Names carry no trailing dot; root is "".
pub const Case = struct {
    id: []const u8,
    bytes: []const u8,
    /// dnsmessage refused the message (Go's text); the rest is empty.
    err: ?[]const u8,
    header: []const u8,
    questions: []const []const u8,
    answers: []const []const u8,
    authorities: []const []const u8,
    additionals: []const []const u8,
};

/// A query dnsmessage's Builder produced (or refused to) for these
/// parameters: what ` + "`encodeQuery`" + ` must produce byte for byte.
pub const QueryCase = struct {
    name: []const u8,
    ty: u16,
    id: u16,
    rd: bool,
    edns: ?u16,
    /// null when Go's Builder (or NewName) refused the name.
    bytes: ?[]const u8,
};

`)
	emitDecode(&b, "built", "/// Messages dnsmessage's own Builder produced (compression on where noted).", built())
	emitDecode(&b, "crafted", "/// Messages built byte by byte in main.go.", crafted())
	emitQueries(&b)
	b.Truncate(b.Len() - 1)
	if *out == "" {
		os.Stdout.Write(b.Bytes())
		return
	}
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type msgCase struct {
	id   string
	data []byte
}

// ── rendering ───────────────────────────────────────────────────────────────

func nameText(n dnsmessage.Name) string {
	s := n.String()
	return strings.TrimSuffix(s, ".")
}

func b2i(b bool) int {
	if b {
		return 1
	}
	return 0
}

func renderRR(r dnsmessage.Resource) string {
	h := r.Header
	head := fmt.Sprintf("%s %d %d %d ", nameText(h.Name), h.Type, h.Class, h.TTL)
	switch body := r.Body.(type) {
	case *dnsmessage.AResource:
		return head + fmt.Sprintf("A %d.%d.%d.%d", body.A[0], body.A[1], body.A[2], body.A[3])
	case *dnsmessage.AAAAResource:
		return head + "AAAA " + hex.EncodeToString(body.AAAA[:])
	case *dnsmessage.NSResource:
		return head + "NS " + nameText(body.NS)
	case *dnsmessage.CNAMEResource:
		return head + "CNAME " + nameText(body.CNAME)
	case *dnsmessage.PTRResource:
		return head + "PTR " + nameText(body.PTR)
	case *dnsmessage.MXResource:
		return head + fmt.Sprintf("MX %d %s", body.Pref, nameText(body.MX))
	case *dnsmessage.TXTResource:
		var parts []string
		for _, t := range body.TXT {
			parts = append(parts, hex.EncodeToString([]byte(t)))
		}
		return head + "TXT " + strings.Join(parts, ",")
	case *dnsmessage.SOAResource:
		return head + fmt.Sprintf("SOA %s %s %d %d %d %d %d", nameText(body.NS), nameText(body.MBox), body.Serial, body.Refresh, body.Retry, body.Expire, body.MinTTL)
	case *dnsmessage.SRVResource:
		return head + fmt.Sprintf("SRV %d %d %d %s", body.Priority, body.Weight, body.Port, nameText(body.Target))
	case *dnsmessage.OPTResource:
		var opts []byte
		for _, o := range body.Options {
			opts = binary.BigEndian.AppendUint16(opts, o.Code)
			opts = binary.BigEndian.AppendUint16(opts, uint16(len(o.Data)))
			opts = append(opts, o.Data...)
		}
		return head + fmt.Sprintf("OPT %d %d %d %d %s", h.Class, h.TTL>>24, (h.TTL>>16)&0xff, b2i(h.TTL&0x8000 != 0), hex.EncodeToString(opts))
	case *dnsmessage.UnknownResource:
		return head + "RAW " + hex.EncodeToString(body.Data)
	}
	return head + fmt.Sprintf("GO-UNHANDLED %T", r.Body)
}

func zigLines(items []string) string {
	if len(items) == 0 {
		return "&.{}"
	}
	var q []string
	for _, s := range items {
		q = append(q, zigStr(s))
	}
	return "&.{\n            " + strings.Join(q, ",\n            ") + ",\n        }"
}

func emitDecode(b *bytes.Buffer, name, doc string, cases []msgCase) {
	fmt.Fprintf(b, "%s\npub const %s = [_]Case{\n", doc, name)
	for _, c := range cases {
		var m dnsmessage.Message
		err := m.Unpack(c.data)
		e, hdr := "null", `""`
		var qs, an, ns, ar []string
		if err != nil {
			e = zigStr(err.Error())
		} else {
			h := m.Header
			hdr = zigStr(fmt.Sprintf("id=%d qr=%d op=%d aa=%d tc=%d rd=%d ra=%d rcode=%d", h.ID, b2i(h.Response), h.OpCode,
				b2i(h.Authoritative), b2i(h.Truncated), b2i(h.RecursionDesired), b2i(h.RecursionAvailable), h.RCode))
			for _, q := range m.Questions {
				qs = append(qs, fmt.Sprintf("%s %d %d", nameText(q.Name), q.Type, q.Class))
			}
			for _, r := range m.Answers {
				an = append(an, renderRR(r))
			}
			for _, r := range m.Authorities {
				ns = append(ns, renderRR(r))
			}
			for _, r := range m.Additionals {
				ar = append(ar, renderRR(r))
			}
		}
		fmt.Fprintf(b, "    .{\n        .id = %s,\n        .bytes = %s,\n        .err = %s,\n        .header = %s,\n        .questions = %s,\n        .answers = %s,\n        .authorities = %s,\n        .additionals = %s,\n    },\n",
			zigStr(c.id), zigStr(string(c.data)), e, hdr, zigLines(qs), zigLines(an), zigLines(ns), zigLines(ar))
	}
	fmt.Fprintf(b, "};\n\n")
}

// ── Builder-made messages ───────────────────────────────────────────────────

func mustName(s string) dnsmessage.Name { return dnsmessage.MustNewName(s) }

func rh(name string, t dnsmessage.Type, ttl uint32) dnsmessage.ResourceHeader {
	return dnsmessage.ResourceHeader{Name: mustName(name), Type: t, Class: dnsmessage.ClassINET, TTL: ttl}
}

func built() []msgCase {
	var out []msgCase
	add := func(id string, compress bool, h dnsmessage.Header, f func(b *dnsmessage.Builder) error) {
		b := dnsmessage.NewBuilder(nil, h)
		if compress {
			b.EnableCompression()
		}
		if err := f(&b); err != nil {
			fmt.Fprintln(os.Stderr, id, err)
			os.Exit(1)
		}
		msg, err := b.Finish()
		if err != nil {
			fmt.Fprintln(os.Stderr, id, err)
			os.Exit(1)
		}
		out = append(out, msgCase{id, msg})
	}
	resp := dnsmessage.Header{ID: 0xbeef, Response: true, RecursionDesired: true, RecursionAvailable: true}
	q := func(b *dnsmessage.Builder, name string, t dnsmessage.Type) error {
		if err := b.StartQuestions(); err != nil {
			return err
		}
		return b.Question(dnsmessage.Question{Name: mustName(name), Type: t, Class: dnsmessage.ClassINET})
	}
	for _, compress := range []bool{false, true} {
		sfx := "_plain"
		if compress {
			sfx = "_compressed"
		}
		add("every_type"+sfx, compress, resp, func(b *dnsmessage.Builder) error {
			if err := q(b, "example.com.", dnsmessage.TypeA); err != nil {
				return err
			}
			b.StartAnswers()
			b.AResource(rh("example.com.", dnsmessage.TypeA, 300), dnsmessage.AResource{A: [4]byte{93, 184, 216, 34}})
			b.AAAAResource(rh("example.com.", dnsmessage.TypeAAAA, 300), dnsmessage.AAAAResource{AAAA: [16]byte{0x26, 0x06, 0x28, 0, 2, 0x20, 0, 1, 2, 0x48, 0x18, 0x93, 0x25, 0xc8, 0x19, 0x46}})
			b.CNAMEResource(rh("www.example.com.", dnsmessage.TypeCNAME, 60), dnsmessage.CNAMEResource{CNAME: mustName("example.com.")})
			b.MXResource(rh("example.com.", dnsmessage.TypeMX, 3600), dnsmessage.MXResource{Pref: 10, MX: mustName("mail.example.com.")})
			b.TXTResource(rh("example.com.", dnsmessage.TypeTXT, 60), dnsmessage.TXTResource{TXT: []string{"v=spf1 -all", "", "second"}})
			b.SRVResource(rh("_sip._tcp.example.com.", dnsmessage.TypeSRV, 60), dnsmessage.SRVResource{Priority: 1, Weight: 2, Port: 5060, Target: mustName("sip.example.com.")})
			b.PTRResource(rh("34.216.184.93.in-addr.arpa.", dnsmessage.TypePTR, 60), dnsmessage.PTRResource{PTR: mustName("example.com.")})
			b.UnknownResource(rh("example.com.", 257, 60), dnsmessage.UnknownResource{Type: 257, Data: append([]byte{0, 5}, "issueletsencrypt.org"...)})
			b.UnknownResource(rh("example.com.", 99, 60), dnsmessage.UnknownResource{Type: 99, Data: []byte{1, 2, 3}})
			b.StartAuthorities()
			b.NSResource(rh("example.com.", dnsmessage.TypeNS, 86400), dnsmessage.NSResource{NS: mustName("a.iana-servers.net.")})
			b.SOAResource(rh("example.com.", dnsmessage.TypeSOA, 3600), dnsmessage.SOAResource{NS: mustName("ns.icann.org."), MBox: mustName("noc.dns.icann.org."), Serial: 2024093001, Refresh: 7200, Retry: 3600, Expire: 1209600, MinTTL: 3600})
			b.StartAdditionals()
			var opt dnsmessage.ResourceHeader
			opt.SetEDNS0(1232, dnsmessage.RCodeSuccess, true)
			return b.OPTResource(opt, dnsmessage.OPTResource{Options: []dnsmessage.Option{{Code: 10, Data: []byte("cookie12")}}})
		})
	}
	add("nxdomain_soa", true, dnsmessage.Header{ID: 7, Response: true, Authoritative: true, RCode: dnsmessage.RCodeNameError}, func(b *dnsmessage.Builder) error {
		if err := q(b, "nope.example.com.", dnsmessage.TypeAAAA); err != nil {
			return err
		}
		b.StartAuthorities()
		return b.SOAResource(rh("example.com.", dnsmessage.TypeSOA, 900), dnsmessage.SOAResource{NS: mustName("ns.example.com."), MBox: mustName("host\\.master.example.com."), Serial: 1, Refresh: 2, Retry: 3, Expire: 4, MinTTL: 5})
	})
	add("extended_rcode", false, dnsmessage.Header{ID: 9, Response: true, RCode: dnsmessage.RCode(16)}, func(b *dnsmessage.Builder) error {
		if err := q(b, "example.com.", dnsmessage.TypeA); err != nil {
			return err
		}
		b.StartAdditionals()
		var opt dnsmessage.ResourceHeader
		opt.SetEDNS0(4096, dnsmessage.RCode(16), false)
		return b.OPTResource(opt, dnsmessage.OPTResource{})
	})
	add("query_flags", false, dnsmessage.Header{ID: 0xffff, OpCode: 2, Truncated: true, RecursionDesired: true}, func(b *dnsmessage.Builder) error {
		return q(b, ".", dnsmessage.TypeNS)
	})
	add("class_chaos", false, dnsmessage.Header{ID: 1, Response: true}, func(b *dnsmessage.Builder) error {
		if err := b.StartQuestions(); err != nil {
			return err
		}
		b.Question(dnsmessage.Question{Name: mustName("version.bind."), Type: dnsmessage.TypeTXT, Class: dnsmessage.ClassCHAOS})
		b.StartAnswers()
		h := rh("version.bind.", dnsmessage.TypeTXT, 0)
		h.Class = dnsmessage.ClassCHAOS
		return b.TXTResource(h, dnsmessage.TXTResource{TXT: []string{"9.18.0"}})
	})
	add("long_name_compressed", true, resp, func(b *dnsmessage.Builder) error {
		long := strings.Repeat("a", 63) + "." + strings.Repeat("b", 63) + "." + strings.Repeat("c", 63) + "." + strings.Repeat("d", 61) + "."
		if err := q(b, long, dnsmessage.TypeCNAME); err != nil {
			return err
		}
		b.StartAnswers()
		return b.CNAMEResource(rh(long, dnsmessage.TypeCNAME, 1), dnsmessage.CNAMEResource{CNAME: mustName("x." + long[64:])})
	})
	return out
}

// ── crafted messages ────────────────────────────────────────────────────────

func hdr(id, flags, qd, an, ns, ar uint16) []byte {
	b := make([]byte, 12)
	for i, v := range []uint16{id, flags, qd, an, ns, ar} {
		binary.BigEndian.PutUint16(b[2*i:], v)
	}
	return b
}

func wname(labels ...string) []byte {
	var b []byte
	for _, l := range labels {
		b = append(b, byte(len(l)))
		b = append(b, l...)
	}
	return append(b, 0)
}

func u16(v uint16) []byte { return binary.BigEndian.AppendUint16(nil, v) }
func u32(v uint32) []byte { return binary.BigEndian.AppendUint32(nil, v) }
func ptr(off uint16) []byte {
	return u16(0xc000 | off)
}
func cat(parts ...[]byte) []byte { return bytes.Join(parts, nil) }

// rr: owner bytes, type, class, ttl, rdata (RDLENGTH from len(rdata) unless rdlen >= 0)
func rr(owner []byte, t, class uint16, ttl uint32, rdata []byte) []byte {
	return cat(owner, u16(t), u16(class), u32(ttl), u16(uint16(len(rdata))), rdata)
}
func rrLen(owner []byte, t, class uint16, ttl uint32, rdlen uint16, rdata []byte) []byte {
	return cat(owner, u16(t), u16(class), u32(ttl), u16(rdlen), rdata)
}

