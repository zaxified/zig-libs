// Differential oracle for modules/dns: golang.org/x/net/dns/dnsmessage
// (BSD-3-Clause; the parser Go's own resolver uses) as an independent
// implementation of this module's message codec. The inputs are OURS:
// messages Go's Builder produced from tables below, messages built byte by
// byte, and query parameters. Go only answers them; the answers are written
// out as a Zig file that the module's own tests replay hermetically.
//
//	cd modules/dns/tools/go_oracle && GOPROXY=off go run . -out ../../src/go_oracle_vectors.zig
//
// Needs golang.org/x/net v0.59.0 in the module cache (go.sum pins it);
// GOPROXY=off keeps the run offline.
package main

