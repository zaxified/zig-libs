#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Regenerate `src/tsig_vectors.zig`: RFC 8945 TSIG and RFC 2136 UPDATE
messages rendered by dnspython (2.8.0 when last run), pinned as goldens.

    python3 -I modules/dns/tools/tsig_oracle.py > modules/dns/src/tsig_vectors.zig

RFC 8945 publishes no test vectors, so an independent implementation is the
reference. dnspython compresses names when it renders; `dns` never does, so
the renderer's compression table is replaced by one that remembers nothing --
the message is then byte-comparable, and the TSIG MAC (computed by dnspython
over exactly those bytes) is too. `time.time` is pinned so the signatures are
reproducible. Needs dnspython -- a foreign toolchain the module's tests must
never require, which is why this lives in tools/ (CONVENTIONS.md §9).
"""

import time

FIXED_TIME = 1_760_000_000
time.time = lambda: float(FIXED_TIME)

import dns.message  # noqa: E402
import dns.name  # noqa: E402
import dns.rdataclass  # noqa: E402
import dns.rdataset  # noqa: E402
import dns.rdatatype  # noqa: E402
import dns.renderer  # noqa: E402
import dns.rrset  # noqa: E402
import dns.tsig  # noqa: E402
import dns.tsigkeyring  # noqa: E402
import dns.update  # noqa: E402
import dns.version  # noqa: E402


class NoCompress(dict):
    def __setitem__(self, k, v):
        pass


_orig_init = dns.renderer.Renderer.__init__


def _init(self, *a, **kw):
    _orig_init(self, *a, **kw)
    self.compress = NoCompress()


dns.renderer.Renderer.__init__ = _init


def zig_bytes(b):
    return '"' + "".join(f"\\x{c:02x}" for c in b) + '"'


ALGS = [
    ("hmac_sha1", dns.tsig.HMAC_SHA1),
    ("hmac_sha224", dns.tsig.HMAC_SHA224),
    ("hmac_sha256", dns.tsig.HMAC_SHA256),
    ("hmac_sha384", dns.tsig.HMAC_SHA384),
    ("hmac_sha512", dns.tsig.HMAC_SHA512),
]
KEY_NAME = "acme-update.example.org."
SECRET = bytes(range(1, 33))  # 32 bytes, as `tsig-keygen` makes for sha256
FUDGE = 300


def acme_update(msg_id):
    u = dns.update.UpdateMessage("example.org", id=msg_id)
    u.add("_acme-challenge", 60, "TXT", '"LoqXcYV8q5ONbJQxbmR7SCTNo3tiAXDfowyjxAjEuX0"')
    return u


out = []
out.append("// SPDX-License-Identifier: MIT")
out.append("")
out.append(f"//! GENERATED by `tools/tsig_oracle.py` from dnspython {dns.version.version} -- do not edit.")
out.append("//! TSIG-signed messages (`signed`) and an UPDATE with every operation")
out.append("//! (`update_all_ops`), rendered uncompressed. See the script for the recipe.")
out.append("")
out.append('const tsig = @import("tsig.zig");')
out.append("")
out.append("pub const Vector = struct {")
out.append("    key_name: []const u8,")
out.append("    algorithm: tsig.Algorithm,")
out.append("    secret: []const u8,")
out.append("    time: u48,")
out.append("    fudge: u16,")
out.append("    request_mac: ?[]const u8,")
out.append("    unsigned: []const u8,")
out.append("    signed: []const u8,")
out.append("};")
out.append("")
out.append("/// 0..4: requests, one per algorithm; 5: the hmac-sha256 response to 2.")
out.append("pub const signed = [_]Vector{")

vec = []
sha256_request = None
for i, (zname, alg) in enumerate(ALGS):
    keyring = {dns.name.from_text(KEY_NAME): dns.tsig.Key(KEY_NAME, SECRET, alg)}
    u = acme_update(0x1000 + i)
    unsigned = u.to_wire()
    u.use_tsig(keyring, keyname=KEY_NAME, fudge=FUDGE, algorithm=alg)
    signed = u.to_wire()
    vec.append((zname, None, unsigned, signed))
    if zname == "hmac_sha256":
        sha256_request = (signed, keyring, alg)

req_wire, keyring, alg = sha256_request
req = dns.message.from_wire(req_wire, keyring=keyring)
resp = dns.message.make_response(req)
# The unsigned form: the same response rendered without the TSIG record.
plain = dns.message.make_response(req)
plain.keyring = None
plain.tsig = None
plain_wire = plain.to_wire()
resp_wire = resp.to_wire()
vec.append(("hmac_sha256", req.mac, plain_wire, resp_wire))

for zname, rmac, unsigned, signed in vec:
    out.append("    .{")
    out.append(f'        .key_name = "{KEY_NAME}",')
    out.append(f"        .algorithm = .{zname},")
    out.append(f"        .secret = {zig_bytes(SECRET)},")
    out.append(f"        .time = {FIXED_TIME},")
    out.append(f"        .fudge = {FUDGE},")
    out.append(f"        .request_mac = {zig_bytes(rmac) if rmac is not None else 'null'},")
    out.append(f"        .unsigned = {zig_bytes(unsigned)},")
    out.append(f"        .signed = {zig_bytes(signed)},")
    out.append("    },")
out.append("};")
out.append("")

# Every RFC 2136 operation `update.Builder` offers, in the order the Zig test
# writes them. Names absolute (trailing dot): a relative one gets the zone
# appended.
u = dns.update.UpdateMessage("example.org", id=0x4242)
u.present("example.org.")  # name in use
u.absent("new.example.org.")  # name not in use
u.present("www.example.org.", "A")  # rrset exists
u.absent("_acme-challenge.example.org.", "CNAME")  # rrset absent
u.present("www.example.org.", dns.rdataset.from_text("IN", "A", 0, "192.0.2.1"))  # value-dependent
u.add("_acme-challenge.example.org.", 60, "TXT", '"LoqXcYV8q5ONbJQxbmR7SCTNo3tiAXDfowyjxAjEuX0"')
u.add("long.example.org.", 300, "TXT", '"' + "x" * 255 + '" "' + "x" * 45 + '"')
u.delete("_acme-challenge.example.org.", "TXT", '"old"')
u.delete("stale.example.org.", "TXT")
u.delete("gone.example.org.")
out.append(f"pub const update_all_ops = {zig_bytes(u.to_wire())};")

print("\n".join(out))
