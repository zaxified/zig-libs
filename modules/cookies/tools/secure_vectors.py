"""Generate src/secure_vectors.zig: cookie-rs-format signed/private cookie values.

The FORMAT is cookie-rs 0.16-0.18 `src/secure/{key,signed,private}.rs`
(read 2026-10-12): Key = signing(32) | encryption(32); `derive_from` =
HKDF-SHA256 Expand(PRK = master, info = KEYS_INFO, L = 64); signed =
base64(HMAC-SHA256(signing, value)) | value; private = base64(nonce(12) |
AES-256-GCM(encryption, nonce, value, aad = name) | tag(16)); base64 =
standard alphabet with padding. The BYTES come from pyca/cryptography (OpenSSL),
an implementation independent of zig-libs' aesgcm and std's HMAC.

Run:  python3 -I modules/cookies/tools/secure_vectors.py > modules/cookies/src/secure_vectors.zig
Needs: python3 with `cryptography` (tested with 46.0.5). Deterministic output.
"""

import base64
import hashlib
import hmac
import sys

import cryptography
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDFExpand

KEYS_INFO = b"COOKIE;SIGNED:HMAC-SHA256;PRIVATE:AEAD-AES-256-GCM"


def det(label: str, n: int) -> bytes:
    """Deterministic test bytes (SHA-256 counter stream)."""
    out = b""
    i = 0
    while len(out) < n:
        out += hashlib.sha256(f"{label}/{i}".encode()).digest()
        i += 1
    return out[:n]


def derive(master: bytes) -> bytes:
    return HKDFExpand(algorithm=hashes.SHA256(), length=64, info=KEYS_INFO).derive(master)


def b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


def sign(key64: bytes, name: str, value: str, bound: bool) -> str:
    msg = (name + "=" + value).encode() if bound else value.encode()
    return b64(hmac.new(key64[:32], msg, hashlib.sha256).digest()) + value


def seal(key64: bytes, name: str, value: bytes, nonce: bytes) -> str:
    ct = AESGCM(key64[32:]).encrypt(nonce, value, name.encode())  # ct | tag
    return b64(nonce + ct)


def zstr(b) -> str:
    if isinstance(b, str):
        b = b.encode()
    return '"' + "".join(chr(c) if 0x20 <= c < 0x7F and c not in (0x22, 0x5C) else f"\\x{c:02x}" for c in b) + '"'


def main() -> None:
    w = sys.stdout.write
    w("// SPDX-License-Identifier: MIT\n")
    w(f"// GENERATED by modules/cookies/tools/secure_vectors.py (pyca/cryptography {cryptography.__version__}) -- do not hand-edit.\n")
    w("//! cookie-rs-format signed/private values and derived keys, replayed by `secure_test.zig`.\n\n")

    # Key derivation: master lengths 32 (minimum), 33, 64, 100 (PRK longer than a block).
    w("pub const Derive = struct { master: []const u8, key: [64]u8 };\n")
    w("pub const derive = [_]Derive{\n")
    for n in (32, 33, 64, 100):
        m = det(f"master{n}", n)
        w(f"    .{{ .master = {zstr(m)}, .key = {zstr(derive(m))}.* }},\n")
    w("};\n\n")

    key64 = derive(det("master32", 32))
    w(f"/// The key every vector below uses: `derive[0].key`.\n")

    values = ["", "a", "dark", "user=42&role=admin", "x" * 47, "!#$%&'()*+-./09:<=>?@AZ[]^_`az{|}~", "v" * 1000]
    names = ["theme", "sid", "__Host-s", "a"]
    w("pub const Signed = struct { name: []const u8, value: []const u8, bound: []const u8, cookie_rs: []const u8 };\n")
    w("pub const signed = [_]Signed{\n")
    for i, v in enumerate(values):
        n = names[i % len(names)]
        w(f"    .{{ .name = {zstr(n)}, .value = {zstr(v)}, .bound = {zstr(sign(key64, n, v, True))}, .cookie_rs = {zstr(sign(key64, n, v, False))} }},\n")
    w("};\n\n")

    pvalues = [b"", b"a", b"user=42", "žluťoučký kůň".encode(), bytes(range(256)), b"z" * 2000]
    w("pub const Private = struct { name: []const u8, value: []const u8, nonce: [12]u8, sealed: []const u8 };\n")
    w("pub const private = [_]Private{\n")
    for i, v in enumerate(pvalues):
        n = names[i % len(names)]
        nonce = det(f"nonce{i}", 12)
        w(f"    .{{ .name = {zstr(n)}, .value = {zstr(v)}, .nonce = {zstr(nonce)}.*, .sealed = {zstr(seal(key64, n, v, nonce))} }},\n")
    w("};\n")


if __name__ == "__main__":
    main()
