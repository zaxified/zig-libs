#!/usr/bin/env python3
"""Frozen vectors for slice.informationRatio, treynorRatio, greeks, rSquared, and
the capture and rolling alpha and beta functions.

quantstats 0.0.86, ffn 1.3.0 and empyrical-reloaded 0.5.12 are run as black boxes, their source is not read.

    V=~/.local/share/zig-libs/oracle-venvs/finstats
    python3 -m venv $V && $V/bin/pip install quantstats==0.0.86 ffn==1.3.0 empyrical-reloaded==0.5.12 numpy pandas
    $V/bin/python -I modules/finstats/tools/benchmark_oracle.py > modules/finstats/src/testdata/benchmark_vectors.zig
"""
import warnings

import empyrical as em
import ffn
import numpy as np
import pandas as pd
import quantstats as qs

warnings.filterwarnings("ignore")


def arr(xs):
    return "&.{ " + ", ".join(repr(float(x)) for x in xs) + " }"


print("// SPDX-License-Identifier: MIT")
print("// Generated by tools/benchmark_oracle.py. Do not edit.")
print("pub const Case = struct { p: []const f64, b: []const f64, rf: f64, info_qs: f64, info_ffn: f64, treynor: f64, beta: f64, alpha: f64, r2: f64, capture: f64, up: f64, down: f64, up_down: f64, window: usize, roll_up_down: []const f64, roll_alpha: []const f64, roll_beta: []const f64, greeks_alpha: []const f64, greeks_beta: []const f64 };")
print("pub const cases = [_]Case{")
for seed, n, rf in [(5, 120, 0.0), (6, 60, 0.02), (7, 250, 0.05)]:
    r = np.random.default_rng(seed)
    b = r.normal(0.0003, 0.01, n)
    p = 0.8 * b + r.normal(0.0002, 0.008, n)
    p[n // 3] = 0.0
    idx = pd.date_range("2020-01-01", periods=n, freq="B")
    P, B = pd.Series(p, index=idx), pd.Series(b, index=idx)
    g = qs.stats.greeks(P, B, periods=252)
    w = 15
    rab = em.roll_alpha_beta(p, b, window=w)
    rg = qs.stats.rolling_greeks(P, B, periods=w).iloc[w - 1 :]
    print(
        f"    .{{ .p = {arr(p)}, .b = {arr(b)}, .rf = {rf!r}, "
        f".info_qs = {float(qs.stats.information_ratio(P, B))!r}, "
        f".info_ffn = {float(ffn.core.calc_information_ratio(P, B))!r}, "
        f".treynor = {float(qs.stats.treynor_ratio(P, B, periods=252, rf=rf))!r}, "
        f".beta = {float(g['beta'])!r}, .alpha = {float(g['alpha'])!r}, "
        f".r2 = {float(qs.stats.r_squared(P, B))!r}, "
        f".capture = {float(em.capture(p, b))!r}, .up = {float(em.up_capture(p, b))!r}, "
        f".down = {float(em.down_capture(p, b))!r}, .up_down = {float(em.up_down_capture(p, b))!r}, "
        f".window = {w}, .roll_up_down = {arr(em.roll_up_down_capture(p, b, window=w))}, "
        f".roll_alpha = {arr(rab[:, 0])}, .roll_beta = {arr(rab[:, 1])}, "
        f".greeks_alpha = {arr(rg['alpha'])}, .greeks_beta = {arr(rg['beta'])} }},"
    )
print("};")
