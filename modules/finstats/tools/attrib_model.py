"""Independent models for `twrDaily` and `brinsonAttribution`, frozen into
`src/testdata/attrib_vectors.zig` and replayed by `src/period_test.zig`.

    V=~/.local/share/zig-libs/oracle-venvs/finstats
    $V/bin/python modules/finstats/tools/attrib_model.py | zig fmt --stdin > modules/finstats/src/testdata/attrib_vectors.zig

empyrical, ffn and quantstats have no attribution and no Modified Dietz. So these are
MODELS, not external anchors, and the SPEC says so; the published and foreign anchors
(FinanceToolkit, tools/attrib_oracle.py) are in src/attrib_oracle_test.zig:

  - twrDaily: the model is ground truth by construction. A portfolio is
    simulated forward from KNOWN daily returns r_t and external flows f_t, with
    the flow either at the start of the day (value_t = (value_{t-1} + f_t) *
    (1 + r_t), base pe = value_{t-1} + f_t) or at its end (value_t =
    value_{t-1} * (1 + r_t) + f_t, base pe = value_{t-1}). Modified Dietz with
    the matching base must hand the known r_t back; the compounded curve is
    checked against empyrical `cum_returns_final` of the known returns.
  - brinsonAttribution: written from the Brinson-Fachler (1985) definition,
    not from our code: allocation_i = (wp_i - wb_i) * (rb_i - Rb), selection_i =
    wb_i * (rp_i - rb_i), interaction_i = (wp_i - wb_i) * (rp_i - rb_i), with
    Rb = sum wb_i rb_i. The generator ASSERTS the identity (sum of the three
    effects = Rp - Rb) before emitting, so a vector set that violates the theory
    cannot be frozen. Weights are random on the simplex, returns random, one
    portfolio has a segment with zero benchmark weight.
CAVEAT (review 2026-11-02): the Brinson half is a CONSISTENCY CHECK, not an independent
oracle. It repeats the three formulae of the module, and the identity it asserts also holds
for BHB, so it cannot tell Brinson-Fachler from BHB; the Fachler term is pinned separately
by a hand-worked test in src/period_test.zig. Only the twrDaily half is ground truth.
Bacon 2008, ch. 5 is NOT used: the book's numbers could not be confirmed from a source
read in full.
"""
import sys

import empyrical as ep
import numpy as np

rng = np.random.default_rng(20261102)


def f(x):
    return repr(float(x))


def floats(xs):
    return "&.{" + ", ".join(f(x) for x in xs) + "}"


def twr(o):
    o.append("pub const Twr = struct { dates: []const []const u8, value: []const f64, flow: []const f64,"
             " pe: []const f64, ret: []const f64, cum_final: f64 };")
    o.append("pub const twr_cases = [_]Twr{")
    for k in range(4):
        n = 60
        r = rng.normal(0.0004, 0.01, n)
        flow = np.where(rng.random(n) < 0.15, rng.uniform(-2000, 5000, n), 0.0)
        v = np.zeros(n)
        pe = np.zeros(n)
        prev = 50000.0  # day 0 is the seed row (its return is not emitted)
        v[0], pe[0] = prev, prev
        flow[0] = 0.0
        for t in range(1, n):
            if k % 2 == 0:  # flow at start of day
                pe[t] = prev + flow[t]
                v[t] = pe[t] * (1 + r[t])
            else:  # flow at end of day
                pe[t] = prev
                v[t] = prev * (1 + r[t]) + flow[t]
            prev = v[t]
        dates = [f'"2024-{1 + (t // 28):02d}-{1 + (t % 28):02d}"' for t in range(n)]
        o.append(f"    .{{ .dates = &.{{{', '.join(dates)}}}, .value = {floats(v)}, .flow = {floats(flow)},"
                 f" .pe = {floats(pe)}, .ret = {floats(r[1:])}, .cum_final = {f(ep.cum_returns_final(r[1:]))} }},")
    o.append("};")


def brinson(o):
    o.append("pub const Bf = struct { wp: []const f64, wb: []const f64, rp: []const f64, rb: []const f64,"
             " alloc: []const f64, sel: []const f64, inter: []const f64, active: f64 };")
    o.append("pub const bf_cases = [_]Bf{")
    for k, m in enumerate((2, 3, 5, 8, 11, 4)):
        wp = rng.dirichlet(np.ones(m))
        wb = rng.dirichlet(np.ones(m))
        if k == 5:
            wb[0] = 0.0
            wb /= wb.sum()
            wp[1] = 0.0
            wp /= wp.sum()
        rp = rng.normal(0.01, 0.05, m)
        rb = rng.normal(0.01, 0.05, m)
        Rb = float(np.sum(wb * rb))
        Rp = float(np.sum(wp * rp))
        alloc = (wp - wb) * (rb - Rb)
        # A segment not held is pure allocation, whatever return is stated for it
        # (FinanceToolkit's rule, see src/attrib_oracle_test.zig).
        held = np.where(wp == 0, rb, rp)
        sel = wb * (held - rb)
        inter = (wp - wb) * (held - rb)
        assert abs((alloc + sel + inter).sum() - (Rp - Rb)) < 1e-12, "identity"
        o.append(f"    .{{ .wp = {floats(wp)}, .wb = {floats(wb)}, .rp = {floats(rp)}, .rb = {floats(rb)},"
                 f" .alloc = {floats(alloc)}, .sel = {floats(sel)}, .inter = {floats(inter)}, .active = {f(Rp - Rb)} }},")
    o.append("};")


def main():
    o = ["// SPDX-License-Identifier: MIT",
         "// Generated by modules/finstats/tools/attrib_model.py: independent models for twrDaily and",
         "// brinsonAttribution (see that file). Replayed by src/period_test.zig. Do not edit by hand.",
         ""]
    twr(o)
    brinson(o)
    sys.stdout.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
