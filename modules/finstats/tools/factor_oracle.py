"""Recipe for `src/testdata/factor_vectors.zig`: reference values from
empyrical-reloaded `compute_exposures` and `perf_attrib` for `src/factor.zig`,
replayed by `src/factor_test.zig`.

    V=~/.local/share/zig-libs/oracle-venvs/finstats
    $V/bin/pip install numpy pandas empyrical-reloaded
    $V/bin/python modules/finstats/tools/factor_oracle.py | zig fmt --stdin > modules/finstats/src/testdata/factor_vectors.zig

empyrical is run as a black box (none of its source is read). Its inputs are a
stacked positions Series indexed by (dt, ticker), a loadings frame with the
same index and a factor-returns frame by date; the flat arrays here are those
frames in row-major order. Seeded cases:

  0. 6 periods, 3 assets, 2 factors, long-short book, one period with all
     positions 0 (zero gross exposure), a NaN position, a NaN loading;
  1. 8 periods, 5 assets, 3 factors, a NaN return, a NaN factor return;
  2. 5 periods, 4 assets, 2 factors, plain (all finite).

A NaN position or loading stays in the frame as NaN (an absent asset is the
same thing). Expected: exposures, per-factor contributions (the factor columns
of `perf_attrib`), common / specific / total / tilt / timing returns.
Self-check here: contributions + specific == total (finite periods).
"""
import sys
import warnings

warnings.filterwarnings("ignore")
import numpy as np
import pandas as pd
import empyrical as ep


def f(x):
    x = float(x)
    if np.isnan(x):
        return "nan"
    assert np.isfinite(x), x
    return repr(x)


def floats(v):
    return "&.{" + ", ".join(f(x) for x in np.asarray(v).ravel()) + "}"


def case(seed, T, A, F, nan_pos=(), nan_load=(), zero_rows=(), nan_ret=(), nan_fr=()):
    g = np.random.default_rng(seed)
    P = g.normal(0, 1, (T, A))
    P[:, A - 1] *= -1  # long-short
    for t in zero_rows:
        P[t] = 0.0
    L = g.normal(0, 1, (T, A, F))
    FR = g.normal(0, 0.01, (T, F))
    R = g.normal(0, 0.01, T)
    for t, a in nan_pos:
        P[t, a] = np.nan
    for t, a, k in nan_load:
        L[t, a, k] = np.nan
    for t in nan_ret:
        R[t] = np.nan
    for t, k in nan_fr:
        FR[t, k] = np.nan
    dates = pd.date_range("2020-01-01", periods=T)
    assets = ["a%d" % i for i in range(A)]
    facs = ["f%d" % i for i in range(F)]
    idx = pd.MultiIndex.from_product([dates, assets], names=["dt", "ticker"])
    pos = pd.Series(P.ravel(), idx)
    fl = pd.DataFrame(L.reshape(T * A, F), idx, facs)
    fr = pd.DataFrame(FR, dates, facs)
    ret = pd.Series(R, dates)
    ex = ep.compute_exposures(pos, fl)
    e2, a = ep.perf_attrib(ret, pos, fr, fl)
    assert np.allclose(ex.values, e2.values, atol=0, rtol=1e-15)
    contrib = a[facs].values
    ok = ~np.isnan(R)
    chk = np.nansum(contrib, axis=1) + a.specific_returns.values - a.total_returns.values
    assert np.abs(chk[ok]).max() < 1e-15, chk
    return (T, A, F, P, L, FR, R, ex.values, contrib, a)


def main():
    cases = [
        case(1, 6, 3, 2, nan_pos=[(0, 1)], nan_load=[(3, 2, 0)], zero_rows=[2]),
        case(2, 8, 5, 3, nan_ret=[3], nan_fr=[(5, 1)]),
        case(3, 5, 4, 2),
    ]
    o = []
    o.append("// SPDX-License-Identifier: MIT")
    o.append("// Generated by modules/finstats/tools/factor_oracle.py: reference values from empyrical-reloaded")
    o.append("// `compute_exposures` and `perf_attrib` over seeded inputs. Replayed by src/factor_test.zig.")
    o.append("// Do not edit by hand.")
    o.append("")
    o.append("const nan = @import(\"std\").math.nan(f64);")
    o.append("pub const Case = struct {")
    o.append("    t: usize, a: usize, f: usize,")
    o.append("    positions: []const f64, loadings: []const f64, factor_returns: []const f64, returns: []const f64,")
    o.append("    exposures: []const f64, contributions: []const f64,")
    o.append("    common: []const f64, specific: []const f64, total: []const f64, tilt: []const f64, timing: []const f64,")
    o.append("};")
    o.append("pub const cases = [_]Case{")
    for (T, A, F, P, L, FR, R, ex, contrib, a) in cases:
        o.append("    .{")
        o.append(f"        .t = {T}, .a = {A}, .f = {F},")
        o.append(f"        .positions = {floats(P)}, .loadings = {floats(L)}, .factor_returns = {floats(FR)}, .returns = {floats(R)},")
        o.append(f"        .exposures = {floats(ex)}, .contributions = {floats(contrib)},")
        o.append(f"        .common = {floats(a.common_returns.values)}, .specific = {floats(a.specific_returns.values)}, .total = {floats(a.total_returns.values)},")
        o.append(f"        .tilt = {floats(a.tilt_returns.values)}, .timing = {floats(a.timing_returns.values)},")
        o.append("    },")
    o.append("};")
    sys.stdout.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
