"""Recipe for `src/testdata/overfit_vectors.zig`: reference values for `src/overfit.zig`
from ffn 1.3.0 `calc_prob_backtest_overfitting(trial_returns, n_blocks, metric, full_output=True)`,
run as a BLACK BOX (its source is not read; the published definition is Bailey, Borwein,
Lopez de Prado and Zhu, "The Probability of Backtest Overfitting", J. Computational Finance
2017, and each convention below was pinned by running the function). Replayed by
`src/overfit_test.zig`.

    V=~/.local/share/zig-libs/oracle-venvs/finstats
    $V/bin/python modules/finstats/tools/overfit_oracle.py | zig fmt --stdin > modules/finstats/src/testdata/overfit_vectors.zig

Conventions measured on ffn (all reproduced by `overfit.zig`):
  - blocks: T // n_blocks rows each, contiguous, the surplus rows at the END dropped;
  - every combination of n_blocks / 2 blocks is the in-sample half, in lexicographic
    order of block indices; the other blocks are out-of-sample; a half is the chosen
    blocks concatenated in chronological order;
  - in-sample winner: the first column with the largest metric (ties -> first);
  - its out-of-sample rank among all N columns: average rank for ties; omega = rank / (N + 1);
    logit = ln(omega / (1 - omega)); PBO = share of combinations with logit <= 0;
    mean_oos_rank = mean of omega;
  - default metric: per-period Sharpe (mean / sample std) over the non-missing (NaN)
    values of the half; < 2 values or constant -> undefined;
  - any non-finite metric among the N columns in either half -> that logit NaN, and PBO and
    mean_oos_rank NaN. Undefined combinations are NOT dropped;
  - n_blocks odd / < 2 / not an int, N < 2, or T < n_blocks -> ValueError (this module
    answers NaN for these instead; the vectors hold only the cases ffn answers).
Inputs are seeded. Cases: pure noise (n_blocks 4, 8, 12, 16 -> PBO about one half), one
genuinely better strategy (PBO near 0), duplicated columns (in-sample and out-of-sample
ties), trailing surplus rows, NaN holes (skipped by the Sharpe), a constant column and an
infinite value (NaN answer), two non-Sharpe metrics (mean, last value: the second is
sensitive to the order of the concatenated blocks), two columns only. Cases with more than
300 combinations keep their first 300 logits plus the count and the sum of all of them
(1.4 MB of text otherwise).
"""
import sys
import warnings

import ffn
import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")
fn = ffn.core.calc_prob_backtest_overfitting


HEAD = 300  # leading logits kept per case; the rest is checked through the count and the sum


def f(x):
    x = float(x)
    if np.isnan(x):
        return "nan"
    if np.isinf(x):
        return "inf" if x > 0 else "-inf"
    return repr(x)


def floats(xs):
    return "&.{" + ", ".join(f(x) for x in xs) + "}"


METRICS = {
    "sharpe": None,
    "mean": lambda s: float(s.mean()),
    "last": lambda s: float(s.iloc[-1]),
}


def cases():
    g = np.random.default_rng(20261105)
    out = []

    def add(name, X, nb, metric="sharpe"):
        out.append((name, np.asarray(X, dtype=float), nb, metric))

    noise = g.normal(0.0, 0.01, (240, 8))
    for nb in (4, 8, 12, 16):
        add(f"noise_nb{nb}", noise, nb)
    n2 = g.normal(0.0, 0.01, (480, 10))
    add("noise10_nb16", n2, 16)
    dom = g.normal(0.0, 0.01, (320, 6))
    dom[:, 3] += 0.006
    for nb in (4, 8, 16):
        add(f"dominant_nb{nb}", dom, nb)
    surplus = g.normal(0.0, 0.01, (243, 6))
    surplus[:, 2] += 0.002
    add("surplus_rows_nb6", surplus, 6)
    dup = g.normal(0.0, 0.01, (120, 5))
    dup[:, 3] = dup[:, 1]
    dup[:, 4] = dup[:, 0]
    add("duplicated_cols_nb6", dup, 6)
    nanx = g.normal(0.0002, 0.01, (160, 5))
    nanx[g.choice(160, 12, replace=False), 1] = np.nan
    nanx[5, 3] = np.nan
    nanx[40:60, 2] = np.nan
    add("nan_holes_nb4", nanx, 4)
    add("nan_holes_nb8", nanx, 8)
    const = g.normal(0.0, 0.01, (80, 4))
    const[:, 2] = 0.1 / 3
    add("constant_col_nb4", const, 4)
    allnan = g.normal(0.0, 0.01, (80, 4))
    allnan[:, 1] = np.nan
    add("all_nan_col_nb4", allnan, 4)
    inf = g.normal(0.0, 0.01, (80, 4))
    inf[7, 1] = np.inf
    add("inf_value_nb4", inf, 4)
    two = g.normal(0.0, 0.01, (60, 2))
    add("two_cols_nb6", two, 6)
    add("two_blocks_nb2", g.normal(0.0, 0.01, (41, 7)), 2)
    add("one_row_blocks_nb4", g.normal(0.0, 0.01, (4, 5)), 4)
    mm = g.normal(0.0, 0.01, (200, 7))
    mm[:, 5] += 0.001
    add("mean_metric_nb8", mm, 8, "mean")
    add("last_metric_nb8", mm, 8, "last")
    add("last_metric_nb4", mm[:100], 4, "last")
    return out


def main():
    o = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by modules/finstats/tools/overfit_oracle.py: ffn 1.3.0 calc_prob_backtest_overfitting",
        "// over seeded inputs. Replayed by src/overfit_test.zig. Do not edit by hand.",
        "",
    ]
    o += [
        "const nan = @import(\"std\").math.nan(f64);",
        "const inf = @import(\"std\").math.inf(f64);",
        "pub const Metric = enum { sharpe, mean, last };",
        "pub const Case = struct { name: []const u8, trials: []const []const f64, n_blocks: usize, metric: Metric,"
        " pbo: f64, mean_oos_rank: f64, n_logits: usize, logit_sum: f64, logits: []const f64 };",
        "",
        "pub const cases = [_]Case{",
    ]
    for name, X, nb, metric in cases():
        df = pd.DataFrame(X)
        kw = {} if METRICS[metric] is None else {"metric": METRICS[metric]}
        r = fn(df, n_blocks=nb, full_output=True, **kw)
        cols = "&.{" + ", ".join(floats(X[:, j]) for j in range(X.shape[1])) + "}"
        o.append(
            f'    .{{ .name = "{name}", .trials = {cols}, .n_blocks = {nb}, .metric = .{metric},'
            f" .pbo = {f(r['pbo'])}, .mean_oos_rank = {f(r['mean_oos_rank'])}, .n_logits = {len(r['logits'])},"
            f" .logit_sum = {f(np.sum(r['logits'].values))}, .logits = {floats(r['logits'].values[:HEAD])} }},"
        )
        sys.stderr.write(f"{name}: pbo={r['pbo']} combos={len(r['logits'])}\n")
    o.append("};")
    print("\n".join(o))


main()
