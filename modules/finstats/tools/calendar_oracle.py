#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Recipe for `src/testdata/calendar_vectors.zig`: reference values from foreign
implementations for `src/calendar.zig`, replayed by `src/calendar_test.zig`.

    V=~/.local/share/zig-libs/oracle-venvs/finstats
    $V/bin/pip install numpy pandas scipy empyrical-reloaded ffn quantstats
    $V/bin/python modules/finstats/tools/calendar_oracle.py | zig fmt --stdin > modules/finstats/src/testdata/calendar_vectors.zig

Every library is run as a black box (none of its source is read). Three seeded
calendar-day series (2019-11-01 to 2021-03-31: a leap February, two year
ends) with a benchmark, whose zero entries test the tie rules.

  - aggregateReturns monthly / quarterly / yearly -- empyrical
    `aggregate_returns`. Weekly -- empyrical too, but only on 2020-01-06 ..
    2020-12-27 (Monday to Sunday), a span without a year-end week: empyrical keys
    a week by (calendar year, ISO week), which splits the New Year week and merges
    week 1 of two ISO years, so over a year end it is wrong and calendar.zig
    (ISO year) deliberately differs; the year-end case is pinned by hand;
  - bestPeriod / worstPeriod / avgUpMonth / avgDownMonth / expectedMonthlyReturn
    / expectedYearlyReturn / winQuarter -- quantstats `best`, `worst`,
    `avg_win`, `avg_loss`, `expected_return`, `win_rate` with `aggregate="ME"`,
    `"YE"`, `"QE"`; gainToPainMonthly -- quantstats `gain_to_pain_ratio(
    resolution="M")`; mtd / ytd -- plain pandas (the compounded rows of the last
    date's month / year), SELF grade;
  - toReturns -- empyrical `simple_returns`; toLogReturns / toPriceIndex /
    rebase / deannualize / toExcessReturns -- ffn; winsorize -- scipy
    `mstats.winsorize` (and ffn `winsorize` for the symmetric case); rescale --
    ffn;
  - rolling -- quantstats `rolling_sortino` / `rolling_sharpe` (rf annual),
    empyrical `annual_return` per window, `roll_max_drawdown`,
    `roll_up_capture`, `roll_down_capture`; rollingWinRate -- quantstats
    `win_rate` per window;
  - jensen / upAlphaBeta / downAlphaBeta / excessSharpe / battingAverage /
    betaFragilityHeuristic / gpdRiskEstimates -- empyrical `alpha`,
    `up_alpha_beta`, `down_alpha_beta`, `excess_sharpe`, `batting_average`,
    `beta_fragility_heuristic`, `gpd_risk_estimates_aligned` (the public wrapper
    breaks on a float `var_p`); empyrical takes the per-period risk-free rate, so
    the annual rate is converted here, (1 + rf)^(1/ppy) - 1;
  - ewmaVolatility -- pandas `ewm(alpha=1-lambda, adjust=False)` of the squares;
    evarGaussian -- scipy `minimize_scalar` over the defining infimum (an
    independent route to the closed form); hurstExponent -- this file's own
    R/S (SELF grade: the same definition written a second time).

The Monte Carlo functions have no vectors: our PRNG is not numpy's, so
calendar_test.zig pins distribution facts instead (see there).
"""
import sys
import warnings

warnings.filterwarnings("ignore")
import numpy as np
import pandas as pd
import empyrical as ep
import ffn
import quantstats as qs
from scipy import optimize
from scipy.stats import mstats

PPY = 365.0
RF = 0.03
W = 40  # rolling window


def f(x):
    x = float(x)
    assert np.isfinite(x), x
    return repr(x)


def floats(v):
    return "&.{" + ", ".join(f(x) for x in v) + "}"


def per(series):
    """(year, period) keyed series -> Zig PeriodReturn list."""
    out = []
    for k, v in series.items():
        if isinstance(k, tuple):
            y, p = k
        else:
            y, p = k, 0
        out.append(f".{{ .year = {int(y)}, .period = {int(p)}, .value = {f(v)} }}")
    return "&.{" + ", ".join(out) + "}"


def mk(seed):
    g = np.random.default_rng(seed)
    idx = pd.date_range("2019-11-01", "2021-03-31", freq="D")
    n = len(idx)
    r = g.normal(0.0006, 0.012, n)
    r[g.choice(n, 12, replace=False)] = 0.0
    b = g.normal(0.0004, 0.009, n)
    b[g.choice(n, 30, replace=False)] = 0.0
    return idx, pd.Series(r, idx), pd.Series(b, idx), g


def rolling_qs(fn, r, **kw):
    return fn(r, rolling_period=W, periods_per_year=int(PPY), **kw).dropna().values


def main():
    o = []
    idx0 = mk(1)[0]
    o.append("// SPDX-License-Identifier: MIT")
    o.append("// Generated by modules/finstats/tools/calendar_oracle.py: reference values from empyrical-reloaded,")
    o.append("// ffn, quantstats, scipy and pandas over seeded calendar-day series. Replayed by src/calendar_test.zig.")
    o.append("// Do not edit by hand.")
    o.append("")
    o.append("pub const ppy = %s;" % f(PPY))
    o.append("pub const rf = %s;" % f(RF))
    o.append("pub const window = %d;" % W)
    o.append("pub const dates = [_][]const u8{" + ", ".join('"%s"' % d.strftime("%Y-%m-%d") for d in idx0) + "};")
    o.append("pub const Per = struct { year: i32, period: u8, value: f64 };")
    o.append("pub const Pair = struct { f64, f64 };")
    o.append("pub const Cal = struct {")
    o.append("    rets: []const f64, bench: []const f64,")
    o.append("    weekly_lo: usize, weekly_hi: usize, weekly: []const Per, monthly: []const Per, quarterly: []const Per, yearly: []const Per,")
    o.append("    best_m: f64, worst_m: f64, best_y: f64, avg_up_m: f64, avg_down_m: f64, exp_m: f64, exp_y: f64, gtp_m: f64, win_q: f64, mtd: f64, ytd: f64,")
    o.append("    prices: []const f64, simple: []const f64, log: []const f64, index100: []const f64, rebase50: []const f64,")
    o.append("    excess_geo: []const f64, excess_arith: []const f64, wins: []const f64, wins_asym: []const f64, rescaled: []const f64,")
    o.append("    r_sortino: []const f64, r_sharpe: []const f64, r_cagr: []const f64, r_mdd: []const f64, r_win: []const f64, r_up: []const f64, r_down: []const f64,")
    o.append("    alpha: f64, beta: f64, up_alpha: f64, up_beta: f64, down_alpha: f64, down_beta: f64, excess_sharpe: f64,")
    o.append("    bat_all: f64, bat_up: f64, bat_down: f64,")
    o.append("    ewma: []const f64, evar: f64, hurst: f64,")
    o.append("};")
    o.append("pub const cals = [_]Cal{")
    for seed in (1, 2, 3):
        idx, r, b, g = mk(seed)
        n = len(r)
        m = ep.aggregate_returns(r, "monthly")
        q = ep.aggregate_returns(r, "quarterly")
        y = ep.aggregate_returns(r, "yearly")
        lo = int(np.where(idx == "2020-01-06")[0][0])
        hi = int(np.where(idx == "2020-12-27")[0][0]) + 1
        w = ep.aggregate_returns(r.iloc[lo:hi], "weekly")
        S = qs.stats
        best_m, worst_m = S.best(r, aggregate="ME"), S.worst(r, aggregate="ME")
        best_y = S.best(r, aggregate="YE")
        up_m, dn_m = S.avg_win(r, aggregate="ME"), S.avg_loss(r, aggregate="ME")
        exp_m, exp_y = S.expected_return(r, aggregate="ME"), S.expected_return(r, aggregate="YE")
        gtp = S.gain_to_pain_ratio(r, resolution="M")
        winq = S.win_rate(r, aggregate="QE")
        last = idx[-1]
        mtd = (1 + r[(idx.year == last.year) & (idx.month == last.month)]).prod() - 1
        ytd = (1 + r[idx.year == last.year]).prod() - 1
        # converters
        prices = pd.Series(100 * np.cumprod(1 + r.values) + 0.5, idx)
        simple = ep.simple_returns(prices).values
        logr = ffn.to_log_returns(prices).dropna().values
        pidx = ffn.to_price_index(r, 100).values
        reb = ffn.rebase(prices, 50).values
        geo = ffn.to_excess_returns(r, RF, PPY).values
        # a plain index: with a datetime index and no nperiods ffn infers the annualisation from the index frequency
        ari = ffn.to_excess_returns(pd.Series(r.values), 0.0001).values
        wins = ffn.winsorize(r, limits=0.05).values
        wasym = mstats.winsorize(r.values, limits=(0.1, 0.02))
        resc = ffn.rescale(r, -1, 3).values
        # rolling
        rfp = (1 + RF) ** (1 / PPY) - 1
        rs = rolling_qs(S.rolling_sortino, r, rf=RF)
        rsh = rolling_qs(S.rolling_sharpe, r, rf=RF)
        rcagr = np.array([ep.annual_return(r.values[k:k + W], annualization=PPY) for k in range(n - W + 1)])
        rmdd = ep.roll_max_drawdown(r.values, W)
        rwin = np.array([S.win_rate(r.iloc[k:k + W]) for k in range(n - W + 1)])
        rup = ep.roll_up_capture(r, b, window=W).values
        rdn = ep.roll_down_capture(r, b, window=W).values
        # extras (empyrical takes the per-period risk-free rate)
        al = ep.alpha(r, b, risk_free=rfp, annualization=PPY)
        be = ep.beta(r, b, risk_free=rfp)
        uab = ep.up_alpha_beta(r, b, risk_free=rfp, annualization=PPY)
        dab = ep.down_alpha_beta(r, b, risk_free=rfp, annualization=PPY)
        xs = ep.excess_sharpe(r, b)
        bat = ep.batting_average(r, b)
        ew = np.sqrt(pd.Series(r.values ** 2).ewm(alpha=1 - 0.94, adjust=False).mean().values * 252)
        # EVaR of a normal return (mean 0.0004, std 0.01) at 95 %: the defining infimum over z
        evar = optimize.minimize_scalar(
            lambda z: ((-0.0004) * z + (0.01 ** 2) * z * z / 2 - np.log(0.05)) / z,
            bounds=(1e-3, 1e4), method="bounded", options={"xatol": 1e-12}).fun
        hurst = rs_hurst(r.values)
        o.append("    .{")
        o.append(f"        .rets = {floats(r)}, .bench = {floats(b)}, .weekly_lo = {lo}, .weekly_hi = {hi},")
        o.append(f"        .weekly = {per(w)}, .monthly = {per(m)}, .quarterly = {per(q)}, .yearly = {per(y)},")
        o.append(f"        .best_m = {f(best_m)}, .worst_m = {f(worst_m)}, .best_y = {f(best_y)}, .avg_up_m = {f(up_m)}, .avg_down_m = {f(dn_m)},")
        o.append(f"        .exp_m = {f(exp_m)}, .exp_y = {f(exp_y)}, .gtp_m = {f(gtp)}, .win_q = {f(winq)}, .mtd = {f(mtd)}, .ytd = {f(ytd)},")
        o.append(f"        .prices = {floats(prices)}, .simple = {floats(simple)}, .log = {floats(logr)}, .index100 = {floats(pidx)}, .rebase50 = {floats(reb)},")
        o.append(f"        .excess_geo = {floats(geo)}, .excess_arith = {floats(ari)}, .wins = {floats(wins)}, .wins_asym = {floats(wasym)}, .rescaled = {floats(resc)},")
        o.append(f"        .r_sortino = {floats(rs)}, .r_sharpe = {floats(rsh)}, .r_cagr = {floats(rcagr)}, .r_mdd = {floats(rmdd)}, .r_win = {floats(rwin)},")
        o.append(f"        .r_up = {floats(rup)}, .r_down = {floats(rdn)},")
        o.append(f"        .alpha = {f(al)}, .beta = {f(be)}, .up_alpha = {f(uab[0])}, .up_beta = {f(uab[1])}, .down_alpha = {f(dab[0])}, .down_beta = {f(dab[1])},")
        o.append(f"        .excess_sharpe = {f(xs)}, .bat_all = {f(bat.iloc[0])}, .bat_up = {f(bat.iloc[1])}, .bat_down = {f(bat.iloc[2])},")
        o.append(f"        .ewma = {floats(ew)}, .evar = {f(evar)}, .hurst = {f(hurst)},")
        o.append("    },")
    o.append("};")

    # -- beta fragility: several lengths (the middle index rounds half to even) --
    o.append("")
    o.append("pub const Frag = struct { n: usize, p: []const f64, b: []const f64, h: f64 };")
    o.append("pub const frags = [_]Frag{")
    for n in (3, 4, 5, 7, 8, 9, 30, 31, 300):
        g = np.random.default_rng(1000 + n)
        p, b = g.normal(0.0006, 0.01, n), g.normal(0.0004, 0.009, n)
        h = ep.beta_fragility_heuristic(pd.Series(p), pd.Series(b))
        o.append(f"    .{{ .n = {n}, .p = {floats(p)}, .b = {floats(b)}, .h = {f(h)} }},")
    o.append("};")

    # -- GPD ---------------------------------------------------------------------
    o.append("")
    o.append("pub const Gpd = struct { xs: []const f64, p: f64, threshold: f64, scale: f64, shape: f64, var_: f64, es: f64, n_losses: usize, n_exceed: usize };")
    o.append("pub const gpds = [_]Gpd{")
    for name, seed in (("normal", 11), ("t3", 12), ("t3", 13), ("t5", 14)):
        g = np.random.default_rng(seed)
        n = 400
        if name == "normal":
            x = g.normal(0.0006, 0.01, n)
        elif name == "t3":
            x = 0.01 * g.standard_t(3, n) / 1.7 + 0.0004
        else:
            x = 0.01 * g.standard_t(5, n) / 1.3 + 0.0004
        for p in (0.01, 0.05):
            res = ep.stats.gpd_risk_estimates_aligned(x, p)
            u = res[0]
            losses = -x[x < 0]
            o.append(f"    .{{ .xs = {floats(x)}, .p = {f(p)}, .threshold = {f(res[0])}, .scale = {f(res[1])}, .shape = {f(res[2])},"
                     f" .var_ = {f(res[3])}, .es = {f(res[4])}, .n_losses = {len(losses)}, .n_exceed = {int((losses >= u).sum())} }},")
    o.append("};")
    sys.stdout.write("\n".join(o) + "\n")


def rs_hurst(x):
    """Rescaled-range exponent, block sizes 8, 16, 32, ...: same definition as
    calendar.zig's `hurstExponent`, written a second time (SELF grade)."""
    xs, ys = [], []
    s = 8
    while s <= len(x):
        vals = []
        for k in range(len(x) // s):
            w = x[k * s:(k + 1) * s]
            c = np.cumsum(w - w.mean())
            R = max(c.max(), 0.0) - min(c.min(), 0.0)
            sd = w.std()
            if sd > 0 and R > 0:
                vals.append(R / sd)
        if vals:
            xs.append(np.log(s))
            ys.append(np.log(np.mean(vals)))
        s *= 2
    return float(np.polyfit(xs, ys, 1)[0])


if __name__ == "__main__":
    main()
