"""Foreign vectors for `riskMetrics`' calmar, frozen into `src/testdata/calmar_vectors.zig`.

    V=~/.local/share/zig-libs/oracle-venvs/finstats
    $V/bin/python -I modules/finstats/tools/calmar_oracle.py | zig fmt --stdin > modules/finstats/src/testdata/calmar_vectors.zig

calmar is ffn 1.3.0 `PerformanceStats.calmar`: its calendar-day CAGR over its max drawdown.
Each series starts with a zero return, so ffn's first price is the module's starting level 1
on the first row's date, and both measure the same span and the same peak.

Sharpe and Sortino of `riskMetrics` are not here: no library divides a calendar-day CAGR by
these denominators, see the SPEC's Anchoring section.
"""
import sys

import ffn
import numpy as np
import pandas as pd

rng = np.random.default_rng(20261105)


def main():
    idx = pd.bdate_range("2020-01-01", periods=250)
    o = ["// SPDX-License-Identifier: MIT",
         "// Generated by modules/finstats/tools/calmar_oracle.py. Do not edit by hand.",
         "",
         "pub const dates = [_][]const u8{ " + ", ".join(f'"{d.date().isoformat()}"' for d in idx) + " };",
         "pub const Case = struct { returns: []const f64, calmar: f64 };",
         "pub const cases = [_]Case{"]
    for loc, scale in ((0.0006, 0.008), (0.0002, 0.012), (-0.0003, 0.01), (0.001, 0.006)):
        r = rng.normal(loc, scale, len(idx))
        r[0] = 0.0
        st = ffn.PerformanceStats(pd.Series(np.cumprod(1 + r), index=idx, name="p"))
        o.append("    .{ .returns = &.{" + ", ".join(repr(float(x)) for x in r) + f"}}, .calmar = {float(st.calmar)!r} }},")
    o.append("};")
    sys.stdout.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
