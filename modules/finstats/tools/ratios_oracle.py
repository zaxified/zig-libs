"""Recipe for `src/testdata/ratios_vectors.zig`: reference values for `src/ratios.zig`
from foreign implementations, over seeded synthetic series, replayed by
`src/ratios_test.zig`.

    V=~/.local/share/zig-libs/oracle-venvs/finstats
    $V/bin/python modules/finstats/tools/ratios_oracle.py | zig fmt --stdin > modules/finstats/src/testdata/ratios_vectors.zig

Every expected number is a foreign library run as a BLACK BOX (quantstats 0.0.86,
ffn 1.3.0, scipy, pandas; none of their source is read). Each formula came from
the published description and was then confirmed by running the function.

Inputs: four seeded series (fat tails with 40 exact zeros, crashes, a calm
series with zeros, a short one), every one STARTING with a 0.0 return. The
leading zero is deliberate: quantstats' ulcer index and drawdown series measure
from the first observation, this module's from the level 1 BEFORE the first
return (see oracle.py), and a leading 0.0 makes the two the same thing. It also
makes every series contain an exact zero.

Per series (rf independent):
  - avg_return, risk_return, profit_ratio, win_loss, exposure, csr (common
    sense), cpc, outlier_win / outlier_loss (quantile 0.99 / 0.01), autocorr,
    skew_s / kurt_s -- quantstats functions with prepare_returns=False (its
    price-detection heuristic must not reinterpret a return series);
  - outliers95 / removed90 -- quantstats `outliers` / `remove_outliers`;
  - pct20 -- quantstats `pct_rank(prices, 20)` on 100 * cumprod(1 + r) (ties
    occur: zero returns repeat a price), plus pct_ties on a coarse grid;
  - prom -- ffn `calc_prob_mom(r, other)`.
Per series and rf in (0, 0.03):
  - upi / serenity -- quantstats `ulcer_performance_index` / `serenity_index`,
    times sqrt(points / (points - 1)): quantstats' ulcer index divides by
    points - 1, `slice.ulcerIndex` by points (the series starts with a 0.0
    return, so both measure from level 1 and nothing else differs; if the
    conversion hid a real error the 1e-11 match would not survive four series);
  - rar_qs -- quantstats `rar(rf=rf)`; rar -- the value this module defines:
    `cagr(r - rf_p) / exposure(r)` (quantstats' own rf handling turns every zero
    return nonzero before it counts the exposure; equal to ours at rf = 0, the
    only place the two are compared);
  - smart_sharpe / smart_sortino / sortino_sqrt2 (= quantstats `adjusted_sortino`)
    / smart_sortino_sqrt2 (= `adjusted_sortino(smart=True)`) -- annualised, 252;
  - psr / pso / paso -- `probabilistic_sharpe_ratio` / `_sortino_ratio` /
    `_adjusted_sortino_ratio`; psr_smart / pso_smart / paso_smart -- the same with smart=True;
  - dsr -- ffn `calc_deflated_sharpe_ratio(r, trials, rf)`.
Standalone: normal_cdf (scipy `norm.cdf`), exp_max (ffn `calc_expected_max_sharpe`).
"""
import sys
import warnings

import ffn
import numpy as np
import pandas as pd
import quantstats as qs
from scipy import stats

warnings.filterwarnings("ignore")
S = qs.stats
PPY = 252
TRIALS = [0.5, 1.1, 0.2, 0.9, 1.4, 0.7]


def f(x):
    x = float(x)
    if not np.isfinite(x):
        sys.stderr.write(f"non-finite reference value {x}\n")
        raise SystemExit(1)
    return repr(x)


def floats(xs):
    return "&.{" + ", ".join(f(x) for x in xs) + "}"


def series():
    g = np.random.default_rng(20261105)
    t = g.standard_t(4, 250) * 0.008 + 0.0004
    t[g.choice(250, 40, replace=False)] = 0.0
    c = g.normal(0.0006, 0.006, 250)
    c[g.choice(250, 6, replace=False)] -= g.uniform(0.03, 0.08, 6)
    k = g.normal(0.0004, 0.004, 250)
    k[g.choice(250, 60, replace=False)] = 0.0
    sh = g.normal(0.001, 0.01, 30)
    sh[g.choice(30, 5, replace=False)] = 0.0
    other = g.normal(0.0002, 0.009, 250)
    out = []
    for name, v in (("fat_zeros", t), ("crashes", c), ("calm_zeros", k), ("short", sh)):
        v = np.concatenate([[0.0], v])
        o = np.concatenate([[0.0], other])[: len(v)]
        out.append((name, v, o))
    return out


def ser(v):
    return pd.Series(v, index=pd.bdate_range("2020-01-01", periods=len(v)))


def main():
    o = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by modules/finstats/tools/ratios_oracle.py: reference values from quantstats,",
        "// ffn and scipy over seeded inputs. Replayed by src/ratios_test.zig. Do not edit by hand.",
        "",
        f"pub const ppy = {PPY};",
        "pub const trials = [_]f64{" + ", ".join(f(x) for x in TRIALS) + "};",
        "pub const Ser = struct { name: []const u8, values: []const f64, other: []const f64, avg_return: f64,"
        " risk_return: f64, profit_ratio: f64, win_loss: f64, exposure: f64, csr: f64, cpc: f64, outlier_win: f64,"
        " outlier_loss: f64, autocorr: f64, skew_s: f64, kurt_s: f64, outliers95: []const f64, removed90: []const f64,"
        " pct20: []const f64, prices: []const f64, prom: f64 };",
        "pub const Row = struct { series: usize, rf: f64, upi: f64, serenity: f64, rar_qs: f64, rar: f64,"
        " smart_sharpe: f64, smart_sortino: f64, sortino_sqrt2: f64, smart_sortino_sqrt2: f64, psr: f64, pso: f64,"
        " paso: f64, psr_smart: f64, pso_smart: f64, paso_smart: f64, dsr: f64 };",
        "pub const Pair = struct { f64, f64 };",
        "",
        "pub const series = [_]Ser{",
    ]
    rows = []
    for k, (name, v, ov) in enumerate(series()):
        r, orr = ser(v), ser(ov)
        prices = 100 * np.cumprod(1 + v)
        pct = S.pct_rank(pd.Series(prices), window=20).values
        pr = lambda fn, **kw: fn(r, prepare_returns=False, **kw)
        o.append(
            f'    .{{ .name = "{name}", .values = {floats(v)}, .other = {floats(ov)},'
            f" .avg_return = {f(pr(S.avg_return))}, .risk_return = {f(pr(S.risk_return_ratio))},"
            f" .profit_ratio = {f(pr(S.profit_ratio))}, .win_loss = {f(pr(S.win_loss_ratio))},"
            f" .exposure = {f(pr(S.exposure))}, .csr = {f(pr(S.common_sense_ratio))}, .cpc = {f(pr(S.cpc_index))},"
            f" .outlier_win = {f(pr(S.outlier_win_ratio))}, .outlier_loss = {f(pr(S.outlier_loss_ratio))},"
            f" .autocorr = {f(S.autocorr_penalty(r))}, .skew_s = {f(pr(S.skew))}, .kurt_s = {f(pr(S.kurtosis))},"
            f" .outliers95 = {floats(S.outliers(r, 0.95).values)}, .removed90 = {floats(S.remove_outliers(r, 0.9).values)},"
            f" .pct20 = {floats(pct)}, .prices = {floats(prices)},"
            f" .prom = {f(ffn.core.calc_prob_mom(r, orr))} }},"
        )
        for rf in (0.0, 0.03):
            rfp = (1 + rf) ** (1 / PPY) - 1
            # quantstats' ulcer divides by (points - 1), ours by points: see the docstring
            conv = np.sqrt(len(v) / (len(v) - 1))
            rar = S.cagr(ser(v - rfp)) / S.exposure(r, prepare_returns=False)
            rows.append(
                f"    .{{ .series = {k}, .rf = {f(rf)}, .upi = {f(S.ulcer_performance_index(r, rf=rf) * conv)},"
                f" .serenity = {f(S.serenity_index(r, rf=rf) * conv)}, .rar_qs = {f(S.rar(r, rf=rf))}, .rar = {f(rar)},"
                f" .smart_sharpe = {f(S.smart_sharpe(r, rf=rf, periods=PPY))},"
                f" .smart_sortino = {f(S.smart_sortino(r, rf=rf, periods=PPY))},"
                f" .sortino_sqrt2 = {f(S.adjusted_sortino(r, rf=rf, periods=PPY))},"
                f" .smart_sortino_sqrt2 = {f(S.adjusted_sortino(r, rf=rf, periods=PPY, smart=True))},"
                f" .psr = {f(S.probabilistic_sharpe_ratio(r, rf=rf, periods=PPY))},"
                f" .pso = {f(S.probabilistic_sortino_ratio(r, rf=rf, periods=PPY))},"
                f" .paso = {f(S.probabilistic_adjusted_sortino_ratio(r, rf=rf, periods=PPY))},"
                f" .psr_smart = {f(S.probabilistic_sharpe_ratio(r, rf=rf, periods=PPY, smart=True))},"
                f" .pso_smart = {f(S.probabilistic_sortino_ratio(r, rf=rf, periods=PPY, smart=True))},"
                f" .paso_smart = {f(S.probabilistic_adjusted_sortino_ratio(r, rf=rf, periods=PPY, smart=True))},"
                f" .dsr = {f(ffn.core.calc_deflated_sharpe_ratio(r, np.array(TRIALS), rf=rf, nperiods=PPY))} }},"
            )
    o.append("};")
    o.append("")
    o.append("pub const rows = [_]Row{")
    o.extend(rows)
    o.append("};")
    zs = [-37.0, -10.0, -8.0, -6.5, -4.0, -2.5, -1.3, -0.5, 0.0, 1e-9, 0.3, 1.0, 1.96, 2.2, 3.0, 5.5, 8.0]
    o.append("/// z -> scipy.stats.norm.cdf(z)")
    o.append("pub const normal_cdf = [_]Pair{" + ", ".join(f".{{ {z!r}, {f(stats.norm.cdf(z))} }}" for z in zs) + "};")
    ns = [(2, 0.5), (3, 1.0), (10, 0.1), (100, 0.2), (1000, 1.0), (50000, 0.3), (1, 0.5)]
    o.append("/// (n_trials, sr_std) -> ffn.calc_expected_max_sharpe")
    o.append("pub const exp_max = [_][3]f64{" + ", ".join(
        f".{{ {n}, {s!r}, {f(ffn.core.calc_expected_max_sharpe(n, s)) if n > 1 else '0.0'} }}" for n, s in ns) + "};")
    sys.stdout.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
