"""Recipe for `src/testdata/openssl_kat.zig`: AES-GCM vectors from OpenSSL.

Needs: Python 3 with the `cryptography` package (which encrypts through the
system's OpenSSL libcrypto). Produces: the Zig table on stdout.

    python3 modules/aesgcm/tools/openssl_kat.py > modules/aesgcm/src/testdata/openssl_kat.zig

Key, nonce, AD and plaintext are the test's `pattern` bytes with seeds 1, 2,
3 and 4, so only the tag and SHA-256(ciphertext) need committing. The lengths
cover the paths of the x86-64 kernel: tail only (< 128 bytes), one batch plus
the delayed GHASH (128..255), the stitched loop (>= 256), with and without a
partial last block, AD shorter and longer than one aggregated group.
"""
import hashlib

from cryptography.hazmat.primitives.ciphers.aead import AESGCM


def pattern(n, seed):
    return bytes((i * 31 + seed * 101 + (i >> 8) * 7) & 0xFF for i in range(n))


CASES = [  # (ad_len, m_len)
    (0, 0), (0, 1), (13, 16), (20, 127), (0, 128), (16, 129), (64, 255),
    (0, 256), (129, 257), (7, 383), (128, 384), (13, 480), (300, 1000),
    (0, 1024), (61, 4099), (13, 16384), (1000, 19999),
]

print("// SPDX-License-Identifier: MIT")
print("// Generated by modules/aesgcm/tools/openssl_kat.py (OpenSSL via Python")
print("// `cryptography`). Do not edit by hand.")
print()
print("pub const Vector = struct { bits: u16, ad_len: usize, m_len: usize, tag: []const u8, ct_sha256: []const u8 };")
print()
print("pub const vectors = [_]Vector{")
for bits in (128, 192, 256):
    key = pattern(bits // 8, 1)
    iv = pattern(12, 2)
    for ad_len, m_len in CASES:
        out = AESGCM(key).encrypt(iv, pattern(m_len, 4), pattern(ad_len, 3))
        ct, tag = out[:-16], out[-16:]
        print(f'    .{{ .bits = {bits}, .ad_len = {ad_len}, .m_len = {m_len}, '
              f'.tag = "{tag.hex()}", .ct_sha256 = "{hashlib.sha256(ct).hexdigest()}" }},')
print("};")
