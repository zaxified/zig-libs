"""Generate src/kat_vectors.zig from Python's standard library.

Python (base64.b32encode / base64.b32hexencode, 3.10+) is used only as a
black-box oracle: this script feeds it deterministic inputs and records what it
returns. Nothing of Python's implementation is copied.

Usage: python3 tools/gen_kat.py > src/kat_vectors.zig
"""
import base64
import sys


def inputs():
    # Deterministic, no RNG: lengths 0..41 (covers every length mod 5 and
    # several full groups) over a byte pattern that exercises all 32 symbols,
    # plus a few edge shapes.
    for n in range(0, 42):
        yield bytes((i * 37 + n * 11 + 5) & 0xFF for i in range(n))
    yield bytes(10)  # all zero bits
    yield bytes([0xFF] * 10)  # all one bits
    yield bytes(range(256))  # every byte value


def main():
    out = sys.stdout
    out.write("// SPDX-License-Identifier: MIT\n")
    out.write("//! GENERATED by tools/gen_kat.py -- do not edit by hand.\n")
    out.write("//!\n")
    out.write("//! Known-answer vectors captured from Python's stdlib\n")
    out.write("//! (`base64.b32encode`, `base64.b32hexencode`), used as a black-box\n")
    out.write("//! oracle. Each `raw_hex` is the input; `std` / `hex` are the padded RFC 4648\n")
    out.write("//! section 6 / section 7 encodings Python produced for it.\n\n")
    out.write("pub const Vector = struct { raw_hex: []const u8, std: []const u8, hex: []const u8 };\n\n")
    out.write("pub const vectors = [_]Vector{\n")
    for raw in inputs():
        s = base64.b32encode(raw).decode("ascii")
        h = base64.b32hexencode(raw).decode("ascii")
        out.write('    .{ .raw_hex = "%s", .std = "%s", .hex = "%s" },\n' % (raw.hex(), s, h))
    out.write("};\n")


main()
