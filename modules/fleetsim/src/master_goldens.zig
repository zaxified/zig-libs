test "anchor: replay a real pycomm3 1.2.16 master's recorded session offline" {
    var speed = [_]u8{0} ** 4;
    var level = [_]u8{0} ** 4;
    std.mem.writeInt(i32, speed[0..4], 1500, .little);
    var counts = [_]u8{0} ** (4 * enip_counts.len);
    for (enip_counts, 0..) |v, i| std.mem.writeInt(i32, counts[i * 4 ..][0..4], v, .little);
    var setpoint = [_]u8{0} ** 4;
    std.mem.writeInt(u32, setpoint[0..4], @bitCast(enip_setpoint), .little);
    var verdict = [_]u8{0} ** 32;
    var verdict_pass = [_]u8{0} ** 4;

    const tags = [_]enip.TagBinding{
        .{ .name = "Speed", .type = .dint, .bytes = &speed },
        .{ .name = "Level", .type = .real, .bytes = &level },
        .{ .name = "Counts", .type = .dint, .bytes = &counts },
        .{ .name = "Setpoint", .type = .real, .bytes = &setpoint },
        .{ .name = "Verdict", .type = .dint, .bytes = &verdict },
        .{ .name = "VerdictPass", .type = .dint, .bytes = &verdict_pass },
    };
    var dev = adapters.Enip.init(.{ .product_name = enip_product_name }, &tags);
    try replay(dev.node(), &enip_session, "pycomm3");

    // ── the master's verdict, replayed ─────────────────────────────────────
    // Every number here is one pycomm3 computed from what it decoded, and every
    // expectation is recomputed from the fixture above.
    const slot = struct {
        fn get(b: []const u8, i: usize) i32 {
            return std.mem.readInt(i32, b[i * 4 ..][0..4], .little);
        }
    }.get;
    try testing.expectEqual(@as(i32, 0x0000_F1E9), slot(&verdict, 0)); // "a real master was here"
    try testing.expectEqual(@as(i32, 7), slot(&verdict, 1)); // operations it graded
    try testing.expectEqual(@as(i32, 0), slot(&verdict, 2)); // and none of them failed

    var want_sum: i32 = 0;
    for (enip_counts) |v| want_sum += v;
    try testing.expectEqual(want_sum, slot(&verdict, 3));

    try testing.expectEqual(
        @as(i32, @intFromFloat(@round(enip_setpoint * 10))),
        slot(&verdict, 4),
    );

    var want_name: i32 = 0;
    for (enip_product_name) |c| want_name += c;
    try testing.expectEqual(want_name, slot(&verdict, 5));

    // CIP Vol 1 §B-1.1 0x05 Path destination unknown, as pycomm3 named it for
    // the tag the device does not serve.
    try testing.expectEqual(@as(i32, 0x05), slot(&verdict, 6));

    // Elements 2..4 only. A device that ignored the member segment and read
    // from element 0 would land on 3447 instead — which is exactly the
    // mutation this slot exists to catch.
    var want_slice: i32 = 0;
    for (enip_counts[2..5]) |v| want_slice += v;
    try testing.expectEqual(want_slice, slot(&verdict, 7));

    try testing.expectEqual(@as(i32, 1), slot(&verdict_pass, 0)); // the pass mark
}

