test "anchor: replay a real opendnp3 3.1.2 master's recorded session offline" {
    var binaries: [8]dnp3.outstation.BinaryInput = undefined;
    for (&binaries, dnp3_binaries) |*b, v| b.* = .{ .value = v, .class = .class1 };
    var analogs = [_]dnp3.outstation.AnalogInput{
        .{ .value = dnp3_analog_int[0], .class = .class2 },
        .{ .value = dnp3_analog_int[1], .class = .class2 },
        .{ .value = dnp3_analog_int[2], .class = .class2 },
        .{ .value = dnp3_analog_float, .class = .class2, .static_variation = 5 },
    };
    var counters = [_]dnp3.outstation.Counter{
        .{ .value = dnp3_counters[0], .class = .class3 },
        .{ .value = dnp3_counters[1], .class = .class3 },
    };
    var binary_outputs = [_]dnp3.outstation.BinaryOutputStatus{.{}} ** dnp3_binary_output_count;
    var analog_outputs = [_]dnp3.outstation.AnalogOutputStatus{.{}} ** dnp3_analog_output_count;
    analog_outputs[dnp3_bounded_slot] = .{ .min = 0, .max = 100 };
    var events: [64]dnp3.outstation.Event = undefined;
    var rx_buf: [2048]u8 = undefined;
    var scratch: [512]u8 = undefined;
    var tx_fragment: [2048]u8 = undefined;
    var station: adapters.Dnp3 = undefined;
    station.init(
        .{ .address = 10, .master_address = 1, .unsolicited_supported = true },
        .{
            .binary_inputs = &binaries,
            .analog_inputs = &analogs,
            .counters = &counters,
            .binary_outputs = &binary_outputs,
            .analog_outputs = &analog_outputs,
        },
        dnp3.outstation.EventBuffer.init(&events),
        &rx_buf,
        &scratch,
        &tx_fragment,
    );

    try replay(station.node(), &dnp3_before_fault, "opendnp3");
    // What the live run's scheduled fault does at t=15 s. A replay has no
    // clock, so the same `Control` the fault engine issues is issued here — and
    // the frozen post-fault poll, whose IIN carries device-trouble, is what
    // proves the master saw it.
    try testing.expect(station.node().control(.trouble_on, 0));
    try replay(station.node(), &dnp3_after_fault, "opendnp3");

    // ── the marks, recomputed from the fixture rather than restated ─────────
    const mark = struct {
        fn get(aos: []const dnp3.outstation.AnalogOutputStatus, i: usize) i32 {
            return @intFromFloat(aos[i].value);
        }
    }.get;

    try testing.expectEqual(@as(i32, 53619), mark(&analog_outputs, 0)); // magic
    try testing.expectEqual(@as(i32, 20), mark(&analog_outputs, 1)); // checks run
    try testing.expectEqual(@as(i32, 0), mark(&analog_outputs, 2)); // checks failed

    // A bitmap packed from eight SEPARATE binary decodes, not an echo of any
    // one of them.
    var bitmap: i32 = 0;
    for (dnp3_binaries, 0..) |v, i| {
        if (v) bitmap |= @as(i32, 1) << @intCast(i);
    }
    try testing.expectEqual(bitmap, mark(&analog_outputs, 3));

    var sum: f64 = 0;
    for (dnp3_analog_int) |v| sum += v;
    try testing.expectEqual(@as(i32, @intFromFloat(sum)), mark(&analog_outputs, 4));

    // A difference across two DIFFERENT type decodes — an unsigned g20 counter
    // minus a signed g30v1 analog. No echo of either operand can produce it.
    const counter_minus_analog =
        @as(i32, @intCast(dnp3_counters[0])) - @as(i32, @intFromFloat(dnp3_analog_int[0]));
    try testing.expectEqual(counter_minus_analog, mark(&analog_outputs, 5));

    // The short float taken out of the float domain (x100), then differenced
    // against a signed integer decode: two codecs in one number.
    const float_x100: i32 = @intFromFloat(@round(dnp3_analog_float * 100));
    try testing.expectEqual(
        float_x100 - @as(i32, @intFromFloat(dnp3_analog_int[1])),
        mark(&analog_outputs, 6),
    );

    // The integrity poll's whole SET: every point's index folded with the DNP3
    // group opendnp3's own dispatch chose for it. A device reporting a superset,
    // a missing header, or the right values under the wrong type fails this and
    // passes every value check above.
    const kinds = [_]struct { n: usize, group: i64 }{
        .{ .n = dnp3_binaries.len, .group = 1 },
        .{ .n = dnp3_analog_int.len + 1, .group = 30 },
        .{ .n = dnp3_counters.len, .group = 20 },
        .{ .n = dnp3_binary_output_count, .group = 10 },
        .{ .n = dnp3_analog_output_count, .group = 40 },
    };
    var checksum: i64 = 0;
    for (kinds) |k| {
        for (0..k.n) |i| checksum += @as(i64, @intCast(i)) * 7 + k.group;
    }
    try testing.expectEqual(@as(i32, @intCast(@rem(checksum, 30011))), mark(&analog_outputs, 7));

    // Two DIFFERENT refusals the OUTSTATION chose, as opendnp3's own parser
    // named them: OUT_OF_RANGE (12) for a write past a bounded analog output's
    // limit, NOT_SUPPORTED (4) for a control against an index that does not
    // exist. A device that collapsed them would satisfy either check alone.
    try testing.expectEqual(@as(i32, 12), mark(&analog_outputs, 8));
    try testing.expectEqual(@as(i32, 4), mark(&analog_outputs, 9));
    // The application header, not the object data: IIN1.7 at startup, IIN1.6
    // clear before the fault and set after it.
    try testing.expectEqual(@as(i32, 0b111), mark(&analog_outputs, 10));

    // The bounded slot is still untouched — its refusal is a mark in itself.
    try testing.expectEqual(@as(f64, 0), analog_outputs[dnp3_bounded_slot].value);
    // Commanded last, commanded either way.
    try testing.expect(binary_outputs[1].value); // fault observed
    try testing.expect(binary_outputs[0].value); // pass bit
}
