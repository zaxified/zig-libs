// 0xFFFF (§7.2.5), and `open_connection[1]`'s frozen reply carries `2F 00` —
// this station answering with its OWN common address, which is what §7.2.4
// requires and what the conformance fix in `modules/iec104` (`4158b1d`)
// changed. A real master's recording is now what holds that fix in place.
//
// The recording is split in two because the device is *changed* half way
// through: the live run schedules a `trouble` fault at t=15 s, and the master
