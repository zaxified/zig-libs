// The seventh and last master, and the only one that is not a Python library:
// no installable DNP3 master exists for this guest (see
// `scripts/vm/manifest.sh`'s VM_DEBIAN_SRC for the four candidates and why
// each is closed), so the counterpart is `opendnp3` itself — Apache-2.0,
// upstream archived 2022-05-18 — built from a pinned source inside the
// provisioning recipe and driven by `scripts/vm/guests/fleetsim-dnp3-master.cpp`.
// Every byte below was composed or parsed by opendnp3's own stack; the driver
// contains no DNP3 framing, no CRC and no object parsing of its own.
//
// The fixture is the live test's, rebuilt exactly: eight binary inputs in a
// fixed pattern, three g30v1 signed analogs plus one g30v5 short float, two
// counters, four binary outputs and twelve analog outputs — the last of which
// is range-bounded so the OUTSTATION gets to choose a refusal code. Nothing is
// animated: the earlier version of the live test drove analog input 0 with a
// ramp, which would have made this corpus pin the scheduler's timing rather
// than the protocol.
//
// Order is load-bearing twice over. The first four exchanges are opendnp3's
// own startup handshake — disable unsolicited, clear the restart IIN, the
// startup integrity poll, enable unsolicited — and the restart IIN is *set* in
// the first reply and *clear* from the second, which only a replay in order can
// show. Then the scheduled fault, then everything after it.
//
// The last thirteen exchanges are the master's marks, written back through
// DNP3's control direction (g41v1 analog output blocks, g12v1 control relay
// output blocks). Those request bytes are a function of what the device said,
// computed by a third party — and the assertions at the bottom recompute the
// expected values from the fixture rather than restating them, so a device
// that mis-encoded its replies could not have produced them: opendnp3 would
// have summed different numbers.
