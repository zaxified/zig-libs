test "anchor: replay a real pymodbus 3.14.0 master's recorded session offline" {
    // The live test's fixture, rebuilt exactly (src/root.zig, test "live: a
    // real Modbus master drives a simulated slave over the TCP binding").
    var holdings = [_]u16{0} ** 32;
    var coils = [_]bool{false} ** 32;
    var inputs = [_]u16{ 1000, 2000, 3000, 4000 };
    for (&holdings, 0..) |*h, i| h.* = @intCast(i * 111);

    var slave = adapters.Modbus.init(
        .{ .unit_id = 1, .framing = .tcp, .accept_any_unit = true, .slave_id = "zig-fleetsim" },
        .{
            .holding_registers = .{ .base = 0, .values = &holdings },
            .input_registers = .{ .base = 0, .values = &inputs },
            .coils = .{ .base = 0, .values = &coils },
            .discrete_inputs = .{ .base = 0, .values = &coils },
        },
    );
    const n = slave.node();

    for (session) |x| {
        var out: [512]u8 = undefined;
        const reply = (try n.deliver(x.request, &out, 0)) orelse {
            std.debug.print(
                "pymodbus anchor: the device answered nothing to {s}\n",
                .{x.op},
            );
            return error.NoReplyToRecordedRequest;
        };
        testing.expectEqualSlices(u8, x.response, reply) catch |e| {
            std.debug.print(
                "pymodbus anchor: {s}\n  a real master read this reply as: {s}\n",
                .{ x.op, x.decoded },
            );
            return e;
        };
    }

    // The writes in the recording must actually have landed. If they had not,
    // exchanges 6 and 8 could still have matched by the device echoing state it
    // never stored.
    try testing.expectEqual(@as(u16, 0x1234), holdings[10]);
    try testing.expect(coils[3]);

    // ── the master's verdict, replayed ──────────────────────────────────────
    // The last two exchanges carry numbers pymodbus computed from what it
    // decoded. Comparing them against the fixture — recomputed here, not
    // restated as literals — is the part of this corpus that grades the
    // device's encoding rather than replaying it. A byte-swapped register
    // encoder cannot reach these values: the master would have summed 28416,
    // 56832, … instead of 111, 222, ….
    try testing.expectEqual(@as(u16, 0xF135), holdings[24]); // "a real master was here"
    try testing.expectEqual(@as(u16, 10), holdings[25]); // operations it graded
    try testing.expectEqual(@as(u16, 0), holdings[26]); // and none of them failed
    try testing.expectEqual(@as(u16, 0x02), holdings[27]); // Illegal Data Address, as pymodbus named it

    var want_hsum: u16 = 0;
    for (1..9) |i| want_hsum +%= @intCast(i * 111);
    try testing.expectEqual(want_hsum, holdings[28]);

    var want_isum: u16 = 0;
    for (inputs) |v| want_isum +%= v;
    try testing.expectEqual(want_isum, holdings[29]);

    // Coil 3 set, LSB-first within the byte — the bit order as a third party
    // unpacked it, not as we packed it.
    try testing.expectEqual(@as(u16, 1 << 3), holdings[30]);

    // The pass bit. `false` here would be a real master saying, over the wire,
    // that it was there and is not satisfied.
    try testing.expect(coils[31]);
}

// ─────────────────────────────────────────────────────────────────────────────
// The other four masters, recorded in the same VM lane on the same run.
// ─────────────────────────────────────────────────────────────────────────────
//
// `scripts/vm/run.sh fleetsim debian` drives five counterparts in one boot —
// pymodbus above, plus pycomm3 1.2.16 (EtherNet/IP), bacpypes3 0.0.106
// (BACnet), python-snap7 3.1.0 (S7comm) and asyncua 2.0.1 (OPC UA). Each one
// grades what it read in its own number domain and commands its marks back
// into the device through that protocol's own write service; the live tests in
// `root.zig` assert on those marks, and what follows replays the same sessions
// **offline**, with no VM and no counterpart installed.
//
// ## What "replay" can and cannot mean, per protocol
//
// A replay corpus only works when the device's answer is a pure function of the
// request and the state the earlier requests put it in. That holds for Modbus,
// EtherNet/IP, BACnet and S7comm, and every one of those is replayed
// byte-for-byte below, handshake included — the session/connection setup is
// part of the recording precisely because it is what moves the responder out
// of its initial state.
//
// It does **not** hold for OPC UA, and that is a property of the protocol
// rather than a gap in the effort. A UA session is established with material
// the *server* mints — a server nonce, a session id, an authentication token —
// and every subsequent request carries the token it was handed. Replaying a
// recorded ReadRequest against a freshly constructed server means presenting a
// token that server never issued. There is no byte-exact offline replay of an
// OPC UA session, so none is claimed here: the OPC UA transcript is recorded in
// SPEC.md and graded live by `opcua_verdict`, and this file says so rather than
// freezing something that would only look like evidence.

/// One recorded request and the device's answer to it. `response == null` means
/// the protocol says to answer nothing (an EtherNet/IP `UnRegisterSession`, for
/// instance) — a case a corpus that only stored pairs could not express, and
/// one worth pinning: a device that answered anyway would break a real master.
const Step = struct {
    op: []const u8,
    request: []const u8,
    response: ?[]const u8 = null,
    decoded: []const u8 = "",
};

/// Feed a recorded session to a node and check every answer byte-for-byte.
fn replay(n: Node, steps: []const Step, label: []const u8) !void {
    var out: [64 * 1024]u8 = undefined;
    for (steps) |x| {
        const reply = try n.deliver(x.request, &out, 0);
        if (x.response) |want| {
            const got = reply orelse {
                std.debug.print(
                    "{s} anchor: the device answered nothing to {s}\n  a real master read the" ++
                        " recorded reply as: {s}\n",
                    .{ label, x.op, x.decoded },
                );
                return error.NoReplyToRecordedRequest;
            };
            testing.expectEqualSlices(u8, want, got) catch |e| {
                std.debug.print(
                    "{s} anchor: {s}\n  a real master read this reply as: {s}\n",
                    .{ label, x.op, x.decoded },
                );
                return e;
            };
        } else if (reply != null) {
            std.debug.print(
                "{s} anchor: the device answered {s}, which the protocol says gets no reply\n",
                .{ label, x.op },
            );
            return error.UnexpectedReply;
        }
    }
}

