    // clock, so the same `Control` the fault engine issues is issued here —
    // and the frozen post-fault interrogation is what proves the master saw it.
    try testing.expect(rtu.node().control(.trouble_on, 0));
    try replay(rtu.node(), &iec104_after_fault, "c104");

    // ── the marks, recomputed from the fixture rather than restated ─────────
    const mark = struct {
        fn get(ps: []const iec104.Point, i: usize) i16 {
            for (ps) |p| {
                if (p.ioa != 900 + i) continue;
                return p.element.setpoint_scaled.value;
            }
            unreachable;
        }
    }.get;
    try testing.expectEqual(@as(i16, 26104), mark(&points, 0));
    try testing.expectEqual(@as(i16, 6), mark(&points, 1));
    try testing.expectEqual(@as(i16, 0), mark(&points, 2));
    try testing.expectEqual(iec104_observed_all, mark(&points, 3));

    // The short float, scaled out of the float domain. Commanding it back as a
    // short float would be the read's inverse; a codec wrong in both directions
    // would round-trip it clean.
    const measured_x10: i16 = @intFromFloat(@round(iec104_float * 10));
    try testing.expectEqual(measured_x10, mark(&points, 4));
    // A difference across two DIFFERENT type decodes — SVA minus scaled R32.
    // No echo of either operand can produce it.
    try testing.expectEqual(iec104_scaled - measured_x10, mark(&points, 5));

    // The interrogation SET, not any one value: which IOAs came back under
    // which type ids. A device reporting a superset, or the right values under
    // the wrong types, fails this and passes every value check above.
    var checksum: i32 = 0;
    for (points) |p| {
        if (!p.type_id.isMonitoring()) continue;
        checksum = @rem(checksum + @as(i32, @intCast(p.ioa)) * 7 + @intFromEnum(p.type_id), 30011);
    }
    try testing.expectEqual(@as(i16, @intCast(checksum)), mark(&points, 6));

    // Two DIFFERENT causes the outstation chose, as c104's own APDU analyser
    // named them: §7.2.3 cause 47 for a command to an IOA that is not bound,
    // cause 46 for an interrogation of a common address that is not ours. A
    // device that collapsed them would satisfy either check alone.
    try testing.expectEqual(@as(i16, 47), mark(&points, 7));
    try testing.expectEqual(@as(i16, 46), mark(&points, 8));
    try testing.expectEqual(iec104_invalid_mask, mark(&points, 9));

    // Commanded last, commanded either way.
    for (points) |p| {
        if (p.ioa != 910) continue;
        try testing.expect(p.element.sco.on);
    }
}

