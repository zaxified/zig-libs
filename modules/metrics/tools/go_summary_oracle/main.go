// The Summary oracle: beorn7/perks `quantile.Stream` (MIT) -- the engine that
// prometheus/client_golang v1.24.1 `Summary` feeds every observation to -- run
// as a black box. client_golang's Summary has no public clock seam (`now` is
// an unexported SummaryOpts field), so the sliding window cannot be driven
// from outside; the windowless case (one age bucket, no expiry) is exactly
// "Stream.Insert per observation, Stream.Query per objective", which is what
// this program does. No source is copied.
//
//	go_summary_oracle              interpret a script on stdin, print results
//	go_summary_oracle gen N SEED   print the Zig vectors file for N scripts
//
// Script lines: "objectives q:eps q:eps ...", "observe <v> <t_ns>" (t_ns is
// accepted and ignored: no window), "snapshot <t_ns>" -> "q <v> ..." per
// objective (the stream is empty -> NaN, as client_golang reports).
package main

import (
	"bufio"
	"fmt"
	"math"
	"math/rand"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/beorn7/perks/quantile"
)

type objective struct{ q, eps float64 }

type session struct {
	objs   []objective
	stream *quantile.Stream
	n      int
}

func (s *session) setObjectives(objs []objective) {
	s.objs = objs
	m := map[float64]float64{}
	for _, o := range objs {
		m[o.q] = o.eps
	}
	s.stream = quantile.NewTargeted(m)
	s.n = 0
}

func (s *session) observe(v float64) {
	s.stream.Insert(v)
	s.n++
}

// snapshot mirrors client_golang's summary.Write: NaN for an empty stream.
func (s *session) snapshot() []float64 {
	out := make([]float64, len(s.objs))
	for i, o := range s.objs {
		if s.stream.Count() == 0 {
			out[i] = math.NaN()
		} else {
			out[i] = s.stream.Query(o.q)
		}
	}
	return out
}

func fmtF(v float64) string {
	if math.IsNaN(v) {
		return "nan"
	}
	return strconv.FormatFloat(v, 'g', -1, 64)
}

func interpret() {
	var s session
	sc := bufio.NewScanner(os.Stdin)
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) == 0 {
			continue
		}
		switch f[0] {
		case "objectives":
			var objs []objective
			for _, p := range f[1:] {
				qe := strings.SplitN(p, ":", 2)
				q, _ := strconv.ParseFloat(qe[0], 64)
				e, _ := strconv.ParseFloat(qe[1], 64)
				objs = append(objs, objective{q, e})
			}
			s.setObjectives(objs)
		case "observe":
			v, _ := strconv.ParseFloat(f[1], 64)
			s.observe(v)
		case "snapshot":
			parts := []string{"q"}
			for _, v := range s.snapshot() {
				parts = append(parts, fmtF(v))
			}
			fmt.Println(strings.Join(parts, " "))
		}
	}
}

func gen(nScripts int, seed int64) {
	rng := rand.New(rand.NewSource(seed))
	objSets := [][]objective{
		{{0.5, 0.05}, {0.9, 0.01}, {0.99, 0.001}},
		{{0.5, 0.05}},
		{{0.01, 0.001}, {0.5, 0.02}, {0.95, 0.005}, {0.999, 0.0001}},
		{{0.9, 0.0}, {0.5, 0.0}},
		{{0.25, 0.01}, {0.75, 0.01}},
	}
	fmt.Println("// SPDX-License-Identifier: MIT")
	fmt.Printf("// GENERATED by modules/metrics/tools/go_summary_oracle (beorn7/perks v1.0.1 quantile.Stream, as used by client_golang v1.24.1; gen %d %d) -- do not hand-edit.\n", nScripts, seed)
	fmt.Println("//! Observation scripts and the quantiles perks' Stream reports at each snapshot; replayed by the")
	fmt.Println("//! differential test in `summary.zig` (bit-exact). Regenerate: `cd tools/go_summary_oracle && go run . gen N SEED | zig fmt --stdin > ../../src/summary_oracle_vectors.zig`.")
	fmt.Println()
	fmt.Println("const nan: f64 = @import(\"std\").math.nan(f64);")
	fmt.Println("pub const Snap = struct { after: usize, expect: []const f64 };")
	fmt.Println("pub const Script = struct { objectives: []const @import(\"summary.zig\").Objective, values: []const f64, snaps: []const Snap };")
	fmt.Println()
	fmt.Println("pub const scripts = [_]Script{")
	for i := 0; i < nScripts; i++ {
		objs := objSets[i%len(objSets)]
		n := []int{0, 1, 2, 7, 30, 499, 500, 501, 999, 1000, 1500, 1203, 640, 2100}[rng.Intn(14)]
		if n == 0 {
			n = 1 + rng.Intn(1200)
		}
		var s session
		s.setObjectives(objs)
		vals := make([]float64, n)
		kind := i % 5
		for j := range vals {
			switch kind {
			case 0:
				vals[j] = math.Round(rng.Float64()*100000) / 100
			case 1:
				vals[j] = float64(rng.Intn(40))
			case 2:
				vals[j] = math.Round(math.Exp(rng.NormFloat64())*1000) / 1000
			case 3:
				vals[j] = float64(n - j)
			default:
				vals[j] = float64(j) / 4
			}
		}
		// snapshots: a few random points plus the end (also 0 for NaN case).
		pts := map[int]bool{n: true}
		for k := 0; k < 3; k++ {
			pts[rng.Intn(n+1)] = true
		}
		var after []int
		for p := range pts {
			after = append(after, p)
		}
		sort.Ints(after)
		fmt.Println("    .{")
		fmt.Print("        .objectives = &.{")
		for _, o := range objs {
			fmt.Printf(" .{ .quantile = %s, .epsilon = %s },", fmtZ(o.q), fmtZ(o.eps))
		}
		fmt.Println(" },")
		fmt.Print("        .values = &.{")
		for j, v := range vals {
			if j%12 == 0 {
				fmt.Print("\n            ")
			}
			fmt.Print(fmtZ(v), ", ")
		}
		fmt.Println("\n        },")
		fmt.Println("        .snaps = &.{")
		next := 0
		for _, p := range after {
			for ; next < p; next++ {
				s.observe(vals[next])
			}
			fmt.Printf("            .{ .after = %d, .expect = &.{", p)
			for _, v := range s.snapshot() {
				fmt.Print(" ", fmtZ(v), ",")
			}
			fmt.Println(" } },")
		}
		fmt.Println("        },")
		fmt.Println("    },")
	}
	fmt.Println("};")
}

// fmtZ renders a float as a Zig literal that round-trips exactly.
func fmtZ(v float64) string {
	if math.IsNaN(v) {
		return "nan"
	}
	s := strconv.FormatFloat(v, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

func main() {
	if len(os.Args) == 4 && os.Args[1] == "gen" {
		n, _ := strconv.Atoi(os.Args[2])
		seed, _ := strconv.ParseInt(os.Args[3], 10, 64)
		gen(n, seed)
		return
	}
	interpret()
}
