//! Byte-exact ctnetlink wire captures used by this module's golden tests.
//!
//! Every buffer below is a **raw netlink frame captured off the wire** — not a
//! hand-written or reconstructed layout. Capture recipe (run on this repo's
//! development host; the `nlmon` device delivers a verbatim copy of every
//! netlink frame in the current network namespace to a normal pcap):
//!
//! ```sh
//! # one unprivileged user+network namespace, root inside it:
//! unshare -rn bash -c '
//!   sysctl -w net.netfilter.nf_conntrack_acct=1        # capture set 2 only
//!   sysctl -w net.netfilter.nf_conntrack_timestamp=1   # capture set 2 only
//!   ip link add nlmon0 type nlmon && ip link set nlmon0 up
//!   tcpdump -i nlmon0 -s 0 -c 400 -U -w nl.pcap -Z root &
//!   sleep 2
//!   conntrack -I -s 192.168.1.10 -d 93.184.216.34 -p tcp --sport 51000 \
//!             --dport 443 --state ESTABLISHED -t 431990 -u SEEN_REPLY,ASSURED
//!   conntrack -I -s 10.0.0.1 -d 10.0.0.2 -p udp --sport 5353 --dport 53 -t 30
//!   conntrack -I -s fd00::1 -d fd00::2 -p tcp --sport 40000 --dport 80 \
//!             --state ESTABLISHED -t 300 -u SEEN_REPLY
//!   conntrack -L; conntrack -L -f ipv6
//!   conntrack -G -s 10.0.0.1 -d 10.0.0.2 -p udp --sport 5353 --dport 53
//!   conntrack -D -s 10.0.0.1 -d 10.0.0.2 -p udp --sport 5353 --dport 53
//!   wait'
//! ```
//!
//! (Set 2 additionally passed `-m 42 -w 7` to the first `-I` — mark and zone —
//! and inserted an ICMP flow with `-p icmp --icmp-type 8 --icmp-code 0
//! --icmp-id 1234`.) In a DLT_NETLINK pcap each record carries a 16-byte cooked
//! header whose last two bytes are the netlink family (`0x000c` =
//! `NETLINK_NETFILTER`); the bytes below are what follows that header, i.e. the
//! `nlmsghdr` onwards, exactly as the kernel/conntrack-tools put them on the
//! wire. The same traffic decoded by `strace -f -e trace=sendto,recvmsg -xx`
//! agrees attribute-for-attribute (that capture is what the layout comments in
//! `wire.zig` were cross-checked against).
//!
//! `conntrack` is conntrack-tools v1.4.9; kernel 7.0.0 (x86_64, little-endian).
//! Provenance: these are OS-ABI byte streams produced by the running kernel and
//! by an unmodified upstream tool — no third-party source was read; see /NOTICE.

