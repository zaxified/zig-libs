/// The captures below are little-endian netlink frames (the capture host's
/// byte order). Netlink framing is host-endian, so on a big-endian target the
/// header words and the `nlattr` headers are swapped here, at comptime, into
/// what that kernel would have written; the attribute *values* are big-endian
/// on the wire (ctnetlink) and stay as captured. On a little-endian target
/// this is the identity. Walks `nlmsghdr`s, and the attributes of ctnetlink
/// messages (`type >> 8 == 1`), recursing into `NLA_F_NESTED` ones.
pub fn hostOrder(comptime le: []const u8) [le.len]u8 {
    var out: [le.len]u8 = le[0..le.len].*;
    if (builtin.cpu.arch.endian() == .little) return out;
    @setEvalBranchQuota(2_000_000);
    var off: usize = 0;
    while (off + 16 <= out.len) {
        const len: usize = rd32(&out, off);
        const ty = rd16(&out, off + 4);
        sw32(&out, off);
        sw16(&out, off + 4);
        sw16(&out, off + 6);
        sw32(&out, off + 8);
        sw32(&out, off + 12);
        if (ty >> 8 == 1 and len > 20) swapAttrs(&out, off + 20, off + len);
        off += (len + 3) & ~@as(usize, 3);
    }
    return out;
}

fn swapAttrs(out: []u8, start: usize, end: usize) void {
    var at = start;
    while (at + 4 <= end) {
        const alen: usize = rd16(out, at);
        const aty = rd16(out, at + 2);
        sw16(out, at);
        sw16(out, at + 2);
        if (aty & 0x8000 != 0 and alen > 4) swapAttrs(out, at + 4, at + alen);
        if (alen < 4) break;
        at += (alen + 3) & ~@as(usize, 3);
    }
}

fn rd16(b: []const u8, o: usize) u16 {
    return @as(u16, b[o]) | @as(u16, b[o + 1]) << 8;
}
fn rd32(b: []const u8, o: usize) u32 {
    return @as(u32, rd16(b, o)) | @as(u32, rd16(b, o + 2)) << 16;
}
fn sw16(b: []u8, o: usize) void {
    std.mem.swap(u8, &b[o], &b[o + 1]);
}
fn sw32(b: []u8, o: usize) void {
    std.mem.swap(u8, &b[o], &b[o + 3]);
    std.mem.swap(u8, &b[o + 1], &b[o + 2]);
}

