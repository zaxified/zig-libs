/// EksBlowfishSetup — bcrypt's "expensive key schedule": one salted
/// expansion, then 2^cost alternating plain re-expansions keyed by salt and
/// password. NOTE: this is the *bcrypt_pbkdf* ordering (salt first, then
/// password, and the salted expansion takes the salt as chaining data);
/// the classic bcrypt password hash alternates in the opposite order.
pub fn eksBlowfishSetup(cost: u6, salt: []const u8, key: []const u8) Blowfish {
    var st = Blowfish.initial;
    st.expandState(salt, key);
    const n = @as(usize, 1) << cost;
    var i: usize = 0;
    while (i < n) : (i += 1) {
        st.expand0State(salt);
        st.expand0State(key);
    }
    return st;
}

/// bcrypt_pbkdf's inner hash: EksBlowfish at fixed cost 6 (= 64 expensive
/// iterations) keyed by the SHA-512s of passphrase and salt, then the
/// 32-byte magic "OxychromaticBlowfishSwatDynamite" (8 big-endian words, 4
/// Blowfish blocks) ECB-encrypted 64 times; the 8 result words are emitted
/// LITTLE-endian — the deliberate byte swap the OpenBSD algorithm
/// documents, kept so outputs stay incompatible with raw bcrypt.
pub fn bcryptHash(sha2_pass: [64]u8, sha2_salt: [64]u8) [32]u8 {
    const magic = "OxychromaticBlowfishSwatDynamite"; // 32 bytes, 8 words
    var st = eksBlowfishSetup(6, &sha2_salt, &sha2_pass);
    defer std.crypto.secureZero(u8, std.mem.asBytes(&st));

    var cdata: [8]u32 = undefined;
    for (&cdata, 0..) |*w, i| w.* = std.mem.readInt(u32, magic[i * 4 ..][0..4], .big);
    var round: usize = 0;
    while (round < 64) : (round += 1) {
        var b: usize = 0;
        while (b < 8) : (b += 2) st.encryptWords(&cdata[b], &cdata[b + 1]);
    }

    var out: [32]u8 = undefined;
    for (cdata, 0..) |w, i| std.mem.writeInt(u32, out[i * 4 ..][0..4], w, .little);
    std.crypto.secureZero(u32, &cdata);
    return out;
}

pub const PbkdfError = error{InvalidParameters};

/// OpenBSD `bcrypt_pbkdf(3)`: derive `out.len` key bytes from a passphrase
/// and salt. Per 32-byte output block: sha2salt = SHA-512(salt ||
/// be32(block_index)), then `rounds` XOR-accumulated `bcryptHash`
/// invocations, each rekeyed with the SHA-512 of the previous raw hash.
/// Output bytes are laid out with the OpenBSD stride permutation — byte i
/// of block c lands at out[i*stride + c], stride = ceil(out.len/32) — so
/// truncating the output never yields a prefix of a longer derivation.
/// `rounds` >= 1; pass/salt non-empty; out 1..1024 bytes (OpenBSD's bounds).
pub fn bcryptPbkdf(pass: []const u8, salt: []const u8, rounds: u32, out: []u8) PbkdfError!void {
    const Sha512 = std.crypto.hash.sha2.Sha512;
    if (rounds < 1 or pass.len == 0 or salt.len == 0) return error.InvalidParameters;
    if (out.len == 0 or out.len > 1024) return error.InvalidParameters;

    var sha2_pass: [64]u8 = undefined;
    defer std.crypto.secureZero(u8, &sha2_pass);
    Sha512.hash(pass, &sha2_pass, .{});

    const stride = (out.len + 32 - 1) / 32;
    const amt = (out.len + stride - 1) / stride;

    var remaining = out.len;
    var count: u32 = 1;
    while (remaining > 0) : (count += 1) {
        var count_be: [4]u8 = undefined;
        std.mem.writeInt(u32, &count_be, count, .big);
        var sha2_salt: [64]u8 = undefined;
        defer std.crypto.secureZero(u8, &sha2_salt);
        var h = Sha512.init(.{});
        h.update(salt);
        h.update(&count_be);
        h.final(&sha2_salt);

        var tmp = bcryptHash(sha2_pass, sha2_salt);
        var acc = tmp;
        var r: u32 = 1;
        while (r < rounds) : (r += 1) {
            Sha512.hash(&tmp, &sha2_salt, .{});
            tmp = bcryptHash(sha2_pass, sha2_salt);
            for (&acc, tmp) |*a, t| a.* ^= t;
        }
        std.crypto.secureZero(u8, &tmp);

        // Stride permutation: block c contributes at positions c-1, c-1 +
        // stride, c-1 + 2*stride, ...
        const n = @min(amt, remaining);
        var taken: usize = 0;
        var i: usize = 0;
        while (i < n) : (i += 1) {
            const dest = i * stride + (count - 1);
            if (dest >= out.len) break;
            out[dest] = acc[i];
            taken += 1;
        }
        std.crypto.secureZero(u8, &acc);
        remaining -= taken;
    }
}

