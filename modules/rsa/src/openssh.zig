test "bcrypt_pbkdf agrees with std.crypto's bcrypt.opensshKdf (independent oracle)" {
    // std's OpenBSD-compatible function is `opensshKdf` (its `pbkdf` is a
    // generic PBKDF2-with-bcrypt-PRF that only coincides for outputs of a
    // single 32-byte block). Same parameter shape OpenSSH uses for key
    // files (48 = 32-byte key + 16-byte IV), plus a non-block-aligned
    // length for the stride path.
    var mine: [48]u8 = undefined;
    var theirs: [48]u8 = undefined;
    try bcryptPbkdf("hunter2", "0123456789abcdef", 4, &mine);
    try std.crypto.pwhash.bcrypt.opensshKdf("hunter2", "0123456789abcdef", &theirs, 4);
    try testing.expectEqualSlices(u8, &mine, &theirs);

    var mine2: [17]u8 = undefined;
    var theirs2: [17]u8 = undefined;
    try bcryptPbkdf("p", "s", 2, &mine2);
    try std.crypto.pwhash.bcrypt.opensshKdf("p", "s", &theirs2, 2);
    try testing.expectEqualSlices(u8, &mine2, &theirs2);
}

