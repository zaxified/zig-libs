/// Blowfish block cipher (Schneier, FSE '93): 64-bit blocks, 16-round
/// Feistel network, variable-length key folded into an 18-word P-array and
/// four 256-entry S-boxes. Includes the bcrypt key-schedule variants
/// (`expandState`/`expand0State`) that make the "expensive key setup"
/// possible. Table-based S-box lookups are inherently cache-timing
/// sensitive; acceptable here because bcrypt's schedule is
/// password-randomized, and this module is only used for key-file KDF work.
pub const Blowfish = struct {
    p: [subkey_count]u32,
    s: [4][256]u32,

    const feistel_rounds = 16;
    const subkey_count = feistel_rounds + 2;

    /// The spec's initial state: P-array and S-boxes filled with the
    /// fractional hex digits of pi, in order.
    pub const initial: Blowfish = blk: {
        @setEvalBranchQuota(600_000);
        var st: Blowfish = undefined;
        var idx: usize = 0;
        for (&st.p) |*w| {
            w.* = piWord(idx);
            idx += 1;
        }
        for (&st.s) |*box| {
            for (box) |*w| {
                w.* = piWord(idx);
                idx += 1;
            }
        }
        break :blk st;
    };

    fn piWord(i: usize) u32 {
        var v: u32 = 0;
        for (pi_hex[i * 8 ..][0..8]) |c| {
            const digit: u32 = switch (c) {
                '0'...'9' => c - '0',
                'a'...'f' => c - 'a' + 10,
                else => unreachable,
            };
            v = (v << 4) | digit;
        }
        return v;
    }

    /// Standard Blowfish key schedule: XOR the (cyclically repeated) key
    /// into P, then regenerate P and all S-boxes by chain-encrypting the
    /// all-zero block (spec steps 1-7). Key must be 1..72 bytes (the spec
    /// recommends at most 56 = 448 bits; bcrypt feeds 64-byte SHA-512s).
    pub fn init(key: []const u8) Blowfish {
        var st = initial;
        st.expand0State(key);
        return st;
    }

    /// The Feistel F-function: split x into 4 bytes a,b,c,d, then
    /// F = ((S1[a] + S2[b]) ^ S3[c]) + S4[d], addition mod 2^32.
    fn f(self: *const Blowfish, x: u32) u32 {
        const a: u8 = @truncate(x >> 24);
        const b: u8 = @truncate(x >> 16);
        const c: u8 = @truncate(x >> 8);
        const d: u8 = @truncate(x);
        return ((self.s[0][a] +% self.s[1][b]) ^ self.s[2][c]) +% self.s[3][d];
    }

    /// Encrypt one 64-bit block held as two 32-bit halves, in place.
    /// Two spec rounds per loop iteration so the per-round halve swap
    /// cancels out; the trailing lines are the spec's final un-swap plus
    /// P17/P18 whitening.
    pub fn encryptWords(self: *const Blowfish, xl: *u32, xr: *u32) void {
        var l = xl.*;
        var r = xr.*;
        var i: usize = 0;
        while (i < feistel_rounds) : (i += 2) {
            l ^= self.p[i];
            r ^= self.f(l);
            r ^= self.p[i + 1];
            l ^= self.f(r);
        }
        xl.* = r ^ self.p[feistel_rounds + 1];
        xr.* = l ^ self.p[feistel_rounds];
    }

    /// Decrypt one 64-bit block: identical network with the P-array
    /// traversed in reverse (spec: "decryption is the same as encryption,
    /// except that P1..P18 are used in the reverse order").
    pub fn decryptWords(self: *const Blowfish, xl: *u32, xr: *u32) void {
        var l = xl.*;
        var r = xr.*;
        var i: usize = 0;
        while (i < feistel_rounds) : (i += 2) {
            l ^= self.p[subkey_count - 1 - i];
            r ^= self.f(l);
            r ^= self.p[subkey_count - 2 - i];
            l ^= self.f(r);
        }
        xl.* = r ^ self.p[0];
        xr.* = l ^ self.p[1];
    }

    /// ECB-encrypt one 8-byte block (big-endian halves, the conventional
    /// byte order used by the published test vectors).
    pub fn encryptBlock(self: *const Blowfish, block: [8]u8) [8]u8 {
        var l = std.mem.readInt(u32, block[0..4], .big);
        var r = std.mem.readInt(u32, block[4..8], .big);
        self.encryptWords(&l, &r);
        var out: [8]u8 = undefined;
        std.mem.writeInt(u32, out[0..4], l, .big);
        std.mem.writeInt(u32, out[4..8], r, .big);
        return out;
    }

    /// ECB-decrypt one 8-byte block.
    pub fn decryptBlock(self: *const Blowfish, block: [8]u8) [8]u8 {
        var l = std.mem.readInt(u32, block[0..4], .big);
        var r = std.mem.readInt(u32, block[4..8], .big);
        self.decryptWords(&l, &r);
        var out: [8]u8 = undefined;
        std.mem.writeInt(u32, out[0..4], l, .big);
        std.mem.writeInt(u32, out[4..8], r, .big);
        return out;
    }

    /// Next big-endian 32-bit word from `data`, cycling from the start when
    /// the end is reached (bcrypt's "stream2word"; also exactly how the
    /// standard schedule repeats the key over the P-array).
    fn stream2word(data: []const u8, j: *usize) u32 {
        std.debug.assert(data.len > 0);
        var w: u32 = 0;
        var k: usize = 0;
        while (k < 4) : (k += 1) {
            w = (w << 8) | data[j.*];
            j.* += 1;
            if (j.* >= data.len) j.* = 0;
        }
        return w;
    }

    /// bcrypt's salted key-schedule step, ExpandKey(state, data, key):
    /// XOR `key` into P, then rebuild P and the S-boxes by encrypting a
    /// chaining block that is XORed with successive (cyclic) words of
    /// `data` before every encryption. With `data` all-absent this
    /// degenerates to the standard schedule (`expand0State`).
    pub fn expandState(self: *Blowfish, data: []const u8, key: []const u8) void {
        var j: usize = 0;
        for (&self.p) |*pe| pe.* ^= stream2word(key, &j);
        var l: u32 = 0;
        var r: u32 = 0;
        j = 0;
        var i: usize = 0;
        while (i < subkey_count) : (i += 2) {
            l ^= stream2word(data, &j);
            r ^= stream2word(data, &j);
            self.encryptWords(&l, &r);
            self.p[i] = l;
            self.p[i + 1] = r;
        }
        for (&self.s) |*box| {
            i = 0;
            while (i < 256) : (i += 2) {
                l ^= stream2word(data, &j);
                r ^= stream2word(data, &j);
                self.encryptWords(&l, &r);
                box[i] = l;
                box[i + 1] = r;
            }
        }
    }

    /// bcrypt's plain key-schedule step, ExpandKey(state, 0, key): the
    /// standard Blowfish key schedule (no data-XOR into the chaining
    /// block). `initial` + one `expand0State(key)` == the classic schedule
    /// the ECB test vectors exercise.
    pub fn expand0State(self: *Blowfish, key: []const u8) void {
        var j: usize = 0;
        for (&self.p) |*pe| pe.* ^= stream2word(key, &j);
        var l: u32 = 0;
        var r: u32 = 0;
        var i: usize = 0;
        while (i < subkey_count) : (i += 2) {
            self.encryptWords(&l, &r);
            self.p[i] = l;
            self.p[i + 1] = r;
        }
        for (&self.s) |*box| {
            i = 0;
            while (i < 256) : (i += 2) {
                self.encryptWords(&l, &r);
                box[i] = l;
                box[i + 1] = r;
            }
        }
    }
};

