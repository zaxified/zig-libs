"""Recipe for `src/testdata/wycheproof_{pkcs1v15,pss,oaep}.txt`: the Wycheproof
RSA vectors this module's API can take (Apache-2.0 test data -- see ../NOTICE).

    mkdir -p .zig-cache/wycheproof-rsa && cd .zig-cache/wycheproof-rsa
    B=https://raw.githubusercontent.com/C2SP/wycheproof/main/testvectors_v1
    for f in $(python3 -I ../../modules/rsa/tools/wycheproof.py --list); do curl -sSfLO $B/$f; done
    cd ../..
    python3 -I modules/rsa/tools/wycheproof.py .zig-cache/wycheproof-rsa modules/rsa/src/testdata

Output is line based (parsed at test time, not comptime): `# ...` comments,
`G <source> <sha> <mgfSha> <sLen> <keyhex>` opens a group (the public key as
DER SubjectPublicKeyInfo for the verify families, the PKCS#8 private key for
OAEP), `T <tcId> <result> <flags> <hex>...` is one test; `-` stands for an
empty field. PKCS#1 v1.5 / PSS tests carry msg, sig; OAEP tests msg, ct, label.

Kept: groups whose hash is one of SHA-1/224/256/384/512, whose MGF1 hash equals
the digest hash (the module has one Hash parameter for verify; OAEP has two, so
digest != MGF1 is kept there), and whose modulus is 512..4096 bits. Everything
else is dropped, and the counts are printed into each output header.
"""
import json
import os
import sys

FILES = {
    "pkcs1v15": [
        "rsa_signature_2048_sha224", "rsa_signature_2048_sha256", "rsa_signature_2048_sha384",
        "rsa_signature_3072_sha256", "rsa_signature_3072_sha512", "rsa_signature_4096_sha512",
    ],
    "pss": [
        "rsa_pss_2048_sha256_mgf1_32", "rsa_pss_2048_sha256_mgf1_0", "rsa_pss_2048_sha256_mgf1sha1_20",
        "rsa_pss_misc",
    ],
    "oaep": [
        "rsa_oaep_2048_sha256_mgf1sha256", "rsa_oaep_2048_sha256_mgf1sha1", "rsa_oaep_misc",
    ],
}
HASH = {"SHA-1": "sha1", "SHA-224": "sha224", "SHA-256": "sha256", "SHA-384": "sha384", "SHA-512": "sha512"}

if sys.argv[1:] == ["--list"]:
    print("\n".join(f + "_test.json" for fam in FILES.values() for f in fam))
    sys.exit(0)

src, dst = sys.argv[1], sys.argv[2]


def hx(s):
    return s if s else "-"


for fam, names in FILES.items():
    lines, summary = [], []
    tot = {"kept": 0, "dropped": 0}
    for name in names:
        d = json.load(open(os.path.join(src, name + "_test.json")))
        gk = gd = tk = td = 0
        res = {"valid": 0, "invalid": 0, "acceptable": 0}
        for g in d["testGroups"]:
            sha = HASH.get(g["sha"])
            mgf = HASH.get(g.get("mgfSha", g["sha"]))
            ok = sha and mgf and 512 <= g["keySize"] <= 4096
            if fam != "oaep" and mgf != sha:
                ok = False
            if not ok:
                gd += 1
                td += len(g["tests"])
                continue
            gk += 1
            key = g["privateKeyPkcs8"] if fam == "oaep" else g["publicKeyDer"]
            lines.append(f"G {name} {sha} {mgf} {g.get('sLen', 0)} {key}")
            for t in g["tests"]:
                assert t["result"] in res, t["result"]
                res[t["result"]] += 1
                tk += 1
                fl = ",".join(t["flags"]) or "-"
                if fam == "oaep":
                    lines.append(f"T {t['tcId']} {t['result']} {fl} {hx(t['msg'])} {hx(t['ct'])} {hx(t['label'])}")
                else:
                    lines.append(f"T {t['tcId']} {t['result']} {fl} {hx(t['msg'])} {hx(t['sig'])}")
        summary.append(f"{name}: {d['numberOfTests']} tests; groups kept {gk} dropped {gd}; tests kept {tk} dropped {td}; "
                       f"valid {res['valid']} invalid {res['invalid']} acceptable {res['acceptable']}")
        print(fam, summary[-1], file=sys.stderr)
    hdr = ["# SPDX-License-Identifier: MIT",
           "# Generated by modules/rsa/tools/wycheproof.py from C2SP/wycheproof testvectors_v1. Do not edit by hand.",
           "# The vector data is Wycheproof's, Apache-2.0: see modules/rsa/NOTICE."]
    hdr += ["# " + s for s in summary]
    with open(os.path.join(dst, f"wycheproof_{fam}.txt"), "w") as f:
        f.write("\n".join(hdr + lines) + "\n")
