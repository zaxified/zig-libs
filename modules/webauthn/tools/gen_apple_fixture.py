"""Recipe for src/apple_fixture.zig (synthetic, NOT an Apple vector).

No real `apple` attestation is available offline, so this builds one with the
shape WebAuthn §8.8 describes, using python `cryptography`:

  * a P-256 credential key and a self-signed certificate over it carrying the
    extension 1.2.840.113635.100.8.2 = SEQUENCE { [1] EXPLICIT OCTET STRING
    nonce }, nonce = SHA-256(authData || clientDataHash);
  * the attestation object {fmt: "apple", attStmt: {x5c: [cert]}, authData};
  * `bad_nonce_attestation_object`: the same with a nonce over other data;
  * `other_key_attestation_object`: the certificate is over a different key.

Run from the module directory:  python3 tools/gen_apple_fixture.py > src/apple_fixture.zig
"""
import datetime, hashlib

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID, ObjectIdentifier

NONCE_OID = ObjectIdentifier("1.2.840.113635.100.8.2")
client_data_hash = hashlib.sha256(b"apple fixture client data").digest()


def cbor(v):
    def head(mt, n):
        if n < 24: return bytes([mt << 5 | n])
        if n < 256: return bytes([mt << 5 | 24, n])
        return bytes([mt << 5 | 25]) + n.to_bytes(2, "big")
    if isinstance(v, int):
        return head(0, v) if v >= 0 else head(1, -1 - v)
    if isinstance(v, bytes): return head(2, len(v)) + v
    if isinstance(v, str): return head(3, len(v)) + v.encode()
    if isinstance(v, list): return head(4, len(v)) + b"".join(cbor(x) for x in v)
    if isinstance(v, tuple):  # ordered map
        return head(5, len(v)) + b"".join(cbor(k) + cbor(x) for k, x in v)
    raise TypeError(v)


def der(tag, content):
    n = len(content)
    l = bytes([n]) if n < 128 else (bytes([0x81, n]) if n < 256 else bytes([0x82]) + n.to_bytes(2, "big"))
    return bytes([tag]) + l + content


def make(cert_key, cred_key, nonce_data):
    pub = cred_key.public_key().public_numbers()
    x, y = pub.x.to_bytes(32, "big"), pub.y.to_bytes(32, "big")
    cose = cbor(((1, 2), (3, -7), (-1, 1), (-2, x), (-3, y)))
    cred_id = hashlib.sha256(b"apple cred").digest()
    auth = hashlib.sha256(b"example.org").digest() + bytes([0x41]) + (1).to_bytes(4, "big") + bytes(16) \
        + len(cred_id).to_bytes(2, "big") + cred_id + cose
    nonce = hashlib.sha256(auth + nonce_data).digest()
    ext = der(0x30, der(0xA1, der(0x04, nonce)))
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "apple fixture")])
    t0 = datetime.datetime(2026, 1, 1)
    c = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(cert_key.public_key())
         .serial_number(1).not_valid_before(t0).not_valid_after(t0 + datetime.timedelta(days=3650))
         .add_extension(x509.UnrecognizedExtension(NONCE_OID, ext), critical=False)
         .sign(cert_key, hashes.SHA256()))
    cert = c.public_bytes(serialization.Encoding.DER)
    return cbor((("fmt", "apple"), ("attStmt", (("x5c", [cert]),)), ("authData", auth)))


k1 = ec.derive_private_key(0x1111111111111111111111111111111111111111111111111111111111111111, ec.SECP256R1())
k2 = ec.derive_private_key(0x2222222222222222222222222222222222222222222222222222222222222222, ec.SECP256R1())
good = make(k1, k1, client_data_hash)
bad_nonce = make(k1, k1, b"other data")
other_key = make(k2, k1, client_data_hash)

print("// SPDX-License-Identifier: MIT")
print("//! GENERATED by tools/gen_apple_fixture.py -- synthetic, NOT an Apple vector.\n")
print(f'pub const client_data_hash = hexLit("{client_data_hash.hex()}");')
print(f'pub const attestation_object = hexLit("{good.hex()}");')
print(f'pub const bad_nonce_attestation_object = hexLit("{bad_nonce.hex()}");')
print(f'pub const other_key_attestation_object = hexLit("{other_key.hex()}");')
print('''
fn hexLit(comptime hex: []const u8) [hex.len / 2]u8 {
    comptime {
        @setEvalBranchQuota(200_000);
        var out: [hex.len / 2]u8 = undefined;
        _ = @import("std").fmt.hexToBytes(&out, hex) catch unreachable;
        return out;
    }
}''')
