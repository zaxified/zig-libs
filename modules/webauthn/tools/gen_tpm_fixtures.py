"""Recipe for `src/tpm_fixtures.zig`: the real `tpm` attestation responses of py_webauthn's test suite
(duo-labs/py_webauthn, `tests/test_verify_registration_response_tpm.py`, BSD-3-Clause; test data only), taken from
real authenticators (Surface Pro 4, Dell XPS 13, Lenovo Carbon X1, an ECC public-area TPM).

Run (needs the test file, e.g. fetched with curl, as the argument):
    curl -sL https://raw.githubusercontent.com/duo-labs/py_webauthn/master/tests/test_verify_registration_response_tpm.py -o tpm_tests.py
    python3 -I modules/webauthn/tools/gen_tpm_fixtures.py tpm_tests.py > modules/webauthn/src/tpm_fixtures.zig && zig fmt modules/webauthn/src/tpm_fixtures.zig

Each fixture: the attestation object and the clientDataJSON (its SHA-256 is the `clientDataHash` the statement is bound to).
"""
import base64
import json
import re
import sys


def b64u(s):
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


src = open(sys.argv[1]).read()
tests = re.split(r"\n    def (test_\w+)\(", src)
out = ["// SPDX-License-Identifier: MIT\n",
       "//! GENERATED by tools/gen_tpm_fixtures.py -- real `tpm` attestation responses (py_webauthn test data).\n\n",
       "pub const Fixture = struct {\n    name: []const u8,\n    attestation_object: []const u8,\n    client_data_json: []const u8,\n};\n\n",
       "fn hexLit(comptime hex: []const u8) [hex.len / 2]u8 {\n    comptime {\n        @setEvalBranchQuota(2_000_000);\n        var out: [hex.len / 2]u8 = undefined;\n        _ = @import(\"std\").fmt.hexToBytes(&out, hex) catch unreachable;\n        return out;\n    }\n}\n\n",
       "pub const fixtures = [_]Fixture{\n"]
for i in range(1, len(tests), 2):
    name, body = tests[i], tests[i + 1]
    m = re.search(r'credential = """(\{.*?\})"""', body, re.S)
    if not m:
        continue
    cred = json.loads(m.group(1))
    ao = b64u(cred["response"]["attestationObject"])
    cd = b64u(cred["response"]["clientDataJSON"])
    out.append("    .{\n        .name = \"%s\",\n        .attestation_object = &hexLit(\"%s\"),\n        .client_data_json = &hexLit(\"%s\"),\n    },\n" % (name, ao.hex(), cd.hex()))
out.append("};\n")
sys.stdout.write("".join(out))
