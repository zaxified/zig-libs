//! kat_vectors — recorded KNOWN-ANSWER vectors for the DPF core, the
//! ANTI-SELF-CONSISTENCY anchor for this module.
//!
//! Each vector was produced by an INDEPENDENT Python re-derivation of the
//! same BGI16 construction + same SHA-256 PRG (an external Python script; see
//! SPEC.md "External-reference anchoring"), NOT by this module's own code.
//! A Fable pass's `genWithSeeds`/`eval` must reproduce them byte-exact:
//!   - `cw` pins **Gen** exactly given the fixed root seeds (serialized CW
//!     portion, `Key.serializeCw` layout).
//!   - `eval0`/`eval1` (full domain for the small n=4 cases) and `spot`
//!     (selected `x` for the larger cases) pin **Eval** byte-exact.
//! Matching these defeats "self-consistent but nonstandard" — a Gen/Eval
//! pair that reconstructs but derives CWs differently CANNOT match `cw`.

pub const Vector = struct {
    n: usize,
    out_bytes: usize,
    alpha: u64,
    beta: u64,
    seed0: [16]u8,
    seed1: [16]u8,
    /// serialized CW portion (Key.serializeCw output) — the Gen anchor
    cw: []const u8,
    /// full-domain eval of each party, or empty if only spot-checked
    eval0: []const u64,
    eval1: []const u64,
    /// selected (x, eval0(x), eval1(x)) checks for large domains
    spot: []const [3]u64,
};

