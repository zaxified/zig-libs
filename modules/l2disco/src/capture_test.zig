test "real capture: Ubuntu/lldpd LLDPDU decodes — chassis, port, caps, dual mgmt-address, 3 org-TLVs" {
    const du = try lldp.Lldpdu.parse(&lldpdu_mudurl);

    try testing.expectEqual(lldp.ChassisIdSubtype.mac_address, du.chassis_id.subtype);
    try testing.expect(du.chassis_id.mac().?.eql(Mac.parse("00:23:54:c2:57:02").?));
    try testing.expectEqual(lldp.PortIdSubtype.mac_address, du.port_id.subtype);
    try testing.expect(du.port_id.mac().?.eql(Mac.parse("00:23:54:c2:57:02").?));
    try testing.expectEqual(@as(u16, 120), du.ttl_s);
    try testing.expectEqualStrings("upstairs.ofcourseimright.com", du.system_name.?);

    const caps = du.capabilities.?;
    try testing.expect(caps.capabilities.bridge);
    try testing.expect(caps.capabilities.wlan_ap);
    try testing.expect(caps.capabilities.router);
    try testing.expect(caps.capabilities.station_only);
    try testing.expect(caps.enabled.wlan_ap);
    try testing.expect(!caps.enabled.bridge);

    // First Management Address (typed field): IPv4, ifIndex 2.
    const ma = du.management_address.?;
    try testing.expectEqual(@as(u8, 1), ma.address_subtype); // IPv4
    try testing.expectEqual(lldp.InterfaceNumberingSubtype.if_index, ma.interface_subtype);
    try testing.expectEqual(@as(u32, 2), ma.interface_number);

    // Second Management Address (IPv6) is only reachable via the iterator --
    // a real-world instance of the "repeated optional TLV" shape this
    // module's own synthetic test already covers, now with genuine dual
    // v4+v6 management addresses from one device.
    var mait = du.managementAddressIterator();
    const first = (try mait.next()).?;
    try testing.expectEqual(@as(u8, 1), first.address_subtype);
    const second = (try mait.next()).?;
    try testing.expectEqual(@as(u8, 2), second.address_subtype); // IPv6
    try testing.expectEqualSlices(u8, &.{
        0x20, 0x01, 0x08, 0xa8, 0x10, 0x06, 0x00, 0x04,
        0x02, 0x23, 0x54, 0xff, 0xfe, 0xc2, 0x57, 0x02,
    }, second.address);
    try testing.expectEqual(@as(?lldp.ManagementAddress, null), try mait.next());

    // Three organizationally-specific TLVs: one OUI+subtype this module
    // decodes (802.3 MAC/PHY), one OUI it recognizes but has no subtype
    // decode for, one OUI (IETF MUD, RFC 8520) it does not model at all.
    var org = du.orgIterator();
    const o1 = (try org.next()).?;
    try testing.expectEqualSlices(u8, &lldp.oui_ieee_8023, &o1.oui);
    try testing.expectEqual(@as(u8, 3), o1.subtype);
    try testing.expectEqual(@as(?lldp.OrgValue, null), o1.decode()); // recognized OUI, unimplemented subtype

    const o2 = (try org.next()).?;
    try testing.expectEqualSlices(u8, &lldp.oui_ieee_8023, &o2.oui);
    switch (o2.decode().?) {
        .mac_phy => |mp| {
            try testing.expectEqual(@as(u8, 3), mp.autoneg);
            try testing.expectEqual(@as(u16, 0xecc3), mp.pmd_advertised);
            try testing.expectEqual(@as(u16, 0x0010), mp.operational_mau);
        },
        else => return error.WrongOrgValue,
    }

    const o3 = (try org.next()).?; // the MUD-URL TLV, OUI 00:00:5e (IANA)
    try testing.expectEqualSlices(u8, &.{ 0x00, 0x00, 0x5e }, &o3.oui);
    try testing.expectEqual(@as(?lldp.OrgValue, null), o3.decode()); // unmodelled OUI entirely
    try testing.expect(std.mem.indexOf(u8, o3.info, "https://imright.mud.example.com") != null);

    try testing.expectEqual(@as(?lldp.OrgSpecific, null), try org.next());
}

