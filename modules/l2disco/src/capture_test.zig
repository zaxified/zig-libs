test "real capture: Cisco 3560 CDP frame decodes — device id, address, capabilities, unanchored TLVs untouched" {
    const f = try cdp.Frame.parse(&cdp_cisco_3560, .{});
    try testing.expectEqual(@as(u8, 2), f.version);
    try testing.expectEqual(@as(u8, 180), f.ttl_s);
    try testing.expectEqualStrings("Switch", f.device_id.?);
    try testing.expectEqualStrings("GigabitEthernet0/5", f.port_id.?);
    try testing.expectEqualStrings("cisco WS-C3560G-24PS", f.platform.?);
    try testing.expectEqualStrings("Lab", f.vtp_domain.?);
    try testing.expectEqual(@as(u16, 1), f.native_vlan.?);
    try testing.expectEqual(cdp.Duplex.full, f.duplex.?);
    try testing.expect(f.capabilities.?.l2_switch);
    try testing.expect(f.capabilities.?.igmp_capable);

    var ait = (try f.addressIterator()).?;
    const a = (try ait.next()).?;
    try testing.expectEqualSlices(u8, &.{ 192, 168, 0, 1 }, &a.ip().?.v4);
    try testing.expectEqual(@as(?cdp.Address, null), try ait.next());

    // Real device fields this module deliberately does not decode --
    // Protocol-Hello (0x08), AVVID trust bitmap (0x12) / untrusted-ports CoS
    // (0x13), the *separate* Management Addresses TLV (0x16, distinct from
    // Addresses 0x02), and an undocumented type (0x1a) -- pass through raw,
    // unfailed, via the TLV iterator.
    var it = f.tlvIterator();
    var seen_unanchored = std.EnumSet(UnanchoredCdpTlv).initEmpty();
    while (try it.next()) |tlv| {
        switch (tlv.type) {
            0x0008 => seen_unanchored.insert(.hello),
            0x0012 => seen_unanchored.insert(.avvid_trust),
            0x0013 => seen_unanchored.insert(.avvid_cos),
            0x0016 => seen_unanchored.insert(.mgmt_addrs),
            0x001a => seen_unanchored.insert(.unknown_1a),
            else => {},
        }
    }
    try testing.expect(seen_unanchored.eql(std.EnumSet(UnanchoredCdpTlv).initFull()));
}

