test "real capture: a real Static Route (option 33) passes through raw, unmodelled by this codec" {
    const m = try dhcp.Message.parse(&dhcp_static_route);
    try testing.expectEqual(dhcp.MessageType.offer, m.message_type.?);
    try testing.expectEqualSlices(u8, &.{ 192, 168, 1, 1 }, &m.server_id.?);
    try testing.expectEqual(@as(u32, 86400), m.lease_time_s.?);

    var it = m.optionIterator();
    var saw_static_route = false;
    while (try it.next()) |opt| {
        if (opt.code == 33) {
            try testing.expectEqualSlices(u8, &.{ 10, 0, 0, 1, 10, 0, 0, 2 }, opt.data);
            saw_static_route = true;
        }
    }
    try testing.expect(saw_static_route);
}

