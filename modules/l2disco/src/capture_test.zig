test "real capture: Raspberry Pi DHCPREQUEST decodes — client id, hostname, param list; MUD-URL passes through raw" {
    const m = try dhcp.Message.parse(&dhcp_pi_request);
    try testing.expectEqual(dhcp.Op.boot_request, m.op);
    try testing.expectEqual(dhcp.MessageType.request, m.message_type.?);
    try testing.expect(m.clientMac().?.eql(Mac.parse("b8:27:eb:b8:53:c8").?));
    try testing.expectEqualStrings("raspberrypi", m.host_name.?);
    try testing.expectEqualSlices(u8, &([_]u8{0x01} ++ Mac.parse("b8:27:eb:b8:53:c8").?.octets), m.client_id.?);

    // RFC 8520 MUD-URL (option 161): a real IoT option this codec does not
    // model -- must pass through the raw iterator untouched, not fail parse.
    var it = m.optionIterator();
    var saw_mud = false;
    while (try it.next()) |opt| {
        if (opt.code == 161) {
            try testing.expectEqualStrings(
                "https://mudctl.example.com/.well-known/mud/v1/rasbp101",
                opt.data,
            );
            saw_mud = true;
        }
    }
    try testing.expect(saw_mud);
}

