"""Turn JSON-Schema-Test-Suite draft2020-12 files into Zig test vectors.

    python3 -I extract.py TESTS_DIR OUT.zig [COMMIT]

Keeps only cases whose schema stays inside the subset that
modules/mcp/src/schema_check.zig supports (same rules as its `compile`), and
whose numbers survive an f64 round trip; everything else is counted as skipped.
"""
import json
import os
import re
import sys
import urllib.parse

FILES = """type enum const properties required additionalProperties minProperties
maxProperties items prefixItems minItems maxItems uniqueItems minLength maxLength
minimum maximum exclusiveMinimum exclusiveMaximum multipleOf allOf anyOf oneOf not
if-then-else ref defs boolean_schema""".split()

ANNOTATIONS = {"title", "description", "default", "examples", "$schema", "$comment",
               "deprecated", "readOnly", "writeOnly", "format", "contentEncoding",
               "contentMediaType"}
DATA = {"enum", "const"}
SCHEMA = {"additionalProperties", "items", "not", "if", "then", "else"}
SCHEMA_LIST = {"prefixItems", "allOf", "anyOf", "oneOf"}
SCHEMA_MAP = {"properties", "$defs", "definitions"}
PLAIN = {"type", "required", "minProperties", "maxProperties", "minItems", "maxItems",
         "uniqueItems", "minLength", "maxLength", "minimum", "maximum",
         "exclusiveMinimum", "exclusiveMaximum", "multipleOf"}
DIALECT = "https://json-schema.org/draft/2020-12/schema"


class Skip(Exception):
    pass


def resolve(root, ref):
    if ref == "#":
        return True
    for prefix, key in (("#/$defs/", "$defs"), ("#/definitions/", "definitions")):
        if ref.startswith(prefix):
            name = urllib.parse.unquote(ref[len(prefix):], errors="strict")
            if "/" in name:
                return False
            name = name.replace("~1", "/").replace("~0", "~")
            return isinstance(root, dict) and isinstance(root.get(key), dict) and name in root[key]
    return False


def walk(root, s, depth=0):
    if isinstance(s, bool):
        return
    if not isinstance(s, dict):
        raise Skip("not a schema")
    for k, v in s.items():
        if k == "$schema" and v != DIALECT:
            raise Skip("other dialect")
        if k in ANNOTATIONS or k.startswith("x-") or k in DATA or k in PLAIN:
            continue
        if k == "pattern":
            raise Skip("pattern is not checked")
        if k == "$id":
            if depth != 0:
                raise Skip("nested $id")
        elif k == "$ref":
            if not isinstance(v, str) or not resolve(root, v):
                raise Skip("unsupported $ref")
        elif k in SCHEMA:
            walk(root, v, depth + 1)
        elif k in SCHEMA_LIST:
            for x in v:
                walk(root, x, depth + 1)
        elif k in SCHEMA_MAP:
            for x in v.values():
                walk(root, x, depth + 1)
        else:
            raise Skip("unsupported keyword " + k)


inexact = False


def hook_int(s):
    global inexact
    if abs(int(s)) > 2**53:
        inexact = True
    return int(s)


def hook_float(s):
    global inexact
    digits = re.sub(r"[eE].*$", "", s).replace("-", "").replace(".", "").strip("0")
    if len(digits) > 15:
        inexact = True
    return float(s)


def main():
    global inexact
    tests_dir, out = sys.argv[1], sys.argv[2]
    commit = sys.argv[3] if len(sys.argv) > 3 else "unknown"
    cases, stats = [], []
    for name in FILES:
        with open(os.path.join(tests_dir, name + ".json"), encoding="utf-8") as f:
            groups = json.load(f, parse_int=hook_int, parse_float=hook_float)
        run = skipped = 0
        for g in groups:
            inexact = False
            try:
                walk(g["schema"], g["schema"])
                ok = True
            except Skip:
                ok = False
            for t in g["tests"]:
                if ok and not inexact:
                    cases.append((name, g["description"], g["schema"], t["data"],
                                  t["description"], t["valid"]))
                    run += 1
                else:
                    skipped += 1
        stats.append((name, run, skipped))
    # The hooks flag inexact numbers while loading; re-run per test would be
    # costlier than needed, so the flag is per group (conservative).
    def lit(v):
        return json.dumps(v, ensure_ascii=True, separators=(",", ":"), allow_nan=False)
    with open(out, "w", encoding="utf-8") as o:
        o.write("// SPDX-License-Identifier: MIT\n")
        o.write("// GENERATED by tools/schema_suite/extract.py from JSON-Schema-Test-Suite\n")
        o.write("// (MIT, Julian Berman) commit %s, tests/draft2020-12. Do not edit.\n" % commit)
        o.write("// cases: %d run, %d skipped\n" % (len(cases), sum(s for _, _, s in stats)))
        for name, r, s in stats:
            o.write("//   %-22s run %4d  skipped %4d\n" % (name, r, s))
        o.write("\npub const Case = struct {\n    file: []const u8,\n    description: []const u8,\n"
                "    schema: []const u8,\n    data: []const u8,\n    valid: bool,\n};\n\n")
        o.write("pub const cases = [_]Case{\n")
        for name, gd, schema, data, td, valid in cases:
            desc = (gd + " / " + td).encode("ascii", "replace").decode("ascii")  # Zig-safe
            o.write("    .{ .file = %s, .description = %s,\n" % (json.dumps(name), json.dumps(desc)))
            o.write("        .schema =\n        \\\\%s\n        ,\n" % lit(schema))
            o.write("        .data =\n        \\\\%s\n        ,\n" % lit(data))
            o.write("        .valid = %s },\n" % ("true" if valid else "false"))
        o.write("};\n")
    print("cases:", len(cases), "skipped:", sum(s for _, _, s in stats))


main()
