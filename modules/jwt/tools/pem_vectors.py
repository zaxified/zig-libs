"""Recipe for `src/pem_vectors.zig`: private keys in the PEM forms `openssl`
writes, each with its public key (`openssl pkey -pubout`), for the
`PrivateKey.fromPem` / `Key.fromPem` tests. Fresh keys every run; the
committed file is one such run. Published TEST keys: never use them for
anything else.

    python3 -I tools/pem_vectors.py > src/pem_vectors.zig

Needs `openssl` (3.5 or later: ML-DSA) and `zig` (for `zig fmt --stdin`).
"""

import io
import os
import subprocess
import sys
import tempfile


def run(*args, cwd):
    subprocess.run(args, cwd=cwd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def read(cwd, name):
    with open(os.path.join(cwd, name)) as f:
        return f.read()


def zig_str(s):
    lines = s.splitlines(keepends=True)
    body = "\n".join("        \\\\" + l.rstrip("\n") for l in lines) + "\n"
    return body + ("        ++ \"\\n\"\n" if s.endswith("\n") else "")


def main():
    with tempfile.TemporaryDirectory() as d:
        version = subprocess.run(["openssl", "version"], check=True, capture_output=True, text=True).stdout.strip().split(" (")[0]
        ok, refused = [], []
        run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", "p256.p8", cwd=d)
        run("openssl", "ec", "-in", "p256.p8", "-out", "p256.sec1", cwd=d)
        ok += [("p256-pkcs8", "ES256", "p256.p8"), ("p256-sec1", "ES256", "p256.sec1")]
        run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-384", "-out", "p384.p8", cwd=d)
        ok += [("p384-pkcs8", "ES384", "p384.p8")]
        run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-521", "-out", "p521.p8", cwd=d)
        run("openssl", "ec", "-in", "p521.p8", "-out", "p521.sec1", cwd=d)
        ok += [("p521-sec1", "ES512", "p521.sec1")]
        run("openssl", "genpkey", "-algorithm", "ED25519", "-out", "ed.p8", cwd=d)
        ok += [("ed25519-pkcs8", "EdDSA", "ed.p8")]
        run("openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", "rsa.p8", cwd=d)
        run("openssl", "rsa", "-traditional", "-in", "rsa.p8", "-out", "rsa.p1", cwd=d)
        ok += [("rsa-pkcs8", "RS256", "rsa.p8"), ("rsa-pkcs1", "RS256", "rsa.p1")]
        run("openssl", "genpkey", "-algorithm", "ML-DSA-44", "-out", "mldsa.both", cwd=d)
        run("openssl", "pkey", "-in", "mldsa.both", "-provparam", "ml-dsa.output_formats=seed-only", "-out", "mldsa.seed", cwd=d)
        run("openssl", "pkey", "-in", "mldsa.both", "-provparam", "ml-dsa.output_formats=priv-only", "-out", "mldsa.priv", cwd=d)
        ok += [("mldsa44-both", "ML-DSA-44", "mldsa.both"), ("mldsa44-seed", "ML-DSA-44", "mldsa.seed")]
        refused += [("mldsa44-expanded", "mldsa.priv")]
        run("openssl", "genpkey", "-algorithm", "X25519", "-out", "x25519.p8", cwd=d)
        run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:secp256k1", "-out", "k256.p8", cwd=d)
        run("openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:1024", "-out", "rsa1024.p8", cwd=d)
        run("openssl", "pkcs8", "-topk8", "-in", "p256.p8", "-out", "p256.enc", "-passout", "pass:test", cwd=d)
        refused += [("x25519", "x25519.p8"), ("secp256k1", "k256.p8"), ("rsa-1024", "rsa1024.p8"), ("encrypted", "p256.enc")]
        for _, _, key in ok:
            run("openssl", "pkey", "-in", key, "-pubout", "-out", key + ".pub", cwd=d)
        run("openssl", "pkey", "-in", "rsa1024.p8", "-pubout", "-out", "rsa1024.pub", cwd=d)
        run("openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", "rsa2.p8", cwd=d)
        run("openssl", "rsa", "-in", "rsa2.p8", "-RSAPublicKey_out", "-out", "rsa2.pkcs1pub", cwd=d)

        buf = io.StringIO()
        w = buf.write
        w("// SPDX-License-Identifier: MIT\n\n")
        w("//! TEST keys in the PEM forms `openssl` writes, with their public keys,\n")
        w("//! generated by `tools/pem_vectors.py` with %s. Published test\n" % version)
        w("//! fixtures: never use these keys for anything else. Do not edit by hand.\n\n")
        w("pub const Case = struct { name: []const u8, alg: []const u8, key_pem: []const u8, pub_pem: []const u8 };\n\n")
        w("pub const cases = [_]Case{\n")
        for name, alg, key in ok:
            w("    .{\n        .name = \"%s\",\n        .alg = \"%s\",\n        .key_pem =\n%s        ,\n        .pub_pem =\n%s        ,\n    },\n"
              % (name, alg, zig_str(read(d, key)), zig_str(read(d, key + ".pub"))))
        w("};\n\n")
        w("/// Keys `PrivateKey.fromPem` refuses.\n")
        w("pub const refused = [_]struct { name: []const u8, key_pem: []const u8 }{\n")
        for name, key in refused:
            w("    .{\n        .name = \"%s\",\n        .key_pem =\n%s        ,\n    },\n" % (name, zig_str(read(d, key))))
        w("};\n\n")
        w("/// A 1024-bit RSA public key, below the 2048-bit floor.\n")
        w("pub const rsa1024_pub_pem =\n%s;\n" % zig_str(read(d, "rsa1024.pub")))
        w("/// An RSA public key as PKCS#1 `RSA PUBLIC KEY`.\n")
        w("pub const rsa_pkcs1_pub_pem =\n%s;\n" % zig_str(read(d, "rsa2.pkcs1pub")))
        res = subprocess.run(["zig", "fmt", "--stdin"], input=buf.getvalue(), check=True, capture_output=True, text=True).stdout
        sys.stdout.write(res)


if __name__ == "__main__":
    main()
