#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Regenerates modules/bitcointx/src/merkle_kat_vectors.zig: real mainnet blocks
and transactions for the Merkle-root / witness-commitment / weight tests.

Sources (public, unauthenticated GETs against the blockstream.info explorer API):
  * /api/block/<hash>/raw        -- the raw block (header + transactions)
  * /api/block/<hash>            -- the explorer's own reported merkle_root, tx_count, weight
  * /api/tx/<txid>/hex, /api/tx/<txid> -- the raw transaction and the explorer's reported
                                          size/weight

Before emitting anything the script INDEPENDENTLY RECOMPUTES the Merkle root (Bitcoin's
duplicate-last-on-odd rule), the witness commitment (BIP141) and each weight from the raw bytes
in pure Python (it never reads this module's Zig source) and asserts them against the explorer's
values. A mismatch is a hard failure.

    python3 modules/bitcointx/tools/gen_merkle_vectors.py
    python3 modules/bitcointx/tools/gen_merkle_vectors.py --check   # exit 1 on diff, write nothing
"""

import hashlib
import json
import os
import sys
import urllib.request

API = "https://blockstream.info/api"
BLOCKS = [
    # (label, block hash)
    ("genesis", "000000000019d6689c085ae165831e934ff763ae46a2a6c172b3f1b60a8ce26f"),   # height 0, 1 tx
    ("block170", "00000000d1145790a8694403d4063f323d499e655c83426834d4ce2f8dd4a2ee"),  # 2 txs, even count
    ("block484435", "00000000000000000126f2156d4957285e19cc105a74f8711d576a88d9f99779"),  # segwit, 8 txs, commitment
]
TXS = [
    ("segwit_1in1out", "fe6c48bbfdc025670f4db0340650ba5a50f9307b091d9aaa19aa44291961c69f"),  # weight % 4 != 0
    ("segwit_3in3out", "7accfd79a8bac3163eb4b55c929351917c7cf2ed222ec14e944b47f6b7fb3b7d"),
    ("legacy_5in", "1ae52bdc27a98d37d994fe105faaabbe7e04776067677e03a896d4b5bfd477f8"),
]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "merkle_kat_vectors.zig")


def get(path, raw=False):
    with urllib.request.urlopen(API + path, timeout=60) as r:
        b = r.read()
    return b if raw else json.loads(b)


def dsha(b):
    return hashlib.sha256(hashlib.sha256(b).digest()).digest()


def cs(b, o):
    f = b[o]
    if f < 0xFD:
        return f, o + 1
    if f == 0xFD:
        return int.from_bytes(b[o + 1:o + 3], "little"), o + 3
    if f == 0xFE:
        return int.from_bytes(b[o + 1:o + 5], "little"), o + 5
    return int.from_bytes(b[o + 1:o + 9], "little"), o + 9


def parse_tx(b, o):
    """-> (end, legacy_bytes, full_bytes, has_witness)"""
    start = o
    o += 4
    segwit = b[o] == 0 and b[o + 1] != 0
    if segwit:
        o += 2
    n_in, o = cs(b, o)
    in_start = o
    for _ in range(n_in):
        o += 36
        l, o = cs(b, o)
        o += l + 4
    n_out, o = cs(b, o)
    for _ in range(n_out):
        o += 8
        l, o = cs(b, o)
        o += l
    in_out_end = o
    wit_start = o
    if segwit:
        for _ in range(n_in):
            n, o = cs(b, o)
            for _ in range(n):
                l, o = cs(b, o)
                o += l
    wit_end = o
    o += 4
    full = b[start:o]
    if segwit:
        # legacy = version | inputs..outputs | locktime
        legacy = b[start:start + 4] + b[start + 6:in_out_end] + b[wit_end:o]
    else:
        legacy = full
    return o, legacy, full, segwit


def merkle(hs):
    mutated = False
    hs = list(hs)
    if not hs:
        return bytes(32), False
    while len(hs) > 1:
        for i in range(0, len(hs) - 1, 2):
            if hs[i] == hs[i + 1]:
                mutated = True
        if len(hs) & 1:
            hs.append(hs[-1])
        hs = [dsha(hs[i] + hs[i + 1]) for i in range(0, len(hs), 2)]
    return hs[0], mutated


def parse_block(raw):
    hdr = raw[:80]
    n, o = cs(raw, 80)
    txs = []
    for _ in range(n):
        end, legacy, full, seg = parse_tx(raw, o)
        txs.append((legacy, full, seg))
        o = end
    assert o == len(raw)
    return hdr, txs


def weight(legacy, full):
    return len(legacy) * 3 + len(full)


def main():
    check = "--check" in sys.argv
    out = []
    w = out.append
    w("// SPDX-License-Identifier: MIT")
    w("// Generated by tools/gen_merkle_vectors.py from real mainnet data -- see the doc comment below.")
    w("// Do not hand-edit hex payloads; regenerate instead.")
    w("")
    w("//! Real, externally-sourced fixtures for `merkle_test.zig` and the weight tests in `tx.zig`.")
    w("//!")
    w("//! Raw blocks and transactions were fetched from the blockstream.info explorer API by block hash /")
    w("//! txid. The expected Merkle roots (`header_merkle_root`) are the 32 header octets at offset 36 --")
    w("//! values the Bitcoin network itself fixed -- and the expected weights are the explorer's own")
    w("//! reported `weight` (Bitcoin Core's GetTransactionWeight). The generator additionally recomputes")
    w("//! Merkle root, BIP141 witness commitment and weight in pure Python and refuses to emit on any")
    w("//! mismatch. Hashes here are in internal (wire) byte order.")
    w("")
    for label, h in BLOCKS:
        raw = get(f"/block/{h}/raw", raw=True)
        info = get(f"/block/{h}")
        hdr, txs = parse_block(raw)
        assert len(txs) == info["tx_count"], label
        root_wire = hdr[36:68]
        assert root_wire[::-1].hex() == info["merkle_root"], label
        txids = [dsha(t[0]) for t in txs]
        mr, mut = merkle(txids)
        assert mr == root_wire and not mut, label
        wids = [bytes(32)] + [dsha(t[1]) for t in txs[1:]]
        wroot, _ = merkle(wids)
        total_w = sum(weight(t[0], t[1]) for t in txs) + 80 * 4 + (len(raw) - 80 - sum(len(t[1]) for t in txs)) * 4
        assert total_w == info["weight"], (label, total_w, info["weight"])
        has_commit = any(t[2] for t in txs)
        w(f"pub const {label}_hex = \"{raw.hex()}\";")
        w(f"/// Witness merkle root (coinbase wtxid = 0), internal byte order.")
        w(f"pub const {label}_witness_root_hex = \"{wroot.hex()}\";")
        w(f"pub const {label}_tx_count: usize = {len(txs)};")
        w(f"pub const {label}_has_witness_commitment = {'true' if has_commit else 'false'};")
        w("")
    for label, t in TXS:
        raw = get(f"/tx/{t}/hex", raw=True).decode().strip()
        info = get(f"/tx/{t}")
        b = bytes.fromhex(raw)
        end, legacy, full, seg = parse_tx(b, 0)
        assert end == len(b)
        assert dsha(legacy)[::-1].hex() == t, label
        assert len(full) == info["size"], label
        wt = weight(legacy, full)
        assert wt == info["weight"], (label, wt, info["weight"])
        w(f"pub const tx_{label}_hex = \"{raw}\";")
        w(f"pub const tx_{label}_base_size: usize = {len(legacy)};")
        w(f"pub const tx_{label}_total_size: usize = {len(full)};")
        w(f"pub const tx_{label}_weight: usize = {wt};")
        w(f"pub const tx_{label}_vsize: usize = {(wt + 3) // 4};")
        w("")
    text = "\n".join(out)
    if check:
        cur = open(OUT).read()
        sys.exit(0 if cur == text else 1)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", OUT)


main()
