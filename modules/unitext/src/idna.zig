//! UTS #46 (Unicode IDNA Compatibility Processing): `toAscii` and `toUnicode` for domain
//! names, the processing the WHATWG URL Standard, browsers, the Rust `idna` crate, ada and
//! ICU `uidna` run on a host name before it reaches DNS. Mapping (case folding and the
//! compatibility mappings of IdnaMappingTable.txt), NFC, label splitting, Punycode
//! (RFC 3492) and the validity criteria of UTS #46 §4.1: NFC, hyphens, no leading mark,
//! status of every code point, ContextJ (ZWJ / ZWNJ, RFC 5892 Appendix A) and the Bidi rule
//! (RFC 5893). The tables are `idna_tables.zig`, generated by `tools/ucd_gen/idna_gen.py`.
//!
//! `Options` defaults are the WHATWG URL Standard's (CheckHyphens off, CheckBidi and
//! CheckJoiners on, UseSTD3ASCIIRules off, non-transitional, no length check), which keeps
//! underscores and other DNS-legal ASCII in a name; `std3()` gives the strict set of UTS #46
//! `IdnaTestV2.txt`. ContextO (RFC 5892 A.3-A.9) is not part of UTS #46 and is not checked.

const std = @import("std");
const utf8 = @import("utf8.zig");
const norm = @import("norm.zig");
const props = @import("props.zig");
const tab = @import("idna_tables.zig");

/// The Unicode version of the mapping table.
pub const idna_version = tab.idna_version;

/// UTS #46 §4 processing flags.
pub const Options = struct {
    /// V2 / V3: no "--" in positions 3-4, no leading or trailing hyphen; with it off a
    /// label must not start with "xn--" unless it is one (V5).
    check_hyphens: bool = false,
    /// Bn: the Bidi rule of RFC 5893 on every label of a domain that has a right-to-left label.
    check_bidi: bool = true,
    /// Cn: ContextJ for U+200C / U+200D.
    check_joiners: bool = true,
    /// U1: only a-z, 0-9 and "-" among the ASCII code points.
    use_std3_ascii_rules: bool = false,
    /// Transitional processing maps the four deviation characters (ß, ς, ZWJ, ZWNJ) as IDNA2003 did;
    /// the default keeps them (IDNA2008).
    transitional: bool = false,
    /// A4_1 / A4_2 of `toAscii`: the name is 1..253 bytes and every label 1..63 (an empty label,
    /// a trailing dot's included, is an error, as in UTS #46's own tests).
    verify_dns_length: bool = false,
    /// Cap on the bytes of any intermediate or final string (`error.TooLarge`).
    max_output: usize = 1 << 16,

    /// The strict flags of UTS #46's own conformance file `IdnaTestV2.txt`.
    pub fn std3() Options {
        return .{ .check_hyphens = true, .use_std3_ascii_rules = true, .verify_dns_length = true };
    }
};

pub const Error = error{
    /// The input is not well-formed UTF-8.
    InvalidUtf8,
    OutOfMemory,
    TooLarge,
    /// `toAscii`: processing recorded an error (UTS #46 says the result is unusable).
    InvalidDomain,
};

/// `toUnicode`'s answer: the processed text (always produced, as UTS #46 specifies) and
/// whether processing found no error.
pub const Result = struct {
    text: []u8,
    valid: bool,

    pub fn deinit(r: *Result, gpa: std.mem.Allocator) void {
        gpa.free(r.text);
        r.* = undefined;
    }
};

/// UTS #46 ToASCII: the domain as ASCII, each non-ASCII label as "xn--" + Punycode.
/// `error.InvalidDomain` when processing recorded any error. Free the result with `gpa`.
pub fn toAscii(gpa: std.mem.Allocator, domain: []const u8, o: Options) Error![]u8 {
    var p = try process(gpa, domain, o, true);
    defer p.deinit(gpa);
    if (p.bad) return error.InvalidDomain;
    return gpa.dupe(u8, p.text);
}

/// UTS #46 ToUnicode: the domain with every "xn--" label decoded and the rest mapped and
/// normalized; `valid` is false when processing recorded an error (the text is then still
/// the best effort, never to be used as a name).
pub fn toUnicode(gpa: std.mem.Allocator, domain: []const u8, o: Options) Error!Result {
    var p = try process(gpa, domain, o, false);
    defer p.deinit(gpa);
    return .{ .text = try gpa.dupe(u8, p.text), .valid = !p.bad };
}

const Processed = struct {
    arena: std.heap.ArenaAllocator,
    text: []u8 = &.{},
    bad: bool = false,

    fn deinit(p: *Processed, _: std.mem.Allocator) void {
        p.arena.deinit();
    }
};

// ── the mapping table ───────────────────────────────────────────────────────

const Status = enum(u3) { valid, mapped, deviation, disallowed, ignored };

const Entry = struct {
    status: Status,
    /// The mapping (mapped, deviation); empty otherwise.
    to: []const u32,
};

fn entry(cp: u21) Entry {
    // Last range whose start is <= cp.
    var lo: usize = 0;
    var hi: usize = tab.map_starts.len;
    while (hi - lo > 1) {
        const mid = lo + (hi - lo) / 2;
        if (tab.map_starts[mid] <= cp) lo = mid else hi = mid;
    }
    const info = tab.map_info[lo];
    const len = (info >> 3) & 31;
    const off = info >> 8;
    return .{ .status = @fromBackingInt(@intCast(@as(u3, @truncate(info)))), .to = tab.map_pool[off..][0..len] };
}

fn joiningType(cp: u21) u8 {
    var lo: usize = 0;
    var hi: usize = tab.jt_lo.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (cp < tab.jt_lo[mid]) {
            hi = mid;
        } else if (cp > tab.jt_hi[mid]) {
            lo = mid + 1;
        } else return tab.jt_type[mid];
    }
    return 0;
}

const jt_l = 1;
const jt_d = 2;
const jt_r = 3;
const jt_t = 4;

// ── processing ──────────────────────────────────────────────────────────────

fn appendCp(list: *std.ArrayList(u8), a: std.mem.Allocator, cp: u21, cap: usize) Error!void {
    var buf: [4]u8 = undefined;
    const n = std.unicode.utf8Encode(cp, &buf) catch return error.InvalidDomain;
    if (list.items.len + n > cap) return error.TooLarge;
    try list.appendSlice(a, buf[0..n]);
}

const Label = struct {
    text: []const u8,
    /// Came from Punycode: validity is judged non-transitionally.
    from_puny: bool = false,
};

fn process(gpa: std.mem.Allocator, domain: []const u8, o: Options, ascii: bool) Error!Processed {
    var p: Processed = .{ .arena = .init(gpa) };
    errdefer p.arena.deinit();
    const a = p.arena.allocator();
    if (domain.len > o.max_output) return error.TooLarge;

    // 1. Map.
    var mapped: std.ArrayList(u8) = .empty;
    var i: usize = 0;
    while (i < domain.len) {
        const st = utf8.step(domain, i);
        if (!st.valid) return error.InvalidUtf8;
        i += st.len;
        const e = entry(st.cp);
        switch (e.status) {
            .valid => try appendCp(&mapped, a, st.cp, o.max_output),
            .disallowed => {
                p.bad = true;
                try appendCp(&mapped, a, st.cp, o.max_output);
            },
            .ignored => {},
            .mapped => for (e.to) |c| {
                // Transitional processing maps what a mapping produced once more
                // (U+1E9E -> U+00DF -> "ss").
                const d = entry(@intCast(c));
                if (o.transitional and d.status == .deviation) {
                    for (d.to) |c2| try appendCp(&mapped, a, @intCast(c2), o.max_output);
                } else try appendCp(&mapped, a, @intCast(c), o.max_output);
            },
            .deviation => if (o.transitional) {
                for (e.to) |c| try appendCp(&mapped, a, @intCast(c), o.max_output);
            } else try appendCp(&mapped, a, st.cp, o.max_output),
        }
    }

    // 2. Normalize.
    const nfc = norm.normalize(a, mapped.items, .nfc, .{ .max_output = o.max_output }) catch |err| switch (err) {
        error.OutOfMemory => return error.OutOfMemory,
        error.TooLarge => return error.TooLarge,
        error.InvalidUtf8 => unreachable, // appendCp wrote well-formed UTF-8
    };

    // 3. Break into labels and 4. convert Punycode labels.
    var labels: std.ArrayList(Label) = .empty;
    var it = std.mem.splitScalar(u8, nfc, '.');
    while (it.next()) |raw| {
        var lab: Label = .{ .text = raw };
        if (raw.len >= 4 and std.ascii.eqlIgnoreCase(raw[0..4], "xn--")) {
            lab.from_puny = true;
            if (!isAscii(raw)) {
                p.bad = true;
            } else if (punyDecode(a, raw[4..], o.max_output)) |dec| {
                lab.text = dec;
                if (dec.len == 0 or isAscii(dec)) p.bad = true;
            } else |err| switch (err) {
                error.OutOfMemory => return error.OutOfMemory,
                error.TooLarge => return error.TooLarge,
                error.InvalidDomain => p.bad = true,
            }
        }
        try labels.append(a, lab);
    }

    // The Bidi rule applies to every label of a domain with a right-to-left label.
    var bidi_domain = false;
    if (o.check_bidi) for (labels.items) |lab| {
        var j: usize = 0;
        while (j < lab.text.len) {
            const st = utf8.step(lab.text, j);
            j += st.len;
            if (props.bidiClass(st.cp)) |c| switch (c) {
                .r, .al, .an => bidi_domain = true,
                else => {},
            };
        }
    };
    for (labels.items) |lab| {
        if (!try labelOk(a, lab, o, bidi_domain)) p.bad = true;
    }

    // ToAscii: Punycode every non-ASCII label.
    var out: std.ArrayList(u8) = .empty;
    var total: usize = 0;
    const n_labels = labels.items.len;
    for (labels.items, 0..) |lab, k| {
        if (k > 0) try out.append(a, '.');
        var text = lab.text;
        if (ascii and !isAscii(text)) {
            if (punyEncode(a, text, o.max_output)) |enc| {
                text = try std.mem.concat(a, u8, &.{ "xn--", enc });
            } else |err| switch (err) {
                error.OutOfMemory => return error.OutOfMemory,
                error.TooLarge => return error.TooLarge,
                error.InvalidDomain => p.bad = true,
            }
        }
        if (out.items.len + text.len > o.max_output) return error.TooLarge;
        try out.appendSlice(a, text);
        if (ascii and o.verify_dns_length) {
            // UTS #46's own tests (A4_2) count a trailing root label as an empty label too.
            if (text.len == 0 or text.len > 63) p.bad = true;
            total += text.len + @intFromBool(k > 0);
        }
        // X4_2: an empty label is an error in toUnicode, but for the root label after a final dot.
        if (!ascii and text.len == 0 and !(k == n_labels - 1 and n_labels > 1)) p.bad = true;
    }
    if (ascii and o.verify_dns_length and (total == 0 or total > 253)) p.bad = true;
    p.text = out.items;
    return p;
}

fn isAscii(s: []const u8) bool {
    for (s) |b| if (b >= 0x80) return false;
    return true;
}

/// UTS #46 §4.1 Validity Criteria for one label.
fn labelOk(a: std.mem.Allocator, lab: Label, o: Options, bidi_domain: bool) Error!bool {
    const s = lab.text;
    // V1: NFC. A label from Punycode is not normalized yet; a mapped one is.
    if (lab.from_puny) {
        const ok = norm.isNormalized(a, s, .nfc, .{}) catch |err| switch (err) {
            error.OutOfMemory => return error.OutOfMemory,
            error.TooLarge => return error.TooLarge,
            error.InvalidUtf8 => return false,
        };
        if (!ok) return false;
    }
    if (o.check_hyphens) {
        if (s.len >= 4 and s[2] == '-' and s[3] == '-') return false;
        if (s.len > 0 and (s[0] == '-' or s[s.len - 1] == '-')) return false;
    } else if (s.len >= 4 and std.ascii.eqlIgnoreCase(s[0..4], "xn--") and !lab.from_puny) return false;
    // A decoded label may hold a dot; a raw one cannot.
    if (std.mem.indexOfScalar(u8, s, '.') != null) return false;

    var cps: std.ArrayList(u21) = .empty;
    var j: usize = 0;
    while (j < s.len) {
        const st = utf8.step(s, j);
        if (!st.valid) return false;
        j += st.len;
        try cps.append(a, st.cp);
    }
    if (cps.items.len > 0) switch (props.generalCategory(cps.items[0])) {
        .Mn, .Mc, .Me => return false,
        else => {},
    };
    const non_trans = !o.transitional or lab.from_puny;
    for (cps.items) |cp| {
        if (o.use_std3_ascii_rules and cp < 0x80 and !(std.ascii.isLower(@intCast(cp)) or std.ascii.isDigit(@intCast(cp)) or cp == '-')) return false;
        switch (entry(cp).status) {
            .valid => {},
            .deviation => if (!non_trans) return false,
            else => return false,
        }
    }
    if (o.check_joiners and !joinersOk(cps.items)) return false;
    if (o.check_bidi and bidi_domain and !bidiOk(cps.items)) return false;
    return true;
}

/// RFC 5892 Appendix A.1 / A.2 (UTS #46 CheckJoiners).
fn joinersOk(cps: []const u21) bool {
    for (cps, 0..) |cp, i| {
        if (cp != 0x200C and cp != 0x200D) continue;
        if (i > 0 and props.combiningClass(cps[i - 1]) == 9) continue; // after a Virama
        if (cp == 0x200D) return false;
        // ZWNJ: (L|D) T* ZWNJ T* (R|D)
        var l = i;
        while (l > 0 and joiningType(cps[l - 1]) == jt_t) l -= 1;
        if (l == 0) return false;
        const left = joiningType(cps[l - 1]);
        if (left != jt_l and left != jt_d) return false;
        var r = i + 1;
        while (r < cps.len and joiningType(cps[r]) == jt_t) r += 1;
        if (r >= cps.len) return false;
        const right = joiningType(cps[r]);
        if (right != jt_r and right != jt_d) return false;
    }
    return true;
}

/// RFC 5893 §2 conditions 1-6.
fn bidiOk(cps: []const u21) bool {
    if (cps.len == 0) return true;
    const first = props.bidiClass(cps[0]) orelse return false;
    const rtl = switch (first) {
        .r, .al => true,
        .l => false,
        else => return false,
    };
    var has_en = false;
    var has_an = false;
    var last: props.BidiClass = first;
    for (cps) |cp| {
        const c = props.bidiClass(cp) orelse return false;
        const allowed = if (rtl) switch (c) {
            .r, .al, .an, .en, .es, .cs, .et, .on, .bn, .nsm => true,
            else => false,
        } else switch (c) {
            .l, .en, .es, .cs, .et, .on, .bn, .nsm => true,
            else => false,
        };
        if (!allowed) return false;
        if (c == .en) has_en = true;
        if (c == .an) has_an = true;
        if (c != .nsm) last = c;
    }
    if (rtl) {
        switch (last) {
            .r, .al, .en, .an => {},
            else => return false,
        }
        if (has_en and has_an) return false;
    } else switch (last) {
        .l, .en => {},
        else => return false,
    }
    return true;
}

// ── Punycode (RFC 3492) ─────────────────────────────────────────────────────

const base: u32 = 36;
const t_min: u32 = 1;
const t_max: u32 = 26;
const skew: u32 = 38;
const damp: u32 = 700;
const initial_bias: u32 = 72;
const initial_n: u32 = 128;

fn adapt(delta_in: u32, num_points: u32, first: bool) u32 {
    var delta = if (first) delta_in / damp else delta_in / 2;
    delta += delta / num_points;
    var k: u32 = 0;
    while (delta > ((base - t_min) * t_max) / 2) : (k += base) delta /= base - t_min;
    return k + (base - t_min + 1) * delta / (delta + skew);
}

fn digitValue(c: u8) ?u32 {
    return switch (c) {
        'a'...'z' => c - 'a',
        'A'...'Z' => c - 'A',
        '0'...'9' => c - '0' + 26,
        else => null,
    };
}

fn digitChar(d: u32) u8 {
    return if (d < 26) @intCast('a' + d) else @intCast('0' + d - 26);
}

const PunyError = error{ OutOfMemory, TooLarge, InvalidDomain };

/// RFC 3492 §6.2: the code points of `input` (the part after "xn--"), as UTF-8.
fn punyDecode(a: std.mem.Allocator, input: []const u8, cap: usize) PunyError![]u8 {
    var cps: std.ArrayList(u21) = .empty;
    var b: usize = 0;
    if (std.mem.lastIndexOfScalar(u8, input, '-')) |d| {
        for (input[0..d]) |c| {
            if (c >= 0x80) return error.InvalidDomain;
            try cps.append(a, c);
        }
        b = d + 1;
    }
    var n: u32 = initial_n;
    var i: u32 = 0;
    var bias: u32 = initial_bias;
    var pos = b;
    while (pos < input.len) {
        const oldi = i;
        var w: u32 = 1;
        var k: u32 = base;
        while (true) : (k += base) {
            if (pos >= input.len) return error.InvalidDomain;
            const digit = digitValue(input[pos]) orelse return error.InvalidDomain;
            pos += 1;
            const dw = std.math.mul(u32, digit, w) catch return error.InvalidDomain;
            i = std.math.add(u32, i, dw) catch return error.InvalidDomain;
            const t = if (k <= bias) t_min else if (k >= bias + t_max) t_max else k - bias;
            if (digit < t) break;
            w = std.math.mul(u32, w, base - t) catch return error.InvalidDomain;
        }
        const len: u32 = @intCast(cps.items.len + 1);
        bias = adapt(i - oldi, len, oldi == 0);
        n = std.math.add(u32, n, i / len) catch return error.InvalidDomain;
        i %= len;
        if (n > 0x10FFFF or (n >= 0xD800 and n <= 0xDFFF)) return error.InvalidDomain;
        if (cps.items.len >= cap) return error.TooLarge;
        try cps.insert(a, i, @intCast(n));
        i += 1;
    }
    var out: std.ArrayList(u8) = .empty;
    for (cps.items) |cp| {
        var buf: [4]u8 = undefined;
        const k = std.unicode.utf8Encode(cp, &buf) catch return error.InvalidDomain;
        if (out.items.len + k > cap) return error.TooLarge;
        try out.appendSlice(a, buf[0..k]);
    }
    return out.items;
}

/// RFC 3492 §6.3 over UTF-8 `input`: the Punycode (without "xn--").
fn punyEncode(a: std.mem.Allocator, input: []const u8, cap: usize) PunyError![]u8 {
    var cps: std.ArrayList(u21) = .empty;
    var j: usize = 0;
    while (j < input.len) {
        const st = utf8.step(input, j);
        if (!st.valid) return error.InvalidDomain;
        j += st.len;
        try cps.append(a, st.cp);
    }
    var out: std.ArrayList(u8) = .empty;
    var h: u32 = 0;
    for (cps.items) |cp| if (cp < 0x80) {
        try out.append(a, @intCast(cp));
        h += 1;
    };
    const b = h;
    if (b > 0) try out.append(a, '-');
    var n: u32 = initial_n;
    var delta: u32 = 0;
    var bias: u32 = initial_bias;
    const total: u32 = @intCast(cps.items.len);
    while (h < total) {
        var m: u32 = std.math.maxInt(u32);
        for (cps.items) |cp| if (cp >= n and cp < m) {
            m = cp;
        };
        const add = std.math.mul(u32, m - n, h + 1) catch return error.InvalidDomain;
        delta = std.math.add(u32, delta, add) catch return error.InvalidDomain;
        n = m;
        for (cps.items) |cp| {
            if (cp < n) delta = std.math.add(u32, delta, 1) catch return error.InvalidDomain;
            if (cp != n) continue;
            var q = delta;
            var k: u32 = base;
            while (true) : (k += base) {
                const t = if (k <= bias) t_min else if (k >= bias + t_max) t_max else k - bias;
                if (q < t) break;
                try out.append(a, digitChar(t + (q - t) % (base - t)));
                q = (q - t) / (base - t);
            }
            try out.append(a, digitChar(q));
            bias = adapt(delta, h + 1, h == b);
            delta = 0;
            h += 1;
            if (out.items.len > cap) return error.TooLarge;
        }
        delta += 1;
        n += 1;
    }
    return out.items;
}

// ── tests ───────────────────────────────────────────────────────────────────

const testing = std.testing;

fn expectAscii(domain: []const u8, want: []const u8, o: Options) !void {
    const got = try toAscii(testing.allocator, domain, o);
    defer testing.allocator.free(got);
    try testing.expectEqualStrings(want, got);
}

test "toAscii: the examples of UTS #46 and RFC 3492" {
    const o: Options = .{};
    try expectAscii("faß.de", "xn--fa-hia.de", o);
    try expectAscii("Faß.DE", "xn--fa-hia.de", o);
    try expectAscii("faß.de", "fass.de", .{ .transitional = true });
    try expectAscii("bücher.example", "xn--bcher-kva.example", o);
    try expectAscii("BÜCHER.example", "xn--bcher-kva.example", o);
    try expectAscii("例え.テスト", "xn--r8jz45g.xn--zckzah", o);
    try expectAscii("日本語。ＪＰ", "xn--wgv71a119e.jp", o); // ideographic full stop, fullwidth letters
    try expectAscii("xn--bcher-kva.example", "xn--bcher-kva.example", o);
    try expectAscii("_dmarc.example.com", "_dmarc.example.com", o);
    try expectAscii("a.b.", "a.b.", o);
    try expectAscii("EXAMPLE.com", "example.com", o);
    try expectAscii("☃.net", "xn--n3h.net", o);
}

test "toAscii: refusals" {
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, "xn--", .{}));
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, "\u{0301}a.com", .{})); // starts with a mark
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, "a b.com", Options.std3())); // U1
    try expectAscii("a b.com", "a b.com", .{}); // as the WHATWG host parser, which then refuses the space itself
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, "a..com", .{ .verify_dns_length = true }));
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, "", .{ .verify_dns_length = true }));
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, "a\u{200c}b.com", .{})); // ZWNJ without joining context
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, "ab--c.com", .{ .check_hyphens = true }));
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, "-ab.com", .{ .check_hyphens = true }));
    try expectAscii("ab--c.com", "ab--c.com", .{});
    try testing.expectError(error.InvalidUtf8, toAscii(testing.allocator, "a\xffb", .{}));
    var long: [68]u8 = undefined;
    @memset(long[0..64], 'a');
    @memcpy(long[64..], ".com");
    try testing.expectError(error.InvalidDomain, toAscii(testing.allocator, &long, .{ .verify_dns_length = true }));
    const ok = try toAscii(testing.allocator, &long, .{});
    testing.allocator.free(ok);
