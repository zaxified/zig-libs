test "random and hostile input never panics, and what toAscii accepts is accepted again unchanged" {
    var prng: std.Random.DefaultPrng = .init(0x1d4a);
    const rnd = prng.random();
    const pieces = [_][]const u8{ "xn--", "xn--a", ".", "-", "a", "Z", "9", "\u{00df}", "\u{200c}", "\u{200d}", "\u{05d0}", "\u{0627}", "\u{0660}", "\u{0301}", "\u{3002}", "\u{ff21}", "\u{1f600}", "\u{00ad}", "_", "zzzzzzzzzzzzzzzzzzzzzzzzzzzzz", "99999999999", "\u{d7ff}", "\u{e000}", "\u{10ffff}" };
    var buf: [256]u8 = undefined;
    for (0..20000) |_| {
        var n: usize = 0;
        const parts = rnd.intRangeAtMost(usize, 0, 8);
        for (0..parts) |_| {
            const piece = pieces[rnd.uintLessThan(usize, pieces.len)];
            if (n + piece.len > buf.len) break;
            @memcpy(buf[n..][0..piece.len], piece);
            n += piece.len;
        }
        const o: Options = .{ .check_hyphens = rnd.boolean(), .use_std3_ascii_rules = rnd.boolean(), .transitional = rnd.boolean(), .verify_dns_length = rnd.boolean() };
        if (toAscii(testing.allocator, buf[0..n], o)) |a1| {
            defer testing.allocator.free(a1);
            // Idempotence: the ASCII form of an accepted name is itself accepted and unchanged.
            const a2 = try toAscii(testing.allocator, a1, o);
            defer testing.allocator.free(a2);
            try testing.expectEqualStrings(a1, a2);
        } else |err| try testing.expect(err == error.InvalidDomain);
        var u = try toUnicode(testing.allocator, buf[0..n], o);
        u.deinit(testing.allocator);
    }
}
