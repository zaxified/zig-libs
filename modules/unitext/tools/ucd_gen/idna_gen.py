"""Generate `src/idna_tables.zig` (the UTS #46 mapping table and the Joining_Type
ranges `unitext.idna` reads) and `src/testdata/idna_test.txt` (Unicode's IdnaTestV2.txt
without comments) from UCD files.

    tools/ucd_gen/fetch.sh 18.0.0
    python3 -I tools/ucd_gen/idna_gen.py --ucd tools/ucd_gen/data/18.0.0 -out src
    python3 -I tools/ucd_gen/idna_gen.py --ucd tools/ucd_gen/data/18.0.0 -check src

Reads IdnaMappingTable.txt, extracted/DerivedJoiningType.txt (only L, D, R and T are
kept: they are all ContextJ needs) and IdnaTestV2.txt. Python 3 standard library
only; `zig` on PATH for `zig fmt --stdin`. The data are Unicode's (Unicode License
v3, see the module's NOTICE); the encoding and this code are ours.

Table encoding: `map_starts[i]` is the first code point of range i (sorted; range i ends
before `map_starts[i+1]`, the last at U+10FFFF); `map_info[i]` is
`status | len << 3 | off << 8`: status 0 valid, 1 mapped, 2 deviation, 3 disallowed,
4 ignored; `len` and `off` select `map_pool[off..off+len]` (code points) for mapped and
deviation. Adjacent ranges with the same status and no mapping are merged.
"""

import os
import re
import subprocess
import sys

STATUS = {"valid": 0, "mapped": 1, "deviation": 2, "disallowed": 3, "ignored": 4}
JT = {"L": 1, "D": 2, "R": 3, "T": 4}


def die(m):
    sys.stderr.write(m + "\n")
    sys.exit(2)


def mapping_ranges(path):
    ranges = []  # (lo, hi, status, mapping tuple)
    version = None
    for line in open(path, encoding="utf-8"):
        m = re.match(r"# Version: (\S+)", line)
        if m:
            version = m.group(1)
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(";")]
        rng = f[0].split("..")
        lo = int(rng[0], 16)
        hi = int(rng[-1], 16)
        st = f[1]
        if st not in STATUS:
            die(f"status {st} not handled")
        mp = tuple(int(x, 16) for x in f[2].split()) if len(f) > 2 and f[2] else ()
        ranges.append((lo, hi, STATUS[st], mp))
    ranges.sort()
    nxt = 0
    for lo, hi, _, _ in ranges:
        if lo != nxt:
            die(f"gap or overlap at {lo:X} (expected {nxt:X})")
        nxt = hi + 1
    if nxt != 0x110000:
        die(f"table ends at {nxt:X}")
    return ranges, version


def build_map(ranges):
    starts, info, pool, seen = [], [], [], {}
    prev = None
    for lo, hi, st, mp in ranges:
        if prev is not None and prev == (st, mp) and not mp:
            continue
        prev = (st, mp)
        if mp:
            if mp not in seen:
                seen[mp] = len(pool)
                pool.extend(mp)
            off = seen[mp]
        else:
            off = 0
        if len(mp) >= 32 or off >= (1 << 24):
            die("mapping too long")
        starts.append(lo)
        info.append(st | len(mp) << 3 | off << 8)
    return starts, info, pool


def joining(path):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        a, b = [x.strip() for x in line.split(";")]
        if b not in JT:
            continue
        r = a.split("..")
        out.append((int(r[0], 16), int(r[-1], 16), JT[b]))
    out.sort()
    merged = []
    for lo, hi, t in out:
        if merged and merged[-1][1] + 1 == lo and merged[-1][2] == t:
            merged[-1] = (merged[-1][0], hi, t)
        else:
            merged.append((lo, hi, t))
    return merged


def arr(name, typ, vals, per=8, fmt=str, doc=""):
    s = (doc and "/// " + doc + "\n") + f"pub const {name} = [_]{typ}{{\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(fmt(v) for v in vals[i:i + per]) + ",\n"
    return s + "};\n\n"


def zig_fmt(text):
    r = subprocess.run(["zig", "fmt", "--stdin"], input=text.encode(), capture_output=True)
    if r.returncode != 0:
        die("zig fmt failed: " + r.stderr.decode())
    return r.stdout.decode()


def tables(ucd):
    ranges, version = mapping_ranges(os.path.join(ucd, "IdnaMappingTable.txt"))
    starts, info, pool = build_map(ranges)
    jt = joining(os.path.join(ucd, "extracted", "DerivedJoiningType.txt"))
    body = (
        "// SPDX-License-Identifier: MIT\n"
        f"// GENERATED by modules/unitext/tools/ucd_gen/idna_gen.py (Unicode {version}) -- do not hand-edit.\n"
        "//! The UTS #46 IDNA mapping table and the Joining_Type ranges (L, D, R, T) that `idna.zig` reads.\n"
        "//! A transformed form of Unicode's data: see the module's NOTICE for the Unicode License v3.\n\n"
        f'pub const idna_version = "{version}";\n\n'
        + arr("map_starts", "u32", starts, 8, lambda v: "0x%X" % v, "First code point of each mapping range (sorted).")
        + arr("map_info", "u32", info, 8, lambda v: "0x%X" % v, "`status | len << 3 | off << 8` per range (see idna_gen.py).")
        + arr("map_pool", "u32", pool, 8, lambda v: "0x%X" % v, "Mapping targets, `len` code points at `off`.")
        + arr("jt_lo", "u32", [x[0] for x in jt], 8, lambda v: "0x%X" % v, "Joining_Type ranges: first code point.")
        + arr("jt_hi", "u32", [x[1] for x in jt], 8, lambda v: "0x%X" % v, "Joining_Type ranges: last code point.")
        + arr("jt_type", "u8", [x[2] for x in jt], 16, str, "Joining_Type: 1 L, 2 D, 3 R, 4 T.")
    )
    return zig_fmt(body)


def test_file(ucd):
    out = []
    for line in open(os.path.join(ucd, "IdnaTestV2.txt"), encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    opts = {}
    while args:
        a = args.pop(0)
        if not args:
            die(f"{a} needs a value")
        opts[a] = args.pop(0)
    ucd = opts.get("--ucd") or die("usage: idna_gen.py --ucd <UCD dir> (-out <dir> | -check <dir>)")
    files = {"idna_tables.zig": tables(ucd), os.path.join("testdata", "idna_test.txt"): test_file(ucd)}
    if "-out" in opts:
        for f, t in files.items():
            path = os.path.join(opts["-out"], f)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(t)
            sys.stderr.write(f"wrote {path} ({len(t)} bytes)\n")
    elif "-check" in opts:
        bad = False
        for f, t in files.items():
            old = open(os.path.join(opts["-check"], f), encoding="utf-8").read()
            if old != t:
                sys.stderr.write(f"{f}: DRIFT -- committed file differs from a fresh build\n")
                bad = True
            else:
                sys.stderr.write(f"{f}: committed file matches a fresh build\n")
        sys.exit(1 if bad else 0)
    else:
        die("one of -out, -check is required")


if __name__ == "__main__":
    main()
