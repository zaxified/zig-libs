//! **Byte-exact goldens captured from real `iproute2`.**
//!
//! Every constant below is the complete netlink datagram a stock `tc` binary
//! put on the wire, recovered from a `strace` of the `sendmsg` call and
//! re-encoded byte for byte (the reconstruction is checked against the
//! message's own `nlmsg_len`, so a truncated capture cannot slip through).
//! Each test states the exact command it came from.
//!
//! Capture recipe — every command below was run inside one unprivileged
//! network namespace so nothing touched host state:
//!
//! ```sh
//! unshare -rn strace -f -e trace=sendmsg -xx -s 8192 -e abbrev=none ./commands.sh
//! ```
//!
//! Provenance of the capture host: `iproute2-6.19.0`, Linux 7.0, and
//! `/proc/net/psched` = `000003e8 00000040 000f4240 3b9aca00` (t2us=1000,
//! us2t=64, clock_res=1e6, tfsc=1e9). That psched line is what makes the
//! rate tables and every `buffer`/`burst` tick value reproducible; it is
//! pinned as `ratespec.golden_psched` and passed to every builder here, so
//! these tests are host-independent.
//!
//! `nlmsg_seq` is part of the captured bytes, so each golden carries the
//! sequence number its capture used and hands it to the builder.

