def gen_rem_minmax(rng):
    rm = Out('conform_rem.vec', ['BigDecimal.remainder (truncating; sign follows the dividend; exponent = min(ea, eb))',
                                 'Format: a|b|remainder|remainder_exponent'])
    mn = Out('conform_min.vec', ['BigDecimal.min (numeric ties resolved by exponent)', 'Format: a|b|min|min_exponent'])
    mx = Out('conform_max.vec', ['BigDecimal.max (numeric ties resolved by exponent)', 'Format: a|b|max|max_exponent'])

    def rem(a, b):
        if Decimal(b) == 0:
            rm.emit(a, b, 'ERR:DivisionByZero', '-')
            return
        c = ctx()
        r = c.remainder(Decimal(a), Decimal(b))
        assert r.is_finite(), (a, b)
        exact(c)
        rm.emit(a, b, nz(r), r.as_tuple().exponent)

    for a in ['7', '2.5', '0.07', '100', '1.234', '10', '5', '0.1', '123456789.123456789', '1E+5', '3.00', '0', '0.00']:
        for b in ['3', '0.5', '2', '1.1', '0.3', '1E+1', '2.000', '7', '0.07', '1', '0.01', '9', '1E-5', '0']:
            for sa in ('', '-'):
                for sb in ('', '-'):
                    if Decimal(a) == 0 and sa:
                        continue
                    rem(sa + a, sb + b)
    for _ in range(600):
        a = rnd_dec(rng, 25, -15, 15, 0.03)
        b = rnd_dec(rng, 12, -15, 15, 0.01)
        if rng.random() < 0.2:  # exact multiples: the remainder is a zero at the min exponent
            k = rng.randrange(1, 50)
            b2 = Decimal(b)
            if b2 != 0:
                a = str(ctx().multiply(b2, Decimal(k)))
        rem(a, b)

    def pick(op, name, a, b):
        c = ctx()
        r = c.min(Decimal(a), Decimal(b)) if name == 'min' else c.max(Decimal(a), Decimal(b))
        exact(c)
        op.emit(a, b, nz(r), r.as_tuple().exponent)

    base = ['-2', '-1', '0', '1', '2', '0.5', '-0.5', '1.0', '1.00', '-1.0', '-1.00', '100', '1E+2', '10E+1', '-100', '-1E+2',
            '0.0', '0.00', '0E+2', '9.99', '10.00', '-9.99', '1.000001', '123456789012345678901234567890', '1E-30', '-1E-30']
    for a in base:
        for b in base:
            pick(mn, 'min', a, b)
            pick(mx, 'max', a, b)
    for _ in range(300):
        a = rnd_dec(rng, 15, -12, 12, 0.05)
        if rng.random() < 0.5:
            b = same_value_other_scale(rng, a)
            if rng.random() < 0.3 and Decimal(b) != 0:
                b = str(Decimal(b).copy_negate())
        else:
            b = rnd_dec(rng, 15, -12, 12, 0.05)
        pick(mn, 'min', a, b)
        pick(mx, 'max', a, b)
    return [rm, mn, mx]


