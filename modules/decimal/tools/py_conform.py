def gen_add_mul(rng):
    add = Out('conform_add.vec', ['exact BigDecimal.add vectors', 'Format: a|b|sum|sum_exponent'])
    mul = Out('conform_mul.vec', ['exact BigDecimal.mul vectors', 'Format: a|b|product|product_exponent'])

    def one(op, name, a, b):
        c = ctx()
        r = c.add(Decimal(a), Decimal(b)) if name == 'add' else c.multiply(Decimal(a), Decimal(b))
        exact(c)
        op.emit(a, b, nz(r), r.as_tuple().exponent)

    pairs = []
    # carries and borrows through long runs of nines / zeros
    for n in (1, 2, 5, 9, 18, 19, 20, 38, 39, 40, 77, 120):
        nines = '9' * n
        pairs += [(nines, '1'), ('-' + nines, '1'), (nines, nines), (nines + '.' + nines, '0.' + '0' * (n - 1) + '1'),
                  ('1' + '0' * n, '-1'), ('1' + '0' * n, '-' + nines), ('-1' + '0' * n, nines)]
    # exponent alignment, including huge gaps
    for e in (1, 2, 7, 30, 100, 400, 900):
        pairs += [('1E+%d' % e, '1E-%d' % e), ('-1E+%d' % e, '1E-%d' % e), ('123E+%d' % e, '-45E-%d' % e),
                  ('9.5E+%d' % e, '5E+%d' % (e - 1)), ('1E+%d' % e, '-1E+%d' % e), ('7E+%d' % e, '3E+%d' % e)]
    # trailing zeros are kept; values that cancel; zero operands at various exponents
    pairs += [('0.1', '0.2'), ('0.7', '0.3'), ('1.25', '1.25'), ('5.75', '3.3'), ('-7', '2.5'), ('1.50', '1.5'), ('2.50', '-2.5'),
              ('0', '0'), ('0.00', '0'), ('0E+3', '0.1'), ('0E-7', '5'), ('0E+5', '-0E+2'.lstrip('-')), ('0', '-12.5'),
              ('123456789.123456789', '-123456789.123456789'), ('1E+3', '1'), ('1E-3', '1E+3')]
    for a, b in pairs:
        one(add, 'add', a, b)
        one(add, 'add', b, a)
        one(mul, 'mul', a, b)
    for _ in range(700):
        a = rnd_dec(rng, 40, -60, 60)
        b = rnd_dec(rng, 40, -60, 60)
        if rng.random() < 0.15:
            b = same_value_other_scale(rng, a)
            if rng.random() < 0.5:
                b = str(Decimal(b).copy_negate()) if Decimal(b) != 0 else b
        one(add, 'add', a, b)
    for _ in range(500):
        one(mul, 'mul', rnd_dec(rng, 40, -60, 60), rnd_dec(rng, 40, -60, 60))
    for _ in range(60):  # long operands
        one(add, 'add', rnd_dec(rng, 400, -300, 300, 0), rnd_dec(rng, 400, -300, 300, 0))
        one(mul, 'mul', rnd_dec(rng, 400, -300, 300, 0), rnd_dec(rng, 400, -300, 300, 0))
    return [add, mul]


