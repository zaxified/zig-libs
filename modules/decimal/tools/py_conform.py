def gen_pow(rng):
    pw = Out('conform_pow.vec', ['BigDecimal.pow with an integer exponent: exact, result exponent = a.exponent * n;',
                                 'negative exponents and over-budget results are typed errors (Java BigDecimal.pow(int) contract)',
                                 'Format: base|n|result|result_exponent   (ERR:<name>|- for a typed error)'])

    def digits(s):
        return len(Decimal(s).as_tuple().digits)

    def one(b, n):
        B = Decimal(b)
        if n < 0:
            pw.emit(b, n, 'ERR:NegativeExponent', '-')
            return
        if n == 0:
            if B == 0:
                return  # Python raises InvalidOperation for 0**0; the module returns 1 (Java): not emitted
            r = ctx().power(B, 0)
            assert str(r) == '1'
            pw.emit(b, n, '1', 0)
            return
        if B == 0:
            return  # contract mismatch (see header): Python 0E+k ** n = 0E+(k*n), the module's zero keeps exponent 0
        dg = digits(b)
        if dg * n > MAX_RESULT_DIGITS:
            pw.emit(b, n, 'ERR:ResultTooLarge', '-')  # the module's digit budget, checked before any allocation
            return
        e = B.as_tuple().exponent * n
        if e > I32_MAX or e < -(2 ** 31):
            pw.emit(b, n, 'ERR:Overflow', '-')  # result exponent outside i32
            return
        c = ctx(dg * n + 30)
        r = c.power(B, n)
        exact(c)
        assert r.as_tuple().exponent == e, (b, n, r)
        pw.emit(b, n, nz(r), e)

    # designed: small bases and exponents, trailing zeros, signs, exponents on both sides of zero
    for b in ['1', '-1', '2', '-2', '10', '-10', '0.1', '-0.1', '1.1', '-1.1', '1.5', '2.5', '-2.5', '1.50', '1.00', '3', '-3', '7',
              '9', '12', '0.5', '0.25', '1E+1', '1E-1', '5E+3', '-5E+3', '2E-3', '1.001', '0.999', '99', '-99', '123.456', '1E+100',
              '-1E-100', '314159', '0.0007']:
        for n in list(range(0, 13)) + [20, 31, 32, 33, 64, 100]:
            one(b, n)
    for _ in range(300):
        nd = rng.randrange(1, 15)
        b = str(mk(rng.randrange(2), rng.randrange(10 ** (nd - 1), 10 ** nd), rng.randrange(-12, 13)))
        one(b, rng.randrange(0, 30) if rng.random() < 0.8 else rng.randrange(30, 150))
    # negative exponents (typed error), zero and over-budget cases
    for b in ['2', '1.1', '-3', '0', '0.5', '1E+5']:
        for n in (-1, -2, -7, -100, -(2 ** 31)):
            one(b, n)
    # budget boundary: digits * n == 100000 passes, one digit more is refused; unit coefficients keep the result tiny
    for b, n in [('1', 100000), ('1E+5', 100000), ('-1E-5', 100000), ('-1', 99999), ('1', 100001), ('1.0', 50000), ('1.0', 50001),
                 ('12', 50001), ('12345', 20001), ('1.1', 1000000007), ('3', 2147483647), ('1E+2', 1000000), ('7', 100001)]:
        if b in ('1.0', '12', '12345', '1.1', '3', '7') and digits(b) * n <= MAX_RESULT_DIGITS:
            continue  # a passing case would emit a ~100k-digit result: not stored
        one(b, n)
    # exponent product outside i32 (digit budget still fine)
    for b, n in [('1E+30000', 100000), ('1E-30000', 100000), ('1E+2147483647', 2), ('1E-2147483648', 2), ('1E+1073741824', 2),
                 ('1E+1073741823', 2), ('-1E-1073741824', 2), ('1E+1000000', 3000)]:
        one(b, n)
    return [pw]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    outdir = os.path.join(here, '..', 'src', 'testdata')
    rng = random.Random(SEED)
    outs = []
    for g in (gen_add_mul, gen_quant_div, gen_rem_minmax, gen_sqrt, gen_pow):
        outs += g(rng)
    for o in outs:
        o.write(outdir)


if __name__ == '__main__':
    main()
