def gen_quant_div(rng):
    qt = Out('conform_quant.vec', ['BigDecimal.rescale (quantize) vectors, all 8 rounding modes, exact ties included',
                                   'Format: x|new_exponent|mode|result|result_exponent'])
    dv = Out('conform_div.vec', ['BigDecimal.div at an explicit result exponent (scale), all 8 rounding modes',
                                 'Format: a|b|scale|mode|quotient|quotient_exponent   (scale s = result exponent -s)'])
    dp = Out('conform_divprec.vec', ['BigDecimal.divPrec: division rounded to a number of significant digits',
                                     'Format: a|b|precision|mode|quotient|quotient_exponent|inexact|rounded'])

    def quant(x, exp, mode):
        r = Decimal(x).quantize(Decimal((0, (1,), exp)), rounding=MODES[mode], context=ctx())
        qt.emit(x, exp, mode, nz(r), r.as_tuple().exponent)

    ties = ['0.5', '1.5', '2.5', '3.5', '0.05', '0.15', '0.25', '0.35', '1.005', '1.015', '0.125', '0.375', '9.5', '99.5',
            '10.5', '12345.5', '12346.5', '0.0005', '1.0000005', '25', '35', '45', '150', '250', '1250', '15E+1', '25E+1',
            '0.45', '0.55', '4.95', '5.05', '1.1', '2.9', '0.4999', '0.5001', '0.01', '0.99']
    for mode in MODE_NAMES:
        for t in ties:
            for sgn in ('', '-'):
                for exp in (0, -1, -2, -3, 1, 2, -7):
                    quant(sgn + t, exp, mode)
    for _ in range(900):
        quant(rnd_dec(rng, 30, -25, 12), rng.randrange(-30, 15), rng.choice(MODE_NAMES))

    def div(a, b, scale, mode):
        if Decimal(b) == 0:
            dv.emit(a, b, scale, mode, 'ERR:DivisionByZero', '-')
            return
        q = ctx(3000).divide(Decimal(a), Decimal(b))
        r = q.quantize(Decimal((0, (1,), -scale)), rounding=MODES[mode], context=ctx(3000))
        dv.emit(a, b, scale, mode, nz(r), r.as_tuple().exponent)

    # exact ties and terminating quotients, every mode, both signs
    for mode in MODE_NAMES:
        for a, b, scale in [('5', '2', 0), ('1', '2', 0), ('7', '2', 0), ('3', '2', 0), ('1', '8', 2), ('1', '8', 1), ('3', '8', 2),
                            ('1', '3', 5), ('2', '3', 5), ('1', '6', 3), ('10', '4', 0), ('25', '10', 0), ('35', '10', 0),
                            ('1', '4', 1), ('1', '3', 0), ('2', '3', 0), ('100', '7', -1), ('150', '1', -2), ('250', '1', -2),
                            ('0.5', '1', 0), ('5', '0.20', 0), ('1', '1', 0), ('0', '3', 4), ('1', '0', 2), ('9', '1000', 2)]:
            for sa in ('', '-'):
                for sb in ('', '-'):
                    div(sa + a, sb + b, scale, mode)
    for _ in range(900):
        a = rnd_dec(rng, 8, -8, 6, 0.04)
        b = rnd_dec(rng, 5, -6, 4, 0.02)
        if rng.random() < 0.2:
            b = same_value_other_scale(rng, a)
        div(a, b, rng.randrange(-4, 26), rng.choice(MODE_NAMES))

    def divprec(a, b, prec, mode):
        if Decimal(b) == 0:
            dp.emit(a, b, prec, mode, 'ERR:DivisionByZero', '-', 0, 0)
            return
        c = ctx(prec, MODES[mode])
        r = c.divide(Decimal(a), Decimal(b))
        dp.emit(a, b, prec, mode, nz(r), r.as_tuple().exponent, int(bool(c.flags[Inexact])), int(bool(c.flags[Rounded])))

    for mode in MODE_NAMES:
        for a, b in [('1', '3'), ('2', '3'), ('1', '7'), ('10', '3'), ('-1', '3'), ('1', '-3'), ('1', '4'), ('1', '8'), ('5', '8'),
                     ('2.40', '2'), ('100', '10'), ('1000', '100'), ('9.99', '1'), ('0', '5'), ('0', '0.5'), ('1', '0'),
                     ('123456', '7'), ('1', '16'), ('3', '16'), ('0.1', '3')]:
            for prec in (1, 2, 3, 5, 9, 12, 30):
                divprec(a, b, prec, mode)
    for _ in range(700):
        divprec(rnd_dec(rng, 10, -8, 8, 0.03), rnd_dec(rng, 6, -6, 6, 0.01), rng.choice([1, 2, 3, 4, 5, 7, 9, 12, 20, 34, 60]),
                rng.choice(MODE_NAMES))
    return [qt, dv, dp]


