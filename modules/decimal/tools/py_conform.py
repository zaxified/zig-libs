"""Conformance-vector generator for the decimal module's BigDecimal operations.

Run (stdlib only, no network), from the repository root:

    python3 -I modules/decimal/tools/py_conform.py

It (re)writes `modules/decimal/src/testdata/conform_*.vec`, which `src/big.zig`
replays (`@embedFile`); Python is NOT needed at test time. Every operand is
generated here (seeded random plus designed edge classes) and every expected
value is computed by Python's `decimal` module (the GDA reference
implementation, libmpdec) -- no third-party test data is involved. Seeded and
deterministic: re-running reproduces the files byte for byte on the same Python
minor version (each header records it). The case counts are printed to stderr;
`src/big.zig` asserts them so a truncated file fails.

Line format: `operands|...|expected|expected_exponent` (see each file header).
`expected` is Python's `str(Decimal)` (GDA to-scientific-string) compared with
`BigDecimal.toSci`, `expected_exponent` is the integer exponent the result must
carry, because for these operations the scale is part of the specification.
Errors are `ERR:<error name>|-`.

Contract of the module that the generator respects (never emitted):
  * No signed zero: no negative-zero operand is generated and a zero result's
    sign is dropped (`nz`).
  * No NaN / Infinity, no flag register (except `divPrec`'s inexact/rounded).
  * `remainder`, `div` and `sqrt` take no context precision beyond their own
    argument; operands are kept small enough that Python's context (prec 5000)
    never rounds the exact operations (asserted via the Inexact/Rounded flags).
  * `pow` is the integer, non-negative-exponent operation only (Java
    `BigDecimal.pow(int)` contract): a negative exponent is
    `ERR:NegativeExponent`; `0^n` with n > 0 is not emitted (Python gives
    `0E+(n*exp)`, this module gives `0` at exponent 0 -- a deliberate,
    documented module choice, see SPEC.md).
"""
import os
import random
import sys
from decimal import (
    Context, Decimal, ROUND_05UP, ROUND_CEILING, ROUND_DOWN, ROUND_FLOOR,
    ROUND_HALF_DOWN, ROUND_HALF_EVEN, ROUND_HALF_UP, ROUND_UP,
    Inexact, Rounded, MAX_EMAX, MIN_EMIN, getcontext,
)

SEED = 20261021
getcontext().prec = 5000
MODES = {
    'half_even': ROUND_HALF_EVEN, 'half_up': ROUND_HALF_UP, 'half_down': ROUND_HALF_DOWN,
    'up': ROUND_UP, 'down': ROUND_DOWN, 'ceiling': ROUND_CEILING, 'floor': ROUND_FLOOR,
    'round_05up': ROUND_05UP,
}
MODE_NAMES = list(MODES)
MAX_RESULT_DIGITS = 100_000  # BigDecimal.max_result_digits
I32_MAX = 2 ** 31 - 1


def ctx(prec=5000, rounding=ROUND_HALF_EVEN):
    return Context(prec=prec, rounding=rounding, Emax=MAX_EMAX, Emin=MIN_EMIN, traps=[], flags=[])


def nz(d):
    """str() of a decimal with the sign of a zero dropped."""
    s = str(d)
    if d == 0 and s.startswith('-'):
        s = s[1:]
    return s


def mk(sign, coeff, exp):
    return Decimal((sign, tuple(int(c) for c in str(coeff)), exp))


def rnd_dec(rng, max_digits=30, exp_lo=-20, exp_hi=20, zero=0.06):
    """A random decimal string: random digit count, random exponent, trailing
    zeros sometimes, sometimes zero (unsigned)."""
    if rng.random() < zero:
        return str(mk(0, 0, rng.randrange(exp_lo, exp_hi + 1)))
    nd = rng.randrange(1, max_digits + 1)
    coeff = rng.randrange(10 ** (nd - 1), 10 ** nd) if nd > 1 else rng.randrange(1, 10)
    if rng.random() < 0.25:
        coeff = int(str(coeff) + '0' * rng.randrange(1, 5))
    return str(mk(rng.randrange(2), coeff, rng.randrange(exp_lo, exp_hi + 1)))


def rescaled(s, k, rng=None):
    """The same value as `s` written with k more trailing zeros (exponent lowered)."""
    t = Decimal(s).as_tuple()
    return str(Decimal((t.sign, t.digits + (0,) * k, t.exponent - k)))


def same_value_other_scale(rng, s):
    d = Decimal(s)
    if d == 0:
        t = d.as_tuple()
        return str(Decimal((0, (0,), t.exponent + rng.randrange(-4, 5))))
    return rescaled(s, rng.randrange(1, 5))


class Out:
    def __init__(self, name, header):
        self.name = name
        self.header = header
        self.lines = []

    def emit(self, *fields):
        self.lines.append('|'.join(str(f) for f in fields))

    def write(self, directory):
        path = os.path.join(directory, self.name)
        with open(path, 'w', newline='\n') as f:
            f.write('# %s\n' % self.header[0])
            f.write('# Generated by tools/py_conform.py, seed %d, Python %d.%d; expected values come from\n'
                    % (SEED, sys.version_info[0], sys.version_info[1]))
            f.write("# Python's `decimal` module (GDA reference implementation). Do not edit; regenerate.\n")
            for h in self.header[1:]:
                f.write('# %s\n' % h)
            f.write('\n')
            for line in self.lines:
                f.write(line + '\n')
        sys.stderr.write('%s: %d cases\n' % (self.name, len(self.lines)))


def exact(c):
    assert not c.flags[Inexact] and not c.flags[Rounded], 'context rounded an operation that must be exact'


