def gen_sqrt(rng):
    sq = Out('conform_sqrt.vec', ['BigDecimal.sqrt: correctly rounded to `precision` significant digits, all 8 rounding modes',
                                  'Exact roots carry the ideal exponent floor(exponent/2). Python rounds sqrt half_even only, so the',
                                  'expected value for every mode is the root at a much higher precision rounded once in that mode',
                                  '(half_even is also checked against Python\'s direct result).',
                                  'Format: operand|precision|mode|root|root_exponent'])

    def one(x, prec, mode):
        X = Decimal(x)
        if X < 0:
            sq.emit(x, prec, mode, 'ERR:NegativeOperand', '-')
            return
        hi = ctx(2 * prec + 80).sqrt(X)
        cm = ctx(prec, MODES[mode])
        r = cm.plus(hi)
        if mode == 'half_even':
            direct = ctx(prec).sqrt(X)
            assert str(direct) == str(r), (x, prec, direct, r)
        sq.emit(x, prec, mode, nz(r), r.as_tuple().exponent)

    squares = ['0', '0.00', '0E+5', '0E-3', '1', '1.00', '4', '4.00', '9', '0.25', '0.0625', '144E+2', '1.21', '16E-4', '10000',
               '1E+8', '1E-8', '2.25E+4', '15129', '123456789' * 2, str(123456789 ** 2), '1' + '0' * 40, '49E-6', '6.25', '100.00',
               '99.99', '0.01', '1.0E+3', '3E+7']
    plain = ['2', '3', '5', '7', '0.5', '10', '1E+7', '1E-7', '99.99', '0.0001', '123456.789', '0.3', '1.5', '8E-3', '65536.1',
             '6.0', '17', '1E+1', '5E+3', '2E-1', '999999999999', '0.999999999', '1.0000001', '25.1', '1E-1', '3E-2']
    precs = list(range(1, 61))
    for prec in precs:
        for mode in MODE_NAMES:
            for x in rng.sample(squares, 3) + rng.sample(plain, 3):
                one(x, prec, mode)
            if prec % 5 == 0:
                one(rnd_dec(rng, 25, -20, 20, 0), prec, mode)
    one('-4', 5, 'half_even')
    one('-0.5', 1, 'up')
    one('-1E+10', 9, 'floor')
    for prec in (100, 150, 250, 500, 1000):
        for mode in MODE_NAMES:
            for x in ('2', '0.5', '1E+9', '123456789' * 3, '1' + '0' * 60 + '1', '3E-11'):
                one(x, prec, mode)
    # rounding that carries into a new digit, and exact roots wider than the precision
    for prec in (1, 2, 3, 4, 5, 8):
        for mode in MODE_NAMES:
            one('9.9999999' + '9' * 12, prec, mode)
            one(str(99999 ** 2), prec, mode)
            one(str(31622 ** 2) + 'E+2', prec, mode)
            one(str(1234567 ** 2), prec, mode)
    return [sq]


