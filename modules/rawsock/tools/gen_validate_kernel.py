"""Recipe for src/testdata/validate_kernel.zig: classic-BPF programs (hand-picked
corner cases, then seeded random ones, valid and not) and whether the Linux
kernel accepts them through SO_ATTACH_FILTER on an AF_PACKET socket. `validate`
must agree on every one.

    unshare -rn python3 -I modules/rawsock/tools/gen_validate_kernel.py OUTDIR   # repo root

Needs a user+net namespace (no real privileges). Seeded: reproduces.
"""
import ctypes, os, random, socket, struct, sys

OUT = sys.argv[1].rstrip('/') + '/'
os.makedirs(OUT, exist_ok=True)
R = random.Random(20261104)


def ins(code, k=0, jt=0, jf=0):
    return struct.pack('<HBBI', code, jt, jf, k & 0xffffffff)


def kernel_accepts(prog):
    s = socket.socket(socket.AF_PACKET, socket.SOCK_RAW, socket.htons(3))
    buf = b''.join(prog)
    arr = ctypes.create_string_buffer(buf, len(buf))
    fp = struct.pack('H6xQ', len(prog), ctypes.addressof(arr))
    try:
        s.setsockopt(socket.SOL_SOCKET, 26, fp)
        ok = True
    except OSError:
        ok = False
    s.close()
    return ok


RET0, RETA = ins(0x06, 0), ins(0x16)
LDM = lambda k: ins(0x60, k)
STM = lambda k: ins(0x02, k)
JEQ = lambda k, jt, jf: ins(0x15, k, jt, jf)
JA = lambda k: ins(0x05, k)
named = [
    ('ret0, ld M[0], retA (unreachable read)', [RET0, LDM(0), RETA]),
    ('store, ret, read: the mask is carried through a ret', [STM(0), RET0, LDM(0), RETA]),
    ('store on jump path only, read after a ret', [JEQ(0, 2, 0), RET0, STM(0), LDM(0), RETA]),
    ('store on both paths', [JEQ(0, 1, 0), STM(0), STM(0), LDM(0), RETA]),
    ('store on one path, read reached by both', [JEQ(0, 1, 0), STM(0), LDM(0), RETA]),
    ('store then read', [STM(0), LDM(0), RETA]),
    ('read in dead code after ja', [JA(1), LDM(0), RETA]),
    ('ja over a store, read', [JA(1), STM(3), LDM(3), RETA]),
    ('ret only', [RET0]),
    ('empty-ish: ld imm no ret', [ins(0x00, 1)]),
    ('jump to last', [JEQ(1, 0, 0), RET0]),
]
progs = [(n, p) for n, p in named]
CODES = [0x00, 0x01, 0x20, 0x28, 0x30, 0x40, 0x48, 0x50, 0x60, 0x61, 0x80, 0x81, 0xb1, 0x02, 0x03, 0x07, 0x87,
         0x04, 0x0c, 0x14, 0x24, 0x34, 0x3c, 0x44, 0x54, 0x64, 0x6c, 0x74, 0x84, 0x94, 0xa4, 0x05,
         0x15, 0x1d, 0x25, 0x35, 0x45, 0x06, 0x16, 0x0e, 0x99]
for i in range(200):
    n = R.randint(1, 9)
    p = []
    for j in range(n):
        c = R.choice(CODES)
        k = R.choice([0, 1, 2, 3, 15, 16, 31, 32, 0xfffff000, 0xfffffffe, R.randrange(0, 20)])
        p.append(ins(c, k, R.randrange(0, 3), R.randrange(0, 3)))
    if R.random() < 0.8:
        p.append(R.choice([RET0, RETA]))
    progs.append(('random %d' % i, p))
rows = [(b''.join(p), kernel_accepts(p), n) for n, p in progs]
print(len(rows), 'programs;', sum(1 for r in rows if r[1]), 'accepted by the kernel')
with open(OUT + 'validate_kernel.zig', 'w') as z:
    z.write('// SPDX-License-Identifier: MIT\n// Generated by tools/gen_validate_kernel.py: classic-BPF programs and whether the Linux kernel\n// accepts them via SO_ATTACH_FILTER (Linux 7.0). Do not edit.\n\npub const Case = struct { prog: []const u8, kernel_ok: bool, name: []const u8 };\n\npub const cases = [_]Case{\n')
    for b, ok, n in rows:
        z.write('    .{ .prog = "%s", .kernel_ok = %s, .name = "%s" },\n' % (b.hex(), 'true' if ok else 'false', n))
    z.write('};\n')
