"""Recipe for src/testdata/ppp_oracle.zig: the frame corpus of src/filter.zig as a DLT_PPP (9)
savefile (address 0xff, control 0x03, the PPP protocol, the payload), and which frames
`tcpdump -y PPP -n -tt -r FILE EXPR` (libpcap, black box) selects for each expression, plus the
expressions libpcap refuses on PPP. Record i is stamped at second 1000 + i. IPv4, IPv6 and ARP
frames are kept (ARP under its Ethernet type 0x0806, which is what libpcap tests); others are left out.

    python3 -I modules/rawsock/tools/gen_ppp_oracle.py OUTDIR      # from the repository root
"""
import re, struct, subprocess, sys, os

D = sys.argv[1].rstrip('/') + '/'
os.makedirs(D, exist_ok=True)
src = open('modules/rawsock/src/filter.zig').read()
m = re.search(r'const corpus_pcap = hex\((.*?)\n\);', src, re.S)
data = bytes.fromhex(''.join(re.findall(r'"([0-9a-f]+)"', m.group(1))))
frames = []
pos = 24
while pos < len(data):
    ts, tu, cl, ol = struct.unpack_from('<IIII', data, pos)
    frames.append((ts, data[pos + 16:pos + 16 + cl]))
    pos += 16 + cl

PPP = {0x0800: 0x0021, 0x86dd: 0x0057, 0x0806: 0x0806}
out = struct.pack('<IHHiIII', 0xa1b2c3d4, 2, 4, 0, 0, 262144, 9)
for ts, f in frames:
    if len(f) < 14:
        continue
    ety = struct.unpack('>H', f[12:14])[0]
    if ety not in PPP:
        continue
    b = b'\xff\x03' + struct.pack('>H', PPP[ety]) + f[14:]
    out += struct.pack('<IIII', ts, 0, len(b), len(b)) + b
path = D + 'ppp.pcap'
open(path, 'wb').write(out)

EXPRS = [
    'ip', 'ip6', 'arp', 'rarp', 'tcp port 80', 'udp port 53', 'host 10.0.0.1', 'src host 10.0.0.1', 'dst host 10.0.0.9', 'net 10',
    'ip[8] = 64', 'tcp[13] & 2 != 0', 'ip6 net 2001:db8::/32', 'icmp', 'icmp6', 'proto 6', 'proto 17', 'portrange 20-30',
    'less 60', 'greater 100', 'len > 60', 'tcp or udp and port 53', 'ip6 host 2001:db8::1', 'ip and host 10.0.0.1 or ip6',
    'ip proto 6', 'ip6 proto 17', 'ip6 proto \\tcp', 'ether proto 0x800', 'ether proto 0x86dd', 'ether proto \\ip', 'not ip',
    'tcp[tcpflags] & tcp-syn != 0', 'icmp[icmptype] = icmp-echo', 'udp portrange 5000-5400', 'ip[6:2] & 0x1fff = 0',
    'ip6[6] = 17', 'ip6 or ip', 'sctp', 'tcp dst port 80 or 443', 'net 10.0.0.0 mask 255.0.255.0', 'ip6 dst net 2001:db8::/32',
    'not (tcp or udp)', 'arp host 10.0.0.9', 'arp src host 10.0.0.1', 'host 10.0.0.9', 'net 10.0.0.0/8', 'ether proto 0x806',
    'ether proto \\arp', 'arp[6:2] = 1', 'arp or icmp', 'ether[0] = 0', 'ether[2:2] = 0x21',
]
REFUSED = ['ether host 00:11:22:33:44:55', 'ether src 00:11:22:33:44:55', 'multicast', 'broadcast', 'vlan', 'vlan 5', 'pppoes', 'pppoed']


def esc(e):
    return e.replace('\\', '\\\\')


def verdicts(e):
    r = subprocess.run(['tcpdump', '-Z', 'root', '-n', '-tt', '-r', path, e], capture_output=True, text=True)
    if r.returncode != 0:
        return None
    return sorted(int(float(l.split()[0])) - 1000 for l in r.stdout.splitlines() if l and l[0].isdigit())


h = out.hex()
z = '// SPDX-License-Identifier: MIT\n// Generated by tools/gen_ppp_oracle.py (tcpdump -y PPP -r, libpcap 1.10.6). Do not edit.\n\n'
z += 'pub const Row = struct { []const u8, []const usize };\n\npub const corpus =\n'
lines = [h[i:i + 100] for i in range(0, len(h), 100)]
for j, l in enumerate(lines):
    z += '    "%s"%s\n' % (l, ' ++' if j < len(lines) - 1 else ';')
z += '\npub const oracle = [_]Row{\n'
for e in EXPRS:
    v = verdicts(e)
    if v is None:
        print('REFUSED (not in the table)', e, file=sys.stderr)
        continue
    z += '    .{ "%s", &.{ %s } },\n' % (esc(e), ', '.join(map(str, v)))
z += '};\n\npub const refused = [_][]const u8{\n'
for e in REFUSED:
    if verdicts(e) is None:
        z += '    "%s",\n' % esc(e)
z += '};\n'
open(D + 'ppp_oracle.zig', 'w').write(z)
print('ok')
