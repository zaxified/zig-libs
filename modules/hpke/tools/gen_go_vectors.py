"""Regenerates src/testdata/go_vectors.zig from Go's crypto/hpke test vectors:
testdata/rfc9180.json (RFC 9180 suites as accumulated SHAKE128 digests over 1000
seal/open and export rounds, including the export-only AEAD) and
testdata/hpke-pq.json (draft-ietf-hpke-pq: ML-KEM, the hybrids, SHAKE and
TurboSHAKE KDFs). The vector data is Go's, BSD-3-Clause: see modules/hpke/NOTICE.

    python3 -I modules/hpke/tools/gen_go_vectors.py /usr/lib/go-1.26/src/crypto/hpke/testdata \
        > modules/hpke/src/testdata/go_vectors.zig

Inputs used (Go 1.26.8, Debian golang-1.26-src):
    sha256 rfc9180.json  see the generated file's header
    sha256 hpke-pq.json  see the generated file's header
"""
import hashlib
import json
import os
import sys

d = sys.argv[1]
FILES = ["rfc9180.json", "hpke-pq.json"]


def hx(v):
    return '"' + (v or "") + '"'


out = []
out.append("// SPDX-License-Identifier: MIT")
out.append("// GENERATED by modules/hpke/tools/gen_go_vectors.py from Go 1.26 crypto/hpke testdata -- do not edit.")
for f in FILES:
    raw = open(os.path.join(d, f), "rb").read()
    out.append(f"// {f} sha256 {hashlib.sha256(raw).hexdigest()}")
out.append("// The vector data is Go's (BSD-3-Clause): see modules/hpke/NOTICE.")
out.append("")
out.append("pub const Encryption = struct { aad: []const u8, pt: []const u8, nonce: []const u8, ct: []const u8 };")
out.append("pub const Export = struct { context: []const u8, len: usize, value: []const u8 };")
out.append("pub const Vector = struct {")
out.append("    source: []const u8,")
out.append("    mode: u8,")
out.append("    kem_id: u16,")
out.append("    kdf_id: u16,")
out.append("    aead_id: u16,")
for k in ["info", "ikmE", "ikmR", "skRm", "pkRm", "enc", "shared_secret", "key", "base_nonce", "exporter_secret", "encryptions_accumulated", "exports_accumulated"]:
    out.append(f"    {k}: []const u8 = \"\",")
out.append("    encryptions: []const Encryption = &.{},")
out.append("    exports: []const Export = &.{},")
out.append("};")
out.append("")
out.append("pub const vectors = [_]Vector{")
for f in FILES:
    for v in json.load(open(os.path.join(d, f))):
        fields = [f'.source = "{f}"', f".mode = {v['mode']}", f".kem_id = 0x{v['kem_id']:04x}", f".kdf_id = 0x{v['kdf_id']:04x}", f".aead_id = 0x{v['aead_id']:04x}"]
        for k in ["info", "ikmE", "ikmR", "skRm", "pkRm", "enc", "shared_secret", "key", "base_nonce", "exporter_secret", "encryptions_accumulated", "exports_accumulated"]:
            if k in v:
                fields.append(f".{k} = {hx(v[k])}")
        if "encryptions" in v:
            es = ", ".join(
                f".{{ .aad = {hx(e['aad'])}, .pt = {hx(e['pt'])}, .nonce = {hx(e['nonce'])}, .ct = {hx(e['ct'])} }}"
                for e in v["encryptions"])
            fields.append(f".encryptions = &.{{ {es} }}")
        if "exports" in v:
            xs = ", ".join(
                f".{{ .context = {hx(e['exporter_context'])}, .len = {e['L']}, .value = {hx(e['exported_value'])} }}"
                for e in v["exports"])
            fields.append(f".exports = &.{{ {xs} }}")
        out.append("    .{ " + ", ".join(fields) + " },")
out.append("};")
print("\n".join(out))
