# Recipe for src/testdata/: frames written by the reference `lz4` CLI over
# deterministic inputs, and goldens.zig with the SHA-256 and length of each
# input. `src/golden_test.zig` decodes every frame and checks the digest.
#
# Needs: lz4 (v1.10.0 was used: `lz4 --version`), python3.
# Run from the repository root:  bash modules/lz4/tools/capture-goldens.sh
set -euo pipefail

out=modules/lz4/src/testdata
work=.zig-cache/lz4-goldens
mkdir -p "$out" "$work"

# Inputs: generated, never committed (only their digests are).
python3 -I - "$work" <<'EOF'
import random, sys, os
d = sys.argv[1]
r = random.Random(20261117)
words = [b"the ", b"of ", b"lz4 ", b"frame ", b"block ", b"match ", b"offset ", b"\n", b"literal "]
def text(n):
    b = bytearray()
    while len(b) < n: b += r.choice(words)
    return bytes(b[:n])
open(os.path.join(d, "empty.bin"), "wb").write(b"")
open(os.path.join(d, "hello.bin"), "wb").write(b"hello hello hello hello world\n")
open(os.path.join(d, "text100k.bin"), "wb").write(text(100_000))
open(os.path.join(d, "mixed140k.bin"), "wb").write(bytes(c if r.random() > 0.05 else r.randrange(256) for c in text(140_000)))
open(os.path.join(d, "random20k.bin"), "wb").write(bytes(r.randrange(256) for _ in range(20_000)))
EOF

# name  input  lz4 flags
cases=(
  "empty-default    empty.bin      "
  "hello-default    hello.bin      "
  "hello-legacy     hello.bin      -l"
  "text-default     text100k.bin   "
  "text-linked-64k  text100k.bin   -BD -B4 --content-size -BX"
  "text-hc12        text100k.bin   -12 -B5"
  "text-fast9       text100k.bin   --fast=9 -B4 --no-frame-crc"
  "text-legacy      text100k.bin   -l"
  "mixed-linked     mixed140k.bin  -BD -B4 -BX"
  "random-default   random20k.bin  -B4 -BX"
)

{
  echo "// SPDX-License-Identifier: MIT"
  echo "//"
  echo "// GENERATED by modules/lz4/tools/capture-goldens.sh with $(lz4 --version 2>&1 | sed 's/^\*\*\* //; s/ \*\*\*$//' | cut -d, -f1)."
  echo "// Each frame was written by the lz4 CLI with the flags shown; \`len\` and"
  echo "// \`sha256\` are those of the input it compressed."
  echo
  echo "pub const Golden = struct { name: []const u8, flags: []const u8, len: usize, sha256: []const u8, frame: []const u8 };"
  echo
  echo "pub const goldens = [_]Golden{"
  for c in "${cases[@]}"; do
    read -r name input flags <<<"$c"
    # shellcheck disable=SC2086
    lz4 -q -f $flags "$work/$input" "$out/$name.lz4"
    len=$(stat -c %s "$work/$input")
    sha=$(sha256sum "$work/$input" | cut -d' ' -f1)
    echo "    .{ .name = \"$name\", .flags = \"$flags\", .len = $len, .sha256 = \"$sha\", .frame = @embedFile(\"$name.lz4\") },"
  done
  echo "};"
} > "$out/goldens.zig"
ls -l "$out"
