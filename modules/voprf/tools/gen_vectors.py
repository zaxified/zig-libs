"""Regenerate src/suite_vectors.zig and src/h2c_vectors.zig from the RFC texts.

Usage: python3 -I tools/gen_vectors.py <rfc9497.txt> <rfc9380.txt> <out_dir>
       zig fmt <out_dir>/suite_vectors.zig <out_dir>/h2c_vectors.zig

The RFC plain-text files come from https://www.rfc-editor.org/rfc/rfc9497.txt
and https://www.rfc-editor.org/rfc/rfc9380.txt. Nothing is computed here: the
script only re-flows the wrapped hex values of RFC 9497 Appendix A (A.1..A.5)
and RFC 9380 Appendix J.1.1/J.2.1/J.3.1 and K.1/K.3 into Zig literals, so the
goldens are the RFC's bytes, not this module's output.
"""
import re
import sys

PAGE_RE = re.compile(r'^(RFC 9\d{3} .*\d{4}|.*\[Page \d+\])$')


def clean_lines(path):
    out = []
    for ln in open(path, encoding='utf-8').read().split('\n'):
        ln = ln.replace('\f', '')
        if PAGE_RE.match(ln.strip()):
            continue
        out.append(ln.rstrip())
    return out


def section(lines, start, end):
    """Lines from the header line that equals `start` up to (excluding) the
    first header line starting with `end` (or the end of file)."""
    i = next(k for k, l in enumerate(lines) if l == start)
    j = len(lines)
    for k in range(i + 1, len(lines)):
        if end is not None and lines[k].startswith(end):
            j = k
            break
    return lines[i:j]


TOKEN_RE = re.compile(r'^\s+[0-9A-Za-z_,]+$')
KV_RE = re.compile(r'^\s+([A-Za-z_\[\]0-9.]+(?: [a-z_]+)?)\s*=\s*(.*)$')


def records(lines):
    """Yield (key, value) pairs in order; wrapped values (continuation lines,
    possibly across a removed page break) are joined."""
    pairs = []
    k = 0
    while k < len(lines):
        m = KV_RE.match(lines[k])
        if not m:
            k += 1
            continue
        key, val = m.group(1).strip(), m.group(2).strip()
        k += 1
        while k < len(lines):
            if lines[k] == '':
                # a blank line inside a value only happens at a page break
                n = k
                while n < len(lines) and lines[n] == '':
                    n += 1
                if n < len(lines) and TOKEN_RE.match(lines[n]) and not KV_RE.match(lines[n]) and key not in ('msg',) and val != '':
                    k = n
                    continue
                break
            if KV_RE.match(lines[k]) or not TOKEN_RE.match(lines[k]):
                break
            val += lines[k].strip()
            k += 1
        pairs.append((key, val))
    return pairs


def zstr(s):
    return '"' + s + '"'


def zlist(vals):
    return '&.{ ' + ', '.join(zstr(v) for v in vals) + ' }'


def gen_9497(lines):
    suites = [
        ('ristretto255_sha512', 'A.1.  ristretto255-SHA512', 'A.2.  '),
        ('decaf448_shake256', 'A.2.  decaf448-SHAKE256', 'A.3.  '),
        ('p256_sha256', 'A.3.  P256-SHA256', 'A.4.  '),
        ('p384_sha384', 'A.4.  P384-SHA384', 'A.5.  '),
        ('p521_sha512', 'A.5.  P521-SHA512', 'Acknowledgements'),
    ]
    out = ['// SPDX-License-Identifier: MIT',
           '//! RFC 9497 Appendix A test vectors for all five ciphersuites and all',
           '//! three modes, GENERATED by `tools/gen_vectors.py` from the RFC text',
           '//! (do not edit by hand; see `NOTICE`). Values are lower-case hex;',
           '//! batch vectors hold one entry per batch element.',
           '',
           'pub const Vector = struct {',
           '    /// Appendix section, e.g. "A.3.2.3".',
           '    name: []const u8,',
           '    input: []const []const u8,',
           '    info: ?[]const u8 = null,',
           '    blind: []const []const u8,',
           '    blinded_element: []const []const u8,',
           '    evaluation_element: []const []const u8,',
           '    proof: ?[]const u8 = null,',
           '    proof_random_scalar: ?[]const u8 = null,',
           '    output: []const []const u8,',
           '};',
           '',
           'pub const ModeVectors = struct {',
           '    name: []const u8,',
           '    seed: []const u8,',
           '    key_info: []const u8,',
           '    sk: []const u8,',
           '    pk: ?[]const u8 = null,',
           '    vectors: []const Vector,',
           '};',
           '',
           'pub const SuiteVectors = struct { oprf: ModeVectors, voprf: ModeVectors, poprf: ModeVectors };',
           '']
    total = 0
    for ident, start, end in suites:
        sec = section(lines, start, end)
        num = start.split()[0]  # "A.3."
        out.append(f'pub const {ident} = SuiteVectors{{')
        for mi, mode in enumerate(['oprf', 'voprf', 'poprf']):
            mnum = f'{num}{mi + 1}.'
            mhead = {'oprf': 'OPRF Mode', 'voprf': 'VOPRF Mode', 'poprf': 'POPRF Mode'}[mode]
            nxt = f'{num}{mi + 2}.' if mi < 2 else None
            msec = section(sec, f'{mnum}  {mhead}', nxt)
            # split into header + vectors
            idx = [k for k, l in enumerate(msec) if re.match(r'^' + re.escape(mnum) + r'\d+\.  Test Vector', l)]
            head = dict(records(msec[:idx[0]]))
            out.append(f'    .{mode} = .{{')
            out.append(f'        .name = "{mnum[:-1]}",')
            out.append(f'        .seed = {zstr(head["Seed"])},')
            out.append(f'        .key_info = {zstr(head["KeyInfo"])},')
            out.append(f'        .sk = {zstr(head["skSm"])},')
            if 'pkSm' in head:
                out.append(f'        .pk = {zstr(head["pkSm"])},')
            out.append('        .vectors = &.{')
            for vi, s in enumerate(idx):
                e = idx[vi + 1] if vi + 1 < len(idx) else len(msec)
                name = msec[s].split()[0].rstrip('.')
                rec = dict(records(msec[s + 1:e]))
                out.append('            .{')
                out.append(f'                .name = "{name}",')
                out.append(f'                .input = {zlist(rec["Input"].split(","))},')
                if 'Info' in rec:
                    out.append(f'                .info = {zstr(rec["Info"])},')
                for key, fld in [('Blind', 'blind'), ('BlindedElement', 'blinded_element'),
                                 ('EvaluationElement', 'evaluation_element'), ('Output', 'output')]:
                    out.append(f'                .{fld} = {zlist(rec[key].split(","))},')
                if 'Proof' in rec:
                    out.append(f'                .proof = {zstr(rec["Proof"])},')
                    out.append(f'                .proof_random_scalar = {zstr(rec["ProofRandomScalar"])},')
                out.append('            },')
                total += 1
            out.append('        },')
            out.append('    },')
        out.append('};')
        out.append('')
    out.append(f'/// Number of Appendix A test vectors transcribed (all suites, all modes).')
    out.append(f'pub const total_vectors = {total};')
    return '\n'.join(out) + '\n'


def gen_9380(lines):
    out = ['// SPDX-License-Identifier: MIT',
           '//! RFC 9380 test vectors, GENERATED by `tools/gen_vectors.py` from the',
           '//! RFC text (do not edit by hand): Appendix J.1.1 / J.2.1 / J.3.1',
           '//! (P256/P384/P521 `_XMD:SHA-*_SSWU_RO_`, with the `u[0]`/`u[1]`',
           '//! hash_to_field and `Q0`/`Q1` map_to_curve intermediates) and Appendix',
           '//! K.1 (`expand_message_xmd(SHA-256)`) / K.3 (SHA-512).',
           '',
           'pub const H2cVector = struct { msg: []const u8, px: []const u8, py: []const u8, u0: []const u8, u1: []const u8, q0x: []const u8, q0y: []const u8, q1x: []const u8, q1y: []const u8 };',
           'pub const H2cSuite = struct { name: []const u8, dst: []const u8, vectors: []const H2cVector };',
           'pub const XmdVector = struct { msg: []const u8, len_in_bytes: usize, uniform_bytes: []const u8 };',
           'pub const XmdSuite = struct { name: []const u8, dst: []const u8, vectors: []const XmdVector };',
           '']
    for ident, start, end in [('p256', 'J.1.1.  P256_XMD:SHA-256_SSWU_RO_', 'J.1.2.'),
                              ('p384', 'J.2.1.  P384_XMD:SHA-384_SSWU_RO_', 'J.2.2.'),
                              ('p521', 'J.3.1.  P521_XMD:SHA-512_SSWU_RO_', 'J.3.2.')]:
        recs = records(section(lines, start, end))
        dst = dict(recs)['dst']
        out.append(f'pub const {ident} = H2cSuite{{ .name = "{start.split()[0].rstrip(".")}", .dst = {zstr(dst)}, .vectors = &.{{')
        cur = None
        vecs = []
        for k, v in recs:
            if k == 'msg':
                cur = {'msg': v}
                vecs.append(cur)
            elif cur is not None:
                cur[k] = v
        for v in vecs:
            out.append('    .{ ' + ', '.join([f'.msg = {zstr(v["msg"])}', f'.px = {zstr(v["P.x"])}', f'.py = {zstr(v["P.y"])}',
                                             f'.u0 = {zstr(v["u[0]"])}', f'.u1 = {zstr(v["u[1]"])}',
                                             f'.q0x = {zstr(v["Q0.x"])}', f'.q0y = {zstr(v["Q0.y"])}',
                                             f'.q1x = {zstr(v["Q1.x"])}', f'.q1y = {zstr(v["Q1.y"])}']) + ' },')
        out.append('} };')
        out.append('')
    for ident, start, end in [('xmd_sha256', 'K.1.  expand_message_xmd(SHA-256)', 'K.2.'),
                              ('xmd_sha512', 'K.3.  expand_message_xmd(SHA-512)', 'K.4.')]:
        recs = records(section(lines, start, end))
        dst = dict(recs)['DST']
        out.append(f'pub const {ident} = XmdSuite{{ .name = "{start.split()[0].rstrip(".")}", .dst = {zstr(dst)}, .vectors = &.{{')
        cur = None
        for k, v in recs:
            if k == 'msg':
                cur = {'msg': v}
            elif k == 'len_in_bytes':
                cur['len'] = int(v, 16)
            elif k == 'uniform_bytes':
                out.append(f'    .{{ .msg = {zstr(cur["msg"])}, .len_in_bytes = {cur["len"]}, .uniform_bytes = {zstr(v)} }},')
        out.append('} };')
        out.append('')
    return '\n'.join(out) + '\n'


def main():
    a, b, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
    open(outdir + '/suite_vectors.zig', 'w').write(gen_9497(clean_lines(a)))
    open(outdir + '/h2c_vectors.zig', 'w').write(gen_9380(clean_lines(b)))


main()
