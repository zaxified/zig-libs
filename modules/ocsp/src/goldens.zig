//! Real OCSP responses captured from live public-CA responders, plus the
//! certificate chains they answer for.
//!
//! ## Why this file exists
//!
//! Every fixture in `ocsp_test.zig` is CONSTRUCTED: a `BasicOCSPResponse`
//! hand-built with this module's own DER writer and signed by the sibling
//! `rsa`/`p256` modules — the same encoder that `parseResponse` + `verify`
//! then decode. That is the textbook "encoder and decoder agree on the same
//! misreading" blind spot: nothing in this module had ever been fed DER a
//! real CA actually emits. The goldens below close that gap.
//!
//! ## Capture recipe
//!
//! ```sh
//! openssl s_client -connect <host>:443 -servername <host> -showcerts </dev/null
//! # split the leaf/intermediate PEM blocks out of the printed chain
//! openssl x509 -in leaf.pem -noout -text | grep -A2 "OCSP - URI"   # AIA
//! openssl ocsp -issuer intermediate.pem -cert leaf.pem \
//!              -url <responder-url> -respout resp.der -no_nonce -text
//! ```
//!
//! `openssl ocsp` itself printed "Response verify OK" for both captures below
//! — its own independent signature check against the chain, before this
//! module ever saw the bytes.
//!
//! Captured 2026-08-01. Three public CAs still answered live OCSP at capture
//! time (DigiCert, GoDaddy, Sectigo); two are kept here (a third, Sectigo, was
//! also live but structurally close to DigiCert's direct-responder shape and
//! not needed for additional coverage).
//!
//! - **DigiCert** (`www.digicert.com`, responder `http://ocsp.digicert.com`):
//!   a *direct* responder — `ResponderID` is **byKey** (SHA-1 of the issuing
//!   CA's own key; no delegate cert in `certs`). `CertID.hashAlgorithm` is
//!   **SHA-1** — every constructed response fixture in `ocsp_test.zig` hashes
//!   its `CertID` with SHA-256 (`certIdDer` in that file hardcodes
//!   `Sha256.hash`), so this is the only place `certIdBinds`'s SHA-1 branch
//!   ever runs against a response. RSA-SHA256 signature over a 2048-bit key
//!   (constructed fixtures use 1024-bit). `nextUpdate` present (~7 days out),
//!   no `responseExtensions` (no nonce, consistent with `-no_nonce`).
//! - **GoDaddy** (`www.godaddy.com`, responder `http://ocsp.godaddy.com/`): a
//!   **delegated** responder — `ResponderID` is **byName** = "Go Daddy
//!   Validation Authority - G2", and `certs [0]` embeds a certificate
//!   directly signed by the leaf's issuing CA, carrying the
//!   `id-kp-OCSPSigning` EKU (RFC 6960 §4.2.2.2), on a **4096-bit** RSA key
//!   (the constructed delegate fixtures in `ocsp_test.zig` use 1024-bit) —
//!   the first time `resolveDelegate` runs against a certificate this module
//!   did not build itself. `CertID.hashAlgorithm` SHA-1, RSA-SHA256
//!   signature, `nextUpdate` present, no `responseExtensions`.
//!
//! RFC 6960 does not obligate a CA to run OCSP forever — Let's Encrypt has
//! been winding its responder down (see SPEC.md) — so these bytes are the
//! permanent fixture from here on; regenerating them means repeating the
//! recipe above against whichever public responder still answers.
//!
//! Reference times, independently computed via `date -u -d '<RFC-3339>' +%s`
//! (never this module's own `parseGeneralizedTime`):
//!
//! ```text
//! DigiCert: thisUpdate 2026-07-31T19:27:00Z = 1785526020
//!           nextUpdate 2026-08-07T18:27:00Z = 1786127220
//! GoDaddy:  thisUpdate 2026-07-31T16:20:45Z = 1785514845
//!           nextUpdate 2026-08-04T16:19:45Z = 1785860385
//!           delegate cert validity: 2026-02-26T12:00:00Z = 1772107200
//!                                .. 2027-02-26T12:00:00Z = 1803643200
//! ```
//!
//! Every test below pins `now_unix` to a fixed instant inside these windows
//! (never the wall clock, per the module's own contract) — a rebuild a year
//! from now still asserts against the same captured instant.
//!
//! ## Not covered here, with reasons
//!
//! - **ECDSA-signed real response** — neither live responder that answered
//!   at capture time signs with ECDSA (both are RSA-SHA256); the constructed
//!   fixture in `ocsp_test.zig` ("ECDSA-P256 direct-issuer signature
//!   accepted") already exercises that branch against a real signature, just
//!   not a real CA's. No public CA offering an ECDSA OCSP responder was
//!   found during this capture; revisit if one shows up.
//! - **`revoked` / `unknown` real status** — both captured certificates are
//!   live production leaves in good standing, so both responses say `good`;
//!   a real `revoked`/`unknown` response would require a real revoked
//!   certificate to query, which isn't something to go create. The
//!   constructed fixtures cover both statuses structurally.
//! - **SHA-256 `CertID` in a real response** — both live responders that
//!   answered hash with SHA-1 (RFC 6960's classic-profile default, still
//!   what these CAs key on); no capture here exercises a real SHA-256
//!   `CertID`, though the constructed fixtures use SHA-256 throughout (the
//!   reverse gap).
//! - **`responseExtensions` (e.g. `id-pkix-ocsp-archive-cutoff`)** — neither
//!   capture carries any (both requests used `-no_nonce`, and neither
//!   responder added an archive-cutoff or other extension); the constructed
//!   nonce fixtures already cover the extension-parsing path structurally.
//! - **Multiple `SingleResponse`s in one response** — both captures answer
//!   for exactly one `CertID`; this module's request only ever asks about
//!   one certificate, so a multi-entry response was never going to arise
//!   from a real query anyway.

