/// thisUpdate + 1h — inside the default 24h max_age (this response has no
/// nextUpdate at all).
const openssl_byname_now_unix: i64 = 1785701199 + 3600;

test "golden OpenSSL: byName ResponderID naming the issuer takes the DIRECT path" {
    const parsed = try ocsp.parseResponse(&openssl_byname_response_der);
    try testing.expectEqual(ocsp.ResponseStatus.successful, parsed.status);
    const basic = parsed.basic.?;
    try testing.expect(basic.responder == .by_name);
    try testing.expect(basic.certs == null); // -resp_no_certs: nothing to delegate to
    try testing.expect(basic.nonce == null);

    const verdict = try ocsp.verify(parsed, &openssl_byname_issuer_der, &openssl_byname_leaf_der, .{
        .now_unix = openssl_byname_now_unix,
    });
    try testing.expect(verdict.status == .good);
    // The point of the fixture: byName matched the ISSUER, so the issuer's own
    // key verified the signature and no delegate was looked for. With `certs`
    // absent, a wrong answer here could only be `UntrustedResponder`.
    try testing.expect(!verdict.delegated);
    try testing.expect(verdict.responder == .by_name);
    try testing.expectEqual(@as(i64, 1785701199), verdict.this_update_unix);
    try testing.expectEqual(@as(?i64, null), verdict.next_update_unix);
}

test "golden OpenSSL: with nextUpdate absent, max_age_seconds is what bounds the response" {
    const parsed = try ocsp.parseResponse(&openssl_byname_response_der);
    try testing.expectError(error.ResponseNotYetValid, ocsp.verify(parsed, &openssl_byname_issuer_der, &openssl_byname_leaf_der, .{
        .now_unix = 1785701199 - 1,
    }));
    // Exactly at the default 24h horizon is still fresh; one second later is not.
    _ = try ocsp.verify(parsed, &openssl_byname_issuer_der, &openssl_byname_leaf_der, .{
        .now_unix = 1785701199 + 24 * 60 * 60,
    });
    try testing.expectError(error.ResponseStale, ocsp.verify(parsed, &openssl_byname_issuer_der, &openssl_byname_leaf_der, .{
        .now_unix = 1785701199 + 24 * 60 * 60 + 1,
    }));
}

test "golden OpenSSL: a byName ResponderID that names nobody in the chain is untrusted" {
    // Teeth for the fixture above: flip one byte of the ResponderID's Name so
    // it no longer matches the issuer's subject. `certs` is absent, so there
    // is nothing to fall back to and verification must refuse.
    var mutated = openssl_byname_response_der;
    const name_marker = "zig-libs OCSP test CA";
    const at = std.mem.indexOf(u8, &mutated, name_marker).?;
    mutated[at] ^= 0x20;

    const parsed = try ocsp.parseResponse(&mutated);
    try testing.expect(parsed.basic.?.responder == .by_name);
    try testing.expectError(error.UntrustedResponder, ocsp.verify(parsed, &openssl_byname_issuer_der, &openssl_byname_leaf_der, .{
        .now_unix = openssl_byname_now_unix,
    }));
}
