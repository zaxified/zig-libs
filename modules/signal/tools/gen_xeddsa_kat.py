"""Generate src/xeddsa_kat_vector.zig: an XEdDSA known answer over our own inputs.

    python3 modules/signal/tools/gen_xeddsa_kat.py > modules/signal/src/xeddsa_kat_vector.zig

An independent oracle for `xeddsa.zig`: Edwards25519 arithmetic written here
from RFC 7748 / RFC 8032's curve definitions and the XEdDSA paper, Python
standard library only, sharing no code with the Zig module. It signs one
message with one key in BOTH variants the module ships:

  * spec: calculate_key_pair forces sign 0 (negate a when E's sign bit is 1);
    s is a canonical scalar.
  * deployed libsignal: the natural-sign A and a, with A's sign bit carried in
    the top bit of s (signature[63]).

The key is the first one derived from a fixed label whose natural Edwards
sign bit is 1: for that key the two variants differ, which is the case the
module's tests exist to pin. The nonce input Z is fixed, so the signatures
are fully determined and a rerun reproduces the file byte for byte.
"""

import hashlib

P = 2**255 - 19
L = 2**252 + 27742317777372353535851937790883648493
D = -121665 * pow(121666, -1, P) % P


def inv(x):
    return pow(x, P - 2, P)


def add(p1, p2):
    (x1, y1), (x2, y2) = p1, p2
    t = D * x1 * x2 * y1 * y2 % P
    return ((x1 * y2 + x2 * y1) * inv(1 + t) % P, (y1 * y2 + x1 * x2) * inv(1 - t) % P)


def mul(k, pt):
    acc = (0, 1)
    while k:
        if k & 1:
            acc = add(acc, pt)
        pt = add(pt, pt)
        k >>= 1
    return acc


def recover_x(y, sign):
    xx = (y * y - 1) * inv(D * y * y + 1) % P
    x = pow(xx, (P + 3) // 8, P)
    if (x * x - xx) % P:
        x = x * pow(2, (P - 1) // 4, P) % P
    assert (x * x - xx) % P == 0
    if x & 1 != sign:
        x = P - x
    return x


BY = 4 * inv(5) % P
B = (recover_x(BY, 0), BY)
assert mul(L, B) == (0, 1)


def encode(pt):
    x, y = pt
    return (y | ((x & 1) << 255)).to_bytes(32, "little")


def neg(pt):
    return ((-pt[0]) % P, pt[1])


def sha512_int(*parts):
    h = hashlib.sha512()
    for part in parts:
        h.update(part)
    return int.from_bytes(h.digest(), "little")


HASH1_PREFIX = bytes([0xFE]) + bytes([0xFF]) * 31


def clamp(k):
    b = bytearray(k)
    b[0] &= 248
    b[31] &= 127
    b[31] |= 64
    return bytes(b)


def montgomery_u(pt):
    y = pt[1]
    return ((1 + y) * inv(1 - y) % P).to_bytes(32, "little")


def sign_with(a, a_point, msg, z):
    a_bytes = a.to_bytes(32, "little")
    r = sha512_int(HASH1_PREFIX, a_bytes, msg, z) % L
    r_enc = encode(mul(r, B))
    h = sha512_int(r_enc, encode(a_point), msg) % L
    s = (r + h * a) % L
    return r_enc + s.to_bytes(32, "little")


def verify_with(a_point, msg, sig):
    r_enc, s = sig[:32], int.from_bytes(sig[32:], "little")
    assert s < L
    h = sha512_int(r_enc, encode(a_point), msg) % L
    ry = int.from_bytes(r_enc, "little")
    r_pt = (recover_x(ry & ((1 << 255) - 1), ry >> 255), ry & ((1 << 255) - 1))
    return mul(s, B) == add(r_pt, mul(h, a_point))


# ── pick the key: first label-derived seed whose natural sign bit is 1 ────

counter = 0
while True:
    seed = hashlib.sha512(b"zig-libs signal xeddsa kat " + bytes([counter])).digest()[:32]
    a_nat = int.from_bytes(clamp(seed), "little") % L
    e = mul(a_nat, B)
    if e[0] & 1 == 1:
        break
    counter += 1

mont_pub = montgomery_u(e)
# A serialized Signal public key (0x05 type byte + 32 bytes) as the message,
# the shape X3DH signs.
msg = bytes([0x05]) + hashlib.sha256(b"zig-libs signal xeddsa kat message").digest()
z = hashlib.sha512(b"zig-libs signal xeddsa kat nonce").digest()

# Deployed-libsignal variant: natural a and A, sign bit into signature[63].
sig_ls = bytearray(sign_with(a_nat, e, msg, z))
assert sig_ls[63] & 0x80 == 0
sig_ls[63] |= 0x80
sig_ls = bytes(sig_ls)

# Spec variant: sign 1 here, so a and A are negated (A gets sign 0).
a_spec, e_spec = (L - a_nat) % L, neg(e)
assert encode(e_spec)[31] >> 7 == 0
sig_spec = sign_with(a_spec, e_spec, msg, z)

# Self-checks: both verify under their own reading of A, and differ.
assert verify_with(e, msg, sig_ls[:63] + bytes([sig_ls[63] & 0x7F]))
assert verify_with(e_spec, msg, sig_spec)
assert sig_ls != sig_spec


def zig_bytes(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 8]) for i in range(0, len(data), 8)]
    body = "".join(f"    {row},\n" for row in rows)
    return f"pub const {name}: [{len(data)}]u8 = .{{\n{body}}};"


