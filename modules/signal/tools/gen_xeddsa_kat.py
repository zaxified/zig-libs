print(zig_bytes("message", msg))
print(zig_bytes("z", z))
print("/// Deployed-libsignal variant: natural-sign A, sign bit in `signature[63]`.")
print(zig_bytes("signature_libsignal", sig_ls))
print("/// Spec variant: sign 0 forced, `s` canonical.")
print(zig_bytes("signature_spec", sig_spec))
