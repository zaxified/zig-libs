        .signed_prekey = spk.public_key,
        .signed_prekey_id = 1,
        .signed_prekey_signature = dummySignature(),
    };
    var bytes = bundle.toBytes();
    bytes[key_len_flag_offset()] = 2; // corrupt the has_opk byte
