// ── XEdDSA known-answer vector ──────────────────────────────────────────
//
// `xeddsa_kat_vector.zig`, generated by `tools/gen_xeddsa_kat.py` (see this
// file's module doc comment). The message is a serialized Signal public key
// (0x05 type byte + 32 bytes), the shape X3DH signs.

const kat = @import("xeddsa_kat_vector.zig");
const kat_priv = kat.montgomery_priv;
const kat_pub = kat.montgomery_pub;
const kat_message = kat.message;
const kat_signature = kat.signature_libsignal;

test "XEdDSA KAT: the vector's keypair is a genuine X25519 pair" {
    const derived = X25519.recoverPublicKey(kat_priv);
    try std.testing.expectEqualSlices(u8, &kat_pub, &derived);
}

test "XEdDSA KAT: the oracle's deployed-variant signature is accepted by xeddsa.libsignal.verify; every 1-byte tamper rejected" {
    // EXTERNAL ANCHOR (the independent Python oracle — see this file's
    // module doc comment), exercised against the module's SHIPPED
    // deployed-libsignal-variant verifier. This vector's key is a sign-1 key
    // (sig[63]'s top bit is set), which is exactly the case the spec variant
    // cannot handle — so this is also the required positive anchor for a
    // natural-sign-1 key.
    try std.testing.expectEqual(@as(u8, 1), kat_signature[63] >> 7);
    try std.testing.expect(xeddsa.libsignal.verify(kat_pub, &kat_message, kat_signature));

    // Teeth check: flip
    // the low bit of each of the 64 signature bytes in turn, confirm
    // EVERY one is rejected, then move to the next (each iteration starts
    // from a fresh untampered copy, so the vector itself is never left
    // corrupted for the accept-check above, which already ran first).
    var i: usize = 0;
    while (i < kat_signature.len) : (i += 1) {
        var tampered = kat_signature;
        tampered[i] ^= 0x01;
        try std.testing.expect(!xeddsa.libsignal.verify(kat_pub, &kat_message, tampered));
    }
}

test "XEdDSA KAT: the spec-pure verify deliberately REJECTS the sign-bit-in-s variant signature" {
    // sig[63]'s smuggled sign bit makes `s` >= 2^255 under the spec's
    // reading -> non-canonical scalar -> fail-closed false. This pins the
    // documented variant incompatibility (xeddsa.zig module doc comment);
    // do NOT "fix" verify to accept it.
    try std.testing.expect(!xeddsa.verify(kat_pub, &kat_message, kat_signature));
}

test "XEdDSA KAT: both signers reproduce the oracle's signatures byte for byte" {
    // The oracle fixes the nonce input `z`, so signing is fully determined:
    // this pins the whole signing path (key derivation, sign forcing or bit
    // smuggling, nonce hash, challenge hash, s) against code the module
    // shares nothing with.
    const ls_sig = shim.xeddsa.libsignal.sign(kat_priv, &kat_message, kat.z);
    try std.testing.expectEqualSlices(u8, &kat.signature_libsignal, &ls_sig);
    const spec_sig = shim.xeddsa.sign(kat_priv, &kat_message, kat.z);
    try std.testing.expectEqualSlices(u8, &kat.signature_spec, &spec_sig);
    try std.testing.expect(xeddsa.verify(kat_pub, &kat_message, kat.signature_spec));
    // A spec signature is the sign_bit == 0 special case of the variant.
    try std.testing.expect(xeddsa.libsignal.verify(kat_pub, &kat_message, kat.signature_spec));
}

test "XEdDSA KAT: this module's spec-variant sign round-trips over the vector's own (sign-1) key" {
    // Self round-trip with this test's own `z` — it only checks this
    // module's own sign/verify agree for a nonce the oracle did not use.
    var z: xeddsa.RandomData = undefined;
    for (&z, 0..) |*b, i| b.* = @intCast(i);
    const sig = shim.xeddsa.sign(kat_priv, &kat_message, z);
    // Spec variant: s is canonical, top bit never smuggled.
    try std.testing.expectEqual(@as(u8, 0), sig[63] >> 7);
    try std.testing.expect(xeddsa.verify(kat_pub, &kat_message, sig));
    // And the deployed-variant verifier accepts it too: a spec signature
    // is the sign_bit == 0 special case of the variant.
    try std.testing.expect(xeddsa.libsignal.verify(kat_pub, &kat_message, sig));
}

test "XEdDSA KAT: xeddsa.libsignal.sign self-round-trips over the vector's own (sign-1) key" {
    // Self round-trip with this test's own `z`: the module's deployed-variant
    // signer produces a signature its verifier accepts, carrying the KEY's
    // sign-1 bit.
    var z: xeddsa.RandomData = undefined;
    for (&z, 0..) |*b, i| b.* = @intCast(255 - i);
    const sig = shim.xeddsa.libsignal.sign(kat_priv, &kat_message, z);
    try std.testing.expectEqual(@as(u8, 1), sig[63] >> 7);
    try std.testing.expect(xeddsa.libsignal.verify(kat_pub, &kat_message, sig));
    // A sign-1 deployed-variant signature must NOT verify under the
    // spec-pure verifier (non-canonical s, same reasoning as the KAT
    // above).
    try std.testing.expect(!xeddsa.verify(kat_pub, &kat_message, sig));
}

// ── independent cross-check via std's Ed25519 verifier ─────────────────
//
// XEdDSA's domain separation lives ONLY in the nonce hash (`hash1`, a
// signer-side secret derivation the verifier never recomputes); the
// CHALLENGE hash `SHA-512(R || A || M)` is byte-identical to Ed25519's.
// A spec-pure XEdDSA signature is therefore a valid Ed25519 signature
// under the recovered sign-0 `A` as an Ed25519 public key — verifying
// that with `std.crypto.sign.Ed25519`'s own (independently implemented)
// verifier cross-checks this module's `sign` and Montgomery->Edwards
// recovery against code this module shares nothing with.

test "XEdDSA cross-check: signatures verify under std.crypto.sign.Ed25519 with the recovered sign-0 A" {
    const Ed25519 = std.crypto.sign.Ed25519;
    var z: xeddsa.RandomData = undefined;
    for (&z, 0..) |*b, i| b.* = @intCast(255 - i);

    // The KAT's key (a known sign-1 key) plus deterministic
    // seeds — several keys, both sign-bit branches statistically covered.
    var seeds: [5][32]u8 = undefined;
    seeds[0] = kat_priv;
    var i: u8 = 1;
    while (i < seeds.len) : (i += 1) {
        var wide: [64]u8 = undefined;
        std.crypto.hash.sha2.Sha512.hash(&[_]u8{ 'e', 'd', 'x', 'c', 'h', 'k', i }, &wide, .{});
        seeds[i] = wide[0..32].*;
    }

    for (seeds) |seed| {
        const msg = "cross-checked against std's own Ed25519 verifier";
        const sig = shim.xeddsa.sign(seed, msg, z);
        const mont_pub = X25519.recoverPublicKey(seed);
        try std.testing.expect(xeddsa.verify(mont_pub, msg, sig));

        const a = try xeddsa.edwardsFromMontgomery(mont_pub);
        const ed_pub = try Ed25519.PublicKey.fromBytes(a.toBytes());
        const ed_sig = Ed25519.Signature.fromBytes(sig);
        try ed_sig.verify(msg, ed_pub); // std must ACCEPT — errors fail the test
    }
}

// ── fail-closed on garbage (never panic on attacker input) ─────────────

test "XEdDSA: verify fails closed (false, no panic) on malformed keys and signatures" {
    var threaded = testIo();
    defer threaded.deinit();
    const io = threaded.io();

    const kp = X25519.KeyPair.generate(io);
    var z: xeddsa.RandomData = undefined;
    io.random(&z);
    const msg = "fail closed";
    const good = shim.xeddsa.sign(kp.secret_key, msg, z);
    try std.testing.expect(xeddsa.verify(kp.public_key, msg, good));

    // All-zero public key: maps to the order-2 point (0, -1) -> rejected.
    try std.testing.expect(!xeddsa.verify(@as([32]u8, @splat(0)), msg, good));
    // Non-canonical public key (top bit set).
    var noncanon_pub = kp.public_key;
    noncanon_pub[31] |= 0x80;
    try std.testing.expect(!xeddsa.verify(noncanon_pub, msg, good));
    // u = p - 1 (the birational map's pole).
    var pole = @as([32]u8, @splat(0xFF));
    pole[0] = 0xEC;
    pole[31] = 0x7F;
    try std.testing.expect(!xeddsa.verify(pole, msg, good));
    // Non-canonical s (>= L).
    var bad_s = good;
    bad_s[63] |= 0x20; // pushes s >= 2^253 > L
    try std.testing.expect(!xeddsa.verify(kp.public_key, msg, bad_s));
    // All-zero signature.
    try std.testing.expect(!xeddsa.verify(kp.public_key, msg, @as([64]u8, @splat(0))));
    // All-0xFF signature (non-canonical everything).
    try std.testing.expect(!xeddsa.verify(kp.public_key, msg, @as([64]u8, @splat(0xFF))));
}

