//! Tests for `x3dh.zig` + `xeddsa.zig`. Two groups (the ordering used to
//! matter when group 2 `@panic`ed against the XEdDSA stubs; it is kept
//! for readability now that everything passes):
//!
//!   1. **X3DH agreement + codec.** Exercises `x3dh.initiateUnverified`/
//!      `x3dh.respond` (the DH+HKDF composition, deliberately not routed
//!      through `xeddsa.verify` so the agreement math is tested in
//!      isolation) and the `PreKeyBundle`/`InitialMessage` byte codecs.
//!   2. **XEdDSA + the fail-closed X3DH entry points.** Round-trip,
//!      tamper rejection, fail-closed garbage-input handling, the
//!      known-answer vector (see below), an independent
//!      cross-check of `xeddsa.sign` against `std.crypto.sign.Ed25519`'s
//!      own verifier, and the full `generateSignedPreKey` -> `initiate`
//!      -> `respond` path.
//!
//! **Test-vector provenance:** the XEdDSA spec text publishes no numeric
//! vector. The known answer below (`xeddsa_kat_vector.zig`) is generated by
//! `tools/gen_xeddsa_kat.py` over our own key, message and nonce: an
//! independent Edwards25519 implementation in plain Python that signs in
//! BOTH variants this module ships (`xeddsa.zig`'s module doc comment). The
//! key's natural Edwards sign bit is 1 — exactly the case where the variants
//! differ. `xeddsa.libsignal.sign`/`xeddsa.sign` must reproduce the oracle's
//! signatures byte for byte, `xeddsa.libsignal.verify` must accept the
//! deployed-variant signature with all 64 single-byte tampers rejected, and
//! the spec-pure `xeddsa.verify` must REJECT it.
//!
//! Until 2026-10-26 this was the vector from libsignal-protocol-c's own test
//! suite (GPLv3); it was replaced because copyleft-licensed data may not
//! live in this repository. What the oracle encodes about deployed libsignal
//! is the documented convention (natural-sign `A`, sign bit in
//! `signature[63]`), not a signature libsignal produced.

const std = @import("std");
const x3dh = @import("x3dh.zig");
const xeddsa = @import("xeddsa.zig");
const shim = @import("test_shim.zig");
const X25519 = std.crypto.dh.X25519;

fn testIo() std.Io.Threaded {
    return std.Io.Threaded.init(std.testing.allocator, .{});
}

fn dummySignature() xeddsa.Signature {
    var sig: xeddsa.Signature = undefined;
    for (&sig, 0..) |*b, i| b.* = @intCast(i);
    return sig;
}

