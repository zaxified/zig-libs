//! **More byte-exact goldens captured from the real `nft` binary** (2026-11-07):
//! the expressions, set shapes, table/chain flags, flowtables, destroy/flush/
//! rename/replace commands and stateful objects added when `nftables` moved
//! from `core` to `parity`. Same recipe, same capture host, same rules as
//! `goldens.zig` (see its header): every constant is the complete `sendmsg`
//! payload of one `nft` command run inside `unshare -rn` under
//! `strace -f -e trace=sendmsg -e write=all -xx -s 8192 -e abbrev=none`
//! (nftables v1.1.6, Linux 7.0, x86-64, `nft` seeds its batch at 0).
//! Each constant's comment is the command; where the command needs a table
//! or chain the setup ran before the strace and is not part of the bytes.
//!
//! Where a capture also carries `nft`'s private userdata blob (sets, tables)
//! the blob is handed to the module as opaque bytes, as in `goldens.zig`.

