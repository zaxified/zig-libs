test "kernel dump: 18 rules decode to the typed expressions nft wrote" {
    const bytes = try bytesOf(k_rules);
    defer testing.allocator.free(bytes);
    var it: nl.MessageIterator = .{ .buf = bytes };
    var idx: usize = 0;
    while (try it.next()) |m| : (idx += 1) {
        const rule = try wire.decodeRule(m.payload);
        var buf: [8]expr.Expr = undefined;
        var n: usize = 0;
        var ei = rule.exprIterator();
        while (try ei.next()) |v| : (n += 1) buf[n] = try expr.decodeExpr(v);
        inline for (expected_rules, 0..) |want, i| {
            if (i == idx) try expectTags(buf[0..n], want);
        }
        switch (idx) {
            2 => {
                try testing.expectEqual(expr.HashKind.jenkins, buf[3].hash.kind);
                try testing.expectEqual(@as(u32, 0x1234), buf[3].hash.seed);
                try testing.expectEqual(@as(u32, 2), buf[3].hash.offset);
                try testing.expectEqual(@as(u32, 4), buf[3].hash.modulus);
            },
            3 => {
                try testing.expectEqualSlices(u8, &expr.portBytes(1000), buf[3].range.from);
                try testing.expectEqualSlices(u8, &expr.portBytes(2000), buf[3].range.to);
            },
            4 => {
                try testing.expectEqual(@as(u32, 10), buf[0].connlimit.count);
                try testing.expect(buf[0].connlimit.over);
            },
            6 => {
                try testing.expectEqual(expr.NumgenKind.random, buf[0].numgen.kind);
                try testing.expectEqual(@as(u32, 10), buf[0].numgen.modulus);
                try testing.expectEqual(@as(u32, 5), buf[0].numgen.offset);
            },
            // The 16-bit log group and queue threshold: a real kernel dump.
            7 => {
                try testing.expectEqual(@as(?u32, 5), buf[0].log.group);
                try testing.expectEqual(@as(?u32, 3), buf[0].log.qthreshold);
                try testing.expectEqual(@as(?u32, 64), buf[0].log.snaplen);
            },
            15 => {
                try testing.expectEqual(expr.ShiftDir.left, buf[1].bitshift.dir);
                try testing.expectEqual(@as(u32, 8), buf[1].bitshift.amount);
            },
            17 => {
                try testing.expectEqual(@as(u16, 1460), buf[4].synproxy.mss);
                try testing.expectEqual(@as(u8, 7), buf[4].synproxy.wscale);
            },
            else => {},
        }
    }
    try testing.expectEqual(@as(usize, 18), idx);
}

test "kernel dump: objects, typed state" {
    const bytes = try bytesOf(k_objs);
    defer testing.allocator.free(bytes);
    var it: nl.MessageIterator = .{ .buf = bytes };
    var idx: usize = 0;
    while (try it.next()) |m| : (idx += 1) {
        const o = try wire.decodeObject(m.payload);
        const st = try o.state();
        switch (idx) {
            0 => try testing.expectEqualDeep(wire.ObjectData{ .counter = .{} }, st.?),
            1 => try testing.expectEqualDeep(wire.ObjectData{ .quota = .{ .bytes = 10 * 1024 * 1024, .over = true } }, st.?),
            2 => try testing.expectEqualDeep(wire.ObjectData{ .limit = .{ .rate = 10, .burst = 5 } }, st.?),
            3 => try testing.expectEqualDeep(wire.ObjectData{ .synproxy = .{ .mss = 1460, .wscale = 7, .flags = 3 } }, st.?),
            4 => try testing.expect(st == null), // ct timeout: not typed (needs an allocator)
            5 => try testing.expectEqualDeep(wire.ObjectData{ .ct_expect = .{ .l3proto = 2, .l4proto = 6, .dport = 5000, .timeout_ms = 60000, .size = 12 } }, st.?),
            else => unreachable,
        }
    }
    try testing.expectEqual(@as(usize, 6), idx);
}

test "kernel dump: flowtable, chain, sets and their elements" {
    const ftb = try bytesOf(k_flowtables);
    defer testing.allocator.free(ftb);
    var fit: nl.MessageIterator = .{ .buf = ftb };
    const ft = try wire.decodeFlowtable((try fit.next()).?.payload);
    try testing.expectEqualStrings("ft", ft.name);
    try testing.expectEqual(@as(?u32, 0), ft.hooknum);
    var dev = ft.devices();
    try testing.expectEqualStrings("lo", (try dev.next()).?);
    try testing.expect((try dev.next()) == null);

    const cb = try bytesOf(k_chains);
    defer testing.allocator.free(cb);
    var cit: nl.MessageIterator = .{ .buf = cb };
    const ch = try wire.decodeChain((try cit.next()).?.payload);
    try testing.expectEqualStrings("c", ch.name);

    const sb = try bytesOf(k_sets);
    defer testing.allocator.free(sb);
    var sit: nl.MessageIterator = .{ .buf = sb };
    const s1 = try wire.decodeSet((try sit.next()).?.payload);
    try testing.expectEqualStrings("s", s1.name);
    try testing.expect(s1.flags & wire.NFT_SET_F.TIMEOUT != 0);
    const s2 = try wire.decodeSet((try sit.next()).?.payload);
    try testing.expectEqualStrings("cs", s2.name);
    try testing.expectEqual(@as(u32, wire.NFT_SET_F.INTERVAL | wire.NFT_SET_F.CONCAT), s2.flags);
    try testing.expectEqual(@as(u32, 8), s2.key_len);
    var cf = s2.concatFields();
    try testing.expectEqual(@as(?u32, 4), try cf.next());
    try testing.expectEqual(@as(?u32, 2), try cf.next());
    try testing.expectEqual(@as(?u32, null), try cf.next());
    const s3 = try wire.decodeSet((try sit.next()).?.payload);
    try testing.expect(s3.flags & wire.NFT_SET_MAP != 0);

    // set s: three keys, one with timeout and a running expiration
    const eb = try bytesOf(k_setelems_s);
    defer testing.allocator.free(eb);
    var eit: nl.MessageIterator = .{ .buf = eb };
    var count: usize = 0;
    var timed: usize = 0;
    while (try eit.next()) |m| {
        const reply = try wire.decodeSetElemReply(m.payload);
        var ei = reply.iterator();
        while (try ei.next()) |el| {
            count += 1;
            try testing.expectEqual(@as(usize, 4), el.key.len);
            if (el.timeout_ms) |t| {
                timed += 1;
                try testing.expectEqual(@as(u64, 3600000), t);
                try testing.expect(el.expiration_ms.? <= 3600000);
            }
        }
    }
    try testing.expectEqual(@as(usize, 3), count);
    try testing.expectEqual(@as(usize, 1), timed);

    // set cs: one interval element, key and key_end both 8 bytes
    const cb2 = try bytesOf(k_setelems_cs);
    defer testing.allocator.free(cb2);
    var cit2: nl.MessageIterator = .{ .buf = cb2 };
    var seen_end = false;
    while (try cit2.next()) |m| {
        const reply = try wire.decodeSetElemReply(m.payload);
        var ei = reply.iterator();
        while (try ei.next()) |el| if (el.key_end) |ke| {
            seen_end = true;
            try testing.expectEqual(@as(usize, 8), el.key.len);
            try testing.expectEqual(@as(usize, 8), ke.len);
        };
    }
    try testing.expect(seen_end);

    // map vm: 22 : accept and the keyless catch-all : drop
    const vb = try bytesOf(k_setelems_vm);
    defer testing.allocator.free(vb);
    var vit: nl.MessageIterator = .{ .buf = vb };
    var catchall = false;
    var accept22 = false;
    while (try vit.next()) |m| {
        const reply = try wire.decodeSetElemReply(m.payload);
        var ei = reply.iterator();
        while (try ei.next()) |el| {
            if (el.flags & wire.NFT_SET_ELEM_CATCHALL != 0) {
                catchall = true;
                try testing.expectEqual(@as(usize, 0), el.key.len);
                try testing.expectEqual(@as(i32, 0), el.verdict.?.code); // NF_DROP
            } else {
                accept22 = true;
                try testing.expectEqualSlices(u8, &expr.portBytes(22), el.key);
                try testing.expectEqual(@as(i32, 1), el.verdict.?.code); // NF_ACCEPT
            }
        }
    }
    try testing.expect(catchall and accept22);
}
