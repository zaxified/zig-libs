//! **Decoder goldens from the KERNEL's own replies** (2026-11-07).
//!
//! Every constant is the raw bytes a Linux 7.0 kernel sent back for a dump
//! request, in an unprivileged network namespace (`unshare -rn`) holding the
//! ruleset below, created by `nft -f` (nftables v1.1.6). The requests were
//! sent by a ~40-line Python `AF_NETLINK` script, not by this module, and the
//! replies are stored untouched (all messages of one dump concatenated), so
//! these tests pin the decoders against what a real kernel emits — unlike
//! `expr_decode_test.zig`, whose bytes come from this module's own encoder.
//!
//! ```text
//! add table inet t / add chain inet t c
//! add set inet t s { type ipv4_addr; flags timeout; }
//! add element inet t s { 1.2.3.4 timeout 1h, 5.6.7.8, 9.9.9.9 }
//! add set inet t cs { type ipv4_addr . inet_service; flags interval; }
//! add element inet t cs { 1.2.3.0/24 . 80-90 }
//! add map inet t vm { type inet_service : verdict; }
//! add element inet t vm { 22 : accept, * : drop }
//! add counter cn / quota q { over 10 mbytes } / limit l { rate 10/second burst 5 packets }
//! add synproxy sp { mss 1460; wscale 7; } / ct timeout ctt / ct expectation ce
//! add flowtable ft { hook ingress priority 0; devices = { lo }; }
//! 18 rules in chain c (see `expected_rules`)
//! ```
//!
//! `get2_ack` is the reply to a non-dump `GETSETELEM` of two keys sent with
//! `NLM_F_ACK`: two `NEWSETELEM` messages (one per key) and the ACK.

