fn bytesOf(hex: []const u8) ![]u8 {
    const out = try testing.allocator.alloc(u8, hex.len / 2);
    errdefer testing.allocator.free(out);
    _ = try std.fmt.hexToBytes(out, hex);
    return out;
}

