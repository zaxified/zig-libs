// The W3C Baggage half of the oracle: go.opentelemetry.io/otel/baggage
// (same otel module, Apache-2.0) run as a black box on OUR crafted `baggage`
// header values. Only what baggage.Parse answers (error, members, values,
// properties) and what String() re-serializes is recorded, into
// src/otel_baggage_vectors.zig, replayed by src/otel_baggage_oracle_test.zig.
//
//	cd modules/tracecontext/tools/go_oracle && GOPROXY=off GOSUMDB=off GOFLAGS=-mod=mod go run . -baggage > ../../src/otel_baggage_vectors.zig
//	cd modules/tracecontext/tools/go_oracle && GOPROXY=off GOSUMDB=off GOFLAGS=-mod=mod go run . -baggage -check ../../src/otel_baggage_vectors.zig
package main

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"go.opentelemetry.io/otel/baggage"
)

type bagCase struct{ id, input string }

func bagCases() []bagCase {
	var cs []bagCase
	add := func(id, in string) { cs = append(cs, bagCase{id, in}) }

	spec := "key1=value1;property1;property2, key2 = value2, key3=value3; propertyKey=propertyValue"
	shapes := []string{
		// W3C §3.3.3 and §3.4 examples
		spec,
		"userId=alice,serverNode=DF%2028,isProduction=false",
		"userId=Am%C3%A9lie,serverNode=DF%2028,isProduction=false",
		"userId =   alice, serverNode = DF%2028, isProduction = false",
		// OWS variants
		"", " ", "\t", " \t ", " a=1", "a=1 ", " a=1 ", "a =1", "a= 1", "a = 1", "a\t=\t1", "a=1 ,b=2", "a=1, b=2", "a=1 , b=2",
		"a=1 ; p", "a=1; p", "a=1 ;p", "a=1;p ", "a=1 ; p = q", "a=1;p=q ;r", "a=1\t;\tp\t=\tq", "a b=1", "a=1 2", "a=1;p q", "a=1;p=q r",
		// properties
		"a=1;p", "a=1;p=q", "a=1;p;q", "a=1;p=q;r=s", "a=1;p=", "a=1;=q", "a=1;", "a=1;;p", "a=1;p;", "a=1;p=q=r", "a=1;p=%41", "a=1;p=%zz", "a=1;p=%",
		"a=1;p=\"x\"", "a=1;p=x,b=2", "a=1;p,b=2;q", "a=1;p=a%20b", "a=1;p(=1", "a=1;p=a\\b", "a=1;P=Q", "a=1;;", ";p", "a;p", "a=;p", "a=;p=q",
		// values and keys
		"a=", "a=,b=", "=1", "=", "a", "a,b", "a=b=c", "a==", "a=1=2=3", "A=1", "a1_-.=1", "Tok!#$&'*+-.^_`|~9=1", "k(=v", "k[=v", "k\"=v", "k/=v", "é=1",
		"a=\"v\"", "a=\"", "a=a\\b", "a=a\"b", "a=a;b", "a=é", "a=\xc3\xa9", "a=\x7f", "a=\x01", "a=\x00", "a=\r\n", "a=1\x0b", "a=1\x0c",
		// percent-encoding: valid, case, invalid, non-UTF-8
		"a=%41%62", "a=%2f%2F", "a=%25", "a=%3b%2C%22%5C", "a=100%25", "a=%", "a=%4", "a=%zz", "a=%4g", "a=%g4", "a=a%", "a=a%4", "a=%%41", "a=%25zz",
		"a=%80", "a=%E2%82", "a=%E2%82%AC", "a=ok%E2%82%AC", "a=%C0%AF", "a=%ED%A0%80", "a=%FF", "a=%FE%FF", "a=%F0%9F%98%80", "a=%F0%9F%98", "a=%F0%9F%98%80%80",
		"a=%C3%A9", "a=%c3%a9", "a=%C3", "a=%C3%28", "a=%E2%28%A1", "a=%F4%90%80%80", "a=%00", "a=%0A", "a=%20", "a=%7F", "a=%80%80", "a=x%80y",
		"a=%41,b=%zz", "%41=1", "a%41=1",
		// empty members
		",", ",,", "a=1,", ",a=1", "a=1,,b=2", "a=1, ,b=2", "a=1,\t,b=2", " , ", "a=1,b=2,", "a=1,b=2, ",
		// duplicate keys
		"a=1,a=2", "a=1,b=2,a=3", "a=1;p,a=2;q", "a=1,A=2",
	}
	for i, s := range shapes {
		add(fmt.Sprintf("shape%03d", i), s)
	}

	// limits: members and bytes
	add("members64", bagMembers(64))
	add("members65", bagMembers(65))
	add("members63", bagMembers(63))
	add("members100", bagMembers(100))
	add("members65_trail", bagMembers(65)+",")
	add("members64_trail", bagMembers(64)+",")
	for _, n := range []int{8191, 8192, 8193, 8200} {
		add(fmt.Sprintf("bytes%d", n), "k="+strings.Repeat("x", n-2))
	}
	// 8192 bytes as several members; a member ending exactly at / past the cap
	for _, n := range []int{8192, 8193} {
		add(fmt.Sprintf("bytes%d_multi", n), "a="+strings.Repeat("x", 8000)+",b="+strings.Repeat("y", n-8000-5))
	}
	add("bytes8192_padded", " "+"k="+strings.Repeat("x", 8190)+"\t")
	add("bytes8193_padded", " "+"k="+strings.Repeat("x", 8191)+"\t")
	add("bytes8192_props", "k=v;"+strings.Repeat("p;", 4093)+"q")
	add("bytes8193_props", "k=v;"+strings.Repeat("p;", 4093)+"qq")
	add("key_long", strings.Repeat("k", 4000)+"=1")
	add("value_encoded8192", "k="+strings.Repeat("%41", 2730)+"AA")
	add("value_encoded8193", "k="+strings.Repeat("%41", 2730)+"AAA")

	// every single-character substitution of one valid header
	valid := "k1=v1;p1;p2=v2,k2=Am%C3%A9lie, k3 = a%20b;p3 = q"
	subs := []byte{'=', ';', ',', ' ', '\t', '%', '"', '\\', 'a', '0', 'F', 'g', '(', '\x7f', '\xc3', '\x00'}
	for pos := 0; pos < len(valid); pos++ {
		for _, c := range subs {
			if valid[pos] == c {
				continue
			}
			b := []byte(valid)
			b[pos] = c
			add(fmt.Sprintf("sub%02d_%02x", pos, c), string(b))
		}
		// and deletion of one character
		add(fmt.Sprintf("del%02d", pos), valid[:pos]+valid[pos+1:])
	}
	add("sub_valid", valid)
	return cs
}

func bagMembers(n int) string {
	ms := make([]string, n)
	for i := range ms {
		ms[i] = fmt.Sprintf("k%d=v%d", i, i)
	}
	return strings.Join(ms, ",")
}

func bagVectors(b *bytes.Buffer) {
	fmt.Fprintf(b, "// SPDX-License-Identifier: MIT\n")
	fmt.Fprintf(b, "// GENERATED by modules/tracecontext/tools/go_oracle -baggage (otel v1.46.0) -- do not hand-edit.\n")
	fmt.Fprintf(b, "//! OpenTelemetry Go's `baggage.Parse` on this module's own `baggage` header values,\n")
	fmt.Fprintf(b, "//! replayed by `otel_baggage_oracle_test.zig`. Regenerate with the command in tools/go_oracle/baggage.go.\n\n")
	b.WriteString(`pub const Prop = struct { key: []const u8, value: ?[]const u8 };
pub const Member = struct { key: []const u8, value: []const u8, props: []const Prop };
/// What otel answered for ` + "`input`" + `: ` + "`ok`" + ` = Parse returned no error; the members it
/// returned (also alongside an error), sorted by key (otel keeps a map: its order is
/// not an answer); ` + "`string`" + ` = its re-serialization, comma pieces sorted.
pub const Case = struct {
    id: []const u8,
    input: []const u8,
    /// False when the value holds a control character other than HTAB: an HTTP
    /// server refuses the request (400) and no propagator ever sees it.
    wire_ok: bool,
    ok: bool,
    members: []const Member,
    string: []const u8,
};

pub const cases = [_]Case{
`)
	for _, c := range bagCases() {
		wireOK := true
		for i := 0; i < len(c.input); i++ {
			if x := c.input[i]; (x < 0x20 && x != '\t') || x == 0x7f {
				wireOK = false
			}
		}
		// What an HTTP server hands the propagator: OWS around the field value trimmed.
		bg, err := baggage.Parse(strings.Trim(c.input, " \t"))
		// otel keeps members in a map: their order (also in String()) differs from
		// run to run and is not an answer. Both are recorded sorted by key.
		members := bg.Members()
		sort.SliceStable(members, func(i, j int) bool { return members[i].Key() < members[j].Key() })
		str := strings.Split(bg.String(), ",")
		sort.Strings(str)
		ms := []string{}
		for _, m := range members {
			ps := []string{}
			for _, p := range m.Properties() {
				v, has := p.Value()
				if has {
					ps = append(ps, fmt.Sprintf(".{ .key = %s, .value = %s }", zigStr(p.Key()), zigStr(v)))
				} else {
					ps = append(ps, fmt.Sprintf(".{ .key = %s, .value = null }", zigStr(p.Key())))
				}
			}
			ms = append(ms, fmt.Sprintf(".{ .key = %s, .value = %s, .props = %s }", zigStr(m.Key()), zigStr(m.Value()), zlist(ps)))
		}
		fmt.Fprintf(b, "    .{ .id = %s, .input = %s, .wire_ok = %v, .ok = %v, .members = %s, .string = %s },\n",
			zigStr(c.id), zigStr(c.input), wireOK, err == nil, zlist(ms), zigStr(strings.Join(str, ",")))
	}
	b.WriteString("};\n")
}
