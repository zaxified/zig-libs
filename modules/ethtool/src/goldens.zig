test "golden reply: FEATURES in the VERBOSE encoding — NOMASK changes the rules" {
    // The trap this golden exists for: `hw` is a *masked* verbose bitset and
    // lists all 64 bits with an `ETHTOOL_A_BITSET_BIT_VALUE` flag on the ones
    // that are set, while `active`/`wanted`/`nochange` are **NOMASK** and list
    // *only* the set bits — with no `VALUE` flag at all. A decoder that reads
    // `Bit.value` there sees every feature as off.
    try skipUnlessLittleEndian();
    const gpa = testing.allocator;
    const r = try replyAttrs(&reply_features_verbose);
    try testing.expectEqual(uapi.REPLY.FEATURES_GET, r.cmd);

    var f = try features.parse(gpa, r.attrs);
    defer f.deinit(gpa);
    const hw = f.hw.?;
    const active = f.active.?;
    try testing.expectEqual(bitset.Bitset.Encoding.verbose, hw.encoding());
    try testing.expect(!hw.nomask);
    try testing.expect(active.nomask);
    // Masked: every bit of the 64 is mentioned.
    try testing.expectEqual(@as(usize, 64), hw.bits.?.len);
    // NOMASK: only the nine that are on.
    try testing.expectEqual(@as(usize, 9), active.bits.?.len);
    for (active.bits.?) |b| try testing.expect(!b.value); // no VALUE flags at all
    try testing.expectEqual(@as(u32, 9), active.count());

    // The rule applied: presence is the value in a NOMASK list.
    try testing.expectEqual(@as(?bool, true), f.isActive("highdma"));
    try testing.expectEqual(@as(?bool, true), f.isActive("rx-gro"));
    // …and a NOMASK list knows its own universe, so an absent name is a
    // definite "off" rather than "unknown".
    try testing.expectEqual(@as(?bool, false), f.isActive("tx-tcp-segmentation"));
    // The masked `hw` set answers "unknown" for a bit it never mentioned, and
    // "off" for one it mentioned without a VALUE flag.
    try testing.expectEqual(@as(?bool, false), hw.isSetByName("tx-tcp-segmentation"));
    try testing.expectEqual(@as(?bool, null), hw.isSetByName("no-such-feature"));

    // Cross-check against the compact reply for the same device: every one of
    // the 64 bits must agree, in both directions.
    var compact = try features.parse(gpa, (try replyAttrs(&reply_features_compact)).attrs);
    defer compact.deinit(gpa);
    var i: u32 = 0;
    while (i < 64) : (i += 1) {
        try testing.expectEqual(compact.isActiveAt(i), f.isActiveAt(i));
        try testing.expectEqual(compact.isSupportedAt(i), f.isSupportedAt(i));
        try testing.expectEqual(compact.isFixedAt(i), f.isFixedAt(i));
    }
    try testing.expectEqual(compact.active.?.count(), active.count());
}

