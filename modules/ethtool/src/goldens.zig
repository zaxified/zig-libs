//! Byte-exact goldens captured from a real `ethtool` (v6.19) on Linux 7.0,
//! plus the kernel replies it received, decoded back through this module.
//!
//! ## How the request goldens were captured
//!
//! ```sh
//! strace -f -e trace=%network -e write=all -e read=all -xx -s 16384 \
//!     -e abbrev=none ethtool <args>
//! ```
//!
//! Note `-e trace=%network` rather than the `sendmsg` the sibling `nl80211`
//! goldens use: **`ethtool` sends with `sendto`, not `sendmsg`**, so tracing
//! `sendmsg` alone captures the kernel's replies and none of the requests. The
//! exact command line sits next to every golden below.
//!
//! `-e write=all` dumps the payload with no re-encoding step in between, so
//! what is asserted here is literally the bytes `ethtool` handed the kernel.
//!
//! One field of a captured request is a runtime value rather than encoding:
//! **`nlmsg_seq`**, which is per-socket. Each test simply builds with the
//! sequence number the capture happened to use. `nlmsg_pid` needs no special
//! handling here — `ethtool`, like this module, writes 0 and lets the kernel
//! fill it in. Everything else — length, message type, flags, the
//! `genlmsghdr`, and every attribute with its exact type, length, order and
//! padding — is compared byte for byte.
//!
//! The ethtool family id in every capture is **23 (0x17)**. That is *not* a
//! constant: it is whatever nlctrl assigned on that boot, which is exactly why
//! `client.zig` resolves it at runtime. The goldens simply pass 23 in.
//!
//! ## What could not be captured from `ethtool`
//!
//! * **Compact bitsets in a *request*.** `ethtool` always keys the bitsets it
//!   *sends* by name (`--groups eth-mac`, `-K dev tso off`), because userspace
//!   does not want to hardcode kernel bit numbers. So `bitset.appendCompact`
//!   and `bitset.appendIndexedValues` have no `ethtool` golden; they are
//!   derived from `linux/ethtool_netlink.h` and covered by the round-trip and
//!   hostile-input tests in `bitset.zig`.
//! ## Two capture environments
//!
//! Most goldens below came from an ordinary unprivileged user against the
//! machine's real NICs (`enp0s31f6`, an Intel e1000e, and `wlp2s0`). SET
//! *requests* are real even there: the kernel refuses them **after** `ethtool`
//! has already put the bytes on the wire.
//!
//! SET *replies* and the notification needed CAP_NET_ADMIN, so those four
//! goldens were captured inside an unprivileged user+network namespace
//! (`unshare -rn`) against a `veth` pair — the harness `CONVENTIONS.md` §7
//! prescribes for netlink modules:
//!
//! ```sh
//! unshare -rn
//! ip link add veth0 type veth peer name veth1
//! ethtool -K veth0 tso off        # → reply_features_set_honoured
//! ethtool -K veth0 tx off
//! ethtool -K veth0 tso on         # → reply_features_set_partial (4 of 5 refused)
//! ```
//!
//! The notification golden could not come from `ethtool --monitor` (it only
//! prints, and prints nothing this test could assert on), so the `monitor`
//! group was joined by a 20-line raw AF_NETLINK reader in the same namespace
//! while `ethtool -K` ran. The message is the kernel's, byte for byte.
//! * **Non-empty statistics groups.** No NIC on the capture machine implements
//!   the standardised `eth-mac`/`eth-ctrl`/`rmon` counters, so the real
//!   `STATS_GET` reply below has three groups and no counters in them — which
//!   is itself the case worth pinning. Counter and histogram decoding is
//!   covered by constructed replies in `stats.zig`.
//! * **Module EEPROM data.** The capture machine has no pluggable transceiver,
//!   so `MODULE_EEPROM_GET` was refused; only its request is pinned.
//!
//! ## Anonymisation
//!
//! The reply captures had one **length-preserving** substitution applied
//! before being committed: **`nlmsg_pid` was zeroed** in every reply message.
//! That field is the capturing process's netlink port id, which the kernel
//! derives from its pid; it identifies the machine's session and nothing about
//! the protocol. Netlink message parsing never looks at it here (these goldens
//! are decoded, not matched against a socket), so zeroing it changes no
//! assertion.
//!
//! Nothing else was touched: lengths, offsets, padding, every attribute and
//! every counter are exactly as the kernel sent them. There are no MAC
//! addresses, serial numbers or bus IDs anywhere in these payloads — the
//! ethtool netlink family carries none, and the one command that would
//! (`ethtool -i`, driver/firmware/bus info) has **no netlink message at all**
//! and never left the ioctl path. The interface names `enp0s31f6` and `wlp2s0`
//! were deliberately kept: they are udev bus-path names, carry no identity,
//! and keeping them makes the capture commands in the comments reproducible.

