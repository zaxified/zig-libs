test "golden reply: an EOPNOTSUPP carrying the kernel's own explanation" {
    // `ethtool wlp2s0` — a Wi-Fi interface has no ethtool link settings, and
    // with NETLINK_EXT_ACK enabled the refusal says so in words. This is the
    // reason `client.zig` sets that sockopt unconditionally.
    try skipUnlessLittleEndian();
    var it: codec.MessageIterator = .{ .buf = &reply_err_extack_linkmodes };
    const m = (try it.next()).?;
    try testing.expectEqual(codec.NLMSG_ERROR, m.type);
    try testing.expect(m.flags & codec.NLM_F_ACK_TLVS != 0);
    // The kernel echoes the whole request (not capped) when it attaches a
    // message, so the ext-ACK walk has to skip nlmsg_len bytes, not 16.
    try testing.expect(m.flags & codec.NLM_F_CAPPED == 0);

    try testing.expectEqual(@as(i32, -95), try m.errorCode()); // EOPNOTSUPP
    try testing.expectEqualStrings("failed to retrieve link settings", (try m.errorMessage()).?);
    try testing.expectEqual(error.NotSupported, client.errnoToError(try m.errorCode()));
}

