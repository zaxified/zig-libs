test "golden reply: a FEATURES_SET that was fully honoured" {
    // `ethtool -K veth0 tso off` on a fresh veth: all five TSO bits went off,
    // and `ethtool` printed nothing under "Actual changes".
    try skipUnlessLittleEndian();
    const gpa = testing.allocator;
    const r = try replyAttrs(&reply_features_set_honoured);
    try testing.expectEqual(uapi.REPLY.FEATURES_SET, r.cmd);

    var res = try features.parseSetResult(gpa, r.attrs);
    defer res.deinit(gpa);
    try testing.expectEqualStrings("veth0", res.device.name());
    try testing.expect(res.fullyHonoured());
    try testing.expectEqual(@as(u32, 0), res.unhonouredCount());
    // Five features really did change state — all of them to off.
    try testing.expectEqual(@as(u32, 5), res.changedCount());
    for ([_]u32{ 16, 18, 19, 20, 35 }) |bit| {
        try testing.expect(res.honouredAt(bit));
        try testing.expectEqual(@as(?bool, false), res.newStateAt(bit));
    }
    // A bit nobody touched has no new state at all.
    try testing.expect(res.newStateAt(0) == null);
    try testing.expect(res.honouredAt(0));
}

test "golden reply: a FEATURES_SET the kernel refused four fifths of" {
    // Same veth with tx-checksum turned off first, then `ethtool -K veth0 tso
    // on`. `ethtool` printed:
    //
    //     Actual changes:
    //     tx-tcp-segmentation: off [requested on]
    //     tx-tcp-ecn-segmentation: off [requested on]
    //     tx-tcp-mangleid-segmentation: off [requested on]
    //     tx-tcp6-segmentation: off [requested on]
    //     tx-tcp-accecn-segmentation: on
    //
    // …and the request was still ACKed. This is the whole reason
    // `setFeaturesByName` hands the reply back instead of returning void.
    try skipUnlessLittleEndian();
    const gpa = testing.allocator;
    const r = try replyAttrs(&reply_features_set_partial);
    try testing.expectEqual(uapi.REPLY.FEATURES_SET, r.cmd);

    var res = try features.parseSetResult(gpa, r.attrs);
    defer res.deinit(gpa);
    try testing.expect(!res.fullyHonoured());
    try testing.expectEqual(@as(u32, 4), res.unhonouredCount());
    try testing.expectEqual(@as(u32, 1), res.changedCount());

    // The four the kernel would not do — note their *requested* value is
    // "on", which is exactly what the value half carries.
    for ([_]u32{ 16, 18, 19, 20 }) |bit| {
        try testing.expect(!res.honouredAt(bit));
        try testing.expect(res.unhonoured.?.isSet(bit));
        try testing.expect(res.newStateAt(bit) == null); // never moved
    }
    // …and the one that did move, to on.
    try testing.expect(res.honouredAt(35));
    try testing.expectEqual(@as(?bool, true), res.newStateAt(35));
}

test "golden notification: a real FEATURES_NTF off the monitor group" {
    try skipUnlessLittleEndian();
    const gpa = testing.allocator;
    var it: codec.MessageIterator = .{ .buf = &notification_features_ntf };
    const m = (try it.next()).?;
    try testing.expectEqual(fam, m.type);
    const p = try genl.splitPayload(m.payload);
    try testing.expectEqual(uapi.REPLY.FEATURES_NTF, p.cmd);
    try testing.expect(uapi.isNotification(p.cmd));

    var n = try client.parseNotification(gpa, p.cmd, p.attrs);
    defer n.deinit(gpa);
    try testing.expect(n.isNotification());
    try testing.expectEqualStrings("veth0", n.device.?.name());
    try testing.expectEqual(@as(?u32, 3), n.device.?.index);

    // A notification carries the same payload a FEATURES_GET reply would, so
    // the ordinary typed parser reads it — that is the whole design of the
    // `*_NTF` messages, and why `Notification` hands the attributes back
    // rather than pre-decoding them into a union of every command's shape.
    var f = try features.parse(gpa, n.attrs);
    defer f.deinit(gpa);
    try testing.expectEqual(@as(?u32, 64), f.hw.?.size);
    try testing.expect(f.active != null);
    try testing.expect(f.nochange.?.isSet(10)); // vlan-challenged, as on the NIC
    // Emitted by the kernel with sequence 0 semantics for the *receiver*: it
    // is unsolicited, so nothing here may be matched against a request seq.
    try testing.expectEqual(@as(u32, 0), m.pid);
}
