/// The family id nlctrl handed out on the machine the captures came from.
/// Dynamic in reality — see the file header.
const fam: u16 = 23;

fn hex(comptime s: []const u8) [s.len / 2]u8 {
    @setEvalBranchQuota(40 * s.len + 1000);
    var out: [s.len / 2]u8 = undefined;
    _ = std.fmt.hexToBytes(&out, s) catch unreachable;
    return out;
}

/// Netlink is host-endian, so these little-endian goldens only mean anything
/// on a little-endian host.
fn skipUnlessLittleEndian() !void {
    if (native_endian != .little) return error.SkipZigTest;
}

/// Start a request message exactly the way `client.zig` does: nlmsghdr with
/// REQUEST|ACK, then the genlmsghdr. Returns the header offset for
/// `codec.finishHeader`.
fn beginRequest(
    gpa: std.mem.Allocator,
    msg: *std.ArrayList(u8),
    cmd: u8,
    seq: u32,
) !usize {
    const h = try codec.appendHeader(
        gpa,
        msg,
        fam,
        codec.NLM_F_REQUEST | codec.NLM_F_ACK,
        seq,
        0,
    );
    try genl.appendHeader(gpa, msg, cmd, uapi.family_version);
    return h;
}

/// Split a captured reply into its genlmsghdr command byte and attribute
/// bytes, asserting the message type is the ethtool family.
fn replyAttrs(captured: []const u8) !struct { cmd: u8, attrs: []const u8 } {
    var it: codec.MessageIterator = .{ .buf = captured };
    const m = (try it.next()).?;
    try testing.expectEqual(fam, m.type);
    const p = try genl.splitPayload(m.payload);
    return .{ .cmd = p.cmd, .attrs = p.attrs };
}

