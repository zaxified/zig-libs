#!/usr/bin/env bash
# Regenerate modules/zstd/src/testdata/room_sweep_goldens.zig: libzstd v1.5.7
# through tools/zroom.c at every destination capacity 0..maxcap, one row per
# run, the SHA-256 of its lines (src/room_sweep_test.zig writes the same
# lines and compares).
#
# Needs: git, make, a C compiler, sha256sum. The libzstd checkout goes to a
# disposable directory ($ZSTD_REF, default .zig-cache/zstd-ref under the
# repository root), shared with gen-goldens.sh.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
mod=$(dirname "$here")
root=$(cd "$mod/../.." && pwd)
R=${ZSTD_REF:-$root/.zig-cache/zstd-ref}
pin=f8745da6ff1ad1e7bab384bd1f9d742439278e99 # tag v1.5.7

if [ ! -d "$R/lib" ]; then
    git clone --quiet --depth 1 --branch v1.5.7 https://github.com/facebook/zstd.git "$R"
fi
got=$(git -C "$R" rev-parse HEAD)
if [ "$got" != "$pin" ]; then
    echo "libzstd checkout at $got, expected v1.5.7 ($pin)" >&2
    exit 1
fi
cc -O2 -DZSTD_DISABLE_ASM -I "$R/lib" -I "$R/lib/common" -o "$R/zroom" "$here/zroom.c" \
    "$R"/lib/common/*.c "$R"/lib/compress/*.c "$R"/lib/decompress/*.c

out="$mod/src/testdata/room_sweep_goldens.zig"
# row <mode> <zroom args...>: the Zig fields come from the same arguments
row() {
    local mode=$1 level=$2 kind=z len=0 split=false ck=false shape=l k=0 maxcap sum
    case $mode in
        block) kind=$3 len=$4 maxcap=$5 ;;
        bufferless) kind=$3 len=$4 maxcap=$6; [ "$5" = 1 ] && split=true ;;
        seq) shape=$4 k=$5 maxcap=$6; [ "$3" = 1 ] && ck=true ;;
    esac
    sum=$("$R/zroom" "$@" | sha256sum | cut -d' ' -f1)
    if "$R/zroom" "$@" | grep -q ' err code '; then
        echo "zroom $*: an error other than dstSize_tooSmall" >&2
        exit 1
    fi
    echo "    .{ .args = \"$*\", .mode = .$mode, .level = $level, .kind = '$kind', .len = $len, .split = $split, .checksum = $ck, .shape = '$shape', .k = $k, .maxcap = $maxcap, .sha256 = \"$sum\" },"
}
{
    echo "// SPDX-License-Identifier: MIT"
    echo "//! GENERATED by modules/zstd/tools/gen-room-sweep-goldens.sh -- do not edit."
    echo "//! libzstd v1.5.7 ($pin) through tools/zroom.c at every capacity"
    echo "//! 0..maxcap; \`args\` is zroom's command line, \`sha256\` that of its output."
    echo ""
    echo "pub const Mode = enum { block, bufferless, seq };"
    echo "pub const Golden = struct { args: []const u8, mode: Mode, level: i32, kind: u8, len: usize, split: bool, checksum: bool, shape: u8, k: usize, maxcap: usize, sha256: *const [64]u8 };"
    echo ""
    echo "pub const rows = [_]Golden{"
    # the block API: the minimum block size, the sequences header, RLE
    for level in 1 3 19; do
        for kind in z t r; do
            for len in 1 2 3 5 6 7 8 9 12 16 40 100; do
                row block "$level" "$kind" "$len" $((len + 24))
            done
        done
    done
    # buffer-less: the last empty block, a block start short of a header
    for level in 1 3; do
        for kind in z t r; do
            for len in 0 1 2 5 10 40 300; do
                for split in 0 1; do
                    row bufferless "$level" "$kind" "$len" "$split" $((len + 48))
                done
            done
        done
    done
    # the sequence API: the frame header, the empty frame, raw and RLE blocks
    for level in 1 3; do
        for ck in 0 1; do
            for k in 0 1 2 5 17 60; do
                row seq "$level" "$ck" l "$k" $((k + 48))
            done
            for k in 0 1 2 9 40; do
                row seq "$level" "$ck" a "$k" $((4 * k + 64))
            done
        done
    done
    echo "};"
} >"$out"
echo "wrote $out ($(grep -c '\.args' "$out") rows)"
