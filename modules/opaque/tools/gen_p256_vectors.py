"""Regenerate src/kat_vectors_p256.zig from the RFC 9807 text.

Usage: python3 -I tools/gen_p256_vectors.py <rfc9807.txt> <out.zig> && zig fmt <out.zig>

The text is https://www.rfc-editor.org/rfc/rfc9807.txt. The script only
re-flows the wrapped hex of Appendix C.1.5, C.1.6 (P256-SHA256 real
vectors) and C.2.3 (P256-SHA256 fake vector) into Zig string literals.
"""
import re
import sys

PAGE_RE = re.compile(r'^(RFC 9807 .*\d{4}|.*\[Page \d+\])$')


def lines(path):
    out = []
    for ln in open(path, encoding='utf-8').read().split('\n'):
        ln = ln.replace('\f', '').rstrip()
        if PAGE_RE.match(ln.strip()):
            continue
        out.append(ln)
    return out


KV = re.compile(r'^   ([A-Za-z0-9_]+): (.*)$')
CONT = re.compile(r'^   [0-9a-f]+$')


def section(ls, head, stop):
    i = next(k for k, l in enumerate(ls) if l == head)
    j = next(k for k in range(i + 1, len(ls)) if ls[k].startswith(stop))
    rec = {}
    key = None
    for l in ls[i:j]:
        m = KV.match(l)
        if m:
            key = m.group(1)
            rec[key] = m.group(2).strip()
            continue
        if key and CONT.match(l):
            rec[key] += l.strip()
        elif l.strip() == '':
            continue
        else:
            key = None
    return rec


def main():
    ls = lines(sys.argv[1])
    out = ['// SPDX-License-Identifier: MIT',
           '//! RFC 9807 Appendix C P256-SHA256 test vectors (C.1.5, C.1.6 real; C.2.3',
           '//! fake), GENERATED by `tools/gen_p256_vectors.py` from the RFC text (do',
           '//! not edit by hand). Lower-case hex; decode in the test.',
           '',
           'pub const Vector = struct { name: []const u8, fields: []const [2][]const u8 };',
           '']
    for ident, head, stop in [('real_5', 'C.1.5.  OPAQUE-3DH Real Test Vector 5', 'C.1.6.  '),
                              ('real_6', 'C.1.6.  OPAQUE-3DH Real Test Vector 6', 'C.2.  '),
                              ('fake_3', 'C.2.3.  OPAQUE-3DH Fake Test Vector 3', 'Acknowledgments')]:
        rec = section(ls, head, stop)
        skip = {'OPRF', 'Hash', 'KSF', 'KDF', 'MAC', 'Group', 'Nh', 'Npk', 'Nsk', 'Nm', 'Nx', 'Nok'}
        out.append(f'pub const {ident} = Vector{{ .name = "{head.split()[0].rstrip(".")}", .fields = &.{{')
        for k, v in rec.items():
            if k in skip:
                continue
            assert re.fullmatch(r'[0-9a-f]*', v), (k, v)
            out.append(f'    .{{ "{k}", "{v}" }},')
        out.append('} };')
        out.append('')
    open(sys.argv[2], 'w').write('\n'.join(out))


main()
