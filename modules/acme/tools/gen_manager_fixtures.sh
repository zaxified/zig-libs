# Regenerates src/testdata/manager_fixtures.zig: a test CA and leaf
# certificates with fixed validity windows for the Manager tests (renewal
# timing, coverage and key checks). The keys are throwaway test keys.
#
#   modules/acme/tools/gen_manager_fixtures.sh
#
# Needs openssl >= 3.4 (-not_before / -not_after on `x509 -req`).
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
out="$here/../src/testdata/manager_fixtures.zig"
work=$(mktemp -d)
trap 'rm -f "$work"/*; rmdir "$work"' EXIT
cd "$work"

key() { openssl ecparam -name prime256v1 -genkey -noout -out "$1.key"; }

key ca
openssl req -new -x509 -key ca.key -subj "/CN=acme manager test CA" \
  -not_before 20200101000000Z -not_after 20400101000000Z \
  -addext "basicConstraints=critical,CA:TRUE" \
  -addext "keyUsage=critical,keyCertSign,cRLSign" \
  -addext "subjectKeyIdentifier=hash" -out ca.crt

# leaf NAME SANS NOT_BEFORE NOT_AFTER SERIAL
leaf() {
  key "$1"
  openssl req -new -key "$1.key" -subj "/CN=${2%%,*}" -out "$1.csr"
  {
    echo "basicConstraints=critical,CA:FALSE"
    echo "keyUsage=critical,digitalSignature"
    echo "extendedKeyUsage=serverAuth"
    echo "authorityKeyIdentifier=keyid"
    echo "subjectAltName=$(echo "$2" | sed 's/\([^,]*\)/DNS:\1/g')"
  } > "$1.ext"
  openssl x509 -req -in "$1.csr" -CA ca.crt -CAkey ca.key -set_serial "$5" \
    -not_before "$3" -not_after "$4" -extfile "$1.ext" -out "$1.crt" 2>/dev/null
}

leaf a1 "a.example,www.a.example" 20260101000000Z 20260401000000Z 4097   # 90 days
leaf a2 "a.example,www.a.example" 20260301000000Z 20260530000000Z 4098   # the renewal
leaf short "s.example" 20260101000000Z 20260107000000Z 4099              # 6 days
leaf wild "*.w.example,w.example" 20260101000000Z 20260401000000Z 4100
leaf od1 "od.example" 20260101000000Z 20260401000000Z 4101
leaf od2 "od2.example" 20260101000000Z 20260401000000Z 4102
leaf b1 "b.example" 20260101000000Z 20260401000000Z 4103

emit() { # zig-name file
  printf 'pub const %s =\n' "$1"
  sed 's/^/    \\\\/' "$2"
  printf ';\n'
}

{
  echo "// SPDX-License-Identifier: MIT"
  echo "// GENERATED by tools/gen_manager_fixtures.sh — do not edit. Throwaway test keys."
  echo
  emit ca_pem ca.crt
  for n in a1 a2 short wild od1 od2 b1; do
    emit "${n}_crt" "$n.crt"
    emit "${n}_key" "$n.key"
  done
} > "$out"
echo "wrote $out"
