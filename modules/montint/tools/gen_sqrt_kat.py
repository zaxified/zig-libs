"""Recipe for src/sqrt_vectors.zig (DynModint.sqrt known-answer vectors).

Independent oracle: plain-Python Tonelli-Shanks and Euler's criterion on
CPython integers; no code is shared with montint. Run from modules/montint:

    python3 tools/gen_sqrt_kat.py > src/sqrt_vectors.zig && zig fmt src/sqrt_vectors.zig

Seed 20261014. Per prime: a = 0, 1, p-1, and random residues / non-residues;
`root` is the smaller of the two roots (the Zig test accepts r or p-r).
"""
import random

PRIMES = [
    ("3 mod 4", 3), ("5 mod 8", 5), ("3 mod 4", 7), ("5 mod 8", 13),
    ("1 mod 8, s=4", 17), ("1 mod 8, s=3", 41), ("1 mod 8, s=5", 97),
    ("1 mod 8, s=8", 257), ("1 mod 8, s=16", 65537),
    ("2^61-1", (1 << 61) - 1), ("2^127-1", (1 << 127) - 1),
    ("2^255-19, 5 mod 8", (1 << 255) - 19),
    ("P-224, s=96", (1 << 224) - (1 << 96) + 1),
    ("secp256k1 p, 3 mod 4", (1 << 256) - (1 << 32) - 977),
    ("Goldilocks, s=32", (1 << 64) - (1 << 32) + 1),
    ("BLS12-381 r, s=32", 0x73eda753299d7d483339d80809a1d80553bda402fffe5bfeffffffff00000001),
    ("2^521-1", (1 << 521) - 1),
]


def is_qr(a, p):
    return a == 0 or pow(a, (p - 1) // 2, p) == 1


def tonelli(a, p):
    if a == 0:
        return 0
    assert is_qr(a, p)
    q, s = p - 1, 0
    while q % 2 == 0:
        q //= 2
        s += 1
    z = 2
    while pow(z, (p - 1) // 2, p) != p - 1:
        z += 1
    m, c, t, r = s, pow(z, q, p), pow(a, q, p), pow(a, (q + 1) // 2, p)
    while t != 1:
        i, tt = 0, t
        while tt != 1:
            tt = tt * tt % p
            i += 1
        b = pow(c, 1 << (m - i - 1), p)
        m, c, t, r = i, b * b % p, t * b * b % p, r * b % p
    assert r * r % p == a
    return min(r, p - r)


def limbs(x):
    n = max(1, (x.bit_length() + 63) // 64)
    return "&.{" + ", ".join("0x%016x" % ((x >> (64 * i)) & (2**64 - 1)) for i in range(n)) + "}"


rnd = random.Random(20261014)
print("// SPDX-License-Identifier: MIT")
print("//! Generated by tools/gen_sqrt_kat.py (CPython Tonelli-Shanks); do not edit.")
print("pub const Case = struct { note: []const u8, p: []const u64, a: []const u64, root: []const u64, qr: bool };")
print("pub const cases = [_]Case{")
for note, p in PRIMES:
    inputs = [0, 1, p - 1]
    nqr = nnr = 0
    for _ in range(400):
        if nqr >= 3 and nnr >= 3:
            break
        a = rnd.randrange(2, p) if p > 3 else 2
        if is_qr(a, p) and nqr < 3:
            nqr += 1
            inputs.append(a)
        elif not is_qr(a, p) and nnr < 3:
            nnr += 1
            inputs.append(a)
    seen = set()
    for a in inputs:
        if a in seen or a >= p:
            continue
        seen.add(a)
        qr = is_qr(a, p)
        root = tonelli(a, p) if qr else 0
        print('.{ .note = "%s", .p = %s, .a = %s, .root = %s, .qr = %s },' % (note, limbs(p), limbs(a), limbs(root), "true" if qr else "false"))
print("};")
