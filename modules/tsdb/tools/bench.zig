//! Comparative benchmark: `tsdb` against tsink 0.10.2 (h2337/tsink, an embedded
//! Rust time-series database, MIT) with its WAL fsynced per append -- the
//! program behind the `**Performance:**` line of the maturity card
//! (CONVENTIONS.md §9, kept instrument kind 3).
//!
//! THIS IS A PROGRAM, NOT A TEST. `zig build bench-tsdb` runs it (always
//! ReleaseFast); `zig build check-interop` compiles it. Needs `cargo` and the
//! crates of `tools/tsink_bench/Cargo.lock` in the cargo cache (`cargo fetch`
//! once; the build here is `--locked` and offline). Run from the repository
//! root. The Rust side is built into `.zig-cache/bench-tsdb/target`.
//!
//! The reference side is `tools/tsink_bench/src/main.rs`, one process per
//! workload and round: it times itself exactly as this side does (double the
//! batch until it takes over 100 ms, best of five) and prints
//! `name \t ns \t count`.
//!
//! DURABILITY. Ours: every `kvtree` commit fsyncs (two fsyncs per commit),
//! always. tsink: `WalSyncMode::PerAppend` -- "Each append calls `fsync`
//! before acknowledging the write" (tsink docs/storage-engine.md), the
//! default; one `insert_rows` call is one logical WAL write = one fsync.
//! Both sides write real files under `.zig-cache/bench-tsdb/{ours,tsink}/`.
//!
//! DATA (identical on both sides, generated by formula, see main.rs):
//!   series i of 1000: name "m{i%10}", labels host="h{(i/10)%10}",
//!   region="r{i%7}", inst="i{i}"; scrape k of 200 at ts = 1_792_000_000_000 +
//!   15_000*k ms, value ((i*7919 + k*31) % 1000) / 8.
//!
//!   w1_scrape        fresh store; 200 scrapes, each ONE commit of 1000 series x
//!                    1 sample (ours: `appendBatch`, after ONE `seriesIds`
//!                    commit registering the 1000 series; tsink: one
//!                    `insert_rows` of 1000 rows). 200000 samples, then close.
//!   w2_bulk          fresh store; 1 series x 200000 samples (1 s apart), 200
//!                    commits of 1000 (ours `appendMany`, tsink `insert_rows`)
//!   w2_check         INFO: w2_bulk, then close, reopen, read all back; count
//!                    is the checksum of the read-back (a store that dropped
//!                    data cannot match); also asserted against the generator
//!   w3_range_full    series 0..99 looked up by (name, labels), each read over
//!                    its full range: 100 x 200 samples
//!   w3_range_window  the same, a 10 % window [k=90, k=110): 100 x 20 samples
//!   w4_matcher       `{__name__="m7", host="h3"}` (10 series), then each
//!                    one's full range: 10 x 200 samples
//! The query store is W1's data, built, closed, REOPENED and verified against
//! the generator (all 1000 series, ours and tsink's) before anything is timed.
//!
//! Result count: writes = samples written; reads = FNV-1a/64 over the
//! returned (ts, value bits) per series (seeded with the series index), summed
//! over series, plus the sample count (wrapping). INFO rows (w2_check, the
//! bytes-per-sample line) stay out of the verdict. The sides alternate for
//! BENCH_ROUNDS (default 3) rounds, each keeping its best; ratios are
//! ours/tsink by wall time; the verdict is the worst. Arguments filter
//! workloads.

const std = @import("std");
const bench = @import("testkit").bench;
const tsdb = @import("tsdb");
const kvtree = @import("kvtree");

const bench_name = "bench-tsdb";
const work_dir = ".zig-cache/bench-tsdb";
const rust_dir = "modules/tsdb/tools/tsink_bench";
const gpa = std.heap.smp_allocator;

const n_series = 1000;
const n_scrapes = 200;
const scrape_base: i64 = 1_792_000_000_000;
const scrape_step: i64 = 15_000;
const bulk_samples = 200_000;
const bulk_batch = 1000;
const bulk_base: i64 = 1_790_000_000_000;
const bulk_step: i64 = 1000;
const w3_series = 100;
const w3_win_from = 90;
const w3_win_to = 110;

const Op = enum { w1_scrape, w2_bulk, w2_check, w3_range_full, w3_range_window, w4_matcher };
const W = bench.Work(Op);
const works = [_]W{
    .{ .name = "w1_scrape", .op = .w1_scrape, .ref = "w1_scrape", .wall_only = true },
    .{ .name = "w2_bulk", .op = .w2_bulk, .ref = "w2_bulk", .wall_only = true },
    .{ .name = "w2_check", .op = .w2_check, .ref = "w2_check", .wall_only = true, .info = true },
    .{ .name = "w3_range_full", .op = .w3_range_full, .ref = "w3_range_full", .wall_only = true },
    .{ .name = "w3_range_window", .op = .w3_range_window, .ref = "w3_range_window", .wall_only = true },
    .{ .name = "w4_matcher", .op = .w4_matcher, .ref = "w4_matcher", .wall_only = true },
};

// ── data generators and the checksum (mirror of main.rs) ─────────────────────

fn w1Ts(k: u64) i64 {
    return scrape_base + @as(i64, @intCast(k)) * scrape_step;
}
fn w1Val(i: u64, k: u64) f64 {
    return @as(f64, @floatFromInt((i * 7919 + k * 31) % 1000)) / 8.0;
}
fn w2Ts(k: u64) i64 {
    return bulk_base + @as(i64, @intCast(k)) * bulk_step;
}
fn w2Val(k: u64) f64 {
    return @as(f64, @floatFromInt((k * 7919) % 4001)) / 8.0;
}

const Fnv = struct {
    h: u64,
    fn init(idx: u64) Fnv {
        var f: Fnv = .{ .h = 0xcbf29ce484222325 };
        f.bytes(std.mem.asBytes(&std.mem.nativeToLittle(u64, idx)));
        return f;
    }
    fn bytes(f: *Fnv, b: []const u8) void {
        for (b) |x| {
            f.h ^= x;
            f.h *%= 0x100000001b3;
        }
    }
    fn sample(f: *Fnv, ts: i64, v: f64) void {
        f.bytes(std.mem.asBytes(&std.mem.nativeToLittle(u64, @as(u64, @bitCast(ts)))));
        f.bytes(std.mem.asBytes(&std.mem.nativeToLittle(u64, @as(u64, @bitCast(v)))));
    }
};

const Acc = struct {
    sum: u64 = 0,
    n: u64 = 0,
    fn count(a: Acc) u64 {
        return a.sum +% a.n;
    }
};

const Meta = struct { name: []const u8, labels: [3]tsdb.Label };

fn makeMeta(arena: std.mem.Allocator) ![]Meta {
    const m = try arena.alloc(Meta, n_series);
    for (m, 0..) |*x, i| {
        x.* = .{
            .name = try arena.print("m{d}", .{i % 10}),
            .labels = .{
                .{ .name = "host", .value = try arena.print("h{d}", .{(i / 10) % 10}) },
                .{ .name = "region", .value = try arena.print("r{d}", .{i % 7}) },
                .{ .name = "inst", .value = try arena.print("i{d}", .{i}) },
            },
        };
    }
    return m;
}

const bulk_labels = [3]tsdb.Label{
    .{ .name = "host", .value = "h0" },
    .{ .name = "region", .value = "r0" },
    .{ .name = "inst", .value = "i0" },
};

fn die(what: []const u8, e: anyerror) noreturn {
    std.debug.panic("{s}: {s} failed: {t}", .{ bench_name, what, e });
}

// ── our side ─────────────────────────────────────────────────────────────────

/// One open store: the storage, the caller-owned kvtree, the tsdb view. On the
/// heap, so the addresses the tree and the view hold never move.
const Store = struct {
    fs: kvtree.FsStorage,
    tree: kvtree.Db,
    db: tsdb.Db,

    fn open(io: std.Io, dir: std.Io.Dir, file: []const u8, fresh: bool) *Store {
        if (fresh) removeFiles(io, dir, file);
        const s = gpa.create(Store) catch @panic("oom");
        s.fs = kvtree.FsStorage.init(io, dir);
        s.tree = kvtree.Db.open(gpa, s.fs.storage(), file, .{}) catch |e| die("kvtree open", e);
        s.db = tsdb.Db.init(gpa, &s.tree);
        return s;
    }
    fn close(s: *Store) void {
        s.db.deinit();
        s.tree.close();
        gpa.destroy(s);
    }
};

fn removeFiles(io: std.Io, dir: std.Io.Dir, file: []const u8) void {
    var buf: [128]u8 = undefined;
    dir.deleteFile(io, file) catch {};
    dir.deleteFile(io, std.fmt.bufPrint(&buf, "{s}.lock", .{file}) catch unreachable) catch {};
}

const Ours = struct {
    op: Op = .w1_scrape,
    io: std.Io,
    dir: std.Io.Dir,
    meta: []const Meta,
    pts: []tsdb.Sample,
    batches: []tsdb.SeriesBatch,
    ids: []tsdb.SeriesId,
    bulk: []tsdb.Sample,
    q: ?*Store = null,

    fn buildW1(c: *Ours, s: *Store) u64 {
        var n: u64 = 0;
        // All new series of the first scrape registered in one commit, as
        // tsink registers them inside its first insert.
        var specs: [n_series]tsdb.Db.SeriesSpec = undefined;
        for (c.meta, 0..) |*m, i| specs[i] = .{ .name = m.name, .labels = &m.labels };
        s.db.seriesIds(&specs, c.ids) catch |e| die("seriesIds", e);
        for (0..n_scrapes) |k| {
            for (c.meta, 0..) |*m, i| {
                _ = m;
                c.pts[i] = .{ .ts = w1Ts(k), .value = w1Val(i, k) };
                c.batches[i] = .{ .series = c.ids[i], .points = c.pts[i .. i + 1] };
            }
            s.db.appendBatch(c.batches) catch |e| die("appendBatch", e);
            n += n_series;
        }
        return n;
    }

    fn buildW2(c: *Ours, s: *Store) u64 {
        const id = s.db.seriesId("bulk", &bulk_labels) catch |e| die("seriesId", e);
        var n: u64 = 0;
        for (0..bulk_samples / bulk_batch) |b| {
            for (c.bulk, 0..) |*p, j| {
                const k = b * bulk_batch + j;
                p.* = .{ .ts = w2Ts(k), .value = w2Val(k) };
            }
            s.db.appendMany(id, c.bulk) catch |e| die("appendMany", e);
            n += bulk_batch;
        }
        return n;
    }

    /// Hash and count of one series over [from, to).
    fn readSeries(s: *Store, id: tsdb.SeriesId, idx: u64, from: i64, to: i64, acc: *Acc) void {
        var f = Fnv.init(idx);
        var n: u64 = 0;
        var r = s.db.range(id, from, to) catch |e| die("range", e);
        defer r.deinit();
        while (r.next() catch |e| die("range.next", e)) |p| {
            f.sample(p.ts, p.value);
            n += 1;
        }
        acc.sum +%= f.h;
        acc.n += n;
    }

    fn expectW1(i: u64) Acc {
        var f = Fnv.init(i);
        for (0..n_scrapes) |k| f.sample(w1Ts(k), w1Val(i, k));
        return .{ .sum = f.h, .n = n_scrapes };
    }

    /// Build W1, close, reopen, verify every series against the generator.
    fn prepareQuery(c: *Ours) void {
        const file = "q.kvt";
        const s = Store.open(c.io, c.dir, file, true);
        _ = c.buildW1(s);
        s.close();
        const r = Store.open(c.io, c.dir, file, false);
        for (c.meta, 0..) |*m, i| {
            const id = (r.db.lookupSeries(m.name, &m.labels) catch |e| die("lookupSeries", e)) orelse
                std.debug.panic("{s}: series {d} missing after reopen", .{ bench_name, i });
            var got: Acc = .{};
            readSeries(r, id, i, 0, std.math.maxInt(i64), &got);
            const want = expectW1(i);
            if (got.sum != want.sum or got.n != want.n)
                std.debug.panic("{s}: tsdb lost data in series {d}: {d} of {d} samples", .{ bench_name, i, got.n, want.n });
        }
        c.q = r;
    }

    fn w3(c: *Ours, from: i64, to: i64) u64 {
        const s = c.q.?;
        var acc: Acc = .{};
        for (c.meta[0..w3_series], 0..) |*m, i| {
            const id = (s.db.lookupSeries(m.name, &m.labels) catch |e| die("lookupSeries", e)) orelse
                std.debug.panic("{s}: series {d} missing", .{ bench_name, i });
            readSeries(s, id, i, from, to, &acc);
        }
        return acc.count();
    }

    fn w4(c: *Ours) u64 {
        const s = c.q.?;
        var acc: Acc = .{};
        var it = s.db.findSeriesMatching("m7", &.{.{ .name = "host", .value = "h3" }}) catch |e| die("findSeriesMatching", e);
        defer it.deinit();
        while (it.next(gpa) catch |e| die("next", e)) |entry_const| {
            var entry = entry_const;
            defer entry.deinit(gpa);
            var idx: u64 = 0;
            for (entry.descriptor.labels) |l| {
                if (std.mem.eql(u8, l.name, "inst")) idx = std.fmt.parseInt(u64, l.value[1..], 10) catch @panic("inst label");
            }
            readSeries(s, entry.id, idx, 0, std.math.maxInt(i64), &acc);
        }
        return acc.count();
    }
};

fn once(c: *Ours) u64 {
    switch (c.op) {
        .w1_scrape => {
            const s = Store.open(c.io, c.dir, "w1.kvt", true);
            const n = c.buildW1(s);
            s.close();
            return n;
        },
        .w2_bulk => {
            const s = Store.open(c.io, c.dir, "w2.kvt", true);
            const n = c.buildW2(s);
            s.close();
            return n;
        },
        .w2_check => {
            const s = Store.open(c.io, c.dir, "w2c.kvt", true);
            _ = c.buildW2(s);
            s.close();
            const r = Store.open(c.io, c.dir, "w2c.kvt", false);
            defer r.close();
            const id = (r.db.lookupSeries("bulk", &bulk_labels) catch |e| die("lookupSeries", e)) orelse @panic("bulk series missing");
            var got: Acc = .{};
            Ours.readSeries(r, id, 0, 0, std.math.maxInt(i64), &got);
            var want = Fnv.init(0);
            for (0..bulk_samples) |k| want.sample(w2Ts(k), w2Val(k));
            if (got.n != bulk_samples or got.sum != want.h)
                std.debug.panic("{s}: tsdb lost data in W2: {d} of {d}", .{ bench_name, got.n, @as(u64, bulk_samples) });
            return got.count();
        },
        .w3_range_full => return c.w3(0, std.math.maxInt(i64)),
        .w3_range_window => return c.w3(w1Ts(w3_win_from), w1Ts(w3_win_to)),
        .w4_matcher => return c.w4(),
    }
}

fn buildRust(arena: std.mem.Allocator, io: std.Io, environ: *const std.process.Environ.Map, abs: []const u8) ![]const u8 {
    var env = try environ.clone(arena);
    try env.put("CARGO_TARGET_DIR", try arena.print("{s}/target", .{abs}));
    try env.put("CARGO_NET_OFFLINE", "true");
    std.debug.print("{s}: building the tsink side (cargo build --release --locked) ...\n", .{bench_name});
    const res = std.process.run(arena, io, .{
        .argv = &.{ "cargo", "build", "--release", "--locked" },
        .environ_map = &env,
        .cwd = .{ .path = rust_dir },
    }) catch |e| {
        std.debug.print("{s}: could not run cargo ({t}) -- the benchmark needs it\n", .{ bench_name, e });
        return error.RustBuildFailed;
    };
    if (res.term != .exited or res.term.exited != 0) {
        std.debug.print("{s}: cargo build failed:\n{s}\n", .{ bench_name, res.stderr });
        return error.RustBuildFailed;
    }
    return try arena.print("{s}/target/release/tsink_bench", .{abs});
}

pub fn main(init: std.process.Init) !u8 {
    const io = init.io;
    const arena = init.arena.allocator();
    const cwd = std.Io.Dir.cwd();
    try cwd.createDirPath(io, work_dir ++ "/ours");
    var dir = try cwd.openDir(io, work_dir ++ "/ours", .{});
    defer dir.close(io);
    const abs = try cwd.realPathFileAlloc(io, work_dir, arena);
    const args = try init.minimal.args.toSlice(arena);
    const filters = if (args.len > 1) args[1..] else &[_][:0]const u8{};
    const rounds: usize = if (init.environ_map.get("BENCH_ROUNDS")) |r| try std.fmt.parseInt(usize, r, 10) else 3;

    const exe = try buildRust(arena, io, init.environ_map, abs);

    var ctx: Ours = .{
        .io = io,
        .dir = dir,
        .meta = try makeMeta(arena),
        .pts = try arena.alloc(tsdb.Sample, n_series),
        .batches = try arena.alloc(tsdb.SeriesBatch, n_series),
        .ids = try arena.alloc(tsdb.SeriesId, n_series),
        .bulk = try arena.alloc(tsdb.Sample, bulk_batch),
    };
    var need_query = false;
    for (works) |x| {
        if (bench.selected(x.name, filters) and
            (x.op == .w3_range_full or x.op == .w3_range_window or x.op == .w4_matcher)) need_query = true;
    }
    if (need_query) ctx.prepareQuery();

    var buf: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(io, &buf);
    const w = &stdout.interface;
    try w.print("data: {d} series x 3 labels x {d} scrapes (W1), 1 x {d} samples (W2); ours = tsdb over kvtree (fsync per commit), ref = tsink 0.10.2 WalSyncMode::PerAppend\n", .{ n_series, n_scrapes, bulk_samples });
    const s = bench.drive(io, arena, .{
        .name = bench_name,
        .exes = &.{exe},
        .abs = abs,
        .filters = filters,
        .rounds = rounds,
    }, &ctx, once, works, w) catch |e| {
        try w.flush();
        if (e == error.CountMismatch) return 1;
        return e;
    };

    // INFO: bytes on disk after W1, both sides closed.
    if (filters.len == 0) {
        const st = Store.open(io, dir, "size.kvt", true);
        const n = ctx.buildW1(st);
        st.close();
        const ours_bytes = (try dir.statFile(io, "size.kvt", .{})).size;
        const ref = try bench.foreign(arena, io, bench_name, exe, abs, "size_w1", null);
        try w.print("info: bytes on disk after W1 ({d} samples): ours {d} ({d:.2} B/sample, one kvtree file, uncompacted), tsink {d} ({d:.2} B/sample, whole data dir after close)\n", .{ n, ours_bytes, @as(f64, @floatFromInt(ours_bytes)) / @as(f64, @floatFromInt(n)), ref.count, @as(f64, @floatFromInt(ref.count)) / @as(f64, @floatFromInt(n)) });
        removeFiles(io, dir, "size.kvt");
    }
    if (ctx.q) |q| q.close();
    removeFiles(io, dir, "q.kvt");
    removeFiles(io, dir, "w1.kvt");
    removeFiles(io, dir, "w2.kvt");
    removeFiles(io, dir, "w2c.kvt");

    if (s.banner.len > 0) try w.print("reference: {s}\n", .{std.mem.trim(u8, s.banner, " \n")});
    try w.print("\nworst ours/tsink = {d:.2} (best {d:.2})\n", .{ s.worst_ref, s.best_ref });
    if (filters.len == 0)
        try w.print("card: **Performance:** ref {d:.2}–{d:.2}× tsink 0.10.2 (WAL fsync per append) · fastest ? (measured <today>)\n", .{ s.best_ref, s.worst_ref });
    try w.flush();
    return 0;
}
