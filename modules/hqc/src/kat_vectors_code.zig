//! kat_vectors_code — byte-exact reference vectors for Part 2's RS/RM
//! encode and full concatenated-code encode, obtained by compiling and
//! running the reference implementation's OWN unmodified C source
//! (`gitlab.com/pqc-hqc/hqc` tag `v5.0.0` — the same tag Part 1's
//! SPEC.md/NOTICE pin) locally, then transcribing its stdout.
//!
//! **Provenance / how these were generated** (for future auditing, same
//! spirit as Part 1's `kat_vectors.zig` doc comment): a small standalone
//! `gen.c` harness was written that `#include`s the reference's own
//! `reed_solomon.c`, `reed_muller.c`, `code.c`, `fft.c`, `gf.c`, and
//! `crypto_memset.c` UNMODIFIED (only linked together with a `main()`
//! that calls `reed_solomon_encode`/`reed_muller_encode`/`code_encode` on
//! fixed test messages and prints the output as hex), compiled with
//! `gcc -O0` against each parameter set's own `parameters.h`
//! (`-I src/ref/hqc-{1,3,5} -I src/common/hqc-{1,3,5}`), and run. This is
//! the same "compile the reference and run it" technique as Part 1's
//! `intermediates_values` capture, except Part 1 downloaded a
//! pre-existing reference-produced fixture file, while here no such
//! fixture ships for the RS/RM/code layer in this tag (checked: the
//! v5.0.0 tag's `kats/ref/hqc-*/intermediates_values` files only cover
//! the PKE/KEM layer's PRNG-derived values, not the code layer in
//! isolation) — so a fresh one-off harness was built from the reference's
//! own unmodified files instead. No hex value below was hand-transcribed
//! or LLM-summarized from the reference; the harness's raw stdout was
//! captured to a file and mechanically converted to these Zig array
//! literals by a small Python script, eliminating transcription risk the
//! same way Part 1's `curl`-not-a-summarizer approach did.
//!
//! **Coverage**: full depth (RS encode for 4 message patterns, RM encode
//! for 8 byte values, AND the full `n1n2`-byte concatenated-code encode
//! for 2 message patterns) for hqc-128; lighter depth (RS + RM only, no
//! full-codeword vectors — those are large and hqc-128's already prove
//! the concatenation offset math, see `code.zig`'s own
//! `code_kat_test.zig`-independent block-offset test) for hqc-192/256.
//! This mirrors Part 1's own `gf2x.zig` precedent (full depth on
//! hqc-128, lighter cross-parameter-set sampling on hqc-192/256).
//!
//! Naming: `<param>_rs_<case>` = `reed_solomon_encode` output (n1 bytes);
//! `<param>_code_<case>` = `code_encode` output (n1n2/8 bytes);
//! `<param>_rm_byte_<hex>` = `reed_muller_encode`'s FIRST symbol slot
//! (`block_bytes` bytes) when only that one input byte is set to the
//! given value (isolates one `RM.encodeSymbol` call from RS entirely).
//! Message-pattern cases: `zero` = all-zero message; `ff` = all-0xff
//! message; `incr` = message bytes 0,1,2,...; `msg0_01` = all-zero except
//! byte 0 = 0x01 (isolates the generator polynomial's first tap).

