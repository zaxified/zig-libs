//! The pure string formats of `validate.Format` that follow go-playground/validator
//! v10.30.5 (the second wave: colors, book / account / address checksums, network
//! addresses, ISO code sets, tokens). Each is a total function over bytes: no
//! allocation, no I/O, no recursion, never a panic.
//!
//! go-playground's own verdicts are the oracle (`tools/format_oracle.py`,
//! `go_format_test.zig`). Where this file answers otherwise than the rival the
//! difference is a named class there, with its reason; the rest mirrors the
//! rival's regular expressions byte for byte, written out as scanners.
//!
//! The `*_addr` formats are SYNTAX ONLY: a literal IP, plus a numeric port where
//! the tag has one. The rival resolves with the system resolver; a validator of
//! untrusted input does no name-resolution I/O, so a host name is refused here.
//!
//! The country and currency sets and the Unicode letter / number ranges are
//! data: `format_tables.zig`, generated by `tools/gen_format_tables.py`.

const std = @import("std");
const netaddr = @import("netaddr");
const tables = @import("format_tables.zig");

const Sha256 = std.crypto.hash.sha2.Sha256;
const Keccak256 = std.crypto.hash.sha3.Keccak256;

// ── colors (regexes.go: hexColor, rgb, rgba, hsl, hsla, cmyk) ────────────────

/// A cursor over the input, for the anchored scanners below.
const Scan = struct {
    s: []const u8,
    i: usize = 0,

    /// RE2 `\s*`: space, \t, \n, \f, \r.
    fn ws(self: *Scan) void {
        while (self.i < self.s.len) : (self.i += 1) switch (self.s[self.i]) {
            ' ', '\t', '\n', 0x0c, '\r' => {},
            else => return,
        };
    }
    fn lit(self: *Scan, t: []const u8) bool {
        if (!std.mem.startsWith(u8, self.s[self.i..], t)) return false;
        self.i += t.len;
        return true;
    }
    fn ch(self: *Scan, c: u8) bool {
        if (self.i < self.s.len and self.s[self.i] == c) {
            self.i += 1;
            return true;
        }
        return false;
    }
    fn atEnd(self: *Scan) bool {
        return self.i == self.s.len;
    }
    /// A maximal run of digits read as a canonical decimal (no leading zero)
    /// not above `max`.
    fn num(self: *Scan, max: u32) bool {
        const st = self.i;
        while (self.i < self.s.len and std.ascii.isDigit(self.s[self.i])) self.i += 1;
        const run = self.s[st..self.i];
        if (run.len == 0 or run.len > 3) return false;
        if (run.len > 1 and run[0] == '0') return false;
        return (std.fmt.parseInt(u32, run, 10) catch return false) <= max;
    }
    /// `\s*,\s*`
    fn comma(self: *Scan) bool {
        self.ws();
        if (!self.ch(',')) return false;
        self.ws();
        return true;
    }
    /// A CSS alpha: 0, 1, 0.d+ or 1.0+. (The rival's `0.[1-9]*` has an
    /// unescaped dot: it takes `0x` and refuses `0.05` and `1.0`.)
    fn alpha(self: *Scan) bool {
        const st = self.i;
        while (self.i < self.s.len and (std.ascii.isDigit(self.s[self.i]) or self.s[self.i] == '.')) self.i += 1;
        const t = self.s[st..self.i];
        if (t.len == 0) return false;
        if (t[0] != '0' and t[0] != '1') return false;
        if (t.len == 1) return true;
        if (t[1] != '.' or t.len == 2) return false;
        for (t[2..]) |c| {
            if (!std.ascii.isDigit(c)) return false;
            if (t[0] == '1' and c != '0') return false;
        }
        return true;
    }
};

pub fn isHexColor(s: []const u8) bool {
    if (s.len == 0 or s[0] != '#') return false;
    const n = s.len - 1;
    if (n != 3 and n != 4 and n != 6 and n != 8) return false;
    for (s[1..]) |c| if (!std.ascii.isHex(c)) return false;
    return true;
}

/// `rgb(` / `rgba(`: three 0-255 integers or three 0-255 percentages (the
/// rival's range for a percentage too), then for rgba a CSS alpha.
pub fn isRgb(s: []const u8, with_alpha: bool) bool {
    var sc: Scan = .{ .s = s };
    if (!sc.lit(if (with_alpha) "rgba(" else "rgb(")) return false;
    sc.ws();
    if (!sc.num(255)) return false;
    const pct = sc.ch('%');
    inline for (0..2) |_| {
        if (!sc.comma() or !sc.num(255)) return false;
        if (pct and !sc.ch('%')) return false;
    }
    if (with_alpha) {
        if (!sc.comma() or !sc.alpha()) return false;
    }
    sc.ws();
    return sc.ch(')') and sc.atEnd();
}

/// `hsl(` / `hsla(`: hue 0-360, two 0-100 percentages, for hsla a CSS alpha.
pub fn isHsl(s: []const u8, with_alpha: bool) bool {
    var sc: Scan = .{ .s = s };
    if (!sc.lit(if (with_alpha) "hsla(" else "hsl(")) return false;
    sc.ws();
    if (!sc.num(360)) return false;
    inline for (0..2) |_| {
        if (!sc.comma() or !sc.num(100) or !sc.ch('%')) return false;
    }
    if (with_alpha) {
        if (!sc.comma() or !sc.alpha()) return false;
    }
    sc.ws();
    return sc.ch(')') and sc.atEnd();
}

/// `cmyk(` four 0-100 percentages `)`; no space after `(` or before `)`.
pub fn isCmyk(s: []const u8) bool {
    var sc: Scan = .{ .s = s };
    if (!sc.lit("cmyk(")) return false;
    if (!sc.num(100) or !sc.ch('%')) return false;
    inline for (0..3) |_| {
        if (!sc.comma() or !sc.num(100) or !sc.ch('%')) return false;
    }
    return sc.ch(')') and sc.atEnd();
}

// ── ISBN, ISSN (baked_in.go isISBN10 / isISBN13 / isISSN) ────────────────────

/// `s` with its first `limit` occurrences of `c` removed (`strings.Replace(s,
/// c, "", limit)`), into `dst`; null when it does not fit (then it is no ISBN).
fn dropFirst(dst: []u8, s: []const u8, c: u8, limit: usize) ?[]u8 {
    if (s.len > dst.len) return null;
    var n: usize = 0;
    var dropped: usize = 0;
    for (s) |b| {
        if (b == c and dropped < limit) {
            dropped += 1;
            continue;
        }
        dst[n] = b;
        n += 1;
    }
    return dst[0..n];
}

fn isbnBody(s: []const u8, hyphens: usize, buf: *[48]u8, buf2: *[48]u8) ?[]const u8 {
    const a = dropFirst(buf, s, '-', hyphens) orelse return null;
    return dropFirst(buf2, a, ' ', hyphens);
}

pub fn isIsbn10(s: []const u8) bool {
    var b1: [48]u8 = undefined;
    var b2: [48]u8 = undefined;
    const t = isbnBody(s, 3, &b1, &b2) orelse return false;
    if (t.len != 10) return false;
    var sum: u32 = 0;
    for (t[0..9], 1..) |c, w| {
        if (!std.ascii.isDigit(c)) return false;
        sum += @as(u32, @intCast(w)) * (c - '0');
    }
    if (t[9] == 'X') {
        sum += 100;
    } else if (std.ascii.isDigit(t[9])) {
        sum += 10 * (t[9] - '0');
    } else return false;
    return sum % 11 == 0;
}

pub fn isIsbn13(s: []const u8) bool {
    var b1: [48]u8 = undefined;
    var b2: [48]u8 = undefined;
    const t = isbnBody(s, 4, &b1, &b2) orelse return false;
    if (t.len != 13 or !std.mem.startsWith(u8, t, "97") or (t[2] != '8' and t[2] != '9')) return false;
    var sum: u32 = 0;
    for (t, 0..) |c, i| {
        if (!std.ascii.isDigit(c)) return false;
        if (i < 12) sum += @as(u32, if (i % 2 == 0) 1 else 3) * (c - '0');
    }
    return @as(u32, t[12] - '0') == (10 - sum % 10) % 10;
}

pub fn isIssn(s: []const u8) bool {
    if (s.len != 9 or s[4] != '-') return false;
    var sum: u32 = 0;
    var w: u32 = 8;
    for (s[0..4]) |c| {
        if (!std.ascii.isDigit(c)) return false;
        sum += w * (c - '0');
        w -= 1;
    }
    for (s[5..8]) |c| {
        if (!std.ascii.isDigit(c)) return false;
        sum += w * (c - '0');
        w -= 1;
    }
    if (s[8] == 'X') {
        sum += 10;
    } else if (std.ascii.isDigit(s[8])) {
        sum += s[8] - '0';
    } else return false;
    return sum % 11 == 0;
}

// ── crypto addresses ─────────────────────────────────────────────────────────

pub fn isEthAddr(s: []const u8) bool {
    if (s.len != 42 or s[0] != '0' or s[1] != 'x') return false;
    for (s[2..]) |c| if (!std.ascii.isHex(c)) return false;
    return true;
}

/// EIP-55: the rival's rule, nibble by nibble (a letter is upper-case when its
/// Keccak-256 nibble is above 7, lower-case otherwise).
pub fn isEthAddrChecksum(s: []const u8) bool {
    if (!isEthAddr(s)) return false;
    const addr = s[2..];
    var lower: [40]u8 = undefined;
    for (addr, &lower) |c, *l| l.* = std.ascii.toLower(c);
    var h: [32]u8 = undefined;
    Keccak256.hash(&lower, &h, .{});
    for (addr, 0..) |c, i| {
        if (c <= '9') continue;
        const nib = if (i % 2 == 0) h[i / 2] >> 4 else h[i / 2] & 0x0f;
        if (nib > 7 and c >= 'a') return false;
        if (nib <= 7 and c <= 'F') return false;
    }
    return true;
}

const base58_alphabet = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";

/// Base58Check P2PKH / P2SH: `[13]` + 25..34 base58 characters, decoding to
/// exactly 25 bytes whose last four are the double SHA-256 of the first 21, with
/// version 0 behind `1` and 5 behind `3`, and one leading `1` per leading zero
/// byte. The rival checks the checksum only, and lets a longer number lose its
/// high bytes.
pub fn isBtcAddr(s: []const u8) bool {
    if (s.len < 26 or s.len > 35 or (s[0] != '1' and s[0] != '3')) return false;
    var dec: [25]u8 = @splat(0);
    for (s) |c| {
        var d: u32 = @intCast(std.mem.findScalar(u8, base58_alphabet, c) orelse return false);
        var i: usize = 25;
        while (i > 0) {
            i -= 1;
            d += 58 * @as(u32, dec[i]);
            dec[i] = @truncate(d);
            d >>= 8;
        }
        if (d != 0) return false; // the number does not fit 25 bytes
    }
    if (dec[0] != @as(u8, if (s[0] == '1') 0 else 5)) return false;
    var ones: usize = 0;
    while (ones < s.len and s[ones] == '1') ones += 1;
    var zeros: usize = 0;
    while (zeros < dec.len and dec[zeros] == 0) zeros += 1;
    if (ones != zeros) return false;
    var h1: [32]u8 = undefined;
    var h2: [32]u8 = undefined;
    Sha256.hash(dec[0..21], &h1, .{});
    Sha256.hash(&h1, &h2, .{});
    return std.mem.eql(u8, h2[0..4], dec[21..25]);
}

fn polymodStep(p: u32, v: u8, gen: *const [5]u32) u32 {
    const b = p >> 25;
    var r = ((p & 0x1ffffff) << 5) ^ v;
    for (0..5) |i| {
        if ((b >> @intCast(i)) & 1 == 1) r ^= gen[i];
    }
    return r;
}

const bech32_alphabet = "qpzry9x8gf2tvdw0s3jn54khce6mua7l";

/// A mainnet segwit address (BIP 173 / BIP 350): `bc1` + 7..76 characters, one
/// case, a witness version 0..16 (version 0 is 42 or 62 characters long), the
/// checksum constant of the version (bech32 for 0, bech32m for 1..16), a 2..40
/// byte program, and zero padding bits (BIP 173: "MUST be all zeroes"). The rival
/// checks the bech32 constant for every version, which refuses every taproot
/// address, and does not look at the padding.
pub fn isBtcBech32(s: []const u8) bool {
    if (s.len < 10 or s.len > 79) return false;
    if (!std.ascii.eqlIgnoreCase(s[0..3], "bc1")) return false;
    const upper = std.ascii.isUpper(s[0]);
    for (s) |c| {
        if (upper) {
            if (std.ascii.isLower(c)) return false;
        } else if (std.ascii.isUpper(c)) return false;
    }
    const am = s.len % 8;
    if (am == 0 or am == 3 or am == 5) return false;
    var dp: [76]u8 = undefined;
    const body = s[3..];
    for (body, 0..) |c, i| {
        const ix = std.mem.findScalar(u8, bech32_alphabet, std.ascii.toLower(c)) orelse return false;
        dp[i] = @intCast(ix);
    }
    const ver = dp[0];
    if (ver > 16) return false;
    if (ver == 0 and s.len != 42 and s.len != 62) return false;
    const gen = [5]u32{ 0x3b6a57b2, 0x26508e6d, 0x1ea119fa, 0x3d4233dd, 0x2a1462b3 };
    var p: u32 = 1;
    const hrp = [5]u8{ 3, 3, 0, 2, 3 };
    for (hrp) |v| p = polymodStep(p, v, &gen);
    for (dp[0..body.len]) |v| p = polymodStep(p, v, &gen);
    if (p != (if (ver == 0) @as(u32, 1) else 0x2bc830a3)) return false;
    const data_chars = body.len - 7;
    const pad: u3 = @intCast(data_chars * 5 % 8);
    if (pad != 0 and dp[data_chars] & ((@as(u8, 1) << pad) - 1) != 0) return false;
    const prog = data_chars * 5 / 8;
    return prog >= 2 and prog <= 40;
}

// ── tokens ───────────────────────────────────────────────────────────────────

/// Crockford base32, 26 characters, first at most `7`: the spec's largest ULID is
/// `7ZZZZZZZZZZZZZZZZZZZZZZZZZ`, and anything larger overflows its 128 bits.
pub fn isUlid(s: []const u8) bool {
    if (s.len != 26 or s[0] < '0' or s[0] > '7') return false;
    for (s) |c0| {
        const c = std.ascii.toUpper(c0);
        const ok = (c >= '0' and c <= '9') or (c >= 'A' and c <= 'H') or c == 'J' or c == 'K' or c == 'M' or c == 'N' or
            (c >= 'P' and c <= 'T') or (c >= 'V' and c <= 'Z');
        if (!ok) return false;
    }
    return true;
}

/// RFC 4648 base32 with padding, upper case, whole 8-character groups.
pub fn isBase32(s: []const u8) bool {
    if (s.len == 0 or s.len % 8 != 0) return false;
    var body = s;
    var pad: usize = 0;
    while (body.len > 0 and body[body.len - 1] == '=') : (body = body[0 .. body.len - 1]) pad += 1;
    if (pad != 0 and pad != 1 and pad != 3 and pad != 4 and pad != 6) return false;
    for (body) |c| if (!((c >= 'A' and c <= 'Z') or (c >= '2' and c <= '7'))) return false;
    return true;
}

fn isBase64Padded(s: []const u8) bool {
    if (s.len % 4 != 0) return false;
    var body = s;
    var pad: usize = 0;
    while (pad < 2 and body.len > 0 and body[body.len - 1] == '=') : (pad += 1) body = body[0 .. body.len - 1];
    for (body) |c| if (!std.ascii.isAlphanumeric(c) and c != '+' and c != '/') return false;
    return true;
}

/// Any byte outside ASCII; the empty string passes, as in the rival.
pub fn isMultibyte(s: []const u8) bool {
    if (s.len == 0) return true;
    for (s) |c| if (c >= 0x80) return true;
    return false;
}

/// RFC 2045 token.
fn isMimeToken(s: []const u8) bool {
    if (s.len == 0) return false;
    for (s) |c| {
        if (c <= 0x20 or c >= 0x7f or std.mem.findScalar(u8, "()<>@,;:\\\"/[]?=", c) != null) return false;
    }
    return true;
}

/// RFC 2396 `uric`, the RFC 2397 `urlchar`, without the characters in `except`.
fn isUrlChars(s: []const u8, except: []const u8) bool {
    var i: usize = 0;
    while (i < s.len) {
        const c = s[i];
        if (c == '%') {
            if (!isPct(s, i)) return false;
            i += 3;
            continue;
        }
        if (std.mem.findScalar(u8, except, c) != null) return false;
        if (!std.ascii.isAlphanumeric(c) and std.mem.findScalar(u8, ";/?:@&=+$,-_.!~*'()", c) == null) return false;
        i += 1;
    }
    return true;
}

/// RFC 2397: `data:` [type `/` subtype] *(`;` attribute `=` value) [`;base64`]
/// `,` data. With `;base64` the data is padded base64 and may be empty; without
/// it, URL characters. The rival takes the part after the first comma as base64
/// whatever came before, so `data:text/plain,hello` fails there and
/// `data:foo,QUJD` passes. %-encoded base64 is refused here.
pub fn isDataUri(s: []const u8) bool {
    if (!std.mem.startsWith(u8, s, "data:")) return false;
    const rest = s["data:".len..];
    const comma = std.mem.findScalar(u8, rest, ',') orelse return false;
    var head = rest[0..comma];
    const data = rest[comma + 1 ..];
    const b64 = std.mem.endsWith(u8, head, ";base64");
    if (b64) head = head[0 .. head.len - ";base64".len];
    var it = std.mem.splitScalar(u8, head, ';');
    const mt = it.first();
    if (mt.len != 0) {
        const slash = std.mem.findScalar(u8, mt, '/') orelse return false;
        if (!isMimeToken(mt[0..slash]) or !isMimeToken(mt[slash + 1 ..])) return false;
    }
    while (it.next()) |param| {
        const eq = std.mem.findScalar(u8, param, '=') orelse return false;
        if (!isMimeToken(param[0..eq]) or !isUrlChars(param[eq + 1 ..], "")) return false;
    }
    return if (b64) isBase64Padded(data) else isUrlChars(data, "");
}

fn inRanges(table: []const [2]u21, cp: u21) bool {
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (cp < table[mid][0]) {
            hi = mid;
        } else if (cp > table[mid][1]) {
            lo = mid + 1;
        } else return true;
    }
    return false;
}

/// Non-empty, valid UTF-8, every code point a Unicode letter (`\p{L}`), or with
/// `numbers` a letter or number (`\p{N}`); Unicode 15.0.0, as Go 1.26.
pub fn isUnicodeAlpha(s: []const u8, numbers: bool) bool {
    if (s.len == 0) return false;
    const view = std.unicode.Utf8View.init(s) catch return false;
    var it = view.iterator();
    while (it.nextCodepoint()) |cp| {
        if (inRanges(&tables.unicode_l, cp)) continue;
        if (numbers and inRanges(&tables.unicode_n, cp)) continue;
        return false;
    }
    return true;
}

/// Valid UTF-8 without a control character (general category Cc: U+0000-001F,
/// U+007F-009F); the empty string passes. (Keats/validator's
/// `non_control_character`; go-playground has no such tag.)
pub fn isNonControl(s: []const u8) bool {
    const view = std.unicode.Utf8View.init(s) catch return false;
    var it = view.iterator();
    while (it.nextCodepoint()) |cp| {
        if (cp < 0x20 or (cp >= 0x7f and cp <= 0x9f)) return false;
    }
    return true;
}

pub fn isUrlEncoded(s: []const u8) bool {
    for (s, 0..) |c, i| {
        if (c != '%') continue;
        if (i + 2 >= s.len) return false;
        if (!std.ascii.isHex(s[i + 1]) or !std.ascii.isHex(s[i + 2])) return false;
    }
    return true;
}

/// Contains an HTML entity: `&gt` `&lt` `&quot` `&amp` or `&#` + optional `x` +
/// two hex digits, anywhere in the string (the rival's regex is unanchored).
pub fn isHtmlEncoded(s: []const u8) bool {
    var i: usize = 0;
    while (std.mem.findScalarPos(u8, s, i, '&')) |p| : (i = p + 1) {
        const r = s[p + 1 ..];
        if (std.mem.startsWith(u8, r, "gt") or std.mem.startsWith(u8, r, "lt") or
            std.mem.startsWith(u8, r, "quot") or std.mem.startsWith(u8, r, "amp")) return true;
        if (r.len >= 1 and r[0] == '#') {
            const h = if (r.len >= 2 and r[1] == 'x') r[2..] else r[1..];
            if (h.len >= 2 and std.ascii.isHex(h[0]) and std.ascii.isHex(h[1])) return true;
        }
    }
    return false;
}

// ── URN (RFC 2141, RFC 8141) ─────────────────────────────────────────────────

fn isPct(s: []const u8, i: usize) bool {
    return i + 2 < s.len and s[i] == '%' and std.ascii.isHex(s[i + 1]) and std.ascii.isHex(s[i + 2]);
}

fn urnNid(s: []const u8, rfc8141: bool) ?usize {
    if (s.len < 4 or !std.ascii.eqlIgnoreCase(s[0..4], "urn:")) return null;
    var i: usize = 4;
    while (i < s.len and s[i] != ':') i += 1;
    const nid = s[4..i];
    if (nid.len < (if (rfc8141) @as(usize, 2) else 1) or nid.len > 32 or i >= s.len) return null;
    if (!std.ascii.isAlphanumeric(nid[0])) return null;
    if (rfc8141 and !std.ascii.isAlphanumeric(nid[nid.len - 1])) return null;
    for (nid) |c| if (!std.ascii.isAlphanumeric(c) and c != '-') return null;
    return i + 1;
}

/// RFC 2141: `urn:` NID `:` NSS; NSS one or more of the URN characters or
/// `%XX` escapes. Refused although the ABNF would admit them: the NID `urn`
/// (§2.1: "reserved and MUST NOT be used") and unescaped `/`, `?`, `#` (§2.3.2:
/// "RESERVED for future developments", to be %-encoded).
pub fn isUrn2141(s: []const u8) bool {
    const start = urnNid(s, false) orelse return false;
    if (std.ascii.eqlIgnoreCase(s[4 .. start - 1], "urn")) return false;
    const nss = s[start..];
    if (nss.len == 0) return false;
    var i: usize = 0;
    while (i < nss.len) {
        const c = nss[i];
        if (c == '%') {
            if (!isPct(nss, i)) return false;
            i += 3;
            continue;
        }
        if (!std.ascii.isAlphanumeric(c) and std.mem.findScalar(u8, "()+,-.:=@;$_!*'", c) == null) return false;
        i += 1;
    }
    return true;
}

fn pchar(s: []const u8, i: usize) usize {
    const c = s[i];
    if (std.ascii.isAlphanumeric(c) or std.mem.findScalar(u8, "-._~!$&'()*+,;=:@", c) != null) return 1;
    if (isPct(s, i)) return 3;
    return 0;
}

/// Run of `pchar` and, with `slash` / `query`, `/` and `?`; returns the end.
fn urnRun(s: []const u8, from: usize, slash: bool, query: bool) usize {
    var i = from;
    while (i < s.len) {
        const n = pchar(s, i);
        if (n != 0) {
            i += n;
        } else if ((slash and s[i] == '/') or (query and s[i] == '?')) {
            i += 1;
        } else break;
    }
    return i;
}

/// One r- or q-component from `from` (RFC 8141 section 2): a pchar, then
/// pchar, `/` and `?`; an r-component ends at a `?=`.
fn urnComponent(s: []const u8, from: usize, r_comp: bool) ?usize {
    if (from >= s.len or pchar(s, from) == 0) return null;
    var j = from;
    while (j < s.len) {
        if (s[j] == '?') {
            if (r_comp and j + 1 < s.len and s[j + 1] == '=') break;
            j += 1;
            continue;
        }
        const n = pchar(s, j);
        if (n != 0) {
            j += n;
        } else if (s[j] == '/') {
            j += 1;
        } else break;
    }
    return j;
}

/// RFC 8141: `urn:` NID `:` NSS [`?+` r] [`?=` q] [`#` f].
pub fn isUrn8141(s: []const u8) bool {
    const start = urnNid(s, true) orelse return false;
    if (start >= s.len or pchar(s, start) == 0) return false;
    var i = urnRun(s, start, true, false);
    if (std.mem.startsWith(u8, s[i..], "?+")) i = urnComponent(s, i + 2, true) orelse return false;
    if (std.mem.startsWith(u8, s[i..], "?=")) i = urnComponent(s, i + 2, false) orelse return false;
    if (i < s.len and s[i] == '#') i = urnRun(s, i + 1, true, true);
    return i == s.len;
}

// ── host names, ports, CIDR ──────────────────────────────────────────────────

/// RFC 1123 host name, one or more labels, at most 253 characters.
fn isHostName(s: []const u8) bool {
    if (s.len == 0 or s.len > 253) return false;
    var it = std.mem.splitScalar(u8, s, '.');
    while (it.next()) |label| {
        if (label.len == 0 or label.len > 63) return false;
        if (label[0] == '-' or label[label.len - 1] == '-') return false;
        for (label) |c| if (!std.ascii.isAlphanumeric(c) and c != '-') return false;
    }
    return true;
}

/// RFC 952 host name: RFC 1123 whose first character is a letter.
pub fn isHostnameRfc952(s: []const u8) bool {
    return s.len != 0 and std.ascii.isAlphabetic(s[0]) and isHostName(s);
}

/// A fully qualified domain name: two or more labels (1-63 characters, starting
/// and ending in a letter or digit), the last starting with a letter, an optional
/// trailing dot, at most 253 characters without it. The rival also takes a hyphen
/// at the end of a label; RFC 5321 4.1.2 `Ldh-str` ends in `Let-dig`.
pub fn isFqdn(s: []const u8) bool {
    const t = if (std.mem.endsWith(u8, s, ".")) s[0 .. s.len - 1] else s;
    if (t.len == 0 or t.len > 253) return false;
    var it = std.mem.splitScalar(u8, t, '.');
    var n: usize = 0;
    var last: []const u8 = "";
    while (it.next()) |label| : (n += 1) {
        if (label.len == 0 or label.len > 63 or !std.ascii.isAlphanumeric(label[0])) return false;
        if (!std.ascii.isAlphanumeric(label[label.len - 1])) return false;
        for (label) |c| if (!std.ascii.isAlphanumeric(c) and c != '-') return false;
        last = label;
    }
    return n >= 2 and std.ascii.isAlphabetic(last[0]);
}

/// RFC 1035 label: a letter, then letters / digits / hyphens, ending in a
/// letter or digit; lower case; at most 63.
pub fn isDnsLabel(s: []const u8) bool {
    if (s.len == 0 or s.len > 63) return false;
    const lc = struct {
        fn f(c: u8) bool {
            return (c >= 'a' and c <= 'z') or (c >= '0' and c <= '9');
        }
    }.f;
    if (!(s[0] >= 'a' and s[0] <= 'z')) return false;
    if (!lc(s[s.len - 1])) return false;
    for (s) |c| if (!lc(c) and c != '-') return false;
    return true;
}

/// Go's `net.SplitHostPort`.
fn splitHostPort(hp: []const u8) ?struct { host: []const u8, port: []const u8 } {
    const i = std.mem.findScalarLast(u8, hp, ':') orelse return null;
    var host: []const u8 = undefined;
    var j: usize = 0;
    var k: usize = 0;
    if (hp.len > 0 and hp[0] == '[') {
        const end = std.mem.findScalar(u8, hp, ']') orelse return null;
        if (end + 1 == hp.len) return null;
        if (end + 1 != i) return null;
        host = hp[1..end];
        j = 1;
        k = end + 1;
    } else {
        host = hp[0..i];
        if (std.mem.findScalar(u8, host, ':') != null) return null;
    }
    if (std.mem.findScalar(u8, hp[j..], '[') != null) return null;
    if (std.mem.findScalar(u8, hp[k..], ']') != null) return null;
    return .{ .host = host, .port = hp[i + 1 ..] };
}

/// `host:port`, port 1-65535 (digits only), host empty or an RFC 1123 name;
/// `[host]:port` is split as Go's `net.SplitHostPort` does.
pub fn isHostnamePort(s: []const u8) bool {
    const hp = splitHostPort(s) orelse return false;
    if (!validPort(hp.port)) return false;
    const p = std.fmt.parseInt(u32, hp.port, 10) catch return false;
    if (p < 1) return false;
    return hp.host.len == 0 or isHostName(hp.host);
}

fn validPort(p: []const u8) bool {
    if (p.len == 0) return false;
    for (p) |c| if (!std.ascii.isDigit(c)) return false;
    return (std.fmt.parseInt(u32, p, 10) catch return false) <= 65535;
}

/// `Origin` (RFC 6454): `http` or `https` (any case), `://`, a host name, IP
/// or `[IPv6]`, an optional port 1-65535; no user, path, query or fragment.
pub fn isOrigin(s: []const u8) bool {
    if (s.len == 0 or std.mem.findScalar(u8, s, '#') != null) return false;
    const colon = std.mem.findScalar(u8, s, ':') orelse return false;
    if (!std.ascii.eqlIgnoreCase(s[0..colon], "http") and !std.ascii.eqlIgnoreCase(s[0..colon], "https")) return false;
    if (!std.mem.startsWith(u8, s[colon + 1 ..], "//")) return false;
    const auth = s[colon + 3 ..];
    for (auth) |c| if (c == '/' or c == '?' or c == '@' or c == '%' or c <= 0x20 or c >= 0x7f) return false;
    var host = auth;
    var port: []const u8 = "";
    if (std.mem.findScalarLast(u8, auth, ':')) |ci| {
        const cand = auth[ci + 1 ..];
        var digits = true;
        for (cand) |c| if (!std.ascii.isDigit(c)) {
            digits = false;
        };
        if (digits) {
            host = auth[0..ci];
            port = cand;
        } else if (auth[0] != '[') {
            return false;
        }
    }
    if (port.len != 0) {
        if (!validPort(port) or (std.fmt.parseInt(u32, port, 10) catch 0) == 0) return false;
    }
    if (host.len >= 2 and host[0] == '[' and host[host.len - 1] == ']') {
        const ip = netaddr.parseIp(host[1 .. host.len - 1]) orelse return false;
        return ip == .v6;
    } else if (std.mem.findScalar(u8, host, '[') != null or std.mem.findScalar(u8, host, ']') != null) return false;
    if (host.len == 0) return false;
    if (netaddr.parseIp(host) != null) return true;
    return isHostName(host);
}

/// `cidrv4`: an IPv4 prefix whose host bits are zero. `cidrv6`: an IPv6 prefix.
pub fn isCidr(s: []const u8, v6: bool) bool {
    const p = netaddr.parsePrefix(s) orelse return false;
    if (v6) return p.addr == .v6;
    return p.addr == .v4 and p.addr.eql(p.network());
}

// ── socket addresses, syntax only ────────────────────────────────────────────

/// `a.b.c.d:port`
fn sock4(s: []const u8) bool {
    const c = std.mem.findScalarLast(u8, s, ':') orelse return false;
    if (!validPort(s[c + 1 ..])) return false;
    const ip = netaddr.parseIp(s[0..c]) orelse return false;
    return ip == .v4;
}

/// `[v6]:port`
fn sock6(s: []const u8) bool {
    const c = std.mem.findScalarLast(u8, s, ':') orelse return false;
    if (!validPort(s[c + 1 ..])) return false;
    const h = s[0..c];
    if (h.len < 4 or h[0] != '[' or h[h.len - 1] != ']') return false;
    const ip = netaddr.parseIp(h[1 .. h.len - 1]) orelse return false;
    return ip == .v6;
}

/// `tcp4_addr` / `udp4_addr` (family 4), `tcp6_addr` / `udp6_addr` (6),
/// `tcp_addr` / `udp_addr` (0): a literal IP and a numeric port 0-65535.
pub fn isSockAddr(s: []const u8, family: u8) bool {
    return switch (family) {
        4 => sock4(s),
        6 => sock6(s),
        else => sock4(s) or sock6(s),
    };
}

/// `ip4_addr` / `ip6_addr` / `ip_addr`: a literal IP, no port, no zone.
pub fn isIpAddr(s: []const u8, family: u8) bool {
    const ip = netaddr.parseIp(s) orelse return false;
    return switch (family) {
        4 => ip == .v4,
        6 => ip == .v6,
        else => true,
    };
}

// ── ISO code sets ────────────────────────────────────────────────────────────

fn hasText(set: []const []const u8, s: []const u8) bool {
    var lo: usize = 0;
    var hi: usize = set.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        switch (std.mem.order(u8, s, set[mid])) {
            .lt => hi = mid,
            .gt => lo = mid + 1,
            .eq => return true,
        }
    }
    return false;
}

fn hasCode(set: []const u16, v: u16) bool {
    return std.mem.findScalar(u16, set, v) != null;
}

/// Exactly three ASCII digits (`840`, `008`).
fn code3(s: []const u8) ?u16 {
    if (s.len != 3) return null;
    var v: u16 = 0;
    for (s) |c| {
        if (!std.ascii.isDigit(c)) return null;
        v = v * 10 + (c - '0');
    }
    return v;
}

pub const Iso = enum { alpha2, alpha2_eu, alpha3, alpha3_eu, numeric, numeric_eu, currency, currency_numeric };

pub fn isIso(s: []const u8, which: Iso) bool {
    return switch (which) {
        .alpha2 => hasText(&tables.iso3166_1_alpha2, s),
        .alpha2_eu => hasText(&tables.iso3166_1_alpha2_eu, s),
        .alpha3 => hasText(&tables.iso3166_1_alpha3, s),
        .alpha3_eu => hasText(&tables.iso3166_1_alpha3_eu, s),
        .numeric => if (code3(s)) |v| hasCode(&tables.iso3166_1_numeric, v) else false,
        .numeric_eu => if (code3(s)) |v| hasCode(&tables.iso3166_1_numeric_eu, v) else false,
        .currency => hasText(&tables.iso4217, s),
        .currency_numeric => if (code3(s)) |v| hasCode(&tables.iso4217_numeric, v) else false,
    };
}

// ── BCP 47 (RFC 5646 section 2.1, syntax only) ───────────────────────────────

fn allAlpha(t: []const u8) bool {
    for (t) |c| if (!std.ascii.isAlphabetic(c)) return false;
    return true;
}

fn allAlnum(t: []const u8) bool {
    for (t) |c| if (!std.ascii.isAlphanumeric(c)) return false;
    return true;
}

const grandfathered = [_][]const u8{
    "en-gb-oed",  "i-ami",      "i-bnn",       "i-default", "i-enochian", "i-hak",    "i-klingon", "i-lux",
    "i-mingo",    "i-navajo",   "i-pwn",       "i-tao",     "i-tay",      "i-tsu",    "sgn-be-fr", "sgn-be-nl",
    "sgn-ch-de",  "art-lojban", "cel-gaulish", "no-bok",    "no-nyn",     "zh-guoyu", "zh-hakka",  "zh-min",
    "zh-min-nan", "zh-xiang",
};

/// A well-formed language tag: grandfathered, private use (`x-...`) or `langtag`.
/// `strict` additionally takes a 2-3 letter primary language only (the 4 and
/// 5-8 letter forms are reserved or unregistered).
pub fn isLanguageTag(s: []const u8, strict: bool) bool {
    var lower_buf: [64]u8 = undefined;
    if (s.len <= lower_buf.len) {
        const l = std.ascii.lowerString(&lower_buf, s);
        for (grandfathered) |g| if (std.mem.eql(u8, l, g)) return true;
    }
    var it = std.mem.splitScalar(u8, s, '-');
    const first = it.next() orelse return false;
    var tok = it.next();
    if (first.len == 1 and (first[0] == 'x' or first[0] == 'X')) {
        return privateUse(&it, tok);
    }
    if (first.len < 2 or first.len > 8 or !allAlpha(first)) return false;
    if (strict and first.len > 3) return false;
    if (first.len <= 3) {
        var ext: u8 = 0;
        while (tok) |t| {
            if (ext < 3 and t.len == 3 and allAlpha(t)) {
                ext += 1;
                tok = it.next();
            } else break;
        }
    }
    if (tok) |t| if (t.len == 4 and allAlpha(t)) {
        tok = it.next();
    };
    if (tok) |t| if ((t.len == 2 and allAlpha(t)) or (t.len == 3 and allDigits(t))) {
        tok = it.next();
    };
    while (tok) |t| {
        const v5 = t.len >= 5 and t.len <= 8 and allAlnum(t);
        const v4 = t.len == 4 and std.ascii.isDigit(t[0]) and allAlnum(t);
        if (!v5 and !v4) break;
        tok = it.next();
    }
    while (tok) |t| {
        if (t.len != 1 or !std.ascii.isAlphanumeric(t[0]) or t[0] == 'x' or t[0] == 'X') break;
        tok = it.next();
        var n: usize = 0;
        while (tok) |e| {
            if (e.len < 2 or e.len > 8 or !allAlnum(e)) break;
            n += 1;
            tok = it.next();
        }
        if (n == 0) return false;
    }
    if (tok) |t| {
        if (t.len == 1 and (t[0] == 'x' or t[0] == 'X')) return privateUse(&it, it.next());
        return false;
    }
    return true;
}

fn allDigits(t: []const u8) bool {
    for (t) |c| if (!std.ascii.isDigit(c)) return false;
    return true;
}

/// After the `x`: one or more subtags of 1-8 letters / digits, to the end.
fn privateUse(it: *std.mem.SplitIterator(u8, .scalar), first: ?[]const u8) bool {
    var tok = first orelse return false;
    while (true) {
        if (tok.len < 1 or tok.len > 8 or !allAlnum(tok)) return false;
        tok = it.next() orelse return true;
    }
}

// ── bank, card, identifiers ──────────────────────────────────────────────────

/// ISO 9362:2014: 4 letters, 2 letters, 2 alphanumerics, optional 3
/// alphanumerics; either case. With `strict` (ISO 9362:2022): upper case and the
/// first four may be alphanumeric.
pub fn isBic(s: []const u8, y2022: bool) bool {
    if (s.len != 8 and s.len != 11) return false;
    for (s, 0..) |c, i| {
        const alnum = std.ascii.isAlphanumeric(c);
        if (y2022) {
            const up = std.ascii.isDigit(c) or (c >= 'A' and c <= 'Z');
            if (!up) return false;
            if ((i == 4 or i == 5) and std.ascii.isDigit(c)) return false;
        } else {
            if (!alnum) return false;
            if (i < 6 and !std.ascii.isAlphabetic(c)) return false;
        }
    }
    return true;
}

fn luhn(digits: []const u8) bool {
    var sum: u32 = 0;
    var dbl = false;
    var i = digits.len;
    while (i > 0) {
        i -= 1;
        var d: u32 = digits[i] - '0';
        if (dbl) {
            d *= 2;
            if (d >= 10) d -= 9;
        }
        sum += d;
        dbl = !dbl;
    }
    return sum % 10 == 0;
}

/// At least two digits, nothing else, Luhn sum divisible by 10.
pub fn isLuhn(s: []const u8) bool {
    if (s.len < 2) return false;
    for (s) |c| if (!std.ascii.isDigit(c)) return false;
    return luhn(s);
}

/// Space-separated groups of 3 or more digits, 12-19 digits in all, Luhn.
pub fn isCreditCard(s: []const u8) bool {
    var buf: [19]u8 = undefined;
    var n: usize = 0;
    var it = std.mem.splitScalar(u8, s, ' ');
    while (it.next()) |seg| {
        if (seg.len < 3) return false;
        for (seg) |c| {
            if (!std.ascii.isDigit(c) or n == buf.len) return false;
            buf[n] = c;
            n += 1;
        }
    }
    return n >= 12 and luhn(buf[0..n]);
}

/// The CVE JSON 5 schema's `cveId`, `^CVE-[0-9]{4}-[0-9]{4,19}$`. The rival adds
/// year and leading-zero rules the schema does not have, and writes `[^0]` where
/// a digit is meant.
pub fn isCve(s: []const u8) bool {
    if (!std.mem.startsWith(u8, s, "CVE-") or s.len < 13 or s.len > 28) return false;
    return allDigits(s[4..8]) and s[8] == '-' and allDigits(s[9..]);
}

/// `ddd-dd-dddd` (each separator a space or a hyphen), group not `00`, serial
/// not `0000`; the area number is unrestricted, as in the rival.
pub fn isSsn(s: []const u8) bool {
    if (s.len != 11) return false;
    if ((s[3] != ' ' and s[3] != '-') or (s[6] != ' ' and s[6] != '-')) return false;
    const a = s[0..3];
    const g = s[4..6];
    const r = s[7..11];
    if (!allDigits(a) or !allDigits(g) or !allDigits(r)) return false;
    return !std.mem.eql(u8, g, "00") and !std.mem.eql(u8, r, "0000");
}

/// US employer identification number `dd-ddddddd`.
pub fn isEin(s: []const u8) bool {
    return s.len == 10 and s[2] == '-' and allDigits(s[0..2]) and allDigits(s[3..]);
}

fn cronField(t: []const u8) bool {
    if (t.len == 1) return t[0] == '*' or t[0] == '?' or std.ascii.isDigit(t[0]);
    if (t.len < 2) return false;
    if (!std.ascii.isAlphanumeric(t[0]) and t[0] != '*' and t[0] != '?') return false;
    for (t[1..]) |c| {
        if (!std.ascii.isAlphanumeric(c) and std.mem.findScalar(u8, "*?/,#-", c) == null) return false;
    }
    return true;
}

fn cronEvery(r: []const u8) bool {
    var i: usize = 0;
    var groups: usize = 0;
    while (i < r.len) {
        const st = i;
        while (i < r.len and std.ascii.isDigit(r[i])) i += 1;
        if (i == st) return false;
        const rest = r[i..];
        const units = [_][]const u8{ "ns", "us", "\xc2\xb5s", "ms", "s", "m", "h" };
        var hit: usize = 0;
        for (units) |u| if (std.mem.startsWith(u8, rest, u) and u.len > hit) {
            hit = u.len;
        };
        if (hit == 0) return false;
        i += hit;
        groups += 1;
    }
    return groups > 0;
}

/// A cron expression: `@yearly`-style macro, `@every` + Go durations, or 5-7
/// space-separated fields (syntax of each field only, no ranges).
pub fn isCron(s: []const u8) bool {
    if (s.len == 0) return false;
    if (s[0] == '@') {
        const macros = [_][]const u8{ "@annually", "@yearly", "@monthly", "@weekly", "@daily", "@hourly", "@reboot" };
        for (macros) |m| if (std.mem.eql(u8, s, m)) return true;
        return std.mem.startsWith(u8, s, "@every ") and cronEvery(s[7..]);
    }
    if (s[0] == ' ' or s[s.len - 1] == ' ') return false;
    var n: usize = 0;
    var it = std.mem.tokenizeScalar(u8, s, ' ');
    while (it.next()) |f| : (n += 1) if (!cronField(f)) return false;
    return n >= 5 and n <= 7;
}
