"""Differential oracle for the cross-field presence ops against go-playground/validator v10.30.5.

`required_if`, `required_unless`, `required_with`, `required_without` (the first four ops, anchored
by reading baked_in.go) and the later `required_with_all`, `required_without_all`, `skip_unless`,
`excluded_if`, `excluded_unless`, `excluded_with`, `excluded_with_all`, `excluded_without`,
`excluded_without_all`. Go judges a struct `{F string `validate:"<tag>"`; A, B, C string}` through
`validate.Struct` (`go_cross/`); the verdicts are frozen in `src/go_cross_vectors.zig` and replayed by
`src/go_cross_test.zig` on the tree and the streaming path, with no Go at test time. A sibling or F
is "present" when its Go string is non-empty and its JSON member exists (the module tests key
presence, go the zero value; no case here uses an empty present string, the named difference).

    python3 modules/validate/tools/cross_oracle.py > modules/validate/src/go_cross_vectors.zig
    python3 modules/validate/tools/cross_oracle.py --check
"""
import itertools
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# (go tag, Zig `.cross` entries). Value ops list (sibling, text) pairs.
def entries(op, sibs):
    return ', '.join('.{ .op = .%s, .other = "%s" }' % (op, s) for s in sibs)


def ventries(op, pairs):
    return ', '.join('.{ .op = .%s, .other = "%s", .value = "%s" }' % (op, s, v) for s, v in pairs)


TAGS = []
for op in ['required_with', 'required_without', 'required_with_all', 'required_without_all',
           'excluded_with', 'excluded_with_all', 'excluded_without_all']:
    for sibs in (['A'], ['A', 'B']):
        TAGS.append((op + '=' + ' '.join(sibs), sibs, entries(op, sibs)))
# go's excluded_without reads ONE field name (strings.TrimSpace of the whole param): a space-separated
# `A B` is the single name "A B", found nowhere, so it always counts as absent. Several Zig entries
# are several go tags (`excluded_without=A,excluded_without=B`), each judged alone: "any".
TAGS.append(('excluded_without=A', ['A'], entries('excluded_without', ['A'])))
TAGS.append(('excluded_without=A,excluded_without=B', ['A', 'B'], entries('excluded_without', ['A', 'B'])))
TAGS.append(('excluded_without=A B', ['A', 'B'], entries('excluded_without', ['A B'])))
for op in ['required_if', 'required_unless', 'skip_unless', 'excluded_if', 'excluded_unless']:
    for pairs in ([('A', 'x')], [('A', 'x'), ('B', 'y')]):
        TAGS.append((op + '=' + ' '.join(s + ' ' + v for s, v in pairs), [s for s, _ in pairs], ventries(op, pairs)))

STATES = ['', 'x', 'y']  # '' = absent


def zstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def go_verdicts(items):
    payload = json.dumps([{'tag': t, 'f': f, 'sib': sib} for t, _, _, f, sib in items])
    env = dict(os.environ)
    env.setdefault('GOPROXY', 'off')
    env.setdefault('GOFLAGS', '-mod=readonly')
    r = subprocess.run(['go', 'run', '.'], cwd=os.path.join(HERE, 'go_cross'), input=payload.encode(),
                       capture_output=True, env=env, check=True)
    return json.loads(r.stdout)


def main():
    items = []
    for tag, sibs, ents in TAGS:
        for f in ('', 'v'):
            for combo in itertools.product(STATES, repeat=len(sibs)):
                items.append((tag, sibs, ents, f, dict(zip(sibs, combo))))
    verdicts = go_verdicts(items)
    o = ['// SPDX-License-Identifier: MIT',
         '// GENERATED by modules/validate/tools/cross_oracle.py -- do not hand-edit.',
         '//! go-playground/validator v10.30.5 verdicts on the cross-field presence ops, replayed by `go_cross_test.zig`.',
         '',
         'const Rule = @import("root.zig").Rule;',
         '',
         '/// `doc`: a JSON object with member `F` (when present) and the siblings; `go`: `validate.Struct` passed.',
         'pub const Case = struct { tag: []const u8, doc: []const u8, go: bool, rule: Rule };',
         '',
         'pub const cases = [_]Case{']
    for (tag, sibs, ents, f, sib), go in zip(items, verdicts):
        members = []
        if f:
            members.append('"F":"v"')
        members += ['"%s":"%s"' % (k, v) for k, v in sib.items() if v]
        doc = '{' + ','.join(members) + '}'
        o.append('    .{ .tag = %s, .doc = %s, .go = %s, .rule = .{ .field = "F", .kind = .string, .cross = &.{ %s } } },' % (
            zstr(tag), zstr(doc), 'true' if go else 'false', ents))
    o.append('};')
    text = '\n'.join(o) + '\n'
    text = subprocess.run(['zig', 'fmt', '--stdin'], input=text, capture_output=True, text=True, check=True).stdout
    if '--check' in sys.argv:
        with open(os.path.join(HERE, '..', 'src', 'go_cross_vectors.zig'), encoding='utf-8') as fh:
            if fh.read() != text:
                sys.stderr.write('cross_oracle: committed vectors differ from a fresh run\n')
                sys.exit(1)
        sys.stderr.write('cross_oracle: vectors fresh (%d cases)\n' % len(items))
        return
    sys.stdout.write(text)
    sys.stderr.write('%d cases, %d tags\n' % (len(items), len(TAGS)))


main()
