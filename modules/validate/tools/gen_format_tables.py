#!/usr/bin/env python3
"""Writes src/format_tables.zig: the data tables of the format wave 1 formats.

    python3 modules/validate/tools/gen_format_tables.py > modules/validate/src/format_tables.zig

Sources, both MIT: the country and currency code sets of go-playground/validator
v10.30.5 (`country_codes.go`, `currency_codes.go` in the module cache of
`go_formats/`), and Go's unicode.L / unicode.N tables (`go_unicode/`, run with
GOTOOLCHAIN=go1.26.0 like the other Go tools). Needs `go`, no network.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VERSION = "v10.30.5"


def modroot():
    gopath = subprocess.run(["go", "env", "GOMODCACHE"], capture_output=True, text=True, check=True).stdout.strip()
    return os.path.join(gopath, "github.com/go-playground/validator/v10@" + VERSION)


def go_map(src, name):
    m = re.search(r"^var %s = map\[[a-z]+\]struct\{\}\{(.*?)^\}" % name, src, re.S | re.M)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return sorted(set(re.findall(r'"([A-Z0-9]+)"|\b(\d+):', body) and
                      [a or b for a, b in re.findall(r'"([A-Z0-9]+)"|\b(\d+):', body)]))


def ranges():
    env = dict(os.environ, GOTOOLCHAIN="go1.26.0", GOPROXY="off")
    out = subprocess.run(["go", "run", "."], cwd=os.path.join(HERE, "go_unicode"), capture_output=True, text=True,
                         check=True, env=env).stdout
    sets, cur = {}, None
    for line in out.splitlines():
        if line.startswith("#"):
            cur = line.split()[1]
            sets[cur] = []
        else:
            lo, hi = line.split()
            sets[cur].append((int(lo), int(hi)))
    return sets


def main():
    root = modroot()
    cc = open(os.path.join(root, "country_codes.go")).read()
    cur = open(os.path.join(root, "currency_codes.go")).read()
    o = ["// SPDX-License-Identifier: MIT",
         "// GENERATED by tools/gen_format_tables.py -- do not edit by hand.",
         "// Country and currency code sets: go-playground/validator %s (MIT,"  % VERSION,
         "// Copyright (c) 2015 Dean Karn); Unicode letter / number ranges: Go 1.26.0 unicode.L, unicode.N",
         "// (Unicode 15.0.0, BSD-3-Clause). Sorted, for binary search.",
         ""]
    for zname, gname, src, num in [
        ("iso3166_1_alpha2", "iso3166_1_alpha2", cc, False), ("iso3166_1_alpha2_eu", "iso3166_1_alpha2_eu", cc, False),
        ("iso3166_1_alpha3", "iso3166_1_alpha3", cc, False), ("iso3166_1_alpha3_eu", "iso3166_1_alpha3_eu", cc, False),
        ("iso3166_1_numeric", "iso3166_1_alpha_numeric", cc, True),
        ("iso3166_1_numeric_eu", "iso3166_1_alpha_numeric_eu", cc, True),
        ("iso4217", "iso4217", cur, False), ("iso4217_numeric", "iso4217_numeric", cur, True)]:
        keys = go_map(src, gname)
        if num:
            keys = sorted(int(k) for k in keys)
            o.append("pub const %s = [_]u16{ %s };" % (zname, ", ".join(str(k) for k in keys)))
        else:
            o.append("pub const %s = [_][]const u8{ %s };" % (zname, ", ".join('"%s"' % k for k in keys)))
        o.append("")
    for name, rs in ranges().items():
        o.append("pub const unicode_%s = [_][2]u21{" % name.lower())
        for lo, hi in rs:
            o.append("    .{ 0x%X, 0x%X }," % (lo, hi))
        o.append("};")
        o.append("")
    sys.stdout.write("\n".join(o))


if __name__ == "__main__":
    main()
