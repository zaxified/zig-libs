// Writes src/case_tables.zig: the code points Go's unicode.ToLower and
// unicode.ToUpper change, as (lo, hi, stride) triples. go-playground's
// `lowercase`/`uppercase` are `s == strings.ToLower(s)` / `strings.ToUpper`,
// which map rune by rune with exactly these functions, so a string is
// lowercase when none of its code points is in `changes_when_lowered`.
//
//	cd modules/validate/tools/go_casetables && go run . > ../../src/case_tables.zig
package main

import (
	"fmt"
	"unicode"
)

func ranges(f func(rune) bool) [][2]rune {
	var out [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		if f(r) {
			if n := len(out); n > 0 && out[n-1][1] == r-1 {
				out[n-1][1] = r
			} else {
				out = append(out, [2]rune{r, r})
			}
		}
	}
	return out
}

func stride(rs [][2]rune) [][3]rune {
	var pts []rune
	for _, x := range rs {
		for r := x[0]; r <= x[1]; r++ {
			pts = append(pts, r)
		}
	}
	var out [][3]rune
	for i := 0; i < len(pts); {
		j := i + 1
		if j < len(pts) {
			s := pts[j] - pts[i]
			for j+1 < len(pts) && pts[j+1]-pts[j] == s {
				j++
			}
			if s <= 2 && j > i+1 || s == 1 {
				out = append(out, [3]rune{pts[i], pts[j], s})
				i = j + 1
				continue
			}
		}
		out = append(out, [3]rune{pts[i], pts[i], 1})
		i++
	}
	return out
}

func emit(name string, t [][3]rune) {
	fmt.Printf("pub const %s = [_]Triple{\n", name)
	for _, x := range t {
		fmt.Printf("    .{ .lo = 0x%X, .hi = 0x%X, .stride = %d },\n", x[0], x[1], x[2])
	}
	fmt.Printf("};\n")
}

func main() {
	lo := stride(ranges(func(r rune) bool { return unicode.ToLower(r) != r }))
	up := stride(ranges(func(r rune) bool { return unicode.ToUpper(r) != r }))
	fmt.Printf("// SPDX-License-Identifier: MIT\n")
	fmt.Printf("// GENERATED by tools/go_casetables (Go unicode %s) -- do not edit by hand.\n", unicode.Version)
	fmt.Printf("// Code points Go's unicode.ToLower / unicode.ToUpper change, as\n")
	fmt.Printf("// (lo, hi, stride) triples: lo, lo+stride, ..., hi.\n\n")
	fmt.Printf("pub const unicode_version = \"%s\";\n\n", unicode.Version)
	fmt.Printf("pub const Triple = struct { lo: u21, hi: u21, stride: u21 };\n\n")
	emit("changes_when_lowered", lo)
	fmt.Println()
	emit("changes_when_uppered", up)
}
