//! Byte-exact MMS frames captured from **real traffic between two independent
//! third-party implementations** — an IEC 61850 client and an IEC 61850 server
//! that are not this module — recorded through a TPKT-aware TCP proxy sitting
//! between them inside a network namespace.
//!
//! The oracle was used **as a black box only**: built from source with `cmake`,
//! its example server and its example clients run as binaries, and the octets
//! that crossed the wire logged. **No third-party source file was opened**, so
//! under CONVENTIONS §5 this is a test oracle, not a design reference, and it
//! needs no `/NOTICE` entry — the same status as diffing against `tar` or
//! `nft`. See SPEC.md for the exact provenance statement.
//!
//! **Anonymisation.** These frames contain no real substation, no real IED
//! identity and no MAC address: they are TCP, and every object name comes from
//! the oracle's own shipped *example* data model (`simpleIOGenericIO`,
//! `testComplexArray`, `GGIO1`, `LLN0`). The AP-titles are that example's
//! placeholders. Nothing here was captured from a real installation, so no
//! substitution was necessary; the GOOSE and SV goldens, which do carry MAC
//! addresses, are anonymised with a length-preserving substitution and say so
//! at their own definitions.
//!
//! Four assertions run over the whole table:
//!
//! 1. every frame decodes — TPKT, COTP, and for a data TPDU the session,
//!    presentation and MMS layers under a context table this module negotiated;
//! 2. every frame **re-encodes to the identical octets** wherever this module
//!    has an encoder for it, and the re-encode is built from the *decoded
//!    fields* (an access specification is rebuilt from its decoded object
//!    names, a report from its decoded access results) rather than memcpy'd;
//! 3. **the entire association handshake is reproduced from scratch** — the
//!    COTP CR, and the session CONNECT carrying the presentation CP carrying
//!    the ACSE AARQ carrying the MMS Initiate request, all 187 octets of it,
//!    built by this module and compared against the captured packet;
//! 4. a coverage assertion fails if the table ever stops containing every
//!    service and PDU shape it is supposed to pin.

