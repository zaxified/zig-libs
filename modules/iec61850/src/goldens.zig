pub fn decodeHex(hex: []const u8, out: []u8) []u8 {
    var i: usize = 0;
    while (i * 2 < hex.len) : (i += 1) {
        out[i] = std.fmt.parseInt(u8, hex[i * 2 ..][0..2], 16) catch unreachable;
    }
    return out[0 .. hex.len / 2];
}

/// The context table a client has once the association is up.
fn liveContexts() presentation.ContextTable {
    var t = presentation.ContextTable{};
    t.define(presentation.context_acse, &ber.oids.acse_abstract_syntax) catch unreachable;
    t.define(presentation.context_mms, &ber.oids.mms_abstract_syntax) catch unreachable;
    t.acceptAll();
    return t;
}

/// What one captured frame turned out to be.
const Shape = union(enum) {
    connect: void,
    accept: void,
    abort: void,
    mms: mms.Pdu,
};

fn classify(frame: []const u8) !Shape {
    const pkt = try tpkt.decode(frame);
    const tpdu = try cotp.decode(pkt.payload);
    switch (tpdu) {
        .cr, .cc => return .{ .connect = {} },
        .dt => |dt| {
            const h = try session.decodeHeader(dt.payload);
            switch (h.spdu) {
                .connect => return .{ .connect = {} },
                .accept => return .{ .accept = {} },
                .abort => return .{ .abort = {} },
                .give_tokens_or_data => {
                    const ppdu = try session.decodeDataTransfer(dt.payload);
                    var contexts = liveContexts();
                    const pdv = try presentation.decodeUserData(ppdu, &contexts);
                    return .{ .mms = try mms.decode(pdv.value) };
                },
                else => return error.TestUnexpectedResult,
            }
        },
        else => return error.TestUnexpectedResult,
    }
}

