test "coverage: the table cannot silently rot" {
    var buf: [max_frame_len]u8 = undefined;
    var saw_cr = false;
    var saw_cc = false;
    var saw_session_connect = false;
    var saw_session_accept = false;
    var saw_session_abort = false;
    var saw_read_req = false;
    var saw_read_var_list = false;
    var saw_write_req = false;
    var saw_write_multi = false;
    var saw_getnamelist_domain = false;
    var saw_getnamelist_vars = false;
    var saw_getnamelist_lists = false;
    var saw_nvl_attrs = false;
    var saw_var_attrs = false;
    var saw_report = false;
    var saw_error = false;
    var saw_file = false;
    var saw_access_failure = false;
    var saw_float = false;
    var saw_structure = false;

    for (table) |g| {
        const frame = decodeHex(g.hex, &buf);
        const pkt = tpkt.decode(frame) catch continue;
        switch (cotp.decode(pkt.payload) catch continue) {
            .cr => saw_cr = true,
            .cc => saw_cc = true,
            else => {},
        }
        const shape = classify(frame) catch continue;
        switch (shape) {
            .connect => saw_session_connect = true,
            .accept => saw_session_accept = true,
            .abort => saw_session_abort = true,
            .mms => |p| switch (p) {
                .confirmed_request => |r| switch (r.service) {
                    .read => {
                        saw_read_req = true;
                        const rr = try mms.decodeReadRequest(r.body);
                        if (rr.spec == .variable_list) saw_read_var_list = true;
                    },
                    .write => {
                        saw_write_req = true;
                        const wr = try mms.decodeWriteRequest(r.body);
                        var it = ber.Iterator.init(wr.values);
                        var c: usize = 0;
                        while (try it.next()) |_| c += 1;
                        if (c >= 3) saw_write_multi = true;
                    },
                    .get_name_list => {
                        const q = try mms.decodeGetNameListRequest(r.body);
                        switch (q.class) {
                            .domain => saw_getnamelist_domain = true,
                            .named_variable => saw_getnamelist_vars = true,
                            .named_variable_list => saw_getnamelist_lists = true,
                            else => {},
                        }
                    },
                    .file_open, .file_directory => saw_file = true,
                    else => {},
                },
                .confirmed_response => |r| {
                    if (r.service == .get_named_variable_list_attributes) saw_nvl_attrs = true;
                    if (r.service == .get_variable_access_attributes) saw_var_attrs = true;
                    if (r.service == .read) {
                        var rr = mms.decodeReadResponse(r.body) catch continue;
                        while (try rr.results.next()) |ar| {
                            switch (ar) {
                                .failure => saw_access_failure = true,
                                .success => |d| {
                                    if (d.kind == .floating_point) saw_float = true;
                                    if (d.kind == .structure) saw_structure = true;
                                },
                            }
                        }
                    }
                },
                .confirmed_error => saw_error = true,
                .unconfirmed => saw_report = true,
                else => {},
            },
        }
    }

    try testing.expect(saw_cr and saw_cc);
    try testing.expect(saw_session_connect and saw_session_accept and saw_session_abort);
    try testing.expect(saw_read_req and saw_read_var_list);
    try testing.expect(saw_write_req and saw_write_multi);
    try testing.expect(saw_getnamelist_domain and saw_getnamelist_vars and saw_getnamelist_lists);
    try testing.expect(saw_nvl_attrs and saw_var_attrs);
    try testing.expect(saw_report and saw_error and saw_file);
    try testing.expect(saw_access_failure and saw_float and saw_structure);
    try testing.expect(table.len >= 80);
}

/// The MMS PDU octets inside a captured frame, so a rebuild can be compared
/// against exactly what the peer sent.
fn originalMms(frame: []const u8) []const u8 {
    const pkt = tpkt.decode(frame) catch unreachable;
    const dt = switch (cotp.decode(pkt.payload) catch unreachable) {
        .dt => |d| d,
        else => unreachable,
    };
    const ppdu = session.decodeDataTransfer(dt.payload) catch unreachable;
    var contexts = liveContexts();
    const pdv = presentation.decodeUserData(ppdu, &contexts) catch unreachable;
    return pdv.value;
}
