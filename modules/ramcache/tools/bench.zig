//! Comparative benchmark: `ramcache.Sharded` against maypok86/otter v2.3.0
//! (the reference; a Go port of Caffeine), the program behind the
//! `**Performance:**` line of the maturity card (CONVENTIONS.md §9, kept
//! instrument kind 3).
//!
//! THIS IS A PROGRAM, NOT A TEST. `zig build bench-ramcache` runs it (always
//! ReleaseFast); `zig build check-interop` compiles it. Needs go 1.26.0 and
//! github.com/maypok86/otter/v2 in the module cache (pinned by
//! `tools/go_bench/go.mod`/`go.sum`; `GOPROXY=off`). Run from the repository
//! root.
//!
//! Both sides are a single-threaded driver over the thread-safe cache of the
//! library (`Sharded` with its default 16 shards; otter's striped buffers), 64
//! byte values, string keys "k<decimal>", an entry cap of 10 000 and no byte
//! cap that could bind. Keys and the zipf trace are generated by the same code
//! on both sides (splitmix64, the same seed). One op of a timed run is one PASS:
//! 10 000 cache operations (zipf_mixed: 100 000). The table prints ns per
//! operation.
//!   get_hit       8 000 keys preloaded; lookups round-robin, all hit
//!   get_miss      the same cache; lookups of keys never stored
//!   put_update    the same cache; stores over resident keys, round-robin
//!   put_evict     a full cache; stores of a stream of fresh keys (every store evicts)
//!   zipf_mixed    100 000-key zipf (s = 1.0): 90 % of the ops are a lookup that
//!                 stores on a miss, 10 % an unconditional store
//!   ttl_get_hit   get_hit with a 1 h write-TTL on both sides (otter ExpiryWriting;
//!                 ours reads the clock for every lookup, as otter does)
//!   map_baseline  a plain std.StringHashMap lookup against a Go map lookup
//! The cache is preloaded to 8 000 of its 10 000 entries on purpose: a 16-shard
//! cache enforces 625 per shard, and a hash imbalance across shards would evict
//! a few entries of a 100 % full cache on our side only, breaking the checksum.
//! Value handling differs by API: otter stores and returns the caller's slice;
//! ours copies it in (`put`) and out (`getBuf`, the allocation-free read). That
//! is part of the measured difference, not corrected for.
//!
//! otter's maintenance is asynchronous (goroutines, buffers drained later); the
//! Go side calls `Cache.CleanUp` before the timer starts and again before it
//! stops, see `go_bench/main.go`. Ours does its maintenance inline.
//!
//! Result count: hits + value bytes returned + misses (lookup rows), bytes
//! stored (store rows), plus the entries resident afterwards where that is
//! deterministic. zipf_mixed's count is its hit total: printed on both sides,
//! NOT compared (admission details differ by design). map_baseline is
//! excluded from the verdict. The verdict is the gross ratio ours/otter by wall
//! time (no workload is a common stack to subtract), the WORST over the other
//! six rows. Each side times the same way (double the batch until it takes over
//! 100 ms, best of five); the sides alternate for BENCH_ROUNDS (default 3)
//! rounds, each keeping its best. Arguments filter workloads.
//!
//! Then the fastest in the field (`BENCH_FAST=0` skips it): the Rust caches of
//! `tools/rust_fast_bench` -- quick_cache 0.6.24 and moka 0.12.16 (a Caffeine
//! port), pinned by its Cargo.lock, built offline -- on the same six rows, ours
//! re-timed beside each. Their values are `Arc<[u8]>`, so a hit is a refcount
//! bump where ours copies 64 bytes out (in their favour, not corrected for). A
//! row's ratio is ours / its fastest contender among otter (the reference row
//! above), quick_cache and moka; the verdict is the worst row. quick_cache
//! shards its 10 000-entry cap and evicts a few of the 8 000 preloaded keys of
//! the get rows on its own (about six), so its counts there may differ from
//! ours by under 0.1 %; that is printed and allowed, a larger difference
//! fails. Needs cargo and the crates in the registry (`cargo fetch
//! --manifest-path modules/ramcache/tools/rust_fast_bench/Cargo.toml`).

const std = @import("std");
const bench = @import("testkit").bench;
const ramcache = @import("ramcache");

const Sharded = ramcache.Sharded;

const bench_name = "bench-ramcache";
const work_dir = ".zig-cache/bench-ramcache";
const go_dir = "modules/ramcache/tools/go_bench";
const ref_short = "otter";
const ref_card = "maypok86/otter v2.3.0";

/// No common stack to subtract: ratios are gross (see the header).
const net_base: ?[]const u8 = null;
const info_only = [_][]const u8{"map_baseline"};
/// Rows whose result count is printed on both sides but not compared.
const count_info = [_][]const u8{"zipf_mixed"};
const names = [_][]const u8{ "get_hit", "get_miss", "put_update", "put_evict", "zipf_mixed", "ttl_get_hit", "map_baseline" };
/// Cache operations in one pass of each workload (index-aligned with `names`).
const pass_ops = [_]usize{ 10_000, 10_000, 10_000, 10_000, 100_000, 10_000, 10_000 };

const capacity = 10_000;
const preload = 8_000;
const value_len = 64;
const fresh_keys = 1 << 20;
const zipf_universe = 100_000;
const zipf_ops = 100_000;
const zipf_seed: u64 = 0x853C49E6748FEA9B;
const one_hour_ns: i64 = 3_600_000_000_000;

/// The same generator, constants and seed as the Go side.
fn splitmix(s: *u64) u64 {
    s.* +%= 0x9E3779B97F4A7C15;
    var z = s.*;
    z = (z ^ (z >> 30)) *% 0xBF58476D1CE4E5B9;
    z = (z ^ (z >> 27)) *% 0x94D049BB133111EB;
    return z ^ (z >> 31);
}

const Data = struct {
    io: std.Io,
    hot: []const []const u8,
    missing: []const []const u8,
    fresh: []const []const u8,
    zipf_keys: []const []const u8,
    zipf_ids: []const u32,
    zipf_write: []const bool,
    value: [value_len]u8,
    fresh_pos: usize = 0,
    get_hit: Sharded,
    get_miss: Sharded,
    put_update: Sharded,
    put_evict: Sharded,
    zipf: Sharded,
    ttl: Sharded,
    map: std.StringHashMap([]const u8),
};

fn keyTable(arena: std.mem.Allocator, prefix: []const u8, n: usize) ![]const []const u8 {
    const out = try arena.alloc([]const u8, n);
    for (out, 0..) |*slot, i| slot.* = try arena.print("{s}{d}", .{ prefix, i });
    return out;
}

fn newCache() !Sharded {
    return Sharded.init(std.heap.smp_allocator, .{
        .max_bytes = 1 << 30,
        .max_entries = capacity,
        .shard_seed = 0x5EED_5EED_5EED_5EED, // reproducible placement
    });
}

fn clockNs(io: std.Io) i64 {
    return @intCast(std.Io.Clock.Timestamp.now(io, .awake).raw.nanoseconds);
}

fn setup(arena: std.mem.Allocator, io: std.Io) !Data {
    var d: Data = undefined;
    d.io = io;
    d.fresh_pos = 0;
    for (&d.value, 0..) |*b, i| b.* = @intCast('a' + i % 26);
    d.hot = try keyTable(arena, "k", preload);
    d.missing = try keyTable(arena, "m", 10_000);
    d.fresh = try keyTable(arena, "f", fresh_keys);
    d.zipf_keys = try keyTable(arena, "z", zipf_universe);

    // Preloaded, 80 % full: get_hit, get_miss, put_update, ttl_get_hit.
    d.get_hit = try newCache();
    d.get_miss = try newCache();
    d.put_update = try newCache();
    d.ttl = try newCache();
    const now = clockNs(io);
    for (d.hot) |k| {
        d.get_hit.put(k, &d.value, 0, 0, 0);
        d.get_miss.put(k, &d.value, 0, 0, 0);
        d.put_update.put(k, &d.value, 0, 0, 0);
        d.ttl.put(k, &d.value, now, one_hour_ns, 0);
    }
    // Full: put_evict (warm keys the fresh stream will push out).
    d.put_evict = try newCache();
    for (try keyTable(arena, "w", capacity)) |k| d.put_evict.put(k, &d.value, 0, 0, 0);
    // Empty: zipf_mixed fills itself.
    d.zipf = try newCache();

    // The zipf trace: identical arithmetic to the Go side (IEEE adds and
    // divides in the same order, no fused operations).
    const cdf = try arena.alloc(f64, zipf_universe);
    var total: f64 = 0;
    for (cdf, 0..) |*slot, i| {
        total += 1.0 / @as(f64, @floatFromInt(i + 1));
        slot.* = total;
    }
    const ids = try arena.alloc(u32, zipf_ops);
    const writes = try arena.alloc(bool, zipf_ops);
    var state: u64 = zipf_seed;
    for (ids, writes) |*id, *wr| {
        const u = @as(f64, @floatFromInt(splitmix(&state) >> 11)) * 0x1p-53 * total;
        var lo: usize = 0;
        var hi: usize = zipf_universe - 1;
        while (lo < hi) {
            const mid = (lo + hi) / 2;
            if (cdf[mid] < u) lo = mid + 1 else hi = mid;
        }
        id.* = @intCast(lo);
        wr.* = splitmix(&state) % 10 == 0;
    }
    d.zipf_ids = ids;
    d.zipf_write = writes;

    d.map = .init(std.heap.smp_allocator);
    try d.map.ensureTotalCapacity(preload);
    for (d.hot) |k| d.map.putAssumeCapacity(k, &d.value);
    return d;
}

fn getPass(sc: *Sharded, keys: []const []const u8, now: i64) u64 {
    var buf: [value_len]u8 = undefined;
    var hits: u64 = 0;
    var bytes: u64 = 0;
    var misses: u64 = 0;
    for (0..10_000) |i| {
        switch (sc.getBuf(keys[i % keys.len], now, 0, &buf)) {
            .ok => |v| {
                hits += 1;
                bytes += v.len;
            },
            .miss => misses += 1,
            .buffer_too_small => unreachable,
        }
    }
    return hits + bytes + misses;
}

/// get_hit with the clock read per lookup, as otter does under an expiry.
fn ttlPass(d: *Data) u64 {
    var buf: [value_len]u8 = undefined;
    var hits: u64 = 0;
    var bytes: u64 = 0;
    var misses: u64 = 0;
    for (0..10_000) |i| {
        switch (d.ttl.getBuf(d.hot[i % d.hot.len], clockNs(d.io), 0, &buf)) {
            .ok => |v| {
                hits += 1;
                bytes += v.len;
            },
            .miss => misses += 1,
            .buffer_too_small => unreachable,
        }
    }
    return hits + bytes + misses;
}

fn once(d: *Data, w: usize) u64 {
    switch (w) {
        0 => return getPass(&d.get_hit, d.hot, 0),
        1 => return getPass(&d.get_miss, d.missing, 0),
        2 => {
            for (0..10_000) |i| d.put_update.put(d.hot[i % d.hot.len], &d.value, 0, 0, 0);
            return 10_000 * value_len;
        },
        3 => {
            var pos = d.fresh_pos;
            for (0..10_000) |_| {
                d.put_evict.put(d.fresh[pos], &d.value, 0, 0, 0);
                pos = (pos + 1) & (fresh_keys - 1);
            }
            d.fresh_pos = pos;
            return 10_000 * value_len;
        },
        4 => {
            var buf: [value_len]u8 = undefined;
            var hits: u64 = 0;
            for (d.zipf_ids, d.zipf_write) |id, wr| {
                const k = d.zipf_keys[id];
                if (wr) {
                    d.zipf.put(k, &d.value, 0, 0, 0);
                } else switch (d.zipf.getBuf(k, 0, 0, &buf)) {
                    .ok => hits += 1,
                    .miss => d.zipf.put(k, &d.value, 0, 0, 0),
                    .buffer_too_small => unreachable,
                }
            }
            return hits;
        },
        5 => return ttlPass(d),
        6 => {
            var hits: u64 = 0;
            var bytes: u64 = 0;
            var misses: u64 = 0;
            for (0..10_000) |i| {
                if (d.map.get(d.hot[i % d.hot.len])) |v| {
                    hits += 1;
                    bytes += v.len;
                } else misses += 1;
            }
            return hits + bytes + misses;
        },
        else => unreachable,
    }
}

/// Entries resident after the timed runs, for the rows where that number is
/// deterministic on both sides (added to the row's count).
fn extra(d: *Data, w: usize) u64 {
    return switch (w) {
        0 => d.get_hit.stats().entries,
        1 => d.get_miss.stats().entries,
        2 => d.put_update.stats().entries,
        5 => d.ttl.stats().entries,
        6 => d.map.count(),
        else => 0,
    };
}

pub fn main(init: std.process.Init) !u8 {
    const io = init.io;
    const arena = init.arena.allocator();
    const cwd = std.Io.Dir.cwd();
    try cwd.createDirPath(io, work_dir);
    var dir = try cwd.openDir(io, work_dir, .{});
    defer dir.close(io);
    const abs = try cwd.realPathFileAlloc(io, work_dir, arena);
    const args = try init.minimal.args.toSlice(arena);
    const filters = if (args.len > 1) args[1..] else &[_][:0]const u8{};
    const rounds: usize = if (init.environ_map.get("BENCH_ROUNDS")) |r| try std.fmt.parseInt(usize, r, 10) else 3;

    var d: Data = try setup(arena, io);

    const exe = try bench.goBuild(arena, io, bench_name, init.environ_map, .{ .exe = "go", .dir = go_dir, .abs = abs });
    var buf: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(io, &buf);
    const w = &stdout.interface;
    try w.print("{s:<22} {s:>11} {s:>11} {s:>8} {s:>8} {s:>7} {s:>7}  count\n", .{ "workload", "ours ns/op", ref_short ++ " ns/op", "gross", "net", "spr us", "spr ref" });
    try w.flush();
    var worst: f64 = 0;
    var best: f64 = std.math.inf(f64);
    var max_spread: f64 = 0;
    var mismatch = false;
    var base_ours: f64 = 0;
    var base_ref: f64 = 0;
    for (names, 0..) |name, wi| {
        if (filters.len > 0) {
            var hit = false;
            for (filters) |f| hit = hit or std.mem.find(u8, name, f) != null;
            if (!hit) continue;
        }
        var ours: bench.Side = .{};
        var go: bench.Side = .{};
        for (0..rounds) |_| {
            go.add(try bench.foreign(arena, io, bench_name, exe, abs, name, null));
            var row = bench.timeIt(io, .{ .fd = null }, once, .{ &d, wi }, true);
            row.count += extra(&d, wi);
            ours.add(row);
        }
        const gross = ours.best_ns / go.best_ns;
        // `net_base` (a workload name): the cost of the HTTP stacks both sides
        // carry is that workload; the module's own ratio is what is left over.
        var net: f64 = std.math.nan(f64);
        if (net_base) |nb| {
            if (std.mem.eql(u8, nb, name)) {
                base_ours = ours.best_ns;
                base_ref = go.best_ns;
            } else if (base_ref != 0 and go.best_ns > base_ref) {
                net = (ours.best_ns - base_ours) / (go.best_ns - base_ref);
            }
        }
        const ratio = if (net_base != null and !std.math.isNan(net)) net else gross;
        const info = for (info_only) |n| {
            if (std.mem.eql(u8, n, name)) break true;
        } else false;
        const cmp = for (count_info) |n| {
            if (std.mem.eql(u8, n, name)) break false;
        } else true;
        if (!info) {
            worst = @max(worst, ratio);
            best = @min(best, ratio);
        }
        max_spread = @max(max_spread, @max(ours.spread(false), go.spread(false)));
        const same = !cmp or ours.count == go.count;
        mismatch = mismatch or !same;
        const ops: f64 = @floatFromInt(pass_ops[wi]);
        try w.print("{s:<22} {d:>11.1} {d:>11.1} {d:>8.3} {d:>8.3} {d:>6.1}% {d:>6.1}%  ", .{ name, ours.best_ns / ops, go.best_ns / ops, gross, net, 100 * ours.spread(false), 100 * go.spread(false) });
        if (!cmp) {
            try w.print("ours {d} / {s} {d}  (hit totals, printed not compared)\n", .{ ours.count, ref_short, go.count });
        } else {
            try w.print("{d}{s}\n", .{ ours.count, if (same and !info) "" else if (same) "  (info only, not in the verdict)" else " ≠ " ++ ref_short });
        }
        try w.flush();
    }
    try w.print("rounds: {d}; ratios by wall time{s}; largest spread {d:.1}%{s}\n", .{ rounds, if (net_base != null) " (verdict = net of the " ++ net_base.? ++ " workload)" else " (verdict = gross)", 100 * max_spread, if (max_spread > 0.05) " (OVER 5 %: noisy run, repeat)" else "" });
    if (mismatch) {
        try w.writeAll(bench_name ++ ": FAILED -- a result count differs from the reference's; the timing means nothing until it agrees\n");
        try w.flush();
        return 1;
    }
    try w.print("\nworst ours/{s} = {d:.2} (best {d:.2})\n", .{ ref_short, worst, best });
    const use_fast = if (init.environ_map.get("BENCH_FAST")) |v| !std.mem.eql(u8, v, "0") else true;
    if (filters.len > 0 or !use_fast) {
        if (filters.len == 0)
            try w.print("card: **Performance:** ref {d:.2}–{d:.2}× {s} · fastest ? (measured <today>)\n", .{ best, worst, ref_card });
        try w.flush();
        return 0;
    }

    // ---- fastest in the field: the Rust caches on the same rows ----
    try w.flush();
    try rustBuild(arena, io, init.environ_map);
    try w.print("\nfastest in the field -- {d} rounds, ours re-timed beside each contender\n", .{rounds});
    try w.print("{s:<14} {s:<12} {s:>10} {s:>10} {s:>8}  count\n", .{ "workload", "contender", "its ns/op", "ours ns/op", "ours/it" });
    var worst_fast: f64 = 0;
    var worst_row: []const u8 = "";
    var worst_who: []const u8 = "";
    for (names[0 .. names.len - 1], 0..) |name, wi| { // not map_baseline
        // otter is the first contender: the reference rows above, re-timed here
        // beside ours like the others.
        var row_ratio: f64 = 0;
        var row_who: []const u8 = "";
        for (fast) |who| {
            // quick_cache has no TTL: no ttl_get_hit row (its program prints `n/a`).
            if (std.mem.eql(u8, who, "quick_cache") and std.mem.eql(u8, name, "ttl_get_hit")) {
                try w.print("{s:<14} {s:<12} {s:>10}\n", .{ name, who, "n/a" });
                continue;
            }
            var ours: bench.Side = .{};
            var it: bench.Side = .{};
            for (0..rounds) |_| {
                it.add(if (std.mem.eql(u8, who, ref_short))
                    try bench.foreign(arena, io, bench_name, exe, abs, name, null)
                else
                    try bench.foreignArgv(arena, io, bench_name, &.{ rust_exe, abs, who, name }, name, null));
                var r = bench.timeIt(io, .{ .fd = null }, once, .{ &d, wi }, true);
                r.count += extra(&d, wi);
                ours.add(r);
            }
            const ops: f64 = @floatFromInt(pass_ops[wi]);
            const r = ours.best_ns / it.best_ns;
            if (r > row_ratio) {
                row_ratio = r;
                row_who = who;
            }
            const cmp = for (count_info) |n| {
                if (std.mem.eql(u8, n, name)) break false;
            } else true;
            const diff = @abs(@as(f64, @floatFromInt(it.count)) - @as(f64, @floatFromInt(ours.count)));
            const near = diff <= @as(f64, @floatFromInt(ours.count)) * 0.001;
            const exact = it.count == ours.count;
            const ok = !cmp or exact or (std.mem.eql(u8, who, "quick_cache") and near);
            mismatch = mismatch or !ok;
            try w.print("{s:<14} {s:<12} {d:>10.1} {d:>10.1} {d:>8.3}  {d}{s}\n", .{ name, who, it.best_ns / ops, ours.best_ns / ops, r, it.count, if (!cmp) "  (hit total, not compared)" else if (exact) "" else if (ok) "  (quick_cache's own early evictions, < 0.1 %)" else " ≠ ours" });
            try w.flush();
        }
        if (row_ratio > worst_fast) {
            worst_fast = row_ratio;
            worst_row = name;
            worst_who = row_who;
        }
    }
    if (mismatch) {
        try w.writeAll(bench_name ++ ": FAILED -- a contender's result count differs from ours; the timing means nothing until it agrees\n");
        try w.flush();
        return 1;
    }
    try w.print("\nworst ours/fastest = {d:.2} ({s} vs {s})\n", .{ worst_fast, worst_row, worst_who });
    try w.print("card: **Performance:** ref {d:.2}–{d:.2}× {s} · fastest {d:.2}× {s} ({s}) (measured <today>)\n", .{ best, worst, ref_card, worst_fast, worst_who, worst_row });
    try w.flush();
    return 0;
}

/// The field: otter (the Go reference program) and the Rust caches.
const fast = [_][]const u8{ ref_short, "quick_cache", "moka" };
const rust_manifest = "modules/ramcache/tools/rust_fast_bench/Cargo.toml";
const rust_target = work_dir ++ "/rust-target";
const rust_exe = rust_target ++ "/release/rust_fast_bench";

/// Build the Rust side once, offline (the crates are in the cargo registry
/// after `cargo fetch`; Cargo.lock is committed).
fn rustBuild(arena: std.mem.Allocator, io: std.Io, environ: *const std.process.Environ.Map) !void {
    var env = try environ.clone(arena);
    try env.put("CARGO_NET_OFFLINE", "true");
    std.debug.print("{s}: building the Rust side ...\n", .{bench_name});
    const res = std.process.run(arena, io, .{
        .argv = &.{ "cargo", "build", "--release", "--offline", "--locked", "--manifest-path", rust_manifest, "--target-dir", rust_target },
        .environ_map = &env,
    }) catch |e| {
        std.debug.print("{s}: could not run cargo ({t}) -- BENCH_FAST=0 skips the contenders\n", .{ bench_name, e });
        return error.RustBuildFailed;
    };
    if (res.term != .exited or res.term.exited != 0) {
        std.debug.print("{s}: cargo build failed:\n{s}\n", .{ bench_name, res.stderr });
        return error.RustBuildFailed;
    }
}
