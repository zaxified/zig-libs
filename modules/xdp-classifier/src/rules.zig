//! Rule-table types + LPM key encoding for `xdp-classifier`'s ruleset.
//!
//! A classifier rule maps one IPv4 CIDR prefix to a `u32` class handle. The
//! generated eBPF program (`classifier.zig`) never sees rule CONTENT — it
//! performs one runtime `bpf_map_lookup_elem` against a
//! `BPF_MAP_TYPE_LPM_TRIE` map that the caller populates separately (via
//! `maps.populateRule`), so the same compiled program works for any
//! ruleset. This file's job is (a) validating a caller's rule table before
//! it is loaded into the kernel map and (b) encoding each rule into the
//! exact 8-byte key layout the kernel's LPM trie implementation expects —
//! BYTE FOR BYTE the same layout `classifier.buildClassifierProgram`
//! constructs at runtime from a live packet (see that function's doc
//! comment point 4). A mismatch between the two encodings would silently
//! misclassify every packet rather than fail loudly, so `LpmKey.toBytes`
//! is the single, shared source of truth for the layout — both the
//! populate path (`maps.populateRule`, this file) and the runtime path
//! (the generated bytecode) are documented as committing to it, and
//! `classifier.zig`'s golden test cross-checks its own key-construction
//! instructions produce this exact byte pattern for a matching address.

const std = @import("std");
const builtin = @import("builtin");

/// One IPv4 CIDR prefix: `addr` in wire/dotted order (`addr[0]` is the most
/// significant octet, e.g. `10.0.0.0/8` is `.{ .addr = .{ 10, 0, 0, 0 },
/// .prefix_len = 8 }`) — the same byte order the generated program's
/// packet-to-key copy produces (see `classifier.zig` point 4), so a prefix
/// literal here can be compared directly against packet bytes without any
/// endian conversion.
pub const Ipv4Prefix = struct {
    addr: [4]u8,
    prefix_len: u6,
};

pub const ClassifierRule = struct {
    prefix: Ipv4Prefix,
    class: u32,
};

pub const RuleSetError = error{
    /// `prefix_len > 32` — not representable by an IPv4 LPM key.
    InvalidPrefixLen,
    /// A bit at or beyond `prefix_len` (i.e. a "host bit") is set — the rule
    /// is not in canonical/masked form. Not a kernel requirement (the LPM
    /// trie only ever compares the first `prefix_len` bits), but requiring
    /// canonical input here catches a real caller footgun: two rules that
    /// differ only in don't-care bits look distinct in the table but are
    /// indistinguishable to the trie, silently picking whichever was
    /// inserted last.
    NonCanonicalPrefix,
    /// Two rules share the exact same `(addr, prefix_len)` — ambiguous
    /// which class should win (`map_update_elem` would just let the later
    /// one silently overwrite the earlier).
    DuplicatePrefix,
    /// More rules than the target map's `max_entries` can hold.
    TooManyRules,
};

/// A caller's full rule table, validated as a unit against the LPM map it
/// will be loaded into.
pub const RuleSet = struct {
    rules: []const ClassifierRule,

    /// Check every structural invariant `maps.populateRule` and the kernel
    /// LPM trie itself assume. `max_entries` is the target map's capacity
    /// (see `maps.LpmMapSpec`). Pure, allocation-free, cannot panic on any
    /// input — see the hostile/fuzz test below.
    pub fn validate(self: RuleSet, max_entries: usize) RuleSetError!void {
        if (self.rules.len > max_entries) return RuleSetError.TooManyRules;

        for (self.rules, 0..) |rule, i| {
            if (rule.prefix.prefix_len > 32) return RuleSetError.InvalidPrefixLen;
            if (!isCanonical(rule.prefix)) return RuleSetError.NonCanonicalPrefix;

            var j: usize = 0;
            while (j < i) : (j += 1) {
                const other = self.rules[j].prefix;
                if (other.prefix_len == rule.prefix.prefix_len and
                    std.mem.eql(u8, &other.addr, &rule.prefix.addr))
                {
                    return RuleSetError.DuplicatePrefix;
                }
            }
        }
    }
};

/// True if every bit at or beyond `prefix.prefix_len` is zero. `prefix_len
/// == 32` is trivially canonical (no host bits exist); `prefix_len == 0`
/// requires `addr` to be all-zero (the universal default-route rule).
fn isCanonical(prefix: Ipv4Prefix) bool {
    if (prefix.prefix_len >= 32) return true;
    const addr_bits: u32 = std.mem.readInt(u32, &prefix.addr, .big);
    if (prefix.prefix_len == 0) return addr_bits == 0; // every bit is a host bit
    // Host-bit mask: the low (32 - prefix_len) bits. prefix_len is 1..31
    // here, so 32-prefix_len is 1..31 and fits u5 (shifting by 32 would be
    // out of range for a u32 shift amount).
    const host_bits: u5 = @intCast(32 - @as(u32, prefix.prefix_len));
    const mask: u32 = (@as(u32, 1) << host_bits) -% 1;
    return (addr_bits & mask) == 0;
}

/// The exact 8-byte wire layout `BPF_MAP_TYPE_LPM_TRIE` expects for both
/// `map_update_elem` (populating a rule) and `map_lookup_elem` (a runtime
/// query): `struct { __u32 prefixlen; __u8 data[4]; }`, `prefixlen` in the
/// HOST's native byte order (the kernel reads it as a plain in-memory `u32`
/// — there is no network-order convention for this field, unlike the IPv4
/// address bytes themselves) and `data` in the address's own wire/dotted
/// order (see `Ipv4Prefix`'s doc).
pub const LpmKey = struct {
    prefixlen: u32,
    addr: [4]u8,

    pub fn fromPrefix(p: Ipv4Prefix) LpmKey {
        return .{ .prefixlen = p.prefix_len, .addr = p.addr };
    }

    /// A lookup key for one exact address (`prefixlen = 32`) — what the
    /// generated program constructs per-packet at runtime (see
    /// `classifier.zig` point 4); the kernel's LPM trie itself performs the
    /// longest-prefix search against however-specific each stored rule is.
    pub fn exact(addr: [4]u8) LpmKey {
        return .{ .prefixlen = 32, .addr = addr };
    }

    pub fn toBytes(self: LpmKey) [8]u8 {
        var buf: [8]u8 = undefined;
        std.mem.writeInt(u32, buf[0..4], self.prefixlen, builtin.cpu.arch.endian());
        buf[4..8].* = self.addr;
        return buf;
    }
};

/// Pure userspace longest-prefix-match reference — NOT what the eBPF
/// program executes (the kernel's `BPF_MAP_TYPE_LPM_TRIE` map performs the
/// real lookup at runtime, see `classifier.zig`). Provided so a ruleset's
/// intended behavior can be unit-tested and reasoned about without a
/// kernel: a linear scan is adequate here (rule tables in tests/tooling are
/// small; the kernel trie is what carries the real per-packet cost).
pub fn lookupReference(rules_: []const ClassifierRule, addr: [4]u8, default_class: u32) u32 {
    var best: ?ClassifierRule = null;
    for (rules_) |rule| {
        if (!prefixMatches(rule.prefix, addr)) continue;
        // `>=`, not `>`: on a tie (two rules with the same prefix_len both
        // match), the LATER rule in iteration order must win. This mirrors
        // `map_update_elem` on the real LPM trie -- a duplicate
        // `(addr, prefix_len)` key silently overwrites the earlier value, so
        // the kernel's answer for a duplicate ruleset is always the last one
        // loaded (see rules.zig's `DuplicatePrefix` doc comment and F4's
        // measurement: ref returned the FIRST match (111) where the kernel
        // trie returned the LAST (222) for the identical duplicate ruleset).
        // `RuleSet.validate` rejects duplicates outright, so this only
        // matters for a caller that bypasses validation -- but "matches the
        // kernel" is still the correct answer for an oracle, not "matches
        // whichever branch happened to run first".
        if (best == null or rule.prefix.prefix_len >= best.?.prefix.prefix_len) best = rule;
    }
    return if (best) |b| b.class else default_class;
}

fn prefixMatches(prefix: Ipv4Prefix, addr: [4]u8) bool {
    // `prefix_len > 32` never matches -- it does NOT clamp to /32. Such a
    // prefix is not representable by an IPv4 LPM key (`RuleSet.validate`
    // rejects it with `InvalidPrefixLen`, and `populateRuleSet` therefore
    // never loads it into the kernel map), so the kernel's trie can never
    // return a hit for it either. Clamping used to treat it as an exact /32
    // match instead, which made this reference answer for a rule that (by
    // the module's own contract) does not exist in the kernel: measured as
    // ref=7 vs kernel trie=0 for the same out-of-range rule (F4b). This is
    // still the userspace reference, callable on rules that never went
    // through `validate` -- so it must not panic (see the hostile test
    // below), just correctly report "no match" instead of a wrong one.
    if (prefix.prefix_len > 32) return false;
    const len: u32 = prefix.prefix_len;
    if (len == 0) return true;
    const bits: u32 = std.mem.readInt(u32, &prefix.addr, .big);
    const a: u32 = std.mem.readInt(u32, &addr, .big);
    const shift: u5 = @intCast(32 - len);
    return (bits >> shift) == (a >> shift);
}

