const testing = std.testing;

test "smoke: RuleSet.validate accepts a well-formed small ruleset" {
    const rules = [_]ClassifierRule{
        .{ .prefix = .{ .addr = .{ 10, 0, 0, 0 }, .prefix_len = 8 }, .class = 1 },
        .{ .prefix = .{ .addr = .{ 10, 1, 0, 0 }, .prefix_len = 16 }, .class = 2 },
        .{ .prefix = .{ .addr = .{ 0, 0, 0, 0 }, .prefix_len = 0 }, .class = 0 },
    };
    const rs: RuleSet = .{ .rules = &rules };
    try rs.validate(64);
}

test "RuleSet.validate rejects prefix_len > 32" {
    const rules = [_]ClassifierRule{
        .{ .prefix = .{ .addr = .{ 10, 0, 0, 0 }, .prefix_len = 33 }, .class = 1 },
    };
    const rs: RuleSet = .{ .rules = &rules };
    try testing.expectError(RuleSetError.InvalidPrefixLen, rs.validate(64));
}

test "RuleSet.validate rejects a non-canonical (host-bits-set) prefix" {
    const rules = [_]ClassifierRule{
        // 10.0.0.1/8 — bits below the /8 boundary are non-zero.
