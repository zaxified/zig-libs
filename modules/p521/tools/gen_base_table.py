"""Regenerates src/base_table.zig, the fixed-base comb table of `group.zig`.

  python3 -I modules/p521/tools/gen_base_table.py > modules/p521/src/base_table.zig

table[i][j] = (j + 1) * 2^(5 i) * G in affine coordinates, i < 106, j < 16
(FIPS 186-5 / SP 800-186 secp521r1 constants below), each coordinate as the
nine radix-2^58 limbs of `field.Fe` (l[0..7] 58 bits, l[8] 57 bits),
canonical. Plain affine arithmetic with Python integers: an implementation
independent of `group.zig`, so the table is also a second check of it
(`group.zig` test "comb: base_table entries …" spot-checks it against
`mulPublic`, and the comb differential against `mulCt`).

Why a generated file and not a comptime table: building the 1696 points at
comptime cost every compile of the module ~1 minute and ~2 GB (measured
2026-10-10), paid by every consumer (ssh, x509, jwt, hpke, …).
"""

P = 2**521 - 1
A = P - 3
GX = 0x00c6858e06b70404e9cd9e3ecb662395b4429c648139053fb521f828af606b4d3dbaa14b5e77efe75928fe1dc127a2ffa8de3348b3c1856a429bf97e7e31c2e5bd66
GY = 0x011839296a789a3bc0045c8a5fb42c7d1bd998f54449579b446817afbd17273e662c97ee72995ef42640c550b9013fad0761353c7086a272c24088be94769fd16650
B = 0x0051953eb9618e1c9a1f929a21a0b68540eea2da725b99b315f3b8b489918ef109e156193951ec7e937b1652c0bd3bb1bf073573df883d2c34f1ef451fd46b503f00
W, T, TEETH = 5, 106, 16


def add(p, q):
    if p is None:
        return q
    if q is None:
        return p
    (x1, y1), (x2, y2) = p, q
    if x1 == x2:
        if (y1 + y2) % P == 0:
            return None
        lam = (3 * x1 * x1 + A) * pow(2 * y1, -1, P) % P
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, P) % P
    x3 = (lam * lam - x1 - x2) % P
    return (x3, (lam * (x1 - x3) - y1) % P)


def limbs(v):
    out = [(v >> (58 * k)) & ((1 << 58) - 1) for k in range(8)]
    out.append(v >> (58 * 8))
    assert out[8] < 1 << 57
    return out


def fe(v):
    return ".{ .l = .{ " + ", ".join(f"0x{l:x}" for l in limbs(v)) + " } }"


def main():
    g = (GX, GY)
    assert (GY * GY - (GX ** 3 + A * GX + B)) % P == 0
    print("// SPDX-License-Identifier: MIT")
    print("// GENERATED by tools/gen_base_table.py -- do not edit.")
    print("//! table[i][j] = (j + 1)·2^(5i)·G, affine, radix-2^58 limbs (see group.zig `combMulBaseCt`).")
    print()
    print('const AffineCoordinates = @import("group.zig").AffineCoordinates;')
    print()
    print(f"pub const table: [{T}][{TEETH}]AffineCoordinates = .{{")
    base = g
    for _ in range(T):
        print("    .{")
        pt = base
        for j in range(TEETH):
            x, y = pt
            print(f"        .{{ .x = {fe(x)}, .y = {fe(y)} }},")
            pt = add(pt, base)
        print("    },")
        for _ in range(W):
            base = add(base, base)
    print("};")


main()
