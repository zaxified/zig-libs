"""Recipe for `src/testdata/libsodium.zig`: goldens from the system libsodium
(a foreign implementation) for the ChaCha variants Wycheproof does not cover —
the original 64-bit-nonce stream (with counters that carry across 2^32 and run
up to the end of the 64-bit space), the XChaCha20 stream and HChaCha20.

    python3 -I modules/chachapoly/tools/libsodium_goldens.py > modules/chachapoly/src/testdata/libsodium.zig

Inputs are not stored: key, nonce and message are `fill(len, salt)` — a
pattern the Zig test rebuilds byte for byte (`testdata/libsodium.zig`'s
`fill`). Each row stores SHA-256 of libsodium's output, so a wrong byte
anywhere fails the row.
"""
import ctypes
import hashlib
import sys

so = ctypes.CDLL("libsodium.so.23")
assert so.sodium_init() >= 0
so.sodium_version_string.restype = ctypes.c_char_p
ver = so.sodium_version_string().decode()


def fill(n, salt):
    return bytes(((i * 167 + salt * 13 + (i >> 8) * 59) & 0xFF) for i in range(n))


lens = [0, 1, 63, 64, 65, 127, 128, 129, 511, 512, 513, 575, 576, 1000, 1420, 4103]
rows = []

# Original ChaCha20: crypto_stream_chacha20_xor_ic(c, m, mlen, n[8], ic u64, k[32]).
so.crypto_stream_chacha20_xor_ic.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_ulonglong, ctypes.c_char_p, ctypes.c_uint64, ctypes.c_char_p]
counters64 = [0, 1, (1 << 32) - 3, (1 << 32) - 1, (1 << 32), (1 << 64) - 80]
for ic in counters64:
    for n in lens:
        if (n + 63) // 64 + ic > (1 << 64):
            continue
        m = fill(n, 1)
        out = ctypes.create_string_buffer(max(n, 1))
        assert so.crypto_stream_chacha20_xor_ic(out, m, n, fill(8, 2), ic, fill(32, 3)) == 0
        rows.append(("nonce64", ic, n, hashlib.sha256(out.raw[:n]).hexdigest()))

# XChaCha20 stream: crypto_stream_xchacha20_xor_ic(c, m, mlen, n[24], ic u64, k[32]).
so.crypto_stream_xchacha20_xor_ic.argtypes = so.crypto_stream_chacha20_xor_ic.argtypes
for ic in [0, 1, (1 << 32) - 80]:
    for n in lens:
        m = fill(n, 4)
        out = ctypes.create_string_buffer(max(n, 1))
        assert so.crypto_stream_xchacha20_xor_ic(out, m, n, fill(24, 5), ic, fill(32, 6)) == 0
        rows.append(("xchacha20", ic, n, hashlib.sha256(out.raw[:n]).hexdigest()))

# XChaCha20-Poly1305 (IETF): ciphertext || tag, AD = fill(ad_len, 9).
so.crypto_aead_xchacha20poly1305_ietf_encrypt.argtypes = [ctypes.c_char_p, ctypes.POINTER(ctypes.c_ulonglong), ctypes.c_char_p, ctypes.c_ulonglong, ctypes.c_char_p, ctypes.c_ulonglong, ctypes.c_char_p, ctypes.c_char_p, ctypes.c_char_p]
for ad_len in [0, 13, 300]:
    for n in lens:
        m = fill(n, 7)
        out = ctypes.create_string_buffer(n + 16)
        clen = ctypes.c_ulonglong()
        assert so.crypto_aead_xchacha20poly1305_ietf_encrypt(out, ctypes.byref(clen), m, n, fill(ad_len, 9), ad_len, None, fill(24, 8), fill(32, 10)) == 0
        assert clen.value == n + 16
        rows.append(("xaead", ad_len, n, hashlib.sha256(out.raw[: n + 16]).hexdigest()))

# HChaCha20: crypto_core_hchacha20(out[32], in[16], k[32], c=NULL).
so.crypto_core_hchacha20.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_char_p, ctypes.c_char_p]
draft_key = bytes(range(32))
draft_in = bytes.fromhex("000000090000004a0000000031415927")  # draft-irtf-cfrg-xchacha-03 §2.2.1
hc = ctypes.create_string_buffer(32)
assert so.crypto_core_hchacha20(hc, draft_in, draft_key, None) == 0

o = []
o.append("// SPDX-License-Identifier: MIT")
o.append(f"// Generated by modules/chachapoly/tools/libsodium_goldens.py from libsodium {ver}. Do not edit by hand.")
o.append("// Each row: SHA-256 of libsodium's output for inputs rebuilt by `fill` (see the recipe).")
o.append("")
o.append("pub fn fill(comptime n: usize, salt: u8) [n]u8 {")
o.append("    var b: [n]u8 = undefined;")
o.append("    for (&b, 0..) |*x, i| x.* = @truncate(i *% 167 +% @as(usize, salt) *% 13 +% (i >> 8) *% 59);")
o.append("    return b;")
o.append("}")
o.append("")
o.append("pub fn fillSlice(b: []u8, salt: u8) void {")
o.append("    for (b, 0..) |*x, i| x.* = @truncate(i *% 167 +% @as(usize, salt) *% 13 +% (i >> 8) *% 59);")
o.append("}")
o.append("")
o.append("pub const Kind = enum { nonce64, xchacha20, xaead };")
o.append("/// `arg`: the initial block counter (`nonce64`, `xchacha20`) or the AD length (`xaead`).")
o.append("pub const Row = struct { kind: Kind, arg: u64, len: usize, sha256: []const u8 };")
o.append("")
o.append(f"pub const max_len = {max(lens)};")
o.append("")
o.append("/// draft-irtf-cfrg-xchacha-03 §2.2.1 HChaCha20 input and libsodium's output for it.")
o.append(f'pub const hchacha_key = "{draft_key.hex()}";')
o.append(f'pub const hchacha_in = "{draft_in.hex()}";')
o.append(f'pub const hchacha_out = "{hc.raw.hex()}";')
o.append("")
o.append("pub const rows = [_]Row{")
for kind, arg, n, h in rows:
    o.append(f'    .{{ .kind = .{kind}, .arg = {arg}, .len = {n}, .sha256 = "{h}" }},')
o.append("};")
sys.stdout.write("\n".join(o) + "\n")
